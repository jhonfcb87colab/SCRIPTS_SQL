WITH CTE_PAGO_PRODUCTIVIDAD AS (
SELECT  
	SEG.CONSECUTIVO_SEGUIMIENTO,
	SEG.ID_PROCESO,
	SEG.NUMERO_MOVIMI,
	SEG.CONSECUT_MOVIMI,
	SEG.NUMERO_GUIA,
	TMP.FECHA_HORA_MOVIMIENTO
FROM Mece_Logistico.DBO.SEGUIMIENTO_ENVIO_LIQUIDACION_PAGO_PRODUCTIVIDAD_TERCEROS SEG  (NOLOCK)
INNER JOIN [tmp_borrar_local].[dbo].[DRW_TMP_COSTOS_POR_TRAYECTO_BI_GUIAS_PROCESOS_MANIFISTOS_LIQUIDACION_PAGO_PRODUCTIVIDAD] TMP (NOLOCK) 
ON 	TMP.NUMERO_GUIA=SEG.NUMERO_GUIA
AND TMP.ID_PROCESO=SEG.ID_PROCESO
AND TMP.CONSECUT_MOVIMI=SEG.CONSECUT_MOVIMI
AND TMP.NUMERO_MOVIMI=SEG.NUMERO_MOVIMI
)SELECT 
		SEGLIQ.ID_PROCESO
		,CTE.CONSECUTIVO_SEGUIMIENTO
		,SEGLIQ.NUMERO_MOVIMI
		,SEGLIQ.CONSECUT_MOVIMI
		,SEGLIQ.NUMERO_GUIA
		,SERLIQ.CONSECUTIVO_TIPO_SERVICIO		-- 1-Recoleccion, 2-Distribución, 3-Transporte, 4-Otros (peaje), 5-Servicios adicionales
		,TIPSER.NOMBRE_TIPO_SERVICIO
		,SERLIQ.CONSECUTIVO_SERVICIO		-- 8-Documentos, 10-Paquete tarifa unica	
		,SER.NOMBRE_SERVICIO
		,SEGLIQ.VALOR_TARIFA_SERVICIO
		,CTE.FECHA_HORA_MOVIMIENTO
		,[MODELOS_DE_CONTRATACION_FLOTA] = CASE
												WHEN TRATRA.CONSECUTIVO_TRAYECTO IS NOT NULL THEN
														CASE WHEN SERLIQ.CONSECUTIVO_TIPO_SERVICIO = 3 AND SERLIQ.CONSECUTIVO_SERVICIO = 15
															THEN 3
															ELSE 4
														END
												WHEN TRAREC.CONSECUTIVO_TRAYECTO IS NOT NULL OR TRADIS.CONSECUTIVO_TRAYECTO IS NOT NULL THEN 4
													ELSE (
																CASE WHEN SERLIQ.CONSECUTIVO_TIPO_SERVICIO IN(1,3,8,10,15,16,18,19,20,28) THEN 14
																ELSE 12
																END
															)
												END
		,TIPO_OPERADOR = CASE 
									WHEN TRATRA.CONSECUTIVO_TRAYECTO IS NOT NULL THEN
											CASE WHEN SERLIQ.CONSECUTIVO_TIPO_SERVICIO = 3 AND SERLIQ.CONSECUTIVO_SERVICIO = 15
												THEN 'OUTSOURCING FLETE FIJO'
												ELSE 'OUTSOURCING CONDUCTOR PXP'
											END
										WHEN TRAREC.CONSECUTIVO_TRAYECTO IS NOT NULL OR TRADIS.CONSECUTIVO_TRAYECTO IS NOT NULL THEN 'OURSOURCING PXP'
										ELSE (
												CASE WHEN SERLIQ.CONSECUTIVO_TIPO_SERVICIO IN(1,3,8,10,15,16,18,19,20,28) THEN 'OUTSOURCING CLS PXP'
												ELSE 'OUTSOURCING CLS TRANSPORTE'
												END
										)
									END
FROM CTE_PAGO_PRODUCTIVIDAD CTE
	INNER JOIN Mece_Logistico.DBO.SEGUIMIENTO_ENVIO_LIQUIDACION_PAGO_PRODUCTIVIDAD_TERCEROS SEGLIQ (NOLOCK) 
		 ON CTE.ID_PROCESO = SEGLIQ.ID_PROCESO 
		AND CTE.NUMERO_MOVIMI = SEGLIQ.NUMERO_MOVIMI 
		AND CTE.CONSECUT_MOVIMI = SEGLIQ.CONSECUT_MOVIMI
		AND CTE.NUMERO_GUIA = SEGLIQ.NUMERO_GUIA
		AND CTE.CONSECUTIVO_SEGUIMIENTO = SEGLIQ.CONSECUTIVO_SEGUIMIENTO
	INNER JOIN Mece_Logistico.DBO.SERVICIOS_SEGUIMIENTO_ENVIO_LIQUIDACION_PAGO_PRODUCTIVIDAD_TERCEROS SERLIQ (NOLOCK)
		ON SEGLIQ.CONSECUTIVO_SEGUIMIENTO = SERLIQ.CONSECUTIVO_SEGUIMIENTO
	INNER JOIN Mece_Logistico.DBO.DOCUMENTOS_LIQUIDACION_PAGO_PRODUCTIVIDAD_TERCEROS DOCLIQ (NOLOCK) 
		ON DOCLIQ.ID_PROCESO = SEGLIQ.ID_PROCESO 
		AND DOCLIQ.NUMERO_MOVIMI = SEGLIQ.NUMERO_MOVIMI 
		AND DOCLIQ.CONSECUT_MOVIMI = SEGLIQ.CONSECUT_MOVIMI
	INNER JOIN PARAMETROS.DBO.TIPOS_SERVICIO_PAGO_PRODUCTIVIDAD_TERCEROS TIPSER (NOLOCK) 
		ON TIPSER.CONSECUTIVO_TIPO_SERVICIO = SERLIQ.CONSECUTIVO_TIPO_SERVICIO
	INNER JOIN PARAMETROS.DBO.SERVICIOS_PAGO_PRODUCTIVIDAD_EMPRESARIO_SATELITE SER (NOLOCK) 
		ON SER.CONSECUTIVO_SERVICIO = SERLIQ.CONSECUTIVO_SERVICIO
	LEFT JOIN Mece_Logistico.DBO.TRAYECTOS_TARIFAS_PAGO_PRODUCTIVIDAD_TERCEROS TRAREC (NOLOCK) 
		ON TRAREC.ID_CIUDAD_ORIGEN = DOCLIQ.ID_CIUDAD_DIVISION_ORIGEN 
		AND TRAREC.ID_CIUDAD_DESTINO = DOCLIQ.ID_CIUDAD_DESTINO AND TRAREC.CONSECUTIVO_TIPO_SERVICIO = 1 
		AND TRAREC.PLACA_VEHICULO = DOCLIQ.PLACA_VEHICULO
	LEFT JOIN Mece_Logistico.DBO.TRAYECTOS_TARIFAS_PAGO_PRODUCTIVIDAD_TERCEROS TRADIS (NOLOCK) 
		ON TRADIS.ID_CIUDAD_ORIGEN = DOCLIQ.ID_CIUDAD_DIVISION_ORIGEN 
		AND TRADIS.ID_CIUDAD_DESTINO = DOCLIQ.ID_CIUDAD_DESTINO 
		AND TRADIS.CONSECUTIVO_TIPO_SERVICIO = 2 
		AND TRADIS.PLACA_VEHICULO = DOCLIQ.PLACA_VEHICULO
	LEFT JOIN Mece_Logistico.DBO.TRAYECTOS_TARIFAS_PAGO_PRODUCTIVIDAD_TERCEROS TRATRA (NOLOCK) 
		ON TRATRA.ID_CIUDAD_ORIGEN = DOCLIQ.ID_CIUDAD_DIVISION_ORIGEN 
		AND TRATRA.ID_CIUDAD_DESTINO = DOCLIQ.ID_CIUDAD_DESTINO 
		AND TRATRA.CONSECUTIVO_TIPO_SERVICIO = 3 
		AND TRATRA.PLACA_VEHICULO = DOCLIQ.PLACA_VEHICULO





