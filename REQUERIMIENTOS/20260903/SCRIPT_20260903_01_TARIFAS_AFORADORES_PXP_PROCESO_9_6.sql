
USE Mece_Logistico;
SELECT TOP 100
SEG.ID_PROCESO,
SEG.NUMERO_MOVIMI,
SEG.CONSECUT_MOVIMI,
SEG.NUMERO_GUIA,
SER.FECHA_GESTION_LOGISTICA,
--SEG.NUMERO_PIEZAS,
--SER.CONSECUTIVO_TIPO_SERVICIO,		-- 1-Recoleccion, 2-Distribución, 3-Transporte, 4-Otros (peaje), 5-Servicios adicionales
--SER.CONSECUTIVO_SERVICIO,
SUM(SER.VALOR_TARIFA_SERVICIO) AS VALOR_PRODUCTIVIDAD_TERCERO
FROM SERVICIOS_SEGUIMIENTO_ENVIO_LIQUIDACION_PAGO_PRODUCTIVIDAD_TERCEROS SER (NOLOCK)
INNER JOIN SEGUIMIENTO_ENVIO_LIQUIDACION_PAGO_PRODUCTIVIDAD_TERCEROS SEG (NOLOCK) ON SEG.CONSECUTIVO_SEGUIMIENTO = SER.CONSECUTIVO_SEGUIMIENTO
WHERE SER.FECHA_GESTION_LOGISTICA BETWEEN '20260902' AND '20260902 23:59'
AND ID_PROCESO=9
AND NUMERO_MOVIMI='001009101971001092026'	
AND CONSECUT_MOVIMI=20
AND NUMERO_GUIA=2145709919	         	         	
GROUP BY SEG.ID_PROCESO,SEG.NUMERO_MOVIMI,SEG.CONSECUT_MOVIMI,SEG.NUMERO_GUIA,
SER.FECHA_GESTION_LOGISTICA
    		

