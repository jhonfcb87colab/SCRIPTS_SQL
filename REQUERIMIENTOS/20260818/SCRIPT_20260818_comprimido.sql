    SELECT DISTINCT /*TOP 1000*/ [NUMERO GUIA] AS NUMERO_GUIA
    FROM [dbo].[ELIMINAR_SOLICITUD_DARWIN_20260818_Detalle_Guias_Indemnizadas]
) D
