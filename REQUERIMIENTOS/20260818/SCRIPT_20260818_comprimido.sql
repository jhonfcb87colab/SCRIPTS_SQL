,ISNULL(ISNULL(CO.NOMBRE_CIUDAD,CD.NOMBRE_CIUDAD),'')  AS CIUDAD_ORIGEN_ULT_MOV
,ISNULL(ISNULL(CLD.CENTRO_LOGISTICO,CLO.CENTRO_LOGISTICO),'') AS CPL_DESTINO_ULT_MOV
,ISNULL(ISNULL(RD.NOMBRE_REGIONAL,RO.NOMBRE_REGIONAL),'') AS REGIONAL_DESTINO_ULT_MOV
,ISNULL(ISNULL(CD.NOMBRE_CIUDAD,CO.NOMBRE_CIUDAD),'') AS CIUDAD_DESTINO_MOV
,ISNULL(DOC.PLACA_VEHICULO_DOCU,'') as PLACA_VEHICULO_ULT_MOV
,ISNULL(O.[NOMBRE_OPERATIVO],'') AS NOMBRE_OPERATIVO_ULT_MOV
,ISNULL(CASE
	WHEN ISNULL(DOC.ID_CIUDAD_ZONA_URBA,0) !=0 THEN
	ROZ.NOMBRE_REGIONAL+' - '+ DCOZ.NOMBRE_DEPARTAMENTO +' - '+ COZ.NOMBRE_CIUDAD
	WHEN  ISNULL(DOC.ID_CIUDAD_DIVISION_ORIGEN,0) !=0 THEN
	ROM.NOMBRE_REGIONAL+' - '+ DCOM.NOMBRE_DEPARTAMENTO +' - '+ COM.NOMBRE_CIUDAD
	ELSE
	ROD.NOMBRE_REGIONAL+' - '+ DCOD.NOMBRE_DEPARTAMENTO +' - '+ COD.NOMBRE_CIUDAD
	END,'') AS REG_DEPART_CIUDAD_ULTIMO_MOV
,ISNULL(GR.NOMBRE_PROCESO_ULT_MOV,'') AS PROCESO_LOG_ULTIMO
,ISNULL(cast(GR.ID_PROCESO_ULT_MOV as nvarchar) +' - '+ RTRIM(GR.NOMBRE_PROCESO_ULT_MOV),'') AS NOMBRE_ULTIMO_MOV
,ISNULL(CASE WHEN DIO.ID_DIVISION IS NOT NULL THEN cast(DIO.ID_DIVISION as nvarchar) +' - '+ RTRIM(DIO.NOMBRE_DIVISION)
ELSE cast(DID.ID_DIVISION as nvarchar) +' - '+ RTRIM(DID.NOMBRE_DIVISION) END,'') AS BODEGA_ULTIMO_MOV
,ISNULL(cast(GR.ID_PROCESO_ULT_MOV as nvarchar) +' - '+ RTRIM(GR.[NUMERO_MOVIMI_ULT_MOV])+' - '+  cast(GR.[CONSECUT_MOVIMI_ULT_MOV] as nvarchar),'') as ULTIMO_MOV_LOGISTICO
,ISNULL(CONVERT(nvarchar(20),GR.FECHA_HORA_MOVIMI_ULT_MOV,120),'') AS FECHA_ULTIMO_MOV
,GR.FECHA_HORA_MOVIMI_EZU_EPS
,CANAL = G.TIPO_CLIENTE
,CLIENTE_CDS = G.NOMBRE_CLIENTE_CDS
from #GUIAS_EN_MOVIMIENTO GR
LEFT JOIN #TMP_GUIAS G ON G.NUMERO_GUIA=GR.NUMERO_GUIA
  LEFT JOIN MECE_LOGISTICO.DBO.DOCUMENTOS DOC (NOLOCK) ON
	DOC.ID_PROCESO=GR.[ID_PROCESO_ULT_MOV] AND DOC.NUMERO_MOVIMI=GR.[NUMERO_MOVIMI_ULT_MOV] AND DOC.CONSECUT_MOVIMI=GR.[CONSECUT_MOVIMI_ULT_MOV]
  LEFT JOIN PARAMETROS.DBO.CIUDADES COZ (NOLOCK) ON  COZ.ID_PAIS=1 AND COZ.ID_CIUDAD=DOC.ID_CIUDAD_ZONA_URBA
  LEFT JOIN PARAMETROS.DBO.REGIONALES_PAIS ROZ (NOLOCK) ON  ROZ.ID_PAIS=COZ.ID_PAIS AND ROZ.ID_REGIONAL=COZ.ID_REGIONAL
  LEFT JOIN PARAMETROS.DBO.DEPARTAMENTOS DCOZ (NOLOCK) ON  DCOZ.ID_PAIS=COZ.ID_PAIS AND DCOZ.ID_DEPARTAMENTO=COZ.ID_DEPARTAMENTO
   LEFT JOIN PARAMETROS.DBO.ZONASURBANAS Z (NOLOCK)
	ON Z.ID_PAIS = DOC.ID_PAIS_ZONA_URBA AND Z.ID_CIUDAD = DOC.ID_CIUDAD_ZONA_URBA AND Z.ID_TIPO_ZONA_URBA = DOC.ID_TIPO_ZONA_URBA AND Z.ID_ZONA_URBA = DOC.ID_ZONA_URBA
  LEFT JOIN [PARAMETROS].[dbo].[CATEGORIAZONASURBANAS] CZ (NOLOCK) ON CZ.Id_Categoria=Z.CATEGORIA_ZONA_URBA
  LEFT JOIN [PARAMETROS].[dbo].[TIPOSZONASURBANAS] TZU (NOLOCK) ON TZU.ID_TIPO_ZONA_URBA=Z.ID_TIPO_ZONA_URBA
  LEFT JOIN PARAMETROS.DBO.CIUDADES COM (NOLOCK) ON  COM.ID_PAIS=1 AND COM.ID_CIUDAD=DOC.ID_CIUDAD_DIVISION_ORIGEN
  LEFT JOIN PARAMETROS.DBO.REGIONALES_PAIS ROM (NOLOCK) ON  ROM.ID_PAIS=COM.ID_PAIS AND ROM.ID_REGIONAL=COM.ID_REGIONAL
  LEFT JOIN PARAMETROS.DBO.DEPARTAMENTOS DCOM (NOLOCK) ON  DCOM.ID_PAIS=COM.ID_PAIS AND DCOM.ID_DEPARTAMENTO=COM.ID_DEPARTAMENTO
  LEFT JOIN PARAMETROS.DBO.CIUDADES COD(NOLOCK) ON  COD.ID_PAIS=1 AND COD.ID_CIUDAD=DOC.ID_CIUDAD_DESTINO
  LEFT JOIN PARAMETROS.DBO.REGIONALES_PAIS ROD (NOLOCK) ON  ROD.ID_PAIS=COD.ID_PAIS AND ROD.ID_REGIONAL=COD.ID_REGIONAL
  LEFT JOIN PARAMETROS.DBO.DEPARTAMENTOS DCOD (NOLOCK) ON  DCOD.ID_PAIS=COD.ID_PAIS AND DCOD.ID_DEPARTAMENTO=COD.ID_DEPARTAMENTO
  LEFT JOIN PARAMETROS.DBO.DIVISIONES DIO(NOLOCK) ON DIO.ID_PAIS=DOC.ID_PAIS_DIVISION_ORIGEN
	AND DIO.ID_CIUDAD=DOC.ID_CIUDAD_DIVISION_ORIGEN AND DIO.ID_DIVISION=DOC.ID_DIVISION_ORIGEN
  LEFT JOIN PARAMETROS.DBO.DIVISIONES DID(NOLOCK) ON DID.ID_PAIS=DOC.ID_PAIS_DESTINO
	AND DID.ID_CIUDAD=DOC.ID_CIUDAD_DESTINO AND DID.ID_DIVISION=DOC.ID_DIVISION_DESTINO
  LEFT JOIN [PARAMETROS].[dbo].CIUDADES CO (NOLOCK) ON CO.ID_PAIS=ID_PAIS_DIVISION_ORIGEN AND CO.ID_CIUDAD=DOC.ID_CIUDAD_DIVISION_ORIGEN
  LEFT JOIN [PARAMETROS].[dbo].REGIONALES_PAIS RO (NOLOCK) ON RO.ID_PAIS=1 AND RO.ID_REGIONAL=CO.[ID_REGIONAL]
  LEFT JOIN [PARAMETROS].[dbo].CIUDADES CD (NOLOCK) ON CD.ID_PAIS=DOC.ID_PAIS_DESTINO AND CD.ID_CIUDAD=DOC.ID_CIUDAD_DESTINO
  LEFT JOIN [PARAMETROS].[dbo].REGIONALES_PAIS RD (NOLOCK) ON RD.ID_PAIS=1 AND RD.ID_REGIONAL=CD.[ID_REGIONAL]
  LEFT JOIN [PARAMETROS].[dbo].[OPERATIVOS] O (NOLOCK) ON O.[ID_PAIS_ORIGEN]=DOC.ID_PAIS_OPERATIVO AND O.[ID_CIUDAD_ORIGEN]=DOC.ID_CIUDAD_OPERATIVO
	AND O.[ID_OPERATIVO]=DOC.ID_OPERATIVO
  LEFT JOIN #TMP_CIUDADES_ANEXAS CAO (NOLOCK) ON CAO.ID_PAIS=1 AND CAO.[ID_CIUDAD_ANEXA]=CO.ID_CIUDAD
  LEFT JOIN PARAMETROS.DBO.CENTROS_LOGISTICOS CLO (NOLOCK) ON CLO.ID_PAIS=1 AND CLO.ID_CIUDAD=CAO.ID_CIUDAD AND CLO.ID_CENTRO_LOGISTICO=1 AND CLO.ID_ESTADO=1
  LEFT JOIN #TMP_CIUDADES_ANEXAS CAD (NOLOCK) ON CAD.ID_PAIS=1 AND CAD.[ID_CIUDAD_ANEXA]=CD.ID_CIUDAD
  LEFT JOIN PARAMETROS.DBO.CENTROS_LOGISTICOS CLD (NOLOCK) ON CLD.ID_PAIS=1 AND CLD.ID_CIUDAD=CAD.ID_CIUDAD AND CLD.ID_CENTRO_LOGISTICO=1 AND CLD.ID_ESTADO=1
  order by FECHA_HORA_MOVIMI desc
END
	SET @StartRow = @StartRow + @BatchSize
END

