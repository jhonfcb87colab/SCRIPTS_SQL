	ELSE ISNULL(GIA.CODIGO_ZONA,'')
	END as CODIGO_ZONA_DESTINO
,ISNULL(CD.GUIA_MADRE1,'') AS GUIA_MADRE1_DESTINO
,TIPO_CLIENTE = CASE WHEN G.ID_CLIENTE IS NULL AND ISNULL(G.ID_CANAL,'0')<>'0' THEN 'CONTADOS'
						WHEN G.ID_CLIENTE IS NOT NULL AND ISNULL(G.ID_CANAL,'0')='0' THEN 'CREDITO'
						ELSE 'OTROS'
						END
,CONCAT(LTRIM(RTRIM(GCL.ID_CLIENTE)),'-',GCL.NOMBRE_CLIENTE) AS NOMBRE_CLIENTE_CDS
