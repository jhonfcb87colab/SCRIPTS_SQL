	WHEN [tmp_borrar_local].dbo.ObtenerCodigo_zona(P.ID_PRODUCTO,ISNULL(CDG.CAPA_REMITE,'')) !=''
		THEN [tmp_borrar_local].dbo.ObtenerCodigo_zona(P.ID_PRODUCTO,ISNULL(CDG.CAPA_REMITE,''))
	ELSE ''
	END as CODIGO_ZONA_ORIGEN
