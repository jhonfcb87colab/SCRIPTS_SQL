/****************************************************************************************************
 PASO 1_2 - SERVIDOR MEPVSVWSSDGN01\DBDG001 (mismo servidor del paso 1_1 Informacion_estado_envio)
 Extrae de Mece_Logistico la operación RO de los puntos de canal (CANALES_CO):
   DISTRIBUCION : SEGUIMIENTO_ENVIO proceso 9  (Salida a zona urbana)   -> CDS = DOC.ID_DIVISION_ORIGEN
   RECOLECCION  : SEGUIMIENTO_ENVIO proceso 6  (Entrada de zona urbana) -> CDS = DOC.ID_DIVISION_ORIGEN
 Se excluyen los conceptos de salida a EMPRESARIO SATELITE (7,8,9,10) que son los que liquida PPES.
 La exclusión definitiva de CDS PPES se hace en el paso 2_5 (Retail) contra las tablas PPES.

 En SSIS: parametrizar como ZSCRIPT_PARAM_01_1_1 reemplazando las fechas por
          @[User::STR_01_FECHA_INICIAL] y @[User::STR_02_FECHA_FINAL]

 VALIDAR antes de productivo:
   SELECT * FROM PARAMETROS.dbo.PROCESOS (NOLOCK) WHERE ID_PROCESO IN (6,9)
   SELECT * FROM PARAMETROS.dbo.ITEM_CONCEPTO (NOLOCK) WHERE ID_PROCESO IN (6,9)
   SELECT * FROM PARAMETROS.dbo.ESTADOSENVIO (NOLOCK)
****************************************************************************************************/
	SET NOCOUNT ON;

	DECLARE @FECHA_INICIAL DATETIME = CONVERT(DATETIME,'20260301')	-- @[User::STR_01_FECHA_INICIAL]
	DECLARE @FECHA_FINAL   DATETIME = CONVERT(DATETIME,'20260924')	-- @[User::STR_02_FECHA_FINAL]
	DECLARE @SOLO_ENTREGADAS BIT    = 1								-- 1: distribución sólo de guías entregadas

	IF OBJECT_ID('tempdb..#TMP_CDS') IS NOT NULL				DROP TABLE #TMP_CDS
	IF OBJECT_ID('tempdb..#TMP_ESTADOS_ENTREGADO') IS NOT NULL	DROP TABLE #TMP_ESTADOS_ENTREGADO
	IF OBJECT_ID('tempdb..#TMP_MOVIMIENTOS') IS NOT NULL		DROP TABLE #TMP_MOVIMIENTOS
	IF OBJECT_ID('tempdb..#TMP_CDS_DISTRI_RECOL') IS NOT NULL	DROP TABLE #TMP_CDS_DISTRI_RECOL

	/*------------------------------------------------------------------------------------------
	  Universo de CDS: todos los puntos de canal (directos e indirectos)
	------------------------------------------------------------------------------------------*/
	SELECT CAN.ID_PAIS, CAN.ID_CIUDAD, CAN.ID_DIVISION
	INTO #TMP_CDS
	FROM [Mece_Logistico].[dbo].[CANALES_CO] CAN (NOLOCK)
	WHERE CAN.ID_PAIS = 1
	GROUP BY CAN.ID_PAIS, CAN.ID_CIUDAD, CAN.ID_DIVISION

	CREATE CLUSTERED INDEX IX_CDS ON #TMP_CDS (ID_CIUDAD, ID_DIVISION)

	SELECT E.ID_ESTADOENVIO
	INTO #TMP_ESTADOS_ENTREGADO
	FROM parametros.dbo.ESTADOSENVIO E (NOLOCK)
	WHERE E.NOMBRE_ESTADOENVIO LIKE '%ENTREGAD%'
	AND E.NOMBRE_ESTADOENVIO NOT LIKE '%NO ENTREGAD%'

	/*------------------------------------------------------------------------------------------
	  Movimientos de salida a zona (9) y entrada de zona (6) hechos por un CDS
	------------------------------------------------------------------------------------------*/
	SELECT
	 SEG.NUMERO_GUIA
	,CDS.ID_PAIS AS ID_PAIS_CDS
	,DOC.ID_CIUDAD_DIVISION_ORIGEN AS ID_CIUDAD_CDS
	,DOC.ID_DIVISION_ORIGEN AS ID_DIVISION_CDS
	,SEG.FECHA_HORA_MOVIMIENTO AS FECHA
	,SEG.ID_PROCESO
	,SEG.ID_CONCEPTO
	,SEG.NUMERO_PIEZAS
	,CASE WHEN SEG.ID_PROCESO = 9 THEN 'DISTRIBUCION' ELSE 'RECOLECCION' END AS TIPO_COMISION
	INTO #TMP_MOVIMIENTOS
	FROM [Mece_Logistico].[dbo].[SEGUIMIENTO_ENVIO] SEG (NOLOCK)
	INNER JOIN [Mece_Logistico].[dbo].[DOCUMENTOS] DOC (NOLOCK)
		ON DOC.ID_PROCESO = SEG.ID_PROCESO AND DOC.NUMERO_MOVIMI = SEG.NUMERO_MOVIMI AND DOC.CONSECUT_MOVIMI = SEG.CONSECUT_MOVIMI
	INNER JOIN #TMP_CDS CDS
		ON CDS.ID_CIUDAD = DOC.ID_CIUDAD_DIVISION_ORIGEN AND CDS.ID_DIVISION = DOC.ID_DIVISION_ORIGEN
	WHERE SEG.FECHA_HORA_MOVIMIENTO >= @FECHA_INICIAL AND SEG.FECHA_HORA_MOVIMIENTO < @FECHA_FINAL
	AND (
			(SEG.ID_PROCESO = 9 AND SEG.ID_CONCEPTO NOT IN (7,8,9,10))		-- salida a zona sin empresario satélite
		 OR (SEG.ID_PROCESO = 6 AND SEG.ID_CONCEPTO NOT IN (2,4,7,8,9,10))	-- entrada de zona sin devoluciones/satélite
		)
	AND LEN(SEG.NUMERO_GUIA) > 5
	AND LEFT(SEG.NUMERO_GUIA,1) <> '5'										-- guías internas

	CREATE NONCLUSTERED INDEX IX_NUMERO_GUIA ON #TMP_MOVIMIENTOS (NUMERO_GUIA, TIPO_COMISION, FECHA)

	/*------------------------------------------------------------------------------------------
	  Una fila por guía y tipo:
	    DISTRIBUCION -> última salida a zona (la que terminó en entrega)
	    RECOLECCION  -> primera entrada de zona (recogida al tercero)
	------------------------------------------------------------------------------------------*/
	SELECT
	 T.NUMERO_GUIA
	,T.ID_PAIS_CDS
	,T.ID_CIUDAD_CDS
	,T.ID_DIVISION_CDS
	,T.FECHA
	,T.TIPO_COMISION
	,LEFT(T.TIPO_COMISION + ' ' + ISNULL(RTRIM(LTRIM(CON.NOMBRE_CONCEPTO)),''),150) AS DESCRIPCION_COMISION
	,T.ID_PROCESO
	,T.ID_CONCEPTO
	,CASE WHEN ISNULL(T.NUMERO_PIEZAS,0) > 0 THEN T.NUMERO_PIEZAS
		  WHEN ISNULL(G.NUMERO_PIEZAS,0) > 0 THEN G.NUMERO_PIEZAS ELSE 1 END AS NUMERO_PIEZAS
	,CAST(ISNULL(G.PESO_FISICO_GUIA,0) AS DECIMAL(10,2)) AS PESO_FISICO
	,CAST(ISNULL(G.PESO_GUIA,0) AS DECIMAL(10,2)) AS PESO_LIQUIDADO
	INTO #TMP_CDS_DISTRI_RECOL
	FROM
	(
		SELECT
		 RankUltimo  = ROW_NUMBER() OVER (PARTITION BY M.NUMERO_GUIA, M.TIPO_COMISION ORDER BY M.FECHA DESC)
		,RankPrimero = ROW_NUMBER() OVER (PARTITION BY M.NUMERO_GUIA, M.TIPO_COMISION ORDER BY M.FECHA ASC)
		,M.*
		FROM #TMP_MOVIMIENTOS M
	) AS T
	INNER JOIN [Mece_Logistico].[dbo].[GUIAS] G (NOLOCK) ON G.NUMERO_GUIA = T.NUMERO_GUIA
	LEFT JOIN [PARAMETROS].[dbo].[ITEM_CONCEPTO] CON (NOLOCK) ON CON.ID_PROCESO = T.ID_PROCESO AND CON.ID_CONCEPTO = T.ID_CONCEPTO
	WHERE (
			(T.TIPO_COMISION = 'DISTRIBUCION' AND T.RankUltimo = 1)
		 OR (T.TIPO_COMISION = 'RECOLECCION'  AND T.RankPrimero = 1)
		)
	AND (
			T.TIPO_COMISION = 'RECOLECCION'
		 OR @SOLO_ENTREGADAS = 0
		 OR G.ID_ESTADOENVIO IN (SELECT ID_ESTADOENVIO FROM #TMP_ESTADOS_ENTREGADO)
		)

	TRUNCATE TABLE [tmp_borrar_local].dbo.MECE_LOGISTICO_CDS_DISTRI_RECOL_BI

	INSERT INTO [tmp_borrar_local].dbo.MECE_LOGISTICO_CDS_DISTRI_RECOL_BI
	(NUMERO_GUIA,ID_PAIS_CDS,ID_CIUDAD_CDS,ID_DIVISION_CDS,FECHA,TIPO_COMISION,DESCRIPCION_COMISION
	,ID_PROCESO,ID_CONCEPTO,NUMERO_PIEZAS,PESO_FISICO,PESO_LIQUIDADO)
	SELECT NUMERO_GUIA,ID_PAIS_CDS,ID_CIUDAD_CDS,ID_DIVISION_CDS,FECHA,TIPO_COMISION,DESCRIPCION_COMISION
	,ID_PROCESO,ID_CONCEPTO,NUMERO_PIEZAS,PESO_FISICO,PESO_LIQUIDADO
	FROM #TMP_CDS_DISTRI_RECOL

