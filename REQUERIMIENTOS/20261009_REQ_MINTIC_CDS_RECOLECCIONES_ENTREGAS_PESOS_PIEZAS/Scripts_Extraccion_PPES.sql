--COMISION_DISTRIBUCION_EMPRESARIO PENDINETE MEJORAR FECHAS
SELECT [ID_PERIODO]
,[CODIGO_ACTUAL] AS CODIGO_CDS_PPES_DISTRIBUCION
,[NUMERO_GUIA]
,ISNULL([NUMERO_PIEZAS],1) AS NUMERO_PIEZAS
,[ID_CONCEPTO]
,[ACTIVIDAD_LOGISTICA] AS MODO_ENTREGA_EMPRESARIO
,[FECHA_PRIMER_MOVI_GUIA]
,COSTO_ADICIONAL_VALOR
,COSTO_ADICIONAL_OBSERVACION
,[VALOR_FINAL_LIQUIDACION] AS COMISION_DISTRIBUCION_EMPRESARIO
,[FECHA_LIQUIDACION]
,[ID_ESTADOGUIA]
FROM [PPES].[dbo].[HISTORICO_DETALLE_LIQUIDADOR] (nolock)
where VALOR_FINAL_LIQUIDACION is not null and VALOR_FINAL_LIQUIDACION!=0
AND [FECHA_LIQUIDACION]>='20250101 00:00:00' AND  [FECHA_LIQUIDACION]<=GETDATE()
order by FECHA_PRIMER_MOVI_GUIA desc



--COMISION_RECOLECCION_EMPRESARIO PENDINETE MEJORAR FECHAS
SELECT RL.[ID]
      ,RL.[ID_CONSOLIDADO_POR_EMPRESARIO]
	  ,R.CODIGO_ACTUAL AS CODIGO_CDS_PPES_RECOLECCION
      ,RL.[NUMERO_GUIA]
	  ,ISNULL(R.NUMERO_PIEZAS,1) AS NUMERO_PIEZAS
	  ,FECHA AS FECHA_RECOLECCION
      ,RL.[FECHA_LIQUIDACION]
      ,RL.[VALOR_FINAL_LIQUIDACION] AS COMISION_RECOLECCION_EMPRESARIO
  FROM [PPES].[dbo].[RECOLECCIONES_LIQUIDADAS] RL
  inner join [PPES].[dbo].[RECOLECCIONES] R (nolock) ON R.NUMERO_GUIA=RL.NUMERO_GUIA
  where VALOR_LIQUIDADO!=0
  AND [FECHA_LIQUIDACION]>='20250101 00:00:00' AND  [FECHA_LIQUIDACION]<=GETDATE()
  order by FECHA_LIQUIDACION desc

