TRUNCATE TABLE [TMP].[MOBIVA_SSFF_P04];
INSERT INTO [TMP].[MOBIVA_SSFF_P04]
           ([ID_SOLICITUD]
           ,[REGIONAL]
           ,[CIUDAD]
           ,[MACROPROCESO]
           ,[PROCESO]
           ,[TITULO_PUESTO]
           ,[TIPO_REQUISICION]
           ,[ESTADO_REQUISICION]
           ,[NUMERO_VACANTES]
		   ,[FECHA_MODIFICACION]
		   ,[FECHA_CREACION]
		   ,[FECHA_APROBACION]
		   ,SUBPROCESO
)

SELECT		[ID_SOLICITUD]
			  --,CASE 
				 -- WHEN		(REPLACE(dbo.UFN_SEPARATES_COLUMNS([REGIONAL],1,'('),'(',')) IS NULL
					--		THEN 'NO DISPONIBLE' 
				 -- WHEN		LEN((REPLACE(dbo.UFN_SEPARATES_COLUMNS([REGIONAL],1,'('),'(','))) < 1
					--		THEN 'NO DISPONIBLE' ELSE UPPER((REPLACE(dbo.UFN_SEPARATES_COLUMNS([REGIONAL],1,'('),'(','))) END
				,
				[REGIONAL] =
				CASE
				WHEN UPPER(REPLACE([REGIONAL],dbo.UFN_SEPARATES_COLUMNS([REGIONAL],3,' '),'))='REGIONAL' THEN
				UPPER([REGIONAL]) ELSE
				UPPER(REPLACE([REGIONAL],dbo.UFN_SEPARATES_COLUMNS([REGIONAL],3,' '),')) END
			
			  --,CASE
					--WHEN	REPLACE(dbo.UFN_SEPARATES_COLUMNS([REGIONAL],2,'('),')',')  IS NULL
					--		THEN 'NO DISPONIBLE'
					--WHEN		LEN(REPLACE(dbo.UFN_SEPARATES_COLUMNS([REGIONAL],2,'('),')','))<1
					--		THEN 'NO DISPONIBLE' ELSE UPPER(REPLACE(dbo.UFN_SEPARATES_COLUMNS([REGIONAL],2,'('),')',')) END
					--		AS [CIUDAD]

					,UPPER(dbo.UFN_SEPARATES_COLUMNS([REGIONAL],3,' ')) AS [CIUDAD]
			  ,CASE 
					WHEN [MACROPROCESO] IS NULL OR LEN([MACROPROCESO])<1 THEN 'NO DISPONIBLE' ELSE UPPER(REPLACE([MACROPROCESO],'"',')) END AS [MACROPROCESO]
			  ,CASE
					WHEN [PROCESO] IS NULL OR LEN([PROCESO])<1 THEN 'NO DISPONIBLE' ELSE UPPER(REPLACE([PROCESO],'"',')) END AS [PROCESO]
			  ,CASE
					WHEN [TITULO_PUESTO] IS NULL OR LEN([TITULO_PUESTO])<1 THEN 'NO DISPONIBLE' ELSE UPPER(REPLACE([TITULO_PUESTO],'"','))  END AS [TITULO_PUESTO]
			  ,CASE
					WHEN [TIPO_REQUISICION] IS NULL OR LEN([TIPO_REQUISICION])<1 THEN 'NO DISPONIBLE' ELSE  UPPER(REPLACE([TIPO_REQUISICION],'"','))  END AS [TIPO_REQUISICION]
			  ,CASE
					WHEN [ESTADO_REQUISICION] IS NULL OR LEN([ESTADO_REQUISICION])<1 THEN 'NO DISPONIBLE' ELSE UPPER(REPLACE([ESTADO_REQUISICION],'"',')) END AS [ESTADO_REQUISICION]
			  ,CASE
					WHEN [NUMERO_VACANTES] IS NULL OR ([NUMERO_VACANTES])<1 THEN 0 ELSE [NUMERO_VACANTES] END AS [NUMERO_VACANTES]
			  ,CASE
					WHEN [FECHA_CREACION] IS NULL OR ([FECHA_MODIFICACION])<1 THEN '1900-01-01' ELSE [FECHA_MODIFICACION] END AS [FECHA_MODIFICACION]
			  ,CASE
					WHEN [FECHA_CREACION] IS NULL OR ([FECHA_CREACION])<1 THEN '1900-01-01' ELSE [FECHA_CREACION] END AS [FECHA_CREACION]
			  ,CASE
					WHEN [FECHA_APROBACION] IS NULL OR ([FECHA_APROBACION])<1 THEN '1900-01-01' ELSE [FECHA_APROBACION] END AS [FECHA_APROBACION]
			  ,SUBPROCESO = ISNULL(SUBPROCESO,'NO DISPONIBLE')

FROM [SIG_COLOMBIA_DW].[TMP].[MOBIVA_SSFF_P03] WITH (NOLOCK)




