WITH CTE_MOBIVA_SSFF
(
		id
		,[ID_SOLICITUD]
		,[REGIONAL]
		,[MACROPROCESO]
		,[PROCESO]
		,[TITULO_PUESTO]
		,[TIPO_REQUISICION]
		,[NUMERO_VACANTES]
		,[ESTADO_REQUISICION]
		,[FECHA_MODIFICACION]
		,[FECHA_CREACION]
		,[FECHA_APROBACION]
		,SUBPROCESO
)
AS(
	SELECT 
		ROW_NUMBER ( )   OVER ( PARTITION BY REPLACE([ID_SOLICITUD],'"',') order by [ID_SOLICITUD] asc )  id
			,CONVERT(VARCHAR(150),RTRIM(LTRIM(LEFT(REPLACE([ID_SOLICITUD],'"','),50)))) AS [ID_SOLICITUD]
				,[REGIONAL]
				,[MACROPROCESO]
				,[PROCESO]
				,[TITULO_PUESTO]
				,[TIPO_REQUISICION]
				,CONVERT(INT,[NUMERO_VACANTES]) AS [NUMERO_VACANTES]
				,[ESTADO_REQUISICION]
				,CONVERT(DATETIME,[FECHA_MODIFICACION],20) AS [FECHA_MODIFICACION]
				,CONVERT(DATETIME,
				DATEFROMPARTS ( 
				[dbo].[UFN_SEPARATES_COLUMNS]([dbo].[UFN_SEPARATES_COLUMNS](FECHA_CREACION,3,'/'),1,' ') 
				,[dbo].[UFN_SEPARATES_COLUMNS](FECHA_CREACION,2,'/')
				,[dbo].[UFN_SEPARATES_COLUMNS](FECHA_CREACION,1,'/') 
				)) AS [FECHA_CREACION]
				,CONVERT(DATETIME,
				DATEFROMPARTS ( 
				[dbo].[UFN_SEPARATES_COLUMNS]([dbo].[UFN_SEPARATES_COLUMNS](FECHA_APROBACION,3,'/'),1,' '), 
				[dbo].[UFN_SEPARATES_COLUMNS](FECHA_APROBACION,2,'/'), 
				[dbo].[UFN_SEPARATES_COLUMNS](FECHA_APROBACION,1,'/') 
				)) AS [FECHA_APROBACION]
				,SUBPROCESO
		FROM [SIG_COLOMBIA_DW].[TMP].[MOBIVA_SSFF_P01] with(nolock)
  )
SELECT 
    [ID_SOLICITUD]
    ,[REGIONAL]
    ,[MACROPROCESO]
    ,[PROCESO]
    ,[TITULO_PUESTO]
    ,[TIPO_REQUISICION]
    ,[NUMERO_VACANTES]
    ,[ESTADO_REQUISICION]
	,FECHA_MODIFICACION
	,[FECHA_CREACION]
	,[FECHA_APROBACION]
	,SUBPROCESO
FROM CTE_MOBIVA_SSFF WHERE ID=1
ORDER BY ID_SOLICITUD ASC






