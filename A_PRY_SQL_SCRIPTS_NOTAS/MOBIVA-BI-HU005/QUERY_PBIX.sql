WITH CTE_CALENDARIO_01
(
TIME_ID	
,ANIO_MES	
,ANIO_MES_DIA	
,FECHA	
,AÑO	
,DIA	
,MES	
,MES_TEXTO	
,NUMERO_SEMANA	
,NUMERO_MES	
,TRIMESTRE	
,NUMERO_SEMESTRE	
,AÑO_SEMESTRE
) AS (
SELECT [TIME_ID]
	  ,ANIO_MES = YEAR([DATE])*100+MONTH([DATE])
	  ,ANIO_MES_DIA = (YEAR([DATE])*100+MONTH([DATE]))*100++DAY([DATE])
      ,FECHA = [DATE]
      ,AÑO = [YEAR]
	  ,DIA = DAY_OF_MONTH
      ,MES = 
		  CASE 
			  WHEN [MONTH_OF_YEAR]=1 THEN 'ENERO' 
			  WHEN [MONTH_OF_YEAR]=2 THEN 'FEBRERO'
			  WHEN [MONTH_OF_YEAR]=3 THEN 'MARZO'
			  WHEN [MONTH_OF_YEAR]=4 THEN 'ABRIL'
			  WHEN [MONTH_OF_YEAR]=5 THEN 'MAYO'
			  WHEN [MONTH_OF_YEAR]=6 THEN 'JUNIO'
			  WHEN [MONTH_OF_YEAR]=7 THEN 'JULIO'
			  WHEN [MONTH_OF_YEAR]=8 THEN 'AGOSTO'
			  WHEN [MONTH_OF_YEAR]=9 THEN 'SEPTIEMBRE'
			  WHEN [MONTH_OF_YEAR]=10 THEN 'OCTUBRE'
			  WHEN [MONTH_OF_YEAR]=11 THEN 'NOVIEMBRE'
			  WHEN [MONTH_OF_YEAR]=12 THEN 'DICIEMBRE'
		  ELSE 'NO DISPONIBLE'
	  END
	  ,MES_TEXTO = [DAY_OF_MONTH_NAME]
      ,NUMERO_SEMANA = [WEEK_OF_YEAR]
      ,NUMERO_MES = [MONTH_OF_YEAR]
      ,TRIMESTRE = [QUARTER_OF_YEAR]
      ,NUMERO_SEMESTRE = [SEMESTER_OF_YEAR]
      ,AÑO_SEMESTRE = [SEMESTER]
  FROM [SIG_MEVI_DM].[DIM].[TIEMPO] WITH (NOLOCK)
WHERE [DATE] >= DATEADD(yy,DATEDIFF(yy,0,DATEADD(YY,-3,GETDATE())),0)
AND [DATE] <= DATEADD(ms,-3,DATEADD(mm,0,DATEADD(mm,DATEDIFF(mm,0,GETDATE())+1,0)))

)
SELECT * FROM CTE_CALENDARIO_01

