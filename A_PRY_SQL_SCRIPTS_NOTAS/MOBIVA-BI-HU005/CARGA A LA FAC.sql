      ,[REGIONAL]
      ,[CIUDAD]
      ,[MACROPROCESO]
      ,[PROCESO]
      ,[TITULO_PUESTO]
      ,CASE 
		WHEN [TIPO_REQUISICION] LIKE 'RECALIFICACI%N%' THEN 'RECALIFICACION'	
		WHEN [TIPO_REQUISICION] LIKE 'AMPLIACI%N%' THEN 'AMPLIACION'
		WHEN [TIPO_REQUISICION] LIKE '%VINCULACI%N DIRECTA%' THEN 'VINCULACION DIRECTA'
		WHEN [TIPO_REQUISICION] LIKE 'CREACI%N%' THEN 'VINCULACION DIRECTA'
		ELSE [TIPO_REQUISICION]
		END [TIPO_REQUISICION]
      ,[ESTADO_REQUISICION]
      ,[NUMERO_VACANTES]
,FECHA_MODIFICACION
,FECHA_CREACION
,FECHA_APROBACION
,SUBPROCESO = UPPER(SUBPROCESO)
  FROM [SIG_COLOMBIA_DW].[TMP].[MOBIVA_SSFF_P04] (NOLOCK)