	 GR_NUMERO_GUIA
	,GR_FECHA_ENVIO
	,GR_ID_CLIENTE_REMI
	,GR_NOMBRE_CLIENTE_REMI
	,GR_ID_CIUDAD_ORIG
	,GR_ID_CIUDAD_DEST
	,GR_ID_CLIENTE    
	,ISNULL(CONVERT(INT,CLIE.ID_TIPO_IDENTIFIC),-888) GR_TIPO_ID_CLIENTE
	,ISNULL(DIGITO_VERIFICACION,'-888') GR_ID_CLIENTE_VERI
    ,ISNULL(NOMBRE_EMPRESA,'NO DISPONIBLE')  GR_CLIENTE
	,ISNULL(CLIE.CODIGO_CLIENTE,'-888')  GR_CODIGO_CLIENTE
FROM
	CTE_GR
