  WITH CTE_GR
(
	 GR_NUMERO_GUIA
	,GR_FECHA_ENVIO
	,GR_ID_CLIENTE_REMI
	,GR_NOMBRE_CLIENTE_REMI
	,GR_ID_CIUDAD_ORIG
	,GR_ID_CIUDAD_DEST
	,GR_ID_CLIENTE
)
AS
(
	SELECT 
		 L_RG.NUMERO_GUIA GR_NUMERO_GUIA
		,L_RG.FECHA_CREACION GR_FECHA_ENVIO
		,CASE WHEN L_RG.ID_CLIENTE_REMITENTE IS NULL THEN '-888'
			  WHEN L_RG.ID_CLIENTE_REMITENTE = ' ' THEN '-888'
			  ELSE L_RG.ID_CLIENTE_REMITENTE
		  END GR_ID_CLIENTE_REMI
		,CASE WHEN L_RG.NOMBRE_CLIENTE_REMITENTE IS NULL THEN 'NO DISPONIBLE'
			  WHEN L_RG.NOMBRE_CLIENTE_REMITENTE = ' ' THEN 'NO DISPONIBLE'
			  ELSE L_RG.NOMBRE_CLIENTE_REMITENTE
		 END GR_NOMBRE_CLIENTE_REMI
		,ISNULL(L_RG.ID_CIUDAD_ORIGEN,-888) GR_ID_CIUDAD_ORIG
		,ISNULL(L_RG.ID_CIUDAD_DESTINO,-888) GR_ID_CIUDAD_DEST
		,CASE WHEN L_RG.ID_CLIENTE IS NULL THEN '-888' 
		      WHEN L_RG.ID_CLIENTE = ' ' THEN '-888' 
			  ELSE L_RG.ID_CLIENTE
		 END GR_ID_CLIENTE		
	FROM 
		LOG.GUIA_RECAUDO L_RG WITH(NOLOCK)
		INNER JOIN LOG.WALLET_TRANSACCION WALLET WITH(NOLOCK)
		ON L_RG.NUMERO_GUIA=WALLET.NUMERO_GUIA
	WHERE 
		FECHA_CREACION >= CONVERT(DATETIME,CONVERT(DATE,GETDATE()-10)) AND ID_TIPO_COBRO = 2
)
