WITH CTE AS (
		SELECT 
			  BASE_TEMP.GR_NUMERO_GUIA	
			  ,MODLPG.[ID_MODALPAGO]
			  ,DIM_MODLPG.NOMBRE_MODALPAGO AS MEDIO_DE_RECAUDO
			  ,MODLPG.NUMERO_APROBACION AS NUMERO_DE_APROBACION	
		FROM	[TMP].[TMP_BORRAR_TURECAUDO_PYME_CE_BASE_GUIAS] BASE_TEMP
		  INNER JOIN [SIG_COLOMBIA_DW].[LOG].[GUIA_RECAUDO_INFORMACION_RECAUDO] MODLPG WITH(NOLOCK)
		  ON BASE_TEMP.GR_NUMERO_GUIA  = MODLPG.NUMERO_GUIA
		  INNER JOIN [SIG_COLOMBIA_DW].[PAR.].[MODALIDADPAGO] DIM_MODLPG WITH(NOLOCK)
		  ON MODLPG.ID_MODALPAGO=DIM_MODLPG.ID_MODALPAGO
		UNION ALL
		SELECT 
			  BASE_TEMP.GR_NUMERO_GUIA	
			  ,MODLPG.[ID_MODALPAGO]
			  ,DIM_MODLPG.NOMBRE_MODALPAGO AS MEDIO_DE_RECAUDO
			  ,MODLPG.NUMERO_APROBACION AS NUMERO_DE_APROBACION	
		FROM	[TMP].[TMP_BORRAR_TURECAUDO_PYME_CE_BASE_GUIAS] BASE_TEMP
		  INNER JOIN [SIG_COLOMBIA_DW].[LOG].[WALLET_TRANSACCION] MODLPG WITH(NOLOCK)
		  ON BASE_TEMP.GR_NUMERO_GUIA  = MODLPG.NUMERO_GUIA
		  INNER JOIN [SIG_COLOMBIA_DW].[PAR.].[MODALIDADPAGO] DIM_MODLPG WITH(NOLOCK)
		  ON MODLPG.ID_MODALPAGO=DIM_MODLPG.ID_MODALPAGO
)
SELECT 
GR_NUMERO_GUIA	
,ID_MODALPAGO	
,MEDIO_DE_RECAUDO	
,NUMERO_DE_APROBACION
FROM CTE
GROUP BY 
GR_NUMERO_GUIA	
,ID_MODALPAGO	
,MEDIO_DE_RECAUDO	
,NUMERO_DE_APROBACION






