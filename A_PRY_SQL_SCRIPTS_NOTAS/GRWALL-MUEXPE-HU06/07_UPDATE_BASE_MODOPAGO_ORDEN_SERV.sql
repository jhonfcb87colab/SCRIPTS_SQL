FROM CTE_UPDATE AS CTE
INNER JOIN [TMP].[TURECAUDO_PYME_CE_XXX] TMP WITH(NOLOCK)
ON CTE.GR_NUMERO_GUIA=TMP.GR_NUMERO_GUIA






