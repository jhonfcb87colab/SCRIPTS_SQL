INNER JOIN [TMP].[GRWALL_TURECAUDO_PYMES_CE] TMPCAMPOS WITH(NOLOCK)
ON TMPBASE.GR_NUMERO_GUIA=TMPCAMPOS.GR_NUMERO_GUIA
)
