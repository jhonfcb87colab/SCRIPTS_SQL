DECLARE	@return_value int

EXEC	@return_value = [FAC].[TURECAUDO_PYME_CLIENTE_FECHA]
		@GR_ID_CLIENTE = '1098632108',
		@GR_COD_CLIENTE = 'RET02670',
		@FECHAINI = '2022-01-01',
		@FECHAFIN = '2023-08-01'

