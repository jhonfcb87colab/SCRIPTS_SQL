DECLARE @GR_ID_CLIENTE  VARCHAR(20) = '1098632108'
DECLARE @GR_COD_CLIENTE	 VARCHAR(20) = 'RET02670'
DECLARE @FECHAINI VARCHAR(100) = '2022-01-01'
DECLARE @FECHAFIN VARCHAR(100) = '2023-08-01'
SELECT GR_NUMERO_GUIA, GR_ID_CLIENTE, GR_CODIGO_CLIENTE,GR_FECHA_ENVIO 
FROM [FAC].[TURECAUDO_PYMES_CE] WITH (NOLOCK)
WHERE GR_ID_CLIENTE='1098632108'
AND GR_FECHA_ENVIO >=  @FECHAINI  AND GR_FECHA_ENVIO <  @FECHAFIN  
AND GR_CODIGO_CLIENTE  = 'RET02670'


