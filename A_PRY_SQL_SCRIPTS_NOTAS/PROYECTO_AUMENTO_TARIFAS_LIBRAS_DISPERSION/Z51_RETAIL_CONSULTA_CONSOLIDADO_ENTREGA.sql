USE SIG_COL_LOGISTICA_DW;
DECLARE @ANIOMES AS INT = 202307;
SELECT 
CEDULA
,USUARIO
,FECHA_CREACION_USUARIO = '
,ENVIOS_POR_MES = SUM(ENVIOS_POR_MES)
,AÑO_MES
,ID_PRODUCTO
,NOMBRE_PRODUCTO
--,PERIODO_YYYY_MM_DD
--,FECHA_ENVIO
,ID_TIPOTRAY
,NOMBRE_TIPOTRAY
,TIPO_PESO
,PESO_CONSOLIDADO = SUM(PESO_CONSOLIDADO)
,REGIONAL_ORIGEN
,CIUDAD_ORIGEN
,REGIONAL_DESTINO
,CIUDAD_DESTINO
,CANAL
,VALOR_FACTURADO  = SUM(VALOR_FACTURADO)
,NUMERO_PIEZAS = SUM(NUMERO_PIEZAS)
,GUIA_MOVILIZADA
,FLETE  = SUM(FLETE)
,SOBRE_FLETE = SUM(SOBRE_FLETE)
,DESCUENTO  = SUM(DESCUENTO)
,NOMBRE_MEDTRANS
,NOMBRE_FORMAPAGO
,NOMBRE_TIEMPO
,VALOR_RECAUDO = SUM(VALOR_RECAUDO)
,CON_RECAUDO
--,DIRECCION_REMITENTE
--,MAIL_REMITENTE
--,TELEFONO_REMITENTE
FROM [FAC].[MOBIPE_REATIL_USUARIO_ENVIOS] with(nolock) 
WHERE AÑO_MES=@ANIOMES
GROUP BY 
CEDULA
,USUARIO
,FECHA_CREACION_USUARIO
,AÑO_MES
,ID_PRODUCTO
,NOMBRE_PRODUCTO
,ID_TIPOTRAY
,NOMBRE_TIPOTRAY
,TIPO_PESO
,REGIONAL_ORIGEN
,CIUDAD_ORIGEN
,REGIONAL_DESTINO
,CIUDAD_DESTINO
,CANAL
,GUIA_MOVILIZADA
,NOMBRE_MEDTRANS
,NOMBRE_FORMAPAGO
,NOMBRE_TIEMPO
,CON_RECAUDO
--,DIRECCION_REMITENTE
--,MAIL_REMITENTE
--,TELEFONO_REMITENTE
order by 1 desc









