USE Mece_Logistico

/****** Script for SelectTopNRows command from SSMS  ******/



DECLARE @FE_INI DATETIME = '20220301';
DECLARE @FE_FIN DATETIME = '20220401';

SELECT  @FE_INI,@FE_FIN

WITH CTE_SEGUIMIENTO_PIEZA_ULT_MOV_MERCANCIA_INDUSTRIAL
(
NUMERO_GUIA	
,FECHA_ENVIO	
,NUMERO_PIEZAS	
,ITEM_UNI_GUIA	
,PESO_PIEZA	
,PESO_VOLU_PIEZA
)AS(
	SELECT 
		  GUI.[NUMERO_GUIA]
		  ,GUI.FECHA_ENVIO
		  ,GUI.NUMERO_PIEZAS
		  ,ITEM_UNI_GUIA = SUM(PZ.ITEM_UNI_GUIA)
		  ,[PESO_PIEZA] =  SUM(PZ.[PESO_PIEZA]) 
		  ,[PESO_VOLU_PIEZA] = SUM(PZ.[PESO_VOLU_PIEZA]) 
	  FROM [Mece_Logistico].[dbo].[GUIAS] GUI WITH (NOLOCK)
	  INNER JOIN [Mece_Logistico].[dbo].[SEGUIMIENTO_PIEZA] PZ WITH (NOLOCK)
	  ON GUI.NUMERO_GUIA=PZ.NUMERO_GUIA
	  WHERE GUI.FECHA_ENVIO BETWEEN @FE_INI AND @FE_FIN ---AND 
	  ----GUI.NUMERO_GUIA IN (344154334,344154335)
	  AND GUI.ID_PRODUCTO IN(6,54) AND PZ.ID_PROCESO=6
	  GROUP BY 
			GUI.[NUMERO_GUIA]
			,GUI.FECHA_ENVIO
			,GUI.NUMERO_PIEZAS
)
SELECT  
	NUMERO_GUIA	
	,FECHA_ENVIO	
	,NUMERO_PIEZAS	
	,ITEM_UNI_GUIA	
	,PESO_PIEZA	
	,PESO_VOLU_PIEZA
	,PESO_PZA_CONSOLIDADO = CONVERT(DECIMAL,IIF(PESO_PIEZA>=PESO_VOLU_PIEZA,PESO_PIEZA,PESO_VOLU_PIEZA),1)
FROM CTE_SEGUIMIENTO_PIEZA_ULT_MOV_MERCANCIA_INDUSTRIAL





