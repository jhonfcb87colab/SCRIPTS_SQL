SELECT  
G.[NUMERO_GUIA]
,G.[ID_PRODUCTO]
,P.[NOMBRE_PRODUCTO]
,YEAR(G.[FECHA_ENVIO])*100+MONTH(G.[FECHA_ENVIO]) AS [PERIODO_YYYY_MM_DD]-------------
,G.[FECHA_ENVIO]
,GIA.[ID_TIPOTRAY]
,T.[NOMBRE_TIPOTRAY]
,' AS TIPO_PESO -------------
,G.PESO_FACTURADO AS PESO_CONSOLIDADO
,RO.NOMBRE_REGIONAL AS [REGIONAL_ORIGEN]
,CO.NOMBRE_CIUDAD AS [CIUDAD_ORIGEN]
,RD.NOMBRE_REGIONAL [REGIONAL_DESTINO]
,CD.NOMBRE_CIUDAD AS [CIUDAD_DESTINO]
,'SISCLINET' AS [CANAL] 
,(G.VALOR_FLETES_GUIAS + G.VALOR_SEG_MAN_GUIAS - G.[VALOR_DESCUENTO_GUIAS]) AS VALOR_FACTURADO
,G.[NUMERO_PIEZAS]
,1 AS GUIA_MOVILIZADA
,G.VALOR_FLETES_GUIAS AS FLETE
,G.VALOR_SEG_MAN_GUIAS AS SOBRE_FLETE
,G.[VALOR_DESCUENTO_GUIAS] AS DESCUENTO
,MT.[NOMBRE_MEDTRANS]
,NULL AS [Cantidad_procesamiento_ideal]-------------
,NULL AS [Cantidad_procesamiento_REAL]-------------
,NULL AS [NOMBRE_ESTADOENVIO]-------------
,FP.[NOMBRE_FORMAPAGO] AS[NOMBRE_FORMAPAGO]
,TE.[NOMBRE_TIEMPO]
,G.[PESO_VOLU_OPERA]
,G.[PESO_FISICO_OPERA]
,VALOR_RECAUDO=IIF(LG.VALOR_RECAUDADO=0 OR LG.VALOR_RECAUDADO IS NULL,VALOR_PRODUCTO,VALOR_RECAUDADO) 
,ES_LPC = CASE WHEN LEN(LG.NUMERO_GUIA)>1 THEN 1 ELSE 0 END
  FROM [MERF_INGRESOS].[dbo].[MECE_LOGISTICO_GUIAS]  G (nolock)
  inner join [MERF_INGRESOS].[dbo].MECE_LOGISTICO_GUIAS_INF_ADICIONAL GIA (nolock) ON G.NUMERO_GUIA=GIA.NUMERO_GUIA
  INNER JOIN [PARAMETROS_MDM].[dbo].[TIPOTRAYECTO] T (NOLOCK) ON T.ID_PAIS=1 AND T.[ID_TIPOTRAY]=GIA.[ID_TIPOTRAY]
  INNER JOIN [PARAMETROS_MDM].[dbo].[PRODUCTOS] P (NOLOCK) ON P.ID_PAIS=1 AND P.ID_PRODUCTO=G.[ID_PRODUCTO]
  INNER JOIN [PARAMETROS_MDM].[dbo].[MEDIOTRANSPORTE] MT (NOLOCK) ON MT.ID_PAIS=1 AND MT.[ID_MEDTRANS]=G.[ID_MEDTRANS]
  INNER JOIN [PARAMETROS_MDM].[dbo].[FORMAPAGO] FP (NOLOCK) ON FP.ID_PAIS=1 AND FP.[ID_FORMAPAGO]=GIA.[ID_FORMAPAGO_OPER]
  INNER JOIN [PARAMETROS_MDM].[dbo].[TIEMPOSENTREGA] TE (NOLOCK) ON TE.ID_PAIS=1 AND TE.[ID_TIEMPO]=G.[ID_TIEMPO]
  INNER JOIN [PARAMETROS_MDM].[dbo].CIUDADES CO (NOLOCK) ON CO.ID_PAIS=1 AND CO.ID_CIUDAD=G.[ID_CIUDAD_ORIGEN]
  INNER JOIN [PARAMETROS_MDM].[dbo].REGIONALES_PAIS RO (NOLOCK) ON RO.ID_PAIS=1 AND RO.ID_REGIONAL=CO.[ID_REGIONAL]
  INNER JOIN [PARAMETROS_MDM].[dbo].CIUDADES CD (NOLOCK) ON CD.ID_PAIS=1 AND CD.ID_CIUDAD=G.[ID_CIUDAD_DESTINO]
  INNER JOIN [PARAMETROS_MDM].[dbo].REGIONALES_PAIS RD (NOLOCK) ON RD.ID_PAIS=1 AND RD.ID_REGIONAL=CD.[ID_REGIONAL]
  LEFT JOIN [LOGISTICA_COBRO]..GUIA_RECAUDO_INFORMACION_RECAUDO LG (NOLOCK) ON LG.NUMERO_GUIA=G.NUMERO_GUIA
  where 
  -- G.ID_FACTURADO=10
  --AND G.id_cliente ='901411985'
  --AND YEAR(G.[FECHA_ENVIO])*100+MONTH(G.[FECHA_ENVIO])=@ID_PERIODO
  --and 
  G.NUMERO_GUIA=3034539281


  SELECT * FROM [MERF_INGRESOS].[dbo].MECE_LOGISTICO_GUIAS_INF_ADICIONAL WHERE NUMERO_GUIA IN(
2134591035
,2134591848
,2166644092
,2187796778
,2134591066
)



