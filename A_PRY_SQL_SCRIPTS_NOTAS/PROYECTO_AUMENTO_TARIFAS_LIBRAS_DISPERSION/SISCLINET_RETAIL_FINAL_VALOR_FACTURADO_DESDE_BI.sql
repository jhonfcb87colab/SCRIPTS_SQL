DECLARE @FECHA_INI DATETIME='2022-08-01';
DECLARE @FECHA_FIN DATETIME='2022-09-01';

WITH PREFACT_DETAMOV (
sROW
,NUMERO_DOCUMENTO
,FECHA_ENVIO
,ID_TIPOGUIA
,ID_MOVDETALLE
,ID_MOVIMIENTO
,ID_TIPO_DOCUMENTO
,ID_TIPO_DETALLE_MOVIMIENTO
,VALOR_MOVDETALLE
,NOMBRE_DETALLE
,NATURALEZA
,FECHA_CREACION
,FECHA_MOFICACION
)as(
SELECT 
	ROW_NUMBER() OVER (PARTITION BY M.NUMERO_DOCUMENTO, M.ID_MOVIMIENTO ORDER BY M.FECHA_CREACION DESC ) AS sROW,
	M.NUMERO_DOCUMENTO,
	G.FECHA_ENVIO,
	G.ID_TIPOGUIA,
	M.ID_MOVDETALLE, 
	M.ID_MOVIMIENTO, 
	M.ID_TIPO_DOCUMENTO, 
	M.ID_TIPO_DETALLE_MOVIMIENTO, 
	M.VALOR_MOVDETALLE, 
	D.NOMBRE_DETALLE, 
	D.NATURALEZA, 
	M.FECHA_CREACION, 
	M.FECHA_MOFICACION
FROM MERF_INGRESOS..DETALLES_MOVIMIENTOS M (NOLOCK) 
INNER JOIN MERF_INGRESOS.DBO.TIPO_DETALLE_MOVIMIENTO D (NOLOCK) ON D.ID_TIPO_DETALLE_MOVIMIENTO=M.ID_TIPO_DETALLE_MOVIMIENTO
INNER JOIN MERF_INGRESOS..MECE_LOGISTICO_GUIAS G (NOLOCK)
ON M.NUMERO_DOCUMENTO=G.NUMERO_GUIA
WHERE M.ID_CANAL = D.ID_CANAL AND D.NATURALEZA ='CR'
AND G.FECHA_ENVIO BETWEEN @FECHA_INI AND @FECHA_FIN

) 
SELECT ---* FROM PREFACT_DETAMOV
P.sROW
,P.NUMERO_DOCUMENTO
,P.FECHA_ENVIO
,P.ID_TIPOGUIA
,P.ID_MOVDETALLE
,P.ID_MOVIMIENTO
,P.ID_TIPO_DOCUMENTO
,P.ID_TIPO_DETALLE_MOVIMIENTO
,P.VALOR_MOVDETALLE
,P.NOMBRE_DETALLE
,P.NATURALEZA
,P.FECHA_CREACION
,P.FECHA_MOFICACION
FROM PREFACT_DETAMOV P (NOLOCK)
WHERE P.sROW = 1
