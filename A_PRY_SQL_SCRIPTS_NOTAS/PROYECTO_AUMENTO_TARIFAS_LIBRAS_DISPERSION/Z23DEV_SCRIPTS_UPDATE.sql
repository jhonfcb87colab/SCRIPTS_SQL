UPDATE FACTMP 
SET 
PESO_CONSOLIDADO = CONVERT(NUMERIC,
							CASE 
								WHEN (ID_PRODUCTO <>6 OR ID_PRODUCTO <> 54) AND PESO_FACTURADO>=1000 THEN 0
								WHEN ID_PRODUCTO IN (6,54) AND PESO_FACTURADO>=50000 THEN 0
								WHEN ID_PRODUCTO=1 THEN 1 
									WHEN  PESO_FACTURADO IS NULL AND  (PESO_FISICO_OPERA IS NOT NULL OR PESO_VOLU_OPERA IS NOT NULL) 
											THEN 						
											IIF(PESO_FISICO_OPERA >= PESO_VOLU_OPERA,PESO_FISICO_OPERA,PESO_VOLU_OPERA)
									WHEN  PESO_FACTURADO IS NULL AND (PESO_PIEZA IS NOT NULL AND PESO_VOLU_PIEZA IS NOT NULL)  
											THEN
												IIF(PESO_PIEZA >= PESO_VOLU_PIEZA,PESO_PIEZA,PESO_VOLU_PIEZA)

									WHEN PESO_FACTURADO IS NULL AND (PESO_VOLUMETRICO IS NOT NULL AND PESO_FISICO IS NOT NULL)  
											THEN
												IIF(PESO_VOLUMETRICO >= PESO_FISICO,PESO_VOLUMETRICO,PESO_FISICO)
							ELSE 	PESO_FACTURADO
							END
							)


FROM [FAC].[MOBIPETARIF_GUIAS] FACTMP WITH(NOLOCK) 
