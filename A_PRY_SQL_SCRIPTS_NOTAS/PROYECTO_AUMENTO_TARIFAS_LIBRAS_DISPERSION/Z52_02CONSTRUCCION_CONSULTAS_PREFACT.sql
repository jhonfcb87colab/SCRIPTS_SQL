USE MERF_INGRESOS;

DECLARE @ID_PERIODO INT = 202301;

WITH CTE_CLIENTES_CORPORATIVOS AS (
SELECT 
		MES = YEAR(G.[FECHA_ENVIO])*100+MONTH(G.[FECHA_ENVIO])
		,NUMERO_GUIA = G.[NUMERO_GUIA]
		,FECHA_ENVIO = G.[FECHA_ENVIO]
		,FECHA_EZU = NULL--------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,NUMERO_PIEZAS = G.[NUMERO_PIEZAS]
		,GIA.[ID_TIPOTRAY]---------------------------------COMPLEMENTARIO
		,TIPO_TRAYECTO = T.[NOMBRE_TIPOTRAY]
		,TIEMPO_ENTREGA = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,G.[ID_PRODUCTO]---------------------------------COMPLEMENTARIO
		,PRODUCTO = P.[NOMBRE_PRODUCTO]
		,VALOR_DECLARADO = LG.VALOR_DECLARADO --------------------COMPLEMENTAR CON TABLA DE LOG GUIAS
		,LOG_COBR.ID_TIPO_COBRO
		,TIPO_COBRO = NULL---FP.[NOMBRE_FORMAPAGO]
		,VALOR_RECAUDAR = IIF(LG.VALOR_RECAUDADO=0 OR LG.VALOR_RECAUDADO IS NULL,VALOR_PRODUCTO,VALOR_RECAUDADO) 
		-----------------------------------------------------
		,REGIONAL_ORIGEN = RO.NOMBRE_REGIONAL
		,CO.ID_DEPARTAMENTO AS ID_DEPARTAMENTO_ORI ---------------------------------COMPLEMENTARIO
		,DEPARTAMENTO_ORIGEN = NULL--DEPA_ORI.NOMBRE_DEPARTAMENTO 
		,ID_CIUDAD_ORIGEN = CO.ID_CIUDAD
		,CIUDAD_ORIGEN = CO.NOMBRE_CIUDAD
		--------------------------------------------
		,REGIONAL_DESTINO = RD.NOMBRE_REGIONAL
		,CD.ID_DEPARTAMENTO AS ID_DEPARTAMENTO_DESTI---------------------------------COMPLEMENTARIO
		,DEPARTAMENTO_DESTINO = NULL--DEPA_DESTI.NOMBRE_DEPARTAMENTO
		,ID_CIUDAD_DESTINO = CD.ID_CIUDAD
		,CIUDAD_DESTINO = CD.NOMBRE_CIUDAD
		----------------------------------------------
		,CANAL = 'SISCLINET'
		,ID_CLIENTE = G.id_cliente
		,CLIENTE = CLIE.NOMBRE_CLIENTE
		-----------------------------------------------
		,REGIONAL_ULTI_MOV = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,DEPARTAMENTO_ULTI_MOV = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,CIUDAD_ULTI_MOV = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,ESTADO_ENVIO = NULL --------------------TABLA DE LOG GUIAS
		,FECHA_ULTI_MOV = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,PROC_ULTI_MOV = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,TIENE_SZU = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,FECHA_SZU = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,CONCEPTO_SZU = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,CONFIRMACION = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,CANT_CONFIRMACION = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,SE_CANTIDAD_SZU = NULL --------------------TABLA DE LOG SEGUIMEINTO ENVIO
		,EMPRESARIO = 'PENDIENTE POR PREGUNTAR'
  FROM [MERF_INGRESOS].[dbo].[MECE_LOGISTICO_GUIAS]  G (nolock)
  INNER JOIN [MERF_INGRESOS].[dbo].MECE_LOGISTICO_GUIAS_INF_ADICIONAL GIA (nolock) ON G.NUMERO_GUIA=GIA.NUMERO_GUIA
  LEFT JOIN [LOGISTICA_COBRO].[dbo].[GUIA_RECAUDO] LOG_COBR (nolock) ON G.NUMERO_GUIA=LOG_COBR.NUMERO_GUIA
  INNER JOIN [PARAMETROS_MDM].[dbo].[TIPOTRAYECTO] T (NOLOCK) ON T.ID_PAIS=1 AND T.[ID_TIPOTRAY]=GIA.[ID_TIPOTRAY]
  INNER JOIN [PARAMETROS_MDM].[dbo].[PRODUCTOS] P (NOLOCK) ON P.ID_PAIS=1 AND P.ID_PRODUCTO=G.[ID_PRODUCTO]
  INNER JOIN [PARAMETROS_MDM].[dbo].[MEDIOTRANSPORTE] MT (NOLOCK) ON MT.ID_PAIS=1 AND MT.[ID_MEDTRANS]=G.[ID_MEDTRANS]
  INNER JOIN [PARAMETROS_MDM].[dbo].[FORMAPAGO] FP (NOLOCK) ON FP.ID_PAIS=1 AND FP.[ID_FORMAPAGO]=GIA.[ID_FORMAPAGO_OPER]
  INNER JOIN [PARAMETROS_MDM].[dbo].[TIEMPOSENTREGA] TE (NOLOCK) ON TE.ID_PAIS=1 AND TE.[ID_TIEMPO]=G.[ID_TIEMPO]
  INNER JOIN [PARAMETROS_MDM].[dbo].CIUDADES CO (NOLOCK) ON CO.ID_PAIS=1 AND CO.ID_CIUDAD=G.[ID_CIUDAD_ORIGEN]
  INNER JOIN [PARAMETROS_MDM].[dbo].REGIONALES_PAIS RO (NOLOCK) ON RO.ID_PAIS=1 AND RO.ID_REGIONAL=CO.[ID_REGIONAL]
  INNER JOIN [PARAMETROS_MDM].[dbo].CIUDADES CD (NOLOCK) ON CD.ID_PAIS=1 AND CD.ID_CIUDAD=G.[ID_CIUDAD_DESTINO]
  INNER JOIN [PARAMETROS_MDM].[dbo].REGIONALES_PAIS RD (NOLOCK) ON RD.ID_PAIS=1 AND RD.ID_REGIONAL=CD.[ID_REGIONAL]
  LEFT JOIN [LOGISTICA_COBRO].[dbo].GUIA_RECAUDO_INFORMACION_RECAUDO LG (NOLOCK) ON LG.NUMERO_GUIA=G.NUMERO_GUIA
  LEFT JOIN [PARAMETROS_MDM].[dbo].CLIENTES CLIE WITH(NOLOCK) ON  G.id_cliente=CLIE.ID_CLIENTE
  WHERE 
   G.ID_FACTURADO=10
  AND G.id_cliente IN('901411985','901116547','901358770','900469230','901195703')
  AND YEAR(G.[FECHA_ENVIO])*100+MONTH(G.[FECHA_ENVIO])=@ID_PERIODO
)
SELECT 
	CTE.MES
	,CTE.NUMERO_GUIA
	,CTE.FECHA_ENVIO
	,CTE.FECHA_EZU
	,CTE.NUMERO_PIEZAS
	,CTE.ID_TIPOTRAY
	,CTE.TIPO_TRAYECTO
	,CTE.TIEMPO_ENTREGA
	,CTE.ID_PRODUCTO
	,CTE.PRODUCTO
	,CTE.VALOR_DECLARADO
	,CTE.ID_TIPO_COBRO
	,TIPO_COBRO = TIPOCOBR.NOMBRE_TIPO_COBRO
	,CTE.VALOR_RECAUDAR
	,CTE.REGIONAL_ORIGEN
	,CTE.ID_DEPARTAMENTO_ORI
	,DEPARTAMENTO_ORIGEN = DEPA_ORI.NOMBRE_DEPARTAMENTO
	,CTE.ID_CIUDAD_ORIGEN
	,CTE.CIUDAD_ORIGEN
	,CTE.REGIONAL_DESTINO
	,CTE.ID_DEPARTAMENTO_DESTI 
	,DEPARTAMENTO_DESTINO = DEPA_DESTI.NOMBRE_DEPARTAMENTO
	,CTE.ID_CIUDAD_DESTINO
	,CTE.CIUDAD_DESTINO
	,CTE.CANAL
	,CTE.ID_CLIENTE
	,CTE.CLIENTE
	,CTE.REGIONAL_ULTI_MOV
	,CTE.DEPARTAMENTO_ULTI_MOV
	,CTE.CIUDAD_ULTI_MOV
	,CTE.ESTADO_ENVIO
	,CTE.FECHA_ULTI_MOV
	,CTE.PROC_ULTI_MOV
	,CTE.TIENE_SZU
	,CTE.FECHA_SZU
	,CTE.CONCEPTO_SZU
	,CTE.CONFIRMACION
	,CTE.CANT_CONFIRMACION
	,CTE.SE_CANTIDAD_SZU
	,CTE.EMPRESARIO
FROM CTE_CLIENTES_CORPORATIVOS CTE
LEFT JOIN [PARAMETROS_MDM].[dbo].DEPARTAMENTOS DEPA_ORI WITH(NOLOCK) ON  (CTE.ID_DEPARTAMENTO_ORI=DEPA_ORI.ID_DEPARTAMENTO AND DEPA_ORI.ID_PAIS=1)
LEFT JOIN [PARAMETROS_MDM].[dbo].DEPARTAMENTOS DEPA_DESTI WITH(NOLOCK) ON  (CTE.ID_DEPARTAMENTO_DESTI=DEPA_DESTI.ID_DEPARTAMENTO AND DEPA_DESTI.ID_PAIS=1)
LEFT JOIN [LOGISTICA_COBRO].[dbo].LPC_TIPO_COBRO TIPOCOBR WITH(NOLOCK) ON   CTE.ID_TIPO_COBRO=TIPOCOBR.ID


