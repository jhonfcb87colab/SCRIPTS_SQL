SELECT TMP.NUMERO_GUIA,SE.ID_PROCESO
INTO #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_1
FROM #MOBIPE_CONSOLIDADO_CLIENTE_MERF_FINANCIERA TMP
LEFT JOIN SIG_COLOMBIA_DW.LOG.SEGUIMIENTO_ENVIO SE with(nolock) ON SE.NUMERO_GUIA=TMP.NUMERO_GUIA
WHERE SE.ID_PROCESO IN (6,9,12,14);

GO
WITH CTE AS(
SELECT 
t1.NUMERO_GUIA
,EZU = CASE WHEN t2.ID_PROCESO=6 THEN COUNT(t2.ID_PROCESO) ELSE 0 END	
,SZU = CASE WHEN t2.ID_PROCESO=9 THEN COUNT(t2.ID_PROCESO) ELSE 0 END	
,ERG = CASE WHEN t2.ID_PROCESO=14 THEN COUNT(t2.ID_PROCESO) ELSE 0 END	
,SRG = CASE WHEN t2.ID_PROCESO=12 THEN COUNT(t2.ID_PROCESO) ELSE 0 END
--EZU=count(t2.ID_PROCESO) 
FROM #MOBIPE_CONSOLIDADO_CLIENTE_MERF_FINANCIERA t1
inner join #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_1 t2 on t1.NUMERO_GUIA=t2.NUMERO_GUIA
GROUP BY t1.NUMERO_GUIA,t2.ID_PROCESO
)
select
cte.NUMERO_GUIA	
,EZU = SUM(cte.EZU)	
,SZU = SUM(cte.SZU)	
,ERG = SUM(cte.ERG)	
,SRG = SUM(cte.SRG)
INTO #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_2
FROM CTE cte
GROUP BY cte.NUMERO_GUIA	


GO

--------------------6-ENTRADA DE ZONA URBANA
--------------------9-SALIDA A ZONA URBANA
--------------------12-SALIDA A REGIONAL
--------------------14-ENTRADA DE REGIONAL

GO

select 
T1.NUMERO_GUIA,
(T1.ERG+T1.EZU+T1.SRG+T1.SZU) AS Cantidad_procesamiento_REAL,
(
IIF(T1.ERG>0,1,0)
+
IIF(T1.EZU>0,1,0)
+
IIF(T1.SRG>0,1,0)
+
IIF(T1.SZU>0,1,0)
)
AS Cantidad_procesamiento_ideal
INTO #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_3
from #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_2 T1;


GO



WITH CTE AS(
SELECT 
		ROW_NUMBER ( )   OVER ( PARTITION BY TEMP01.NUMERO_GUIA order by LOGG.FECHA_MODIFICACION_DG  desc )  ROWid  
		,TEMP01.NUMERO_GUIA	
		,Cantidad_procesamiento_ideal = TMP02.Cantidad_procesamiento_ideal	
		,Cantidad_procesamiento_REAL = TMP02.Cantidad_procesamiento_REAL	
		,ID_ESTADOENVIO	= LOGG.ID_ESTADOENVIO
FROM #MOBIPE_CONSOLIDADO_CLIENTE_MERF_FINANCIERA TEMP01
LEFT JOIN #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_3 TMP02 ON TEMP01.NUMERO_GUIA=TMP02.NUMERO_GUIA
LEFT JOIN LOG.GUIAS LOGG WITH(NOLOCK)  ON LOGG.NUMERO_GUIA=TEMP01.NUMERO_GUIA
) 
SELECT 
CTE.NUMERO_GUIA	
,CTE.Cantidad_procesamiento_ideal	
,CTE.Cantidad_procesamiento_REAL	
,CTE.ID_ESTADOENVIO
,EEV.NOMBRE_ESTADOENVIO
INTO #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_4
FROM CTE CTE
INNER JOIN PAR.ESTADOSENVIO EEV WITH(NOLOCK)  ON CTE.ID_ESTADOENVIO=EEV.ID_ESTADOENVIO
WHERE ROWid=1

