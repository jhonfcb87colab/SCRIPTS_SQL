WITH CTE_CARGA_FINAL_MOBIPE_CONSOLIDADO_CLIENTES_CORPORATIVOS AS(
		SELECT 
				ROW_NUMBER ( )   OVER ( PARTITION BY TRANSIT.NUMERO_GUIA order by GUI.FECHA_MODIFICACION_DG  desc )  ROW_id  
				,TRANSIT.MES	
