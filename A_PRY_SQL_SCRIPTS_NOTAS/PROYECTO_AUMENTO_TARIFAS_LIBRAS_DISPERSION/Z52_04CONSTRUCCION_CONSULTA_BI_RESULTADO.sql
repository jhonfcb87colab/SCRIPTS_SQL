				,TRANSIT.ID_PRODUCTO	
				,TRANSIT.PRODUCTO	
				,VALOR_DECLARADO = ISNULL(ISNULL(TRANSIT.VALOR_DECLARADO,TRANSIT.VALOR_DECLARADO),GUI.VALOR_DECLARADO_GUIA)	
				,ID_TIPO_COBRO	= ISNULL(TRANSIT.ID_TIPO_COBRO,RECAUD.ID_FORMA_PAGO)
				,TIPO_COBRO	= ISNULL(TRANSIT.TIPO_COBRO,FORMPG.NOMBRE_FORMAPAGO)
				,VALOR_RECAUDAR	= ISNULL(TRANSIT.VALOR_RECAUDAR,RECAUD.VALOR_RECAUDADO)
				,TRANSIT.REGIONAL_ORIGEN	
				,TRANSIT.ID_DEPARTAMENTO_ORI	
				,TRANSIT.DEPARTAMENTO_ORIGEN	
				,TRANSIT.ID_CIUDAD_ORIGEN	
				,TRANSIT.CIUDAD_ORIGEN	
				,TRANSIT.REGIONAL_DESTINO	
				,TRANSIT.ID_DEPARTAMENTO_DESTI	
				,TRANSIT.DEPARTAMENTO_DESTINO	
				,TRANSIT.ID_CIUDAD_DESTINO	
				,TRANSIT.CIUDAD_DESTINO	
				,TRANSIT.CANAL	
				,TRANSIT.ID_CLIENTE	
				,TRANSIT.CLIENTE	
				,TRANSIT.REGIONAL_ULTI_MOV	
				,TRANSIT.DEPARTAMENTO_ULTI_MOV	
				,TRANSIT.CIUDAD_ULTI_MOV	
				,TRANSIT.ESTADO_ENVIO	
				,FECHA_ULTI_MOV	 = ISNULL(CONVERT(DATETIME,G_MASIV.SE_FECHA_ULTI_MOVI),TRANSIT.FECHA_ULTI_MOV)
				,TRANSIT.PROC_ULTI_MOV	
				,TIENE_SZU = CASE WHEN TRANSIT.TIENE_SZU=1 THEN 'SI' ELSE 'NO' END 				
				,TRANSIT.FECHA_SZU	
				,TRANSIT.CONCEPTO_SZU	
				,CONFIRMACION = IIF(TRANSIT.CONFIRMACION='NO' AND 
								(CASE WHEN TRANSIT.CANT_CONFIRMACION >= G_MASIV.CNF_CANT_CONFIRMACION THEN TRANSIT.CANT_CONFIRMACION ELSE G_MASIV.CNF_CANT_CONFIRMACION END)>0,
								'SI',TRANSIT.CONFIRMACION)						
				,CANT_CONFIRMACION	= CASE WHEN TRANSIT.CANT_CONFIRMACION >= G_MASIV.CNF_CANT_CONFIRMACION THEN TRANSIT.CANT_CONFIRMACION ELSE G_MASIV.CNF_CANT_CONFIRMACION END
				,SE_CANTIDAD_SZU	= CASE WHEN TRANSIT.SE_CANTIDAD_SZU >= G_MASIV.SE_CANT_SZU THEN TRANSIT.SE_CANTIDAD_SZU ELSE G_MASIV.SE_CANT_SZU END
				,TRANSIT.EMPRESARIO
		 FROM [TMP_BORRAR].[DBO].[FAC_MOBIPE_CONSOLIDADO_CLIENTES_CORPORATIVOS] TRANSIT WITH(NOLOCK)
		 LEFT JOIN SIG_COLOMBIA_DW.LOG.GUIA_RECAUDO_INFORMACION_RECAUDO RECAUD WITH(NOLOCK)
		 ON TRANSIT.NUMERO_GUIA=RECAUD.NUMERO_GUIA
		 LEFT JOIN SIG_COLOMBIA_DW.PAR.FORMAPAGO FORMPG WITH(NOLOCK)
		 ON RECAUD.ID_FORMA_PAGO=FORMPG.ID_FORMAPAGO
		 LEFT JOIN SIG_COLOMBIA_DW.LOG.GUIAS GUI  WITH(NOLOCK)
		 ON TRANSIT.NUMERO_GUIA=GUI.NUMERO_GUIA 
		 LEFT JOIN SIG_LOGISTICA_DM.FAC.GUIA_MASIVA G_MASIV WITH(NOLOCK)
		 ON TRANSIT.NUMERO_GUIA=G_MASIV.G_NUMERO_GUIA
  ) SELECT * FROM  CTE_CARGA_FINAL_MOBIPE_CONSOLIDADO_CLIENTES_CORPORATIVOS
  WHERE ROW_id=1
  
