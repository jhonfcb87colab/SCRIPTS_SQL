  USE SIG_COL_LOGISTICA_DW;

 


/* SE VALIDA QUE LA TABLA TEMPORAL GEOGRAFIA NO EXISTA */
DROP TABLE IF EXISTS #GEOGRAFIA;

 

/* SE CREA DATOS DE GEOGRAFIA DE LAS TABLAS CIUDADES Y REGIONALES */
    SELECT 
    C.ID_REGIONAL
    ,R.NOMBRE_REGIONAL
    ,C.ID_CIUDAD
    ,C.NOMBRE_CIUDAD
    INTO #GEOGRAFIA
    FROM SIG_COLOMBIA_DW.PAR.CIUDADES AS C 
    INNER JOIN SIG_COLOMBIA_DW.PAR.REGIONALES_PAIS AS R
    ON C.ID_REGIONAL = R.ID_REGIONAL

 

 

/* SE ACTUALIZA DATOS EN LA TABLA */

 

UPDATE MOB
    SET

    /* DATOS ORIGEN*/
     MOB.ID_REGIONAL_ORIGEN = CO.ID_REGIONAL -- AS ID_REGIONAL_ORIGEN 
    ,MOB.REGIONAL_ORIGEN = CO.NOMBRE_REGIONAL -- AS REGIONAL_ORIGEN
    ,MOB.ID_CIUDAD_ORIGEN = G.ID_CIUDAD_ORIGEN
    ,MOB.CIUDAD_ORIGEN = CO.NOMBRE_CIUDAD -- AS CIUDAD_ORIGEN  
    /* DATOS DESTINO */    
    ,MOB.ID_REGIONAL_DESTINO = CD.ID_REGIONAL -- AS ID_REGIONAL_DESTINO
    ,MOB.REGIONAL_DESTINO = CD.NOMBRE_REGIONAL -- AS REGIONAL_DESTINO
    ,MOB.ID_CIUDAD_DESTINO = G.ID_CIUDAD_DESTINO
    ,MOB.CIUDAD_DESTINO = CD.NOMBRE_CIUDAD -- AS CIUDAD_DESTINO
    FROM [SIG_COL_LOGISTICA_DW].[FAC].[MOBIPETARIF_GUIAS] AS MOB WITH(NOLOCK)
    INNER JOIN SIG_COLOMBIA_DW.LOG.GUIAS AS G  WITH(NOLOCK)
        ON MOB.GUIA = G.NUMERO_GUIA
    LEFT JOIN #GEOGRAFIA AS CO
        ON G.ID_CIUDAD_ORIGEN = CO.ID_CIUDAD
    LEFT JOIN #GEOGRAFIA AS CD
        ON G.ID_CIUDAD_DESTINO = CD.ID_CIUDAD
    WHERE (MOB.ID_CIUDAD_ORIGEN IS NULL OR   MOB.ID_CIUDAD_DESTINO IS NULL)
    AND YEAR(MOB.FECHA_ENVIO)=2023 AND MONTH(MOB.FECHA_ENVIO)=5
    AND G.ID_CIUDAD_ORIGEN <> 0 AND CANAL = 'SISCLINET'

 

 

/* CONSULTA DE PRUEBA */
  SELECT  -- TOP 100
    MOB.GUIA
    /* DATOS ORIGEN*/
    ,CO.ID_REGIONAL AS ID_REGIONAL_ORIGEN 
    ,CO.NOMBRE_REGIONAL AS REGIONAL_ORIGEN
    ,G.ID_CIUDAD_ORIGEN
    ,CO.NOMBRE_CIUDAD AS CIUDAD_ORIGEN  
    /* DATOS DESTINO */    
    ,CD.ID_REGIONAL AS ID_REGIONAL_DESTINO
    ,CD.NOMBRE_REGIONAL AS REGIONAL_DESTINO
    ,G.ID_CIUDAD_DESTINO
    ,CD.NOMBRE_CIUDAD AS CIUDAD_DESTINO
    FROM [SIG_COL_LOGISTICA_DW].[FAC].[MOBIPETARIF_GUIAS] AS MOB WITH(NOLOCK)
    INNER JOIN SIG_COLOMBIA_DW.LOG.GUIAS AS G  WITH(NOLOCK)
        ON MOB.GUIA = G.NUMERO_GUIA
    LEFT JOIN #GEOGRAFIA AS CO
        ON G.ID_CIUDAD_ORIGEN = CO.ID_CIUDAD
    LEFT JOIN #GEOGRAFIA AS CD
        ON G.ID_CIUDAD_DESTINO = CD.ID_CIUDAD
    WHERE (MOB.ID_CIUDAD_ORIGEN IS NULL OR   MOB.ID_CIUDAD_DESTINO IS NULL)
    AND YEAR(MOB.FECHA_ENVIO)=2023 AND MONTH(MOB.FECHA_ENVIO)=5
