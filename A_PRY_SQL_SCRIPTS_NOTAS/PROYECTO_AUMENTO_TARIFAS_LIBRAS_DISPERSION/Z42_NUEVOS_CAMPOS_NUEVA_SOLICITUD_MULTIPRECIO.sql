SELECT 
TRF.GUIA as NUMERO_GUIA,
TRF.ID_PRODUCTO,
TRF.PRODUCTO,
TRF.FECHA_ENVIO,
TRF.ID_TRAYECTO,
TRF.NOMBRE_TRAYECTO,
TRF.TIPO_PESO,
TRF.PESO_CONSOLIDADO,
TRF.REGIONAL_ORIGEN,
TRF.CIUDAD_ORIGEN,
TRF.REGIONAL_DESTINO,
TRF.CIUDAD_DESTINO,
TRF.CANAL,
TRF.VALOR_FACTURADO,
TRF.NUMERO_PIEZAS,
TRF.GUIA_MOVILIZADA,
G.Freight AS FLETE,
G.OnFreight AS SOBRE_FLETE,
I.DiscountValue AS DESCUENTO
INTO [TMP_BORRAR].DBO.[MOBIPETARIF_GUIAS_BK20230613_SOLICITUD]
--INTO #MOBIPETARIF_GUIAS_BK20230613_SOLICITUD
    FROM [SIG_COL_LOGISTICA_DW].[FAC].[MOBIPETARIF_GUIAS] TRF WITH(NOLOCK)
LEFT JOIN [SIG_COLOMBIA_DW].RTW.GUIDE G WITH(NOLOCK) ON TRF.GUIA=G.Number
LEFT JOIN [SIG_COLOMBIA_DW].RTW.INVOICEDETAIL I WITH(NOLOCK) ON I.Id=G.InvoiceDetailId
  WHERE 
  TRF.[CANAL]='RETAIL' 
  AND YEAR(TRF.FECHA_ENVIO)*100+MONTH(TRF.FECHA_ENVIO)=202305
  AND ID_PRODUCTO=2



  SELECT 
  YEAR(FECHA_ENVIO) AS AÑO,
  MONTH(FECHA_ENVIO) AS MES,
  PRODUCTO,
  CANAL,
  NOMBRE_TRAYECTO,
  TIPO_PESO AS Kilogramo,
  count(NUMERO_GUIA) as #Guias,
  sum(NUMERO_PIEZAS) AS #Piezas,
  SUM(FLETE) as FLETE,
  SUM(SOBRE_FLETE) AS SOBRE_FLETE,
  SUM(DESCUENTO) AS DESCUENTO
  FROM [TMP_BORRAR].DBO.[MOBIPETARIF_GUIAS_BK20230613_SOLICITUD]
  GROUP BY 
    YEAR(FECHA_ENVIO),
  MONTH(FECHA_ENVIO),
  PRODUCTO,
  CANAL,
  NOMBRE_TRAYECTO,
  TIPO_PESO
  ORDER BY TIPO_PESO,NOMBRE_TRAYECTO DESC
