ON (SE.ID_PROCESO=DOC.ID_PROCESO	
	AND SE.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI	
	AND SE.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI)
INNER JOIN SIG_COLOMBIA_DW.PAR.DIVISIONES DV WITH(NOLOCK)
ON (DOC.ID_CIUDAD_DIVISION_ORIGEN=DV.ID_CIUDAD	
	AND DOC.ID_DIVISION_ORIGEN=DV.ID_DIVISION)
	WHERE -------NUMERO_GUIA=2173227858 AND
	DOC.ID_DIVISION_ORIGEN IN (SELECT DISTINCT ID_DIVISION  FROM SIG_COLOMBIA_DW.PAR.DIVISIONES WHERE NOMBRE_DIVISION LIKE '%CONFIRMACION%')
GROUP BY SE.NUMERO_GUIA;



