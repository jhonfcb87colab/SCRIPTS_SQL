-----CONTRUCCION CONSULTAS CAMPOS_ULT_MOV

WITH CTE_CAMPOS_ULT_MOV AS (
SELECT --TOP 10 
ROW_NUMBER ( )   OVER ( PARTITION BY SE.NUMERO_GUIA order by SE.FECHA_HORA_MOVIMIENTO desc )  ROW_id
,SE.NUMERO_GUIA----SI
---,ID_ESTADO_ENVIO=SE.G_ID_ESTADOENVIO
,ESTADO_ENVIO = ESTEV.NOMBRE_ESTADOENVIO  ---SI
----,ID_CIUDAD_ULTI_MOV = DOC.ID_CIUDAD_DESTINO 
,CIUDAD_ULTI_MOV = CD.NOMBRE_CIUDAD
,REGIONAL_ULTI_MOV= RG.NOMBRE_REGIONAL
,DEPARTAMENTO_ULTI_MOV = DEPA.NOMBRE_DEPARTAMENTO
,FECHA_ULTI_MOV = SE.FECHA_HORA_MOVIMIENTO
,PROC_ULTI_MOV = PR.NOMBRE_PROCESO_LOG
FROM 
#GUIAS_NUEVA_SOLICITUD_20230809_PARTE_1_SEGUIMIENTO_ENVIO SE
LEFT JOIN SIG_COLOMBIA_DW.LOG.DOCUMENTOS DOC WITH(NOLOCK)
ON (SE.ID_PROCESO=DOC.ID_PROCESO	
	AND SE.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI	
	AND SE.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI)
LEFT JOIN SIG_COLOMBIA_DW.PAR.CIUDADES CD WITH(NOLOCK)
ON  DOC.ID_CIUDAD_DESTINO=CD.ID_CIUDAD
LEFT JOIN SIG_COLOMBIA_DW.PAR.REGIONALES_PAIS RG WITH(NOLOCK)
ON RG.ID_REGIONAL=CD.ID_REGIONAL
LEFT JOIN SIG_COLOMBIA_DW.PAR.DEPARTAMENTOS DEPA WITH(NOLOCK)
ON (DEPA.ID_PAIS=1 AND DEPA.ID_DEPARTAMENTO=CD.ID_DEPARTAMENTO)
LEFT JOIN SIG_COLOMBIA_DW.PAR.PROCESOS PR WITH(NOLOCK)
ON SE.ID_PROCESO=PR.ID_PROCESO
LEFT JOIN SIG_COLOMBIA_DW.PAR.ESTADOSENVIO ESTEV WITH(NOLOCK)
ON ESTEV.ID_ESTADOENVIO=SE.G_ID_ESTADOENVIO
WHERE ROW_id=1
)
SELECT 
NUMERO_GUIA	
,ESTADO_ENVIO	
,CIUDAD_ULTI_MOV	
,REGIONAL_ULTI_MOV	
,DEPARTAMENTO_ULTI_MOV	
,FECHA_ULTI_MOV	
,PROC_ULTI_MOV
INTO #GUIAS_NUEVA_SOLICITUD_20230809_PARTE_21_CAMPOS_ULT_MOV
FROM CTE_CAMPOS_ULT_MOV
WHERE ROW_id=1;


GO

------CONTRUCCION CONSULTA SALIDA_ZONA_URB
SELECT
SE.NUMERO_GUIA	
,TIENE_SZU = 1	
,FECHA_SZU = MAX(SE.FECHA_HORA_MOVIMIENTO)	
,SE_CANTIDAD_SZU = COUNT(SE.ID_PROCESO)
INTO #GUIAS_NUEVA_SOLICITUD_20230809_PARTE_22_SALIDA_ZONA_URB
FROM #GUIAS_NUEVA_SOLICITUD_20230809_PARTE_1_SEGUIMIENTO_ENVIO SE
WHERE ID_PROCESO=9
GROUP BY SE.NUMERO_GUIA;

GO

SELECT
SE.NUMERO_GUIA	
,FECHA_EZU = MIN(SE.FECHA_HORA_MOVIMIENTO)	
INTO #GUIAS_NUEVA_SOLICITUD_20230809_PARTE_23_ENTRADA_ZONA_URB
FROM #GUIAS_NUEVA_SOLICITUD_20230809_PARTE_1_SEGUIMIENTO_ENVIO SE
WHERE ID_PROCESO=6 AND SE.FECHA_HORA_MOVIMIENTO IS NOT NULL
GROUP BY SE.NUMERO_GUIA;



GO



----------------CALCULO DE CAMPOS  DE CONFIRMACIONES 

SELECT 
SE.NUMERO_GUIA,
COUNT(SE.ID_PROCESO) AS CANT_CONFIRMACION	
INTO #GUIAS_NUEVA_SOLICITUD_20230809_PARTE_30_CONATIDAD_CONFIRMACIONES
FROM #GUIAS_NUEVA_SOLICITUD_20230809_PARTE_1_SEGUIMIENTO_ENVIO SE
