WITH CTE AS (
SELECT 
ROW_NUMBER ( )   OVER ( PARTITION BY TP1.NUMERO_GUIA order by TP1.FECHA_ENVIO,FECHA_MODIFICACION_DG desc )  ROW_id, 
TP1.*,
ISNULL(ISNULL(TMP.NOMBRE_MEDTRANS,DIMMED.NOMBRE_MEDTRANS),'NO DISPONIBLE') AS NOMBRE_MEDIO_TRANSP,
ISNULL(TMP.Cantidad_procesamiento_ideal,0) as Cantidad_procesamiento_ideal,
ISNULL(TMP.Cantidad_procesamiento_REAL,0) as Cantidad_procesamiento_REAL,
ESTADOSENVIO.NOMBRE_ESTADOENVIO,
COBRO.NOMBRE_FORMAPAGO,
TIM_ENT.NOMBRE_TIEMPO
FROM [TMP_BORRAR].DBO.[MOBIPETARIF_GUIAS_BK20230613_SOLICITUD] TP1 WITH(NOLOCK) 
LEFT JOIN #GUIAS_NUEVA_SOLICITUD_20230613_PARTE_4 TMP ON TMP.NUMERO_GUIA=TP1.NUMERO_GUIA
LEFT JOIN SIG_COLOMBIA_DW.RTW.GUIDE RTWG WITH(NOLOCK) ON RTWG.Number=TP1.NUMERO_GUIA
LEFT JOIN SIG_COLOMBIA_DW.RTW.INVOICEDETAIL INVOICEDETAIL WITH(NOLOCK) ON RTWG.InvoiceDetailId=INVOICEDETAIL.Id
LEFT JOIN SIG_COLOMBIA_DW.PAR.FORMAPAGO COBRO WITH(NOLOCK) ON COBRO.ID_FORMAPAGO=INVOICEDETAIL.PaymentFormId
LEFT JOIN SIG_COLOMBIA_DW.PAR.MEDIOTRANSPORTE DIMMED WITH(NOLOCK) ON DIMMED.ID_MEDTRANS=RTWG.MeanTransportId
LEFT JOIN SIG_COLOMBIA_DW.LOG.GUIAS LOGGUIAS WITH(NOLOCK) ON LOGGUIAS.NUMERO_GUIA=TP1.NUMERO_GUIA
LEFT JOIN SIG_COLOMBIA_DW.PAR.ESTADOSENVIO WITH(NOLOCK) ON ESTADOSENVIO.ID_ESTADOENVIO=LOGGUIAS.ID_ESTADOENVIO
LEFT JOIN SIG_COLOMBIA_DW.PAR.TIEMPOSENTREGA TIM_ENT WITH(NOLOCK) ON TIM_ENT.ID_TIEMPO=TP1.DeliveryTimeId 
)
