/****** Script for SelectTopNRows command from SSMS  ******/
/****** USE [SIG_MEVI_DM] ******/


WITH CETE_TARIF_GUIAS
(
	id 
	,[GUIA]
    ,[ID_PRODUCTO]
    ,[PRODUCTO]
    ,[TIME_ID]
    ,[FECHA_ENVIO]
    ,[ID_TRAYECTO]
    ,[NOMBRE_TRAYECTO]
    ,[TIPO_PESO]
    ,[PESO_CONSOLIDADO]
    ,[PESO_VOLUMETRICO]
    ,[PESO_FISICO]
    ,[ID_REGIONAL_ORIGEN]
    ,[REGIONAL_ORIGEN]
    ,[ID_CIUDAD_ORIGEN]
    ,[CIUDAD_ORIGEN]
    ,[ID_REGIONAL_DESTINO]
    ,[REGIONAL_DESTINO]
    ,[ID_CIUDAD_DESTINO]
    ,[CIUDAD_DESTINO]
    ,[CANAL]
    ,[FECHA_EXTRACCION]
    ,[VALOR_FACTURADO]
) AS (
SELECT 
		ROW_NUMBER ( )   OVER ( PARTITION BY [GUIA] order by [FECHA_ENVIO] desc )  id  
		,[GUIA]
		,[ID_PRODUCTO]
		,[PRODUCTO]
		,[TIME_ID]
		,[FECHA_ENVIO]
		,[ID_TRAYECTO]
		,[NOMBRE_TRAYECTO]
		,[TIPO_PESO]
		,[PESO_CONSOLIDADO]
		,[PESO_VOLUMETRICO]
		,[PESO_FISICO]
		,[ID_REGIONAL_ORIGEN]
		,[REGIONAL_ORIGEN]
		,[ID_CIUDAD_ORIGEN]
		,[CIUDAD_ORIGEN]
		,[ID_REGIONAL_DESTINO]
		,[REGIONAL_DESTINO]
		,[ID_CIUDAD_DESTINO]
		,[CIUDAD_DESTINO]
		,[CANAL]
		,[FECHA_EXTRACCION]
		,[VALOR_FACTURADO]
  FROM [SIG_MEVI_DM].[FAC].[TARIF_GUIAS] WITH (NOLOCK)
 )
 INSERT INTO [SIG_COL_LOGISTICA_DW].[FAC].[MOBIPETARIF_GUIAS]
 SELECT 
 		 [GUIA]
		,[ID_PRODUCTO]
		,[PRODUCTO]
		,[TIME_ID]
		,[FECHA_ENVIO]
		,[ID_TRAYECTO]
		,[NOMBRE_TRAYECTO]
		,[TIPO_PESO]
		,[PESO_CONSOLIDADO]
		,[PESO_VOLUMETRICO]
		,[PESO_FISICO]
		,[ID_REGIONAL_ORIGEN]
		,[REGIONAL_ORIGEN]
		,[ID_CIUDAD_ORIGEN]
		,[CIUDAD_ORIGEN]
		,[ID_REGIONAL_DESTINO]
		,[REGIONAL_DESTINO]
		,[ID_CIUDAD_DESTINO]
		,[CIUDAD_DESTINO]
		,[CANAL]
		,[FECHA_EXTRACCION]
		,[VALOR_FACTURADO]
 FROM CETE_TARIF_GUIAS
 WHERE id=1