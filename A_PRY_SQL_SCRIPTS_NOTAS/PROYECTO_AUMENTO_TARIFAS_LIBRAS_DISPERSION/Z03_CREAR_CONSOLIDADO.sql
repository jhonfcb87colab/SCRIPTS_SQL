INSERT INTO [FAC].[MOBIPETARIF_TOTALES_TIPO_PESO_MES]
SELECT COUNT([GUIA]) AS [GUIA]
      ,[ID_PRODUCTO]
      ,[PRODUCTO]
      ,0 AS [TIME_ID]
      ,YEAR([FECHA_ENVIO])*100+MONTH([FECHA_ENVIO]) [FECHA_ENVIO]
      ,[ID_TRAYECTO]
      ,[NOMBRE_TRAYECTO]
      ,[TIPO_PESO]
      ,SUM([PESO_CONSOLIDADO]) [PESO_CONSOLIDADO]
      ,SUM([PESO_VOLUMETRICO]) [PESO_VOLUMETRICO]
      ,SUM([PESO_FISICO]) [PESO_FISICO]
      ,[ID_REGIONAL_ORIGEN]
      ,[REGIONAL_ORIGEN]
      ,[ID_CIUDAD_ORIGEN]
      ,[CIUDAD_ORIGEN]
      ,[ID_REGIONAL_DESTINO]
      ,[REGIONAL_DESTINO]
      ,[ID_CIUDAD_DESTINO]
      ,[CIUDAD_DESTINO]
      ,[CANAL]
      ,MAX([FECHA_EXTRACCION]) [FECHA_EXTRACCION]
	  ,SUM([VALOR_FACTURADO]) [TOTAL_VALOR_FACTURADO]
FROM [SIG_COL_LOGISTICA_DW].[FAC].[MOBIPETARIF_GUIAS] (NOLOCK)
GROUP BY 
      [ID_PRODUCTO]
      ,[PRODUCTO]
      --,[TIME_ID]
      ,YEAR([FECHA_ENVIO])*100+MONTH([FECHA_ENVIO])
      ,[ID_TRAYECTO]
      ,[NOMBRE_TRAYECTO]
      ,[TIPO_PESO]
      ,[ID_REGIONAL_ORIGEN]
      ,[REGIONAL_ORIGEN]
      ,[ID_CIUDAD_ORIGEN]
      ,[CIUDAD_ORIGEN]
      ,[ID_REGIONAL_DESTINO]
      ,[REGIONAL_DESTINO]
      ,[ID_CIUDAD_DESTINO]
      ,[CIUDAD_DESTINO]
      ,[CANAL]
