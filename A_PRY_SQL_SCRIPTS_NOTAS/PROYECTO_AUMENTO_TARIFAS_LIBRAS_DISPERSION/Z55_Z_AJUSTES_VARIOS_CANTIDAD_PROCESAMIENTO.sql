USE SIG_LOGISTICA_DM;

DROP TABLE IF EXISTS #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_1;
DROP TABLE IF EXISTS #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_2;


WITH CTE AS(
SELECT 
t1.NUMERO_GUIA
,EZU = CASE WHEN t2.ID_PROCESO=6 THEN COUNT(t2.ID_PROCESO) ELSE 0 END	
,SZU = CASE WHEN t2.ID_PROCESO=9 THEN COUNT(t2.ID_PROCESO) ELSE 0 END	
,ERG = CASE WHEN t2.ID_PROCESO=14 THEN COUNT(t2.ID_PROCESO) ELSE 0 END	
,SRG = CASE WHEN t2.ID_PROCESO=12 THEN COUNT(t2.ID_PROCESO) ELSE 0 END
--EZU=count(t2.ID_PROCESO) 
FROM [SIG_LOGISTICA_DM].[FAC].[MOBIPE_CONSOLIDADO_MERF_FINANCIERA_DETALLE_COSTO] t1 WITH(NOLOCK)   -------->  
inner join TMP.MOBIPE_DEV_PROCESOS_CONSOLIDADO_CLIENTE_MERF_FINANCIERA t2 on t1.NUMERO_GUIA=t2.NUMERO_GUIA
GROUP BY t1.NUMERO_GUIA,t2.ID_PROCESO
)
select
cte.NUMERO_GUIA	
,EZU = SUM(cte.EZU)	
,SZU = SUM(cte.SZU)	
,ERG = SUM(cte.ERG)	
,SRG = SUM(cte.SRG)
INTO #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_1
FROM CTE cte
GROUP BY cte.NUMERO_GUIA	


select 
T1.NUMERO_GUIA,
(T1.ERG+T1.EZU+T1.SRG+T1.SZU) AS Cantidad_procesamiento_REAL,
(
IIF(T1.ERG>0,1,0)
+
IIF(T1.EZU>0,1,0)
+
IIF(T1.SRG>0,1,0)
+
IIF(T1.SZU>0,1,0)
)
AS Cantidad_procesamiento_ideal
INTO #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_2
from #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_1 T1;


----UPDATE FACT SET
SELECT
FACT.NUMERO_GUIA,
TMP.Cantidad_procesamiento_ideal AS TMP_Cantidad_procesamiento_ideal,
TMP.Cantidad_procesamiento_REAL AS TMP_Cantidad_procesamiento_REAL,
FACT.Cantidad_procesamiento_ideal AS FACT_Cantidad_procesamiento_ideal,
FACT.Cantidad_procesamiento_REAL AS  FACT_Cantidad_procesamiento_REAL
--FACT.Cantidad_procesamiento_ideal=TMP.Cantidad_procesamiento_ideal,
--FACT.Cantidad_procesamiento_REAL =TMP.Cantidad_procesamiento_REAL
FROM [SIG_LOGISTICA_DM].[FAC].[MOBIPE_CONSOLIDADO_MERF_FINANCIERA_DETALLE_COSTO] FACT WITH(NOLOCK)
INNER JOIN #GUIAS_NUEVA_SOLICITUD_20230712_PARTE_2 TMP ON FACT.NUMERO_GUIA=TMP.NUMERO_GUIA




