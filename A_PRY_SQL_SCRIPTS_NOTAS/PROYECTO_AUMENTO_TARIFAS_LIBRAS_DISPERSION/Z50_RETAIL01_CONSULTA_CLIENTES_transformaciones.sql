								WHEN PESO_CONSOLIDADO >4 AND TEMP.PESO_CONSOLIDADO <=4.5 THEN '4.1-4.5'
								WHEN PESO_CONSOLIDADO >4.5 AND TEMP.PESO_CONSOLIDADO<=5 THEN '4.51-5'
								WHEN PESO_CONSOLIDADO >5 AND TEMP.PESO_CONSOLIDADO<=5.5 THEN '5.1-5.5'
								WHEN PESO_CONSOLIDADO >5.5 AND TEMP.PESO_CONSOLIDADO<=6 THEN '5.51-6'
								WHEN PESO_CONSOLIDADO >6 AND TEMP.PESO_CONSOLIDADO<=10 THEN '6.1-10'
								WHEN PESO_CONSOLIDADO >10 AND TEMP.PESO_CONSOLIDADO<=20 THEN '10.1-20'
								WHEN PESO_CONSOLIDADO >20 AND TEMP.PESO_CONSOLIDADO<=30 THEN '20.1-30'
								WHEN PESO_CONSOLIDADO > 30 THEN 'Mayor a 30'
								ELSE '0-1' END
			,TEMP.PESO_CONSOLIDADO
			,TEMP.REGIONAL_ORIGEN
			,TEMP.CIUDAD_ORIGEN
			,TEMP.REGIONAL_DESTINO
			,TEMP.CIUDAD_DESTINO
			,TEMP.CANAL
			,TEMP.VALOR_FACTURADO
			,TEMP.NUMERO_PIEZAS
			,TEMP.GUIA_MOVILIZADA
			,TEMP.FLETE
			,TEMP.SOBRE_FLETE
			,TEMP.DESCUENTO
			,TEMP.NOMBRE_MEDTRANS
			,TEMP.NOMBRE_FORMAPAGO
			,TEMP.NOMBRE_TIEMPO
			,TEMP.VALOR_RECAUDO
			,TEMP.CON_RECAUDO
			FROM  SIG_COL_LOGISTICA_DW.[TMP].[MOBIPE_RETAIL_USUARIOS_CREA_ENVIOS] TEMP WITH(NOLOCK)
			----WHERE TEMP.NUMERO_PIEZAS is null
