  TRF.[CANAL]='RETAIL' 
  AND YEAR(TRF.FECHA_ENVIO)*100+MONTH(TRF.FECHA_ENVIO)=@FECHA_ID_MES
  AND ID_PRODUCTO IN(1,2,6)
  AND G.State=1

