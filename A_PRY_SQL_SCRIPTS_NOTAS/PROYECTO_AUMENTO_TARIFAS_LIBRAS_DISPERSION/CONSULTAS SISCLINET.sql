WITH CTE
(
ID,
GUIA,
ID_PRODUCTO,
FECHA_ENVIO,
ID_TRAYECTO,
PESO_VOLUMETRICO,
PESO_FISICO,
ID_CIUDAD_ORIGEN,
ID_CIUDAD_DESTINO,
CANAL
)
AS
(
SELECT  
ROW_NUMBER ( )   OVER ( PARTITION BY G.NUMERO_GUIA ORDER BY G.FECHA_ENVIO DESC )  ID  
,G.NUMERO_GUIA AS GUIA 
,G.ID_PRODUCTO AS ID_PRODUCTO
,G.FECHA_ENVIO AS FECHA_ENVIO     
,MC.ID_TIPOTRAY AS ID_TRAYECTO     
,G.PESO_VOLU_OPERA AS PESO_VOLUMETRICO 
,G.PESO_FISICO_OPERA AS PESO_FISICO     
,G.ID_CIUDAD_ORIGEN AS ID_CIUDAD_ORIGEN     
,G.ID_CIUDAD_DESTINO AS ID_CIUDAD_DESTINO     
,UPPER('Sisclinet') AS CANAL 
FROM GUIAS AS G WITH(NOLOCK)
INNER JOIN PAR.MATRIZ_CIUDADES MC WITH(NOLOCK)
ON MC.ID_CIUDAD_ORIG = G.ID_CIUDAD_ORIGEN 
AND MC.ID_CIUDAD_DEST =G.ID_CIUDAD_DESTINO
AND MC.ID_ESTADO_TRAY = 1
INNER JOIN PAR.PROCESO_LIQUIDACION_SUBPROD LS WITH(NOLOCK) 
ON LS.ID_PRODUCTO =G.ID_PRODUCTO 
AND LS.ID_LIQUIDASUBPROD = 1 
AND LS.ID_GRUPMATRIZ = MC.ID_GRUPMATRIZ
WHERE 
ID_CLIENTE IS NOT NULL AND 
CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,G.FECHA_ENVIO))) 
>= CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,'2022-08-01')))     
AND 
CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,G.FECHA_ENVIO))) 
< CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,'2022-08-02')))     

)
SELECT * FROM CTE
WHERE ID=1