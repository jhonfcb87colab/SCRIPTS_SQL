		WHEN PESO_CONSOLIDADO >5 AND PESO_CONSOLIDADO<=5.5 THEN '5.1-5.5'
		WHEN PESO_CONSOLIDADO >5.5 AND PESO_CONSOLIDADO<=6 THEN '5.51-6'
		WHEN PESO_CONSOLIDADO >6 AND PESO_CONSOLIDADO<=10 THEN '6.1-10'
		WHEN PESO_CONSOLIDADO >10 AND PESO_CONSOLIDADO<=20 THEN '10.1-20'
		WHEN PESO_CONSOLIDADO >20 AND PESO_CONSOLIDADO<=30 THEN '20.1-30'
		WHEN PESO_CONSOLIDADO > 30 THEN 'Mayor a 30'
		ELSE '0-1' END TIPO_PESO 
      ,[PESO_CONSOLIDADO]
      ,[PESO_VOLUMETRICO]
      ,[PESO_FISICO]
	  ,-888 ID_REGIONAL_ORIGEN
	  ,'NO DISPONIBLE' REGIONAL_ORIGEN
	  ,[ID_CIUDAD_ORIGEN]
	  ,'NO DISPONIBLE' CIUDAD_ORIGEN
	  ,-888 ID_REGIONAL_DESTINO
	  ,'NO DISPONIBLE' REGIONAL_DESTINO
      ,[ID_CIUDAD_DESTINO]
	  ,'NO DISPONIBLE' CIUDAD_DESTINO
      ,[CANAL]
      ,[FECHA_EXTRACCION]
  FROM SIG_COLOMBIA_DW.[TMP].[MOBIPETARIF_GUIAS_P02] WITH (NOLOCK) where [GUIA] IN(9164190222,9164281944,9161909328)