WITH CTE(
ID,
GUIA,
ID_PRODUCTO,
FECHA_ENVIO,
ID_TRAYECTO,
PESO_CONSOLIDADO,
PESO_VOLUMETRICO,
PESO_FISICO,
ID_CIUDAD_ORIGEN,
ID_CIUDAD_DESTINO,
CANAL,
FECHA_EXTRACCION
)AS(
SELECT
	  ROW_NUMBER() OVER (PARTITION BY [GUIA] ORDER BY [FECHA_ENVIO] DESC) ID
	  ,[GUIA]
      ,[ID_PRODUCTO]
      ,[FECHA_ENVIO]
      ,[ID_TRAYECTO]
      ,CASE 
	  WHEN  ISNULL([PESO_VOLUMETRICO],1) > ISNULL([PESO_FISICO],1) THEN [PESO_VOLUMETRICO]
	  ELSE [PESO_FISICO]  END AS PESO_CONSOLIDADO
      ,[PESO_VOLUMETRICO] 
	  ,[PESO_FISICO]
      ,[ID_CIUDAD_ORIGEN]
      ,[ID_CIUDAD_DESTINO]
      ,[CANAL]
      ,[FECHA_EXTRACCION]
  FROM [TMP].[MOBIPETARIF_GUIAS_P01]
  )
  SELECT * FROM CTE
  WHERE ID=1

SELECT [GUIA]
      ,[ID_PRODUCTO]
	  ,'NO DISPONIBLE' PRODUCTO
      ,[FECHA_ENVIO]
      ,[ID_TRAYECTO]
	  ,'NO DISPONIBLE' TIPO_TRAYECTO
	  ,CASE
		--WHEN PESO_CONSOLIDADO BETWEEN(0 AND 1) THEN '0-1'
		WHEN PESO_CONSOLIDADO >1 AND PESO_CONSOLIDADO <= 1.5 THEN '1.1-1.5'
