USE SIG_COL_LOGISTICA_DW;
DECLARE @ANIOMES AS INT = 202201;
SELECT NUMERO_GUIA  FROM [FAC].[MOBIPE_REATIL_USUARIO_ENVIOS] with(nolock) 
WHERE AÑO_MES=@ANIOMES
AND CEDULA IS NULL


--SELECT FECHA_MODIFICACION_DG FROM SIG_COLOMBIA_DW.LOG.GUIAS G with(nolock)
--SELECT ID_REMITE FROM SIG_COLOMBIA_DW.LOG.GUIAS with(nolock)  WHERE NUMERO_GUIA=9144233629

WITH CTE_CEDULA AS(
		SELECT 
		ROW_NUMBER ( )   OVER ( PARTITION BY G.NUMERO_GUIA order by G.FECHA_MODIFICACION_DG desc )  ROW_ID,
		TEMP_RT.NUMERO_GUIA,
		CEDULA = G.ID_REMITE
		FROM [FAC].[MOBIPE_REATIL_USUARIO_ENVIOS] TEMP_RT with(nolock)
		INNER JOIN SIG_COLOMBIA_DW.LOG.GUIAS G with(nolock)
		ON  TEMP_RT.NUMERO_GUIA=G.NUMERO_GUIA
		WHERE G.ID_REMITE IS NOT NULL
		AND TEMP_RT.CEDULA IS NULL
)
SELECT ---*
TEMP_RT.NUMERO_GUIA,
--UPDATE TEMP_RT SET
CEDULA = CTE.CEDULA
FROM CTE_CEDULA CTE with(nolock)
INNER JOIN [FAC].[MOBIPE_REATIL_USUARIO_ENVIOS] TEMP_RT with(nolock)
ON  TEMP_RT.NUMERO_GUIA=CTE.NUMERO_GUIA