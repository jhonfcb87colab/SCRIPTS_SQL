SELECT  
G.Number as NUMERO_GUIA,
--C.identification as CEDULA
(case when C.identification is null then C_aux.identification else C.identification end) as CEDULA
,S.SenderName +' '+ S.SenderSurname as USUARIO
,NULL as FECHA_CREACION_USUARIO
, NULL as ENVIOS_POR_MES
, year(i.invoicedate)*100+month(i.invoicedate) AÑO_MES
,P.[ID_PRODUCTO]
,P.[NOMBRE_PRODUCTO]
,NULL AS [PERIODO_YYYY_MM_DD]-------------
,i.invoicedate as [FECHA_ENVIO]
,T.[ID_TIPOTRAY]
,T.[NOMBRE_TIPOTRAY]
,NULL AS TIPO_PESO -------------
,G.BilledWeight AS PESO_CONSOLIDADO
,RO.NOMBRE_REGIONAL AS [REGIONAL_ORIGEN]
,CO.NOMBRE_CIUDAD AS [CIUDAD_ORIGEN]
,RD.NOMBRE_REGIONAL [REGIONAL_DESTINO]
,CD.NOMBRE_CIUDAD AS [CIUDAD_DESTINO]
,'RETAIL' AS [CANAL] 
,ID.TotalValue AS VALOR_FACTURADO
,CASE P.[ID_PRODUCTO] WHEN 1 THEN 1 WHEN 2 tHEN 1 ELSE NULL END AS  [NUMERO_PIEZAS]
,0 AS GUIA_MOVILIZADA
,G.Freight AS FLETE
,G.OnFreight AS SOBRE_FLETE
,ID.DiscountValue AS DESCUENTO
,MT.[NOMBRE_MEDTRANS]
,FP.[NOMBRE_FORMAPAGO] AS[NOMBRE_FORMAPAGO]
,TE.[NOMBRE_TIEMPO],
CASE ID.PaymentFormId WHEN 4 THEN ID.TotalValue ELSE 0 END AS VALOR_RECAUDO,
CASE ID.PaymentFormId WHEN 4 THEN 1 ELSE 0 END as CON_RECAUDO
,s.senderAddress as DIRECCION_REMITENTE, s.senderEmail as MAIL_REMITENTE, s.SenderPhoneNumber as TELEFONO_REMITENTE
FROM INVOICE AS I WITH(NOLOCK)
INNER JOIN InvoiceDetail AS ID WITH(NOLOCK) ON ID.InvoiceId = I.Id
INNER JOIN Guide AS G WITH(NOLOCK) ON G.InvoiceDetailId = ID.Id
INNER JOIN Shipping AS S WITH(NOLOCK) ON S.GuideId = g.ID
LEFT JOIN [dbo].[Customer] AS C WITH(NOLOCK) ON C.ID=S.SenderCustomerId
LEFT JOIN RetailWebR4.[dbo].[Customer] AS C_aux WITH(NOLOCK) ON C_aux.ID=S.SenderCustomerId
left JOIN [PARAMETROS_MDM].[dbo].[TIPOTRAYECTO] T (NOLOCK) ON T.ID_PAIS=1 AND T.[ID_TIPOTRAY]=G.RouteTypeId
left JOIN [PARAMETROS_MDM].[dbo].[PRODUCTOS] P (NOLOCK) ON P.ID_PAIS=1 AND P.ID_PRODUCTO=ID.ProductId
left JOIN [PARAMETROS_MDM].[dbo].[MEDIOTRANSPORTE] MT (NOLOCK) ON MT.ID_PAIS=1 AND MT.[ID_MEDTRANS]=G.MeanTransportId
left JOIN [PARAMETROS_MDM].[dbo].[FORMAPAGO] FP (NOLOCK) ON FP.ID_PAIS=1 AND FP.[ID_FORMAPAGO]=ID.PaymentFormId
left JOIN [PARAMETROS_MDM].[dbo].[TIEMPOSENTREGA] TE (NOLOCK) ON TE.ID_PAIS=1 AND TE.[ID_TIEMPO]=G.DeliveryTimeId
left JOIN [PARAMETROS_MDM].[dbo].CIUDADES CO (NOLOCK) ON CO.ID_PAIS=1 AND CO.ID_CIUDAD=S.SenderCityId
left JOIN [PARAMETROS_MDM].[dbo].REGIONALES_PAIS RO (NOLOCK) ON RO.ID_PAIS=1 AND RO.ID_REGIONAL=CO.[ID_REGIONAL]
left JOIN [PARAMETROS_MDM].[dbo].CIUDADES CD (NOLOCK) ON CD.ID_PAIS=1 AND CD.ID_CIUDAD=S.ReceiverCityId
left JOIN [PARAMETROS_MDM].[dbo].REGIONALES_PAIS RD (NOLOCK) ON RD.ID_PAIS=1 AND RD.ID_REGIONAL=CD.[ID_REGIONAL]
  where (year(i.invoicedate)*100+month(i.invoicedate))=@ANIOMES 
