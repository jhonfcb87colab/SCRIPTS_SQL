/*******************     PASO 1 GENERAR GUIAS LIMPIAS        ************************/
DROP TABLE IF EXISTS #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P01
SELECT TOP 20000 
G.NUMERO_GUIA AS G_NUMERO_GUIA
,CRC.*
INTO #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P01
FROM MECE_LOGISTICO.DBO.GUIAS G (NOLOCK)
--INNER JOIN TMP_BORRAR_LOCAL.DBO.CRC_GUIAS_NACIONAL CRC (NOLOCK)
INNER JOIN MECE_Historico.DBO.CRC_GUIAS_NACIONAL CRC (NOLOCK)
ON G.NUMERO_GUIA=CRC.NUMERO_GUIA
WHERE
--G.FECHA_ENVIO BETWEEN @FECHA_INI AND @FECHA_FIN
CRC.ANNO_CRC=@ANIO /*AND CRC.TRIMESTRE_CRC=4*/
AND G.FECHA_ENTREGA IS NOT NULL 
AND G.ID_ESTADOGUIA=8 AND G.ID_ESTADOENVIO=3 AND G.ID_CLIENTE IS NOT NULL
AND G.ID_PRODUCTO IN(1,2) AND (G.PESO_FISICO_OPERA BETWEEN 1 AND 4) AND G.NUMERO_PIEZAS=1 AND G.ID_CANAL>=0 
AND (
	(G.ID_CIUDAD_ORIGEN = 10 and G.ID_CIUDAD_DESTINO=10) --BOG-BOG
OR  (G.ID_CIUDAD_ORIGEN = 10 and G.ID_CIUDAD_DESTINO=30) --BOG-GIRA
OR	(G.ID_CIUDAD_ORIGEN = 5 and G.ID_CIUDAD_DESTINO=5)  --BARR-BARR
OR	(G.ID_CIUDAD_ORIGEN = 5 and G.ID_CIUDAD_DESTINO=21) --BARR-CART
OR	(G.ID_CIUDAD_ORIGEN = 60 and G.ID_CIUDAD_DESTINO=39) --MANI-PERE
OR	(G.ID_CIUDAD_ORIGEN = 35 and G.ID_CIUDAD_DESTINO=50) --IBAG-NEIV
OR	(G.ID_CIUDAD_ORIGEN = 15 and G.ID_CIUDAD_DESTINO=22) --BUCA-CUCU
OR	(G.ID_CIUDAD_ORIGEN = 85 and G.ID_CIUDAD_DESTINO=10) --TUNJ-BOG
)

DROP TABLE IF EXISTS #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P02;
SELECT GUI.NUMERO_GUIA,COUNT(1) COUNT_SZU
INTO #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P02
FROM #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P01 GUI
INNER JOIN MECE_LOGISTICO.DBO.SEGUIMIENTO_ENVIO SEG (NOLOCK) 
ON SEG.NUMERO_GUIA=GUI.NUMERO_GUIA
WHERE SEG.ID_PROCESO=9
GROUP BY GUI.NUMERO_GUIA
HAVING COUNT(SEG.ID_PROCESO)<=1

/*******************     PASO 2 IMPORTAR RPOCESOS LOGISTICOS        ************************/

DROP TABLE IF EXISTS #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P03_SEGUIMIENTO_ENVIO;
;WITH CTE AS(
SELECT 
ROW_NUMBER ( )   OVER ( PARTITION BY TBL.[NUMERO_GUIA] order by SEG.FECHA_HORA_MOVIMIENTO desc ) #ROW_DESC,
ROW_NUMBER ( )   OVER ( PARTITION BY TBL.[NUMERO_GUIA] order by SEG.FECHA_HORA_MOVIMIENTO ASC )  #ROW_ASC,
SEG.*
FROM #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P02 TBL
INNER JOIN MECE_LOGISTICO.DBO.SEGUIMIENTO_ENVIO SEG (NOLOCK) 
ON SEG.NUMERO_GUIA=TBL.NUMERO_GUIA
WHERE SEG.ID_PROCESO NOT IN(1,2,3)
)SELECT * 
INTO #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P03_SEGUIMIENTO_ENVIO
FROM CTE 


/*******************     PASO 3 CONTAR POR GUIA SALIDAS A ZONA URBANA SZU        ************************/

DROP TABLE IF EXISTS #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P04_SZU;
SELECT 
NUMERO_GUIA,
COUNT(1) CT_SZU
INTO #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P04_SZU
FROM #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P03_SEGUIMIENTO_ENVIO
WHERE ID_PROCESO=9
GROUP BY NUMERO_GUIA

/*******************     PASO 4  BUSCAR TIPO ENVIO    ************************/

DROP TABLE IF EXISTS #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P04_1_TIPO_ENVIO;
SELECT 
NUMERO_GUIA,ID_TIPOENVIO
INTO #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P04_1_TIPO_ENVIO
FROM #TABLA_TEMPORAL_MINTIC_REQ01_NACIONAL_P03_SEGUIMIENTO_ENVIO
WHERE ID_PROCESO=9
GROUP BY NUMERO_GUIA,ID_TIPOENVIO

