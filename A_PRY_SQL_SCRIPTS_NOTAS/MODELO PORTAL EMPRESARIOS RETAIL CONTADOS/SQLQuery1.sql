SELECT 
	 P.FECHA_VENTA
	,P.ID_PAIS
	,P.ID_CIUDAD
	,P.ID_DIVISION
	,F.NUMEROPLANILLA
	,CO.DESCRIPCION_CONCEPTO
	,F.COMPLEMENTO
	,F.ID_PRODUCTO_TERCERO
	,F.VALORFALTANTE
	,F.SALDO_FALTANTE
	,F.ID_FALTANTE
	,P.TOTALCOD
FROM	
	FALTANTES F WITH (NOLOCK)
INNER JOIN 
	PLANILLAS P WITH (NOLOCK)
ON 
	F.NUMEROPLANILLA = P.NUMEROPLANILLA
INNER JOIN
	CONCEPTOS_FALTANTES_SOBRANTES CO WITH (NOLOCK)
ON 
	F.ID_CONCEPTO_FALTANTE = CO.ID_CONCEPTO_FS
AND 
	 CO.TIPOCONCEPTO = 'F'
WHERE 
	F.SALDO_FALTANTE >= 1
AND
	P.IDMOVIMIENTO >= 1
