
USE Mece_Logistico;

SELECT 
    G.ID_1 ID_PAIS, 
    G.ID_2 ID_CIUDAD, 
    G.ID_CANAL ID_DIVISION, 
    G.NUMERO_GUIA AS NUMEROFACTURACT, 
    G.FECHA_ENVIO, G.ID_CIUDAD_DESTINO,  
    ISNULL(gia.ID_FORMAPAGO_OPER,1) ID_FORMA_PAGO,
    ISNULL(G.VALOR_FLETES_GUIAS, 0) + ISNULL(G.VALOR_SEG_MAN_GUIAS, 0) - ISNULL(G.VALOR_DESCUENTO_GUIAS, 0) AS VALOR_GUIA
FROM GUIAS G WITH (NOLOCK) 
   LEFT JOIN GUIAS_INF_ADICIONAL gia with (nolock) ON gia.NUMERO_GUIA = G.NUMERO_GUIA  
  WHERE ID_1 = 1
  AND ID_ESTADOGUIA >= 3  
  AND FECHA_ENVIO >=  (DATEADD(MM, DATEDIFF(MM, 0,  DATEADD(MONTH, -1,GETDATE())), 0))
--BETWEEN convert(VARCHAR(10),@P_FECHA_ENVIO_DESDE,112) AND convert(VARCHAR(10),@P_FECHA_ENVIO_HASTA,112)  
  AND ID_TIPOGUIA IN (2,21,39,40,41,55,62)