		--ISNULL(DATEDIFF(MI,TAREAS.FECHA_CREACION,GETDATE()),0) AS TIEMPO_TOTAL, /*CALCULO ANTERIOR*/
		COUNT(DISTINCT(TAREAS.ID_TAREA)) AS NUM_TAREAS_RESUELTAS,
		ISNULL(TAREAS.FECHA_RESPUESTA_TAREA,0) AS FECHA_RESPUESTA_TAREA,
		ISNULL(TAREAS.FECHA_MODIFICACION,0) AS FECHA_MODIFICACION,
		ISNULL(TAREAS.FECHA_CREACION,0)  AS FECHA_CREACION_TAREA
