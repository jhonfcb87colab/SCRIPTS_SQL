		(
		((TAREAS.FECHA_CREACION >= @FECHA_INICIAL) OR (TAREAS.FECHA_MODIFICACION >= @FECHA_INICIAL))
		AND  
		((TAREAS.FECHA_CREACION < @FECHA_FINAL) OR (TAREAS.FECHA_MODIFICACION < @FECHA_FINAL))
