USE SIG_COLOMBIA_DW;
DECLARE @FECHA_INI DATETIME = DATEADD(yy,0,DATEADD(yy,DATEDIFF(yy,0,GETDATE()),0));
DECLARE @FECHA_FIN DATETIME = DATEADD(DAY,1,CONVERT(DATETIME,CONVERT(DATE,GETDATE())));
DROP TABLE IF EXISTS #TEMPORAL_GUIAS_CON_ULTIMO_PROCESO_LOGISTICO_SLAIDAD_A_DISTRIBUCION;

WITH CTE_GUIAS_CON_ULTIMO_PROCESO_LOGISTICO_SLAIDAD_A_DISTRIBUCION_01
AS(
	SELECT ROW_NUMBER ( )   OVER ( PARTITION BY GUI.[NUMERO_GUIA] order by SEG.FECHA_HORA_MOVIMIENTO desc )  #ROW_ID  
		,GUI.[NUMERO_GUIA]
		,SEG.ID_PROCESO
	FROM LOG.GUIAS GUI WITH(NOLOCK)
	INNER JOIN  LOG.SEGUIMIENTO_ENVIO SEG WITH (NOLOCK)
	ON GUI.NUMERO_GUIA=SEG.NUMERO_GUIA
	WHERE 
	SEG.FECHA_HORA_MOVIMIENTO BETWEEN @FECHA_INI AND @FECHA_FIN AND ID_PROCESO=9 
	AND GUI.ID_ESTADOENVIO IN (1,2,5,6,7) 
)
SELECT 
CTE.NUMERO_GUIA,
CTE.ID_PROCESO
INTO #TEMPORAL_GUIAS_CON_ULTIMO_PROCESO_LOGISTICO_SLAIDAD_A_DISTRIBUCION
FROM CTE_GUIAS_CON_ULTIMO_PROCESO_LOGISTICO_SLAIDAD_A_DISTRIBUCION_01 CTE
WHERE #ROW_ID  = 1;



WITH CTE_GUIAS_CON_ULTIMO_PROCESO_LOGISTICO_SLAIDAD_A_DISTRIBUCION_02 AS(
	SELECT ROW_NUMBER ( )   OVER ( PARTITION BY TEMP.[NUMERO_GUIA] order by SEG.FECHA_HORA_MOVIMIENTO desc )  #ROW_ID  
		,TEMP.[NUMERO_GUIA]
		,SEG.ID_PROCESO
		,SEG.NUMERO_MOVIMI
		,SEG.CONSECUT_MOVIMI
		,SEG.FECHA_HORA_MOVIMIENTO
FROM #TEMPORAL_GUIAS_CON_ULTIMO_PROCESO_LOGISTICO_SLAIDAD_A_DISTRIBUCION TEMP
	INNER JOIN  LOG.SEGUIMIENTO_ENVIO SEG WITH (NOLOCK)
	ON TEMP.NUMERO_GUIA=SEG.NUMERO_GUIA
)
SELECT 
 CTE.NUMERO_GUIA
,CTE.ID_PROCESO	
,CTE.NUMERO_MOVIMI	
,CTE.CONSECUT_MOVIMI	
,CTE.FECHA_HORA_MOVIMIENTO
FROM CTE_GUIAS_CON_ULTIMO_PROCESO_LOGISTICO_SLAIDAD_A_DISTRIBUCION_02 CTE
WHERE CTE.#ROW_ID=1 AND CTE.ID_PROCESO=9;