;WITH CIL AS (
SELECT 
	ROW_NUMBER() OVER(PARTITION BY SEG.NUMERO_GUIA ORDER BY SEG.FECHA_HORA_MOVIMIENTO DESC) as #ROW,
	1 AS X
	
	---,DIV.NOMBRE_DIVISION AS NOMBRE_DIVISION_UBICACION
	,DIVISION_UBICACION = CASE WHEN SEG.ID_PROCESO IN(7,12,9) THEN DOC.ID_DIVISION_ORIGEN
								WHEN SEG.ID_PROCESO IN(5,6,8,10,14,15,17,19,20,21) THEN DOC.ID_DIVISION_DESTINO
								ELSE DOC.ID_DIVISION_DESTINO END
	,G.NUMERO_GUIA	
	
	--,ISNULL(CIUUBICA.NOMBRE_CIUDAD,'NA') AS NOMBRE_CIUDAD_UBICACION   ---ISNULL(DOC.ID_CIUDAD_DESTINO,0) 
	,ID_CIUDAD_UBICACION =  CASE WHEN SEG.ID_PROCESO IN(7,12,9) THEN DOC.ID_CIUDAD_DIVISION_ORIGEN
								WHEN SEG.ID_PROCESO IN(5,6,8,10,14,15,17,19,20,21) THEN DOC.ID_CIUDAD_DESTINO
								ELSE DOC.ID_CIUDAD_DESTINO END	

	,ISNULL(G.ID_CIUDAD_ORIGEN,0) AS CIUDAD_ORIGEN
	,ISNULL(CIUORI.NOMBRE_CIUDAD,'' ) AS NOMBRE_CIUDAD_ORIGEN
	,ISNULL(G.ID_CIUDAD_DESTINO,0) AS CIUDAD_DESTINO
	,ISNULL(CIUDEST.NOMBRE_CIUDAD,'' ) AS NOMBRE_CIUDAD_DEST
	,ISNULL(G.ID_CLIENTE, '' ) AS CLIENTE,ISNULL(CLI.NOMBRE_CLIENTE,'' ) AS NOMBRE_CLIENTE
	,ISNULL(DEP.DIRECCION_PRINCIPAL_DEPENDEN,'' ) AS DIRECCION_DEPENDENCIA,ISNULL(G.ID_CANAL,'' ) AS CANAL
	,ISNULL(CAN.NOMBRE_DIVISION,'' ) AS NOMBRE_CANAL,
	G.PESO_VOLU_OPERA,G.PESO_FISICO_OPERA,G.LARGO_ENV_OPERA,G.ANCHO_ENV_OPERA,G.ALTO_ENV_OPERA,G.NUMERO_PIEZAS,
	ISNULL(PR.ID_PROCESO,'')AS ID_PROCESO,
	ISNULL(PR.NOMBRE_PROCESO_LOG,'' ) AS NOMBRE_PROCESO_LOG ,
	ISNULL(TIPENV.NOMBRE_TIPOENVIO,'' ) AS NOMBRE_TIPOENVIO, G.FECHA_ENVIO,
	LEFT(CAST(SEG.FECHA_HORA_MOVIMIENTO AS VARCHAR(20)),11) AS FECHA_MODIFICACION,
	SUBSTRING(CAST(SEG.FECHA_HORA_MOVIMIENTO AS VARCHAR(20)),13,8) AS HORA_MODIFICACION,
	ISNULL(G.NU_DOCU_ULT_MOVI,'' ) AS NUMMANIF,
	ISNULL(G.CONS_DOCU_ULT_MOVI, 0) As CONS_MANIFIESTO,
	ISNULL(EMP.NOMBRE_EMPLEADO,'' )  + ' '  +  ISNULL(EMP.APELLIDO_EMPLEADO,'' ) AS NOMBRE_EMPLEADO,
	ISNULL(G.ID_PRODUCTO, 0) AS CODPRO, 
	RTRIM(ISNULL(PROD.NOMBRE_PRODUCTO, '')) AS NOMPRO,
	ISNULL(G.ID_SUBPRODUCTO, 0) AS CODSUBPRO, 
	RTRIM(ISNULL(SPROD.NOMBRE_SUBPRODUCTO, '')) AS NOMSUBPRO,
	G.ID_MEDTRANS,
	G.ID_TIEMPO AS TIMEID,
	DOC.ID_ZONA_URBA,
	DOC.ID_TIPO_ZONA_URBA
FROM #LOG_GUIAS_TABLA_TEMPORAL AS G WITH (NOLOCK) 
	INNER JOIN  #LOG_SEGUIMIENTO_ENVIO_TABLA_TEMPORAL AS SEG WITH (NOLOCK) ON SEG.NUMERO_GUIA = G.NUMERO_GUIA 
	INNER JOIN  #LOG_DOCUMENTOS_TABLA_TEMPORAL AS DOC WITH(NOLOCK) ON SEG.ID_PROCESO = DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI = DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI = DOC.CONSECUT_MOVIMI
	LEFT JOIN  PAR.CIUDADES AS CIUORI WITH (NOLOCK) ON G.ID_PAIS_ORIGEN = CIUORI.ID_PAIS AND G.ID_CIUDAD_ORIGEN = CIUORI.ID_CIUDAD 
	LEFT JOIN  PAR.CIUDADES AS CIUDEST WITH (NOLOCK) ON G.ID_PAIS_DESTINO = CIUDEST.ID_PAIS AND G.ID_CIUDAD_DESTINO = CIUDEST.ID_CIUDAD 
	LEFT JOIN  PAR.CLIENTES AS CLI WITH (NOLOCK) ON G.ID_CLIENTE = CLI.ID_CLIENTE 
	LEFT JOIN  PAR.CLIENTES_SUCURSALES_DEPENDEN AS DEP WITH (NOLOCK) ON G.ID_CLIENTE = DEP.ID_CLIENTE AND G.ID_1 = DEP.ID_SUCURSAL AND G.ID_2 = DEP.ID_DEPENDEN 
	LEFT JOIN  PAR.DIVISIONES AS CAN WITH (NOLOCK) ON 1 = DOC.ID_PAIS_DESTINO AND DOC.ID_CIUDAD_DESTINO = CAN.ID_CIUDAD AND DOC.ID_DIVISION_DESTINO = CAN.ID_DIVISION 
	LEFT JOIN  PAR.PROCESOS AS PR WITH (NOLOCK) ON PR.ID_PROCESO =  SEG.ID_PROCESO
	LEFT JOIN  PAR.TIPO_ENVIO AS TIPENV WITH (NOLOCK) ON SEG.ID_TIPOENVIO = TIPENV.ID_TIPOENVIO 
	LEFT JOIN  PAR.EMPLEADOS AS EMP WITH (NOLOCK) ON SEG.ID_EMPLEADO = EMP.ID_EMPLEADO 
	LEFT JOIN  PAR.PRODUCTOS  AS PROD WITH (NOLOCK) ON G.ID_PRODUCTO = PROD.ID_PRODUCTO 
	LEFT JOIN  PAR.SUBPRODUCTOS AS SPROD WITH (NOLOCK) ON G.ID_PRODUCTO = SPROD.ID_PRODUCTO AND G.ID_SUBPRODUCTO = SPROD.ID_SUBPRODUCTO 
)
SELECT 
			----#ROW,
			X,
			DIVISION_UBICACION,
			DIV.NOMBRE_DIVISION NOMBRE_DIVISION_UBICACION,
			NUMERO_GUIA,
			ID_CIUDAD_UBICACION,
			----CIUUBICA.NOMBRE_CIUDAD NOMBRE_CIUDAD_UBICACION,
			CIL.CIUDAD_ORIGEN,
			CIL.NOMBRE_CIUDAD_ORIGEN,
			CIL.CIUDAD_DESTINO,
			CIL.NOMBRE_CIUDAD_DEST,
			CIL.CLIENTE,
			CIL.NOMBRE_CLIENTE,
			CIL.DIRECCION_DEPENDENCIA,
			CIL.CANAL,
			CIL.NOMBRE_CANAL,
			CIL.PESO_VOLU_OPERA,
			CIL.PESO_FISICO_OPERA,
			CIL.LARGO_ENV_OPERA,
			CIL.ANCHO_ENV_OPERA,
			CIL.ALTO_ENV_OPERA,
			CIL.NUMERO_PIEZAS,
			CIL.ID_PROCESO,
			CIL.NOMBRE_PROCESO_LOG,
			CIL.NOMBRE_TIPOENVIO,
			CIL.FECHA_ENVIO,
			CIL.FECHA_MODIFICACION,
			CIL.HORA_MODIFICACION,
			CIL.NUMMANIF,
			CIL.CONS_MANIFIESTO,
			CIL.NOMBRE_EMPLEADO,
			CIL.CODPRO,
			CIL.NOMPRO,
			CIL.CODSUBPRO,
			CIL.NOMSUBPRO,
			CIL.ID_MEDTRANS,
			CIL.TIMEID,
			CIL.ID_ZONA_URBA,
			NOMBRE_ZONA_URBA = ZU.NOMBRE_ZONA_URBA
FROM CIL CIL WITH(NOLOCK) 
LEFT JOIN  PAR.DIVISIONES AS DIV WITH (NOLOCK) ON 1 = DIV.ID_PAIS AND CIL.ID_CIUDAD_UBICACION = DIV.ID_CIUDAD AND CIL.DIVISION_UBICACION = DIV.ID_DIVISION
LEFT JOIN  PAR.CIUDADES AS CIUUBICA WITH (NOLOCK) ON 1 = CIUUBICA.ID_PAIS AND CIL.ID_CIUDAD_UBICACION = CIUUBICA.ID_CIUDAD 
LEFT JOIN  PAR.ZONASURBANAS ZU WITH(NOLOCK) ON ZU.ID_PAIS = 1 AND CIL.ID_CIUDAD_UBICACION = ZU.ID_CIUDAD AND CIL.ID_TIPO_ZONA_URBA = ZU.ID_TIPO_ZONA_URBA AND CIL.ID_ZONA_URBA = ZU.ID_ZONA_URBA  
WHERE #ROW = 1 
AND DIVISION_UBICACION IN(9304,9308,9310,9311,9316,9319,9362,9364,9365,9366,9367,9368,9373,9374,9710,9711,9764,9765,9313,9318,9312,9317,9321,9375,9377) ----PARAMETROS
AND CIL.ID_PROCESO NOT IN(9,24,25,30,31,32,33,34)
