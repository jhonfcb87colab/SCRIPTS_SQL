
USE SIG_COLOMBIA_DW;

DECLARE @FECHA_INICIAL DATETIME = CONVERT(DATETIME,'20240113');
DECLARE @FECHA_FINAL DATETIME	= CONVERT(DATETIME,'20240117');
--------------------------------------------------------------------------------------------------
DROP TABLE IF EXISTS #GUIAS_NECESARIAS_VEJEZ_BODEGAS;
CREATE TABLE #GUIAS_NECESARIAS_VEJEZ_BODEGAS(NUMERO_GUIA NUMERIC(13,0));
CREATE NONCLUSTERED INDEX [idx_GUIAS] ON #GUIAS_NECESARIAS_VEJEZ_BODEGAS
(
	[NUMERO_GUIA] ASC
)WITH (PAD_INDEX = OFF, 
STATISTICS_NORECOMPUTE = OFF, 
SORT_IN_TEMPDB = OFF, 
DROP_EXISTING = OFF, 
ONLINE = OFF, 
ALLOW_ROW_LOCKS = ON, 
ALLOW_PAGE_LOCKS = ON) 
ON [PRIMARY];


DROP TABLE IF EXISTS #LOG_GUIAS_TABLA_TEMPORAL;
DROP TABLE IF EXISTS #LOG_SEGUIMIENTO_ENVIO_TABLA_TEMPORAL;
DROP TABLE IF EXISTS #LOG_DOCUMENTOS_TABLA_TEMPORAL;


SELECT 
*
INTO #LOG_DOCUMENTOS_TABLA_TEMPORAL
FROM 
LOG.DOCUMENTOS DOC WITH(NOLOCK)
WHERE 
	DOC.FECHA_HORA_MOVIMI BETWEEN @FECHA_INICIAL AND @FECHA_FINAL
 AND (
				ID_DIVISION_DESTINO IN(9304,9308,9310,9311,9316,9319,9362,9364,9365,9366,9367,9368,9373,9374,9710,9711,9764,9765,9313,9318,9312,9317,9321,9375,9377) ----PARAMETROS
			OR 
				ID_DIVISION_ORIGEN  IN(9304,9308,9310,9311,9316,9319,9362,9364,9365,9366,9367,9368,9373,9374,9710,9711,9764,9765,9313,9318,9312,9317,9321,9375,9377) ----PARAMETROS
			)



SELECT SE.*
INTO #LOG_SEGUIMIENTO_ENVIO_TABLA_TEMPORAL
FROM LOG.SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
INNER JOIN #LOG_DOCUMENTOS_TABLA_TEMPORAL LOG_DOC_TMP
ON (SE.NUMERO_MOVIMI=LOG_DOC_TMP.NUMERO_MOVIMI AND SE.CONSECUT_MOVIMI=LOG_DOC_TMP.CONSECUT_MOVIMI AND SE.ID_PROCESO=LOG_DOC_TMP.ID_PROCESO);

INSERT INTO #GUIAS_NECESARIAS_VEJEZ_BODEGAS
SELECT NUMERO_GUIA
FROM #LOG_SEGUIMIENTO_ENVIO_TABLA_TEMPORAL WHERE LEN(NUMERO_GUIA)>8
GROUP BY NUMERO_GUIA;


SELECT G.*
INTO #LOG_GUIAS_TABLA_TEMPORAL
FROM LOG.GUIAS G WITH(NOLOCK)
INNER JOIN #GUIAS_NECESARIAS_VEJEZ_BODEGAS LOG_G_TMP ON G.NUMERO_GUIA=LOG_G_TMP.NUMERO_GUIA
WHERE G.ID_ESTADOGUIA <> 8;




