
DROP TABLE IF EXISTS #FAC_VEJEZ_BODEGAS_CONCEPTOS_FALTATES_01;
DROP TABLE IF EXISTS #FAC_VEJEZ_BODEGAS_CONCEPTOS_FALTATES_02;
DROP TABLE IF EXISTS #FAC_VEJEZ_BODEGAS_CONCEPTOS_FALTATES_03;

SELECT NUMERO_GUIA,ULT_CONCP_LOGISTICO,NOM_ULT_CONCP_LOGISTICO
  INTO #FAC_VEJEZ_BODEGAS_CONCEPTOS_FALTATES_01
  FROM [SIG_LOGISTICA_DM].[FAC].[VEJEZ_BODEGAS] WITH(NOLOCK)
  WHERE ID_PROCESO_ULT_MOV IN(5,6,7,8,10,14,15,17,19,21,33,34,35,36,39,46,47,51,52)
  AND (ULT_CONCP_LOGISTICO IS NULL
  OR NOM_ULT_CONCP_LOGISTICO IS NULL);


WITH CTE AS(
		SELECT  
		ROW_NUMBER ( )   
					OVER (		PARTITION BY SE.[NUMERO_GUIA] 
					ORDER BY SE.FECHA_HORA_MOVIMIENTO DESC )  #ROW_ID, 
		SE.ID_PROCESO,
		SE.NUMERO_GUIA,
		SE.ID_CONCEPTO
		FROM SIG_COLOMBIA_DW.LOG.SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
		INNER JOIN #FAC_VEJEZ_BODEGAS_CONCEPTOS_FALTATES_01 TMP WITH(NOLOCK)
		ON TMP.NUMERO_GUIA=SE.NUMERO_GUIA
)
SELECT * 
INTO #FAC_VEJEZ_BODEGAS_CONCEPTOS_FALTATES_02
FROM CTE WHERE #ROW_ID=1


SELECT
TMP.NUMERO_GUIA	
,TMP.ID_PROCESO	
,TMP.ID_CONCEPTO
,CP.NOMBRE_CONCEPTO
INTO #FAC_VEJEZ_BODEGAS_CONCEPTOS_FALTATES_03
FROM #FAC_VEJEZ_BODEGAS_CONCEPTOS_FALTATES_02 TMP
LEFT JOIN SIG_COLOMBIA_DW.PAR.ITEM_CONCEPTO CP WITH(NOLOCK)
ON CP.ID_CONCEPTO=TMP.ID_CONCEPTO AND CP.ID_PROCESO=TMP.ID_PROCESO
WHERE TMP.ID_PROCESO IN(5,6,7,8,10,14,15,17,19,21,33,34,35,36,39,46,47,51,52)
AND TMP.ID_CONCEPTO<>0;

/*
ULT_CONCP_LOGISTICO	int	no
NOM_ULT_CONCP_LOGISTICO	varchar	no
*/


----------------UPDATE VB SET
SELECT VB.NUMERO_GUIA,TMP.ID_PROCESO AS ID_PROCESO_TMP,VB.ID_PROCESO_ULT_MOV AS ID_PROCESO_TMP,	
ULT_CONCP_LOGISTICO = TMP.ID_CONCEPTO	
,NOM_ULT_CONCP_LOGISTICO = TMP.NOMBRE_CONCEPTO
FROM #FAC_VEJEZ_BODEGAS_CONCEPTOS_FALTATES_03 TMP
INNER JOIN SIG_LOGISTICA_DM.FAC.VEJEZ_BODEGAS VB WITH(NOLOCK)
ON VB.NUMERO_GUIA=TMP.NUMERO_GUIA



