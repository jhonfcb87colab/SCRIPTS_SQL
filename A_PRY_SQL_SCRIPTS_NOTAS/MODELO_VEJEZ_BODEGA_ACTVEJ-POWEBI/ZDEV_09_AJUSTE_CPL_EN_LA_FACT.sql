WITH CTE AS (
		SELECT VB.NUMERO_GUIA,
				TMPCDAX.CPL,
		VB.ID_REGIONAL_UBICACION,
		VB.ID_CIUDAD_UBICACION
		FROM SIG_LOGISTICA_DM.FAC.VEJEZ_BODEGAS_SZU VB WITH(NOLOCK)
		INNER JOIN SIG_COLOMBIA_DW.[TMP].[VEJEZ_BODEGAS_CIUDADES_ANEXAS] TMPCDAX WITH(NOLOCK) 
		ON (
				VB.ID_REGIONAL_UBICACION = TMPCDAX.ID_REGIONAL 
				AND VB.ID_CIUDAD_UBICACION = TMPCDAX.ID_CIUDAD 
				AND VB.ID_CIUDAD_UBICACION = TMPCDAX.ID_CIUDAD_ANEXA
			)
			WHERE VB.NUMERO_GUIA IN(
									9164288977,
									2177461832,
									2181327882
									)
)
