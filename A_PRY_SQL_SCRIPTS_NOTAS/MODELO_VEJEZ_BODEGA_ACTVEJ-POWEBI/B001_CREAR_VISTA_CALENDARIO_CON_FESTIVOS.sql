  LEFT JOIN [SIG_COLOMBIA_DW].[PAR.].[FESTIVOSNACIONALES] F WITH(NOLOCK)
  ON CONVERT(INT,[FECHA_FESTIVA])=[TIME_ID] AND F.[ID_PAIS]=1

