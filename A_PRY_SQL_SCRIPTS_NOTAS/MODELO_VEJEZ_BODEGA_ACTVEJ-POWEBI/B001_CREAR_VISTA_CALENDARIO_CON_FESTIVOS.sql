SELECT T.[TIME_ID]
      ,T.[DATE]
      ,T.[DAY]
      ,T.[MONTH]
      ,T.[YEAR]
      ,T.[DAY_OF_MONTH]
      ,T.[WEEK_OF_YEAR]
      ,T.[MONTH_OF_YEAR]
      ,T.[QUARTER_OF_YEAR]
      ,T.[SEMESTER_OF_YEAR]
      ,T.[SEMESTER]
