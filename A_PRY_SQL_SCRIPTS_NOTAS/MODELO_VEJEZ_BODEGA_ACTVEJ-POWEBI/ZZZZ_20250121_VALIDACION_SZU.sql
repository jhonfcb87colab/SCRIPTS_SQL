USE SIG_LOGISTICA_DM;
DROP TABLE IF EXISTS #GUIAS_SZU_VALIDAR_ULPRLOG;
SELECT 
NUMERO_GUIA
INTO #GUIAS_SZU_VALIDAR_ULPRLOG
FROM [FAC].[VEJEZ_BODEGAS_SZU] FAC_SZU WITH (NOLOCK)
WHERE FECHA_EXTRACCION_DM <= DATEADD(dd,DATEDIFF(dd,2,GETDATE()),0)
OPTION(RECOMPILE, OPTIMIZE FOR UNKNOWN, MAXDOP 4)

CREATE NONCLUSTERED INDEX [idx_GUIAS] ON #GUIAS_SZU_VALIDAR_ULPRLOG
([NUMERO_GUIA] ASC)
WITH(PAD_INDEX=OFF,STATISTICS_NORECOMPUTE=OFF,SORT_IN_TEMPDB=OFF,DROP_EXISTING=OFF,ONLINE=OFF,ALLOW_ROW_LOCKS=ON,ALLOW_PAGE_LOCKS=ON) 
ON [PRIMARY];

DROP TABLE IF EXISTS #GUIAS_QUE_FUERON_DIGITALIZADAS;
SELECT TMP.NUMERO_GUIA 
INTO #GUIAS_QUE_FUERON_DIGITALIZADAS
FROM #GUIAS_SZU_VALIDAR_ULPRLOG TMP
INNER JOIN SIG_COLOMBIA_DW.LOG.PRUEBAS_ENTREGA PR_ENT (NOLOCK) ON PR_ENT.NUMERO_GUIA=TMP.NUMERO_GUIA
GROUP BY TMP.NUMERO_GUIA
OPTION(RECOMPILE, OPTIMIZE FOR UNKNOWN, MAXDOP 4)

CREATE NONCLUSTERED INDEX [idx_GUIAS] ON #GUIAS_QUE_FUERON_DIGITALIZADAS
([NUMERO_GUIA] ASC)
WITH(PAD_INDEX=OFF,STATISTICS_NORECOMPUTE=OFF,SORT_IN_TEMPDB=OFF,DROP_EXISTING=OFF,ONLINE=OFF,ALLOW_ROW_LOCKS=ON,ALLOW_PAGE_LOCKS=ON) 
ON [PRIMARY];

DROP TABLE IF EXISTS #GUIAS_EVALUAR_ULTIMO_PROCESO_LOG;
;WITH CTE AS(
SELECT 
#ROWID = ROW_NUMBER() OVER(PARTITION BY TMP.NUMERO_GUIA ORDER BY SE.FECHA_HORA_MOVIMIENTO DESC)
,TMP.NUMERO_GUIA
,SE.FECHA_HORA_MOVIMIENTO
,SE.CONSECUT_MOVIMI
,SE.NUMERO_MOVIMI
,SE.ID_PROCESO
FROM SIG_COLOMBIA_DW.LOG.SEGUIMIENTO_ENVIO SE (NOLOCK)
INNER JOIN #GUIAS_SZU_VALIDAR_ULPRLOG TMP (NOLOCK)
ON TMP.NUMERO_GUIA=SE.NUMERO_GUIA
LEFT OUTER JOIN #GUIAS_QUE_FUERON_DIGITALIZADAS GUI_DIG ON TMP.NUMERO_GUIA=GUI_DIG.NUMERO_GUIA 
--OPTION(RECOMPILE, OPTIMIZE FOR UNKNOWN, MAXDOP 4)
)SELECT * 
INTO #GUIAS_EVALUAR_ULTIMO_PROCESO_LOG
FROM CTE WHERE #ROWID=1

DROP TABLE IF EXISTS #ULTIMO_PROCESO_REGISTRADO_FECHA_MAYOR_ALA_FAC;
SELECT TMP.*,PR.NOMBRE_PROCESO_LOG 
INTO #ULTIMO_PROCESO_REGISTRADO_FECHA_MAYOR_ALA_FAC
FROM #GUIAS_EVALUAR_ULTIMO_PROCESO_LOG TMP
INNER JOIN [FAC].[VEJEZ_BODEGAS_SZU] FAC (NOLOCK)
ON FAC.NUMERO_GUIA=TMP.NUMERO_GUIA
INNER JOIN SIG_COLOMBIA_DW.PAR.PROCESOS PR (NOLOCK)
ON PR.ID_PROCESO=TMP.ID_PROCESO
WHERE TMP.FECHA_HORA_MOVIMIENTO>FAC.FECHA_HORA_MOVIMIENTO
OPTION(RECOMPILE, OPTIMIZE FOR UNKNOWN, MAXDOP 4)

DROP TABLE IF EXISTS #GUIAS_DELETE_SZU;
SELECT TMPFC.NUMERO_GUIA
--,DOC.ID_DIVISION_DESTINO,DOC.ID_CIUDAD_DESTINO,DOC.ID_PAIS_DESTINO, 
--DIV.NOMBRE_DIVISION,TMPFC.NOMBRE_PROCESO_LOG
INTO #GUIAS_DELETE_SZU
FROM #ULTIMO_PROCESO_REGISTRADO_FECHA_MAYOR_ALA_FAC TMPFC
INNER JOIN SIG_COLOMBIA_DW.LOG.DOCUMENTOS DOC (NOLOCK)
ON TMPFC.ID_PROCESO=DOC.ID_PROCESO AND TMPFC.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND TMPFC.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI
INNER JOIN SIG_COLOMBIA_DW.PAR.DIVISIONES DIV (NOLOCK)
ON DOC.ID_DIVISION_DESTINO=DIV.ID_DIVISION
AND DOC.ID_CIUDAD_DESTINO=DIV.ID_CIUDAD
AND DOC.ID_PAIS_DESTINO=DIV.ID_PAIS
WHERE DIV.NOMBRE_DIVISION LIKE '%REZAGO%' OR DIV.NOMBRE_DIVISION LIKE '%COMPENSACION%'
GROUP BY TMPFC.NUMERO_GUIA
OPTION(RECOMPILE, OPTIMIZE FOR UNKNOWN, MAXDOP 4)


CREATE NONCLUSTERED INDEX [idx_GUIAS] ON #GUIAS_DELETE_SZU
([NUMERO_GUIA] ASC)
WITH(PAD_INDEX=OFF,STATISTICS_NORECOMPUTE=OFF,SORT_IN_TEMPDB=OFF,DROP_EXISTING=OFF,ONLINE=OFF,ALLOW_ROW_LOCKS=ON,ALLOW_PAGE_LOCKS=ON) 
ON [PRIMARY];

