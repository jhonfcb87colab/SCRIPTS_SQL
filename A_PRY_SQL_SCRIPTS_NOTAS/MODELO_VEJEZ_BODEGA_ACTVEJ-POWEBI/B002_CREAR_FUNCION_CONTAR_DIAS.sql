				WHERE 
				[DATE] BETWEEN @FE_INI AND @FE_FIN
			)

			SET @DIAS_RESULTADO =
							CASE	WHEN
									@DIAS_HABIL-@DIAS_FESTIVOS_Y_DOMINGOS <= 0 THEN 0
									ELSE  @DIAS_HABIL-@DIAS_FESTIVOS_Y_DOMINGOS END
			
			SELECT @DIAS_RESULTADO ------------RETURN @DIAS_RESULTADO

