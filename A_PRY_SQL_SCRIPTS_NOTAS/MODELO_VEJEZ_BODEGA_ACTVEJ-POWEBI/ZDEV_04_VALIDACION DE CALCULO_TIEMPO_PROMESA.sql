WITH CTE AS
(
	SELECT 
		 C.NUMERO_GUIA
		,C.FECHA_ENVIO SE_ID_FECHA_ENTREGA
		,CONVERT(INT,C.TIEMPO_OFERTA_DIA) SE_ID_DIAS_PROMESA
		,C.TIEMPO_OFERTA_DIA
		,C.FECHA_PROMESA_ENTREGA
	FROM
			(
			SELECT 
				 TMP.NUMERO_GUIA
				,TMP.FECHA_ENVIO
				,ISNULL(R.TIEMPO_ENTREGA_COMERCIAL_DIA,0) TIEMPO_OFERTA_DIA
				,TMP.TIEMPO_OFERTA
				,TMP.FECHA_PROMESA_ENTREGA
			FROM
					SIG_LOGISTICA_DM.FAC.VEJEZ_BODEGAS_SZU TMP WITH(NOLOCK) 
				INNER JOIN
					[SERV-DBI01,9971].SIG_COL_LOGISTICA_DW.TMP.RED_OPERATIVA_RUTA_V2 RA WITH(NOLOCK) 
				ON
					TMP.ID_CIUDAD_ORIGEN = RA.ID_CIUDAD_ORIGEN
				AND
					TMP.ID_CIUDAD_DESTINO = RA.ID_CIUDAD_DESTINO
				AND
					CASE WHEN ISNULL(TMP.ID_TIEMPO,0) <> 0 THEN TMP.ID_TIEMPO ELSE 1 END = RA.ID_TIEMPO
				AND
					CASE WHEN ISNULL(TMP.ID_MEDTRANS,0) <> 0 THEN TMP.ID_MEDTRANS ELSE 1 END = RA.ID_MEDTRANS
				INNER JOIN
					[SERV-DBI01,9971].SIG_COL_LOGISTICA_DW.DIM.RED_OPERATIVA_RUTA R WITH(NOLOCK) 
				ON
					RA.ID_RUTA = R.ID_RUTA
			WHERE TMP.NUMERO_GUIA IN(
									219553492,
									219553497,
									224485965,
									231824682,
									234146326,
									237492882,
									237492883,
									237492884)
		) C
)
SELECT * FROM 
CTE
ORDER BY NUMERO_GUIA DESC

