/******************************EXTRAER INVERIO DE MANIFIESTOS EN BODEGAS SOLICITADAS *******************************************/
INSERT INTO @LOG_DOCUMENTOS_TABLA_TEMPORAL
SELECT * FROM 
Mece_Logistico..DOCUMENTOS DOC WITH(NOLOCK)
WHERE 
	DOC.FECHA_HORA_MOVIMI BETWEEN @FECHA_INICIAL AND @FECHA_FINAL
 AND (
				ID_DIVISION_DESTINO IN(SELECT BODEGA FROM @BODEGAS ) ----PARAMETROS
			OR 
				ID_DIVISION_ORIGEN  IN(SELECT BODEGA FROM @BODEGAS ) ----PARAMETROS
			)



/******************************EXTRAER INVERIO DE GUIAS EN BODEGAS SOLICITADAS *******************************************/

INSERT INTO @LOG_SEGUIMIENTO_ENVIO_TABLA_TEMPORAL
SELECT SE.NUMERO_GUIA
FROM Mece_Logistico..SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
INNER JOIN @LOG_DOCUMENTOS_TABLA_TEMPORAL LOG_DOC_TMP
ON (SE.NUMERO_MOVIMI=LOG_DOC_TMP.NUMERO_MOVIMI AND SE.CONSECUT_MOVIMI=LOG_DOC_TMP.CONSECUT_MOVIMI AND SE.ID_PROCESO=LOG_DOC_TMP.ID_PROCESO)
GROUP BY SE.NUMERO_GUIA




/******************************EXTRAER INVERIO DE GUIAS QUE NO TENGAN MALA CAPTURA *******************************************/

INSERT INTO @GUIAS_NECESARIAS_VEJEZ_BODEGAS
SELECT NUMERO_GUIA
FROM @LOG_SEGUIMIENTO_ENVIO_TABLA_TEMPORAL WHERE LEN(NUMERO_GUIA)>8
GROUP BY NUMERO_GUIA


/******************************EXTRAER TABLA DE DBO.GUIAS CON LAS GUIAS EN BODEGA *******************************************/

INSERT INTO @LOG_GUIAS_TABLA_TEMPORAL
SELECT G.*
FROM Mece_Logistico..GUIAS G WITH(NOLOCK)
INNER JOIN @GUIAS_NECESARIAS_VEJEZ_BODEGAS LOG_G_TMP ON G.NUMERO_GUIA=LOG_G_TMP.NUMERO_GUIA
WHERE G.ID_ESTADOGUIA <> 8


/******************************EXTRAER TABLA DE DBO.SEGUIMIENTO_ENVIO CON HISTORIA DE PROCESOS LOGISTICOS DE LAS GUIAS EN BODEGA *******************************************/

INSERT INTO @LOG_SEGUIMIENTO_ENVIO_TABLA_TEMPORAL_02
