;WITH CIL AS (
SELECT 
	ROW_NUMBER() OVER(PARTITION BY SEG.NUMERO_GUIA ORDER BY 
						IIF(SEG.FECHA_HORA_MOVIMIENTO>DOC.FECHA_HORA_MOVIMI,SEG.FECHA_HORA_MOVIMIENTO,DOC.FECHA_HORA_MOVIMI)
						DESC) as #ROW,
	1 AS X
	,DIVISION_UBICACION = CASE WHEN SEG.ID_PROCESO IN(7,12,9) THEN DOC.ID_DIVISION_ORIGEN
								WHEN SEG.ID_PROCESO IN(5,6,8,10,14,15,17,19,20,21) THEN DOC.ID_DIVISION_DESTINO
								ELSE DOC.ID_DIVISION_DESTINO END
	,G.NUMERO_GUIA	
	,ID_CIUDAD_UBICACION =  CASE WHEN SEG.ID_PROCESO IN(7,12,9) THEN DOC.ID_CIUDAD_DIVISION_ORIGEN
								WHEN SEG.ID_PROCESO IN(5,6,8,10,14,15,17,19,20,21) THEN DOC.ID_CIUDAD_DESTINO
								ELSE DOC.ID_CIUDAD_DESTINO END	

	,ISNULL(G.ID_CIUDAD_ORIGEN,0) AS CIUDAD_ORIGEN
	,ISNULL(CIUORI.NOMBRE_CIUDAD,'' ) AS NOMBRE_CIUDAD_ORIGEN
	,ISNULL(G.ID_CIUDAD_DESTINO,0) AS CIUDAD_DESTINO
	,ISNULL(CIUDEST.NOMBRE_CIUDAD,'' ) AS NOMBRE_CIUDAD_DEST
	,ISNULL(G.ID_CLIENTE, '' ) AS CLIENTE,ISNULL(CLI.NOMBRE_CLIENTE,'' ) AS NOMBRE_CLIENTE
	,ISNULL(DEP.DIRECCION_PRINCIPAL_DEPENDEN,'' ) AS DIRECCION_DEPENDENCIA,ISNULL(G.ID_CANAL,'' ) AS CANAL
	,ISNULL(CAN.NOMBRE_DIVISION,'' ) AS NOMBRE_CANAL,
	G.PESO_VOLU_OPERA,G.PESO_FISICO_OPERA,G.LARGO_ENV_OPERA,G.ANCHO_ENV_OPERA,G.ALTO_ENV_OPERA,G.NUMERO_PIEZAS,
	ISNULL(PR.ID_PROCESO,'')AS ID_PROCESO,
	ISNULL(PR.NOMBRE_PROCESO_LOG,'' ) AS NOMBRE_PROCESO_LOG ,
	ISNULL(TIPENV.NOMBRE_TIPOENVIO,'' ) AS NOMBRE_TIPOENVIO, 
	G.FECHA_ENVIO,
	LEFT(CAST(IIF(SEG.FECHA_HORA_MOVIMIENTO>DOC.FECHA_HORA_MOVIMI,SEG.FECHA_HORA_MOVIMIENTO,DOC.FECHA_HORA_MOVIMI) AS VARCHAR(20)),11) AS FECHA_MODIFICACION,
	SUBSTRING(CAST(IIF(SEG.FECHA_HORA_MOVIMIENTO>DOC.FECHA_HORA_MOVIMI,SEG.FECHA_HORA_MOVIMIENTO,DOC.FECHA_HORA_MOVIMI) AS VARCHAR(20)),13,8) AS HORA_MODIFICACION,
	SEG.NUMERO_MOVIMI AS NUMMANIF,
	SEG.CONSECUT_MOVIMI As CONS_MANIFIESTO,	
	ISNULL(EMP.NOMBRE_EMPLEADO,'' )  + ' '  +  ISNULL(EMP.APELLIDO_EMPLEADO,'' ) AS NOMBRE_EMPLEADO,
	ISNULL(G.ID_PRODUCTO, 0) AS CODPRO, 
	RTRIM(ISNULL(PROD.NOMBRE_PRODUCTO, '')) AS NOMPRO,
	ISNULL(G.ID_SUBPRODUCTO, 0) AS CODSUBPRO, 
	RTRIM(ISNULL(SPROD.NOMBRE_SUBPRODUCTO, '')) AS NOMSUBPRO,
	G.ID_MEDTRANS,
	G.ID_TIEMPO AS TIMEID,
	DOC.ID_ZONA_URBA,
	DOC.ID_TIPO_ZONA_URBA,
