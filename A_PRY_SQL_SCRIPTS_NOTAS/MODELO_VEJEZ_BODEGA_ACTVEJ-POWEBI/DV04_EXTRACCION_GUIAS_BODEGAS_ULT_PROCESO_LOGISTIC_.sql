USE Mece_Logistico;
DECLARE @TABLA_GUIAS_TEMPORALES AS TABLE ([NUMERO_GUIA] [numeric](20, 0) NOT NULL) 
INSERT INTO @TABLA_GUIAS_TEMPORALES
SELECT G.NUMERO_GUIA
FROM MECE_LOGISTICO..GUIAS G WITH(NOLOCK)
INNER JOIN MECE_LOGISTICO..SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
ON SE.NUMERO_GUIA = G.NUMERO_GUIA
INNER JOIN MECE_LOGISTICO..DOCUMENTOS DOC WITH(NOLOCK)
ON SE.ID_PROCESO=DOC.ID_PROCESO AND SE.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND SE.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI
WHERE G.ID_ESTADOENVIO NOT IN (3,4)
AND LEN(G.NUMERO_GUIA)>7
AND DOC.ID_DIVISION_DESTINO IN (9304,9308,9310,9311,9316,9319,9362,9364,9365,9366,9367,9368,9373,9374,9710,9711,9764,9765,9313,9318,9312,9317,9321,9375,9377) ----PARAMETROS
AND SE.FECHA_HORA_MOVIMIENTO BETWEEN '20230825' AND '20230830'
GROUP BY G.NUMERO_GUIA;

SELECT * FROM @TABLA_GUIAS_TEMPORALES;


WITH CIL AS (
SELECT 
ROW_NUMBER() OVER(PARTITION BY SEG.NUMERO_GUIA ORDER BY SEG.FECHA_HORA_MOVIMIENTO DESC) as #ROW,
1 AS X,
DOC.ID_DIVISION_DESTINO AS DIVISION_UBICACION   ------G.ID_DIVISION_UBICACION
,DIV.NOMBRE_DIVISION AS NOMBRE_DIVISION_UBICACION
,G.NUMERO_GUIA
,ISNULL(DOC.ID_CIUDAD_DESTINO,0) AS ID_CIUDAD_UBICACION  ------,ISNULL(G.ID_CIUDAD_UBICACION,0)
,ISNULL(CIUUBICA.NOMBRE_CIUDAD,'NA') AS NOMBRE_CIUDAD_UBICACION
,ISNULL(G.ID_CIUDAD_ORIGEN,0) AS CIUDAD_ORIGEN
,ISNULL(CIUORI.NOMBRE_CIUDAD,' ) AS NOMBRE_CIUDAD_ORIGEN
,ISNULL(G.ID_CIUDAD_DESTINO,0) AS CIUDAD_DESTINO
,ISNULL(CIUDEST.NOMBRE_CIUDAD,' ) AS NOMBRE_CIUDAD_DEST
,ISNULL(G.ID_CLIENTE, ' ) AS CLIENTE,ISNULL(CLI.NOMBRE_CLIENTE,' ) AS NOMBRE_CLIENTE
,ISNULL(DEP.DIRECCION_PRINCIPAL_DEPENDEN,' ) AS DIRECCION_DEPENDENCIA,ISNULL(G.ID_CANAL,' ) AS CANAL
,ISNULL(CAN.NOMBRE_DIVISION,' ) AS NOMBRE_CANAL,
G.PESO_VOLU_OPERA,G.PESO_FISICO_OPERA,G.LARGO_ENV_OPERA,G.ANCHO_ENV_OPERA,G.ALTO_ENV_OPERA,G.NUMERO_PIEZAS,
ISNULL(PR.ID_PROCESO,')AS ID_PROCESO,
ISNULL(PR.NOMBRE_PROCESO_LOG,' ) AS NOMBRE_PROCESO_LOG ,
ISNULL(TIPENV.NOMBRE_TIPOENVIO,' ) AS NOMBRE_TIPOENVIO, G.FECHA_ENVIO,
LEFT(CAST(SEG.FECHA_HORA_MOVIMIENTO AS VARCHAR(20)),11) AS FECHA_MODIFICACION,
SUBSTRING(CAST(SEG.FECHA_HORA_MOVIMIENTO AS VARCHAR(20)),13,8) AS HORA_MODIFICACION,
ISNULL(G.NU_DOCU_ULT_MOVI,' ) AS NUMMANIF,
ISNULL(G.CONS_DOCU_ULT_MOVI, 0) As CONS_MANIFIESTO,
ISNULL(EMP.NOMBRE_EMPLEADO,' )  + ' '  +  ISNULL(EMP.APELLIDO_EMPLEADO,' ) AS NOMBRE_EMPLEADO,
ISNULL(G.ID_PRODUCTO, 0) AS CODPRO, 
RTRIM(ISNULL(PROD.NOMBRE_PRODUCTO, ')) AS NOMPRO,
ISNULL(G.ID_SUBPRODUCTO, 0) AS CODSUBPRO, 
RTRIM(ISNULL(SPROD.NOMBRE_SUBPRODUCTO, ')) AS NOMSUBPRO,
G.ID_MEDTRANS,
G.ID_TIEMPO AS TIMEID,
ZU.ID_ZONA_URBA,
ZU.NOMBRE_ZONA_URBA
FROM GUIAS AS G WITH (NOLOCK) 
INNER JOIN @TABLA_GUIAS_TEMPORALES TL ON TL.NUMERO_GUIA=G.NUMERO_GUIA
INNER JOIN  SEGUIMIENTO_ENVIO AS SEG WITH (NOLOCK) ON SEG.NUMERO_GUIA = G.NUMERO_GUIA 
INNER JOIN  DOCUMENTOS AS DOC WITH(NOLOCK) ON SEG.ID_PROCESO = DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI = DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI = DOC.CONSECUT_MOVIMI
---------LEFT JOIN  PAR.DIVISIONES AS DIV WITH (NOLOCK) ON G.ID_PAIS_UBICACION = DIV.ID_PAIS AND G.ID_CIUDAD_UBICACION = DIV.ID_CIUDAD AND G.ID_DIVISION_UBICACION = DIV.ID_DIVISION 
LEFT JOIN  PAR.DIVISIONES AS DIV WITH (NOLOCK) ON 1 = DIV.ID_PAIS AND DOC.ID_CIUDAD_DESTINO = DIV.ID_CIUDAD AND DOC.ID_DIVISION_DESTINO = DIV.ID_DIVISION
LEFT JOIN  PAR.CIUDADES AS CIUORI WITH (NOLOCK) ON G.ID_PAIS_ORIGEN = CIUORI.ID_PAIS AND G.ID_CIUDAD_ORIGEN = CIUORI.ID_CIUDAD 
LEFT JOIN  PAR.CIUDADES AS CIUDEST WITH (NOLOCK) ON G.ID_PAIS_DESTINO = CIUDEST.ID_PAIS AND G.ID_CIUDAD_DESTINO = CIUDEST.ID_CIUDAD 
LEFT JOIN  PAR.CIUDADES AS CIUUBICA WITH (NOLOCK) ON DOC.ID_PAIS_DESTINO = CIUUBICA.ID_PAIS AND DOC.ID_CIUDAD_DESTINO = CIUUBICA.ID_CIUDAD 
LEFT JOIN  PAR.CLIENTES AS CLI WITH (NOLOCK) ON G.ID_CLIENTE = CLI.ID_CLIENTE 
LEFT JOIN  PAR.CLIENTES_SUCURSALES_DEPENDEN AS DEP WITH (NOLOCK) ON G.ID_CLIENTE = DEP.ID_CLIENTE AND G.ID_1 = DEP.ID_SUCURSAL AND G.ID_2 = DEP.ID_DEPENDEN 
LEFT JOIN  PAR.DIVISIONES AS CAN WITH (NOLOCK) ON 1 = DOC.ID_PAIS_DESTINO AND DOC.ID_CIUDAD_DESTINO = CAN.ID_CIUDAD AND DOC.ID_DIVISION_DESTINO = CAN.ID_DIVISION 
LEFT JOIN  PAR.PROCESOS AS PR WITH (NOLOCK) ON PR.ID_PROCESO =  SEG.ID_PROCESO
LEFT JOIN  TIPO_ENVIO AS TIPENV WITH (NOLOCK) ON SEG.ID_TIPOENVIO = TIPENV.ID_TIPOENVIO 
LEFT JOIN  PAR.EMPLEADOS AS EMP WITH (NOLOCK) ON SEG.ID_EMPLEADO = EMP.ID_EMPLEADO 
LEFT JOIN  PAR.PRODUCTOS  AS PROD WITH (NOLOCK) ON G.ID_PRODUCTO = PROD.ID_PRODUCTO 
LEFT JOIN  PAR.SUBPRODUCTOS AS SPROD WITH (NOLOCK) ON G.ID_PRODUCTO = SPROD.ID_PRODUCTO AND G.ID_SUBPRODUCTO = SPROD.ID_SUBPRODUCTO 
LEFT JOIN  PAR.ZONASURBANAS ZU WITH(NOLOCK) ON ZU.ID_PAIS = 1 AND DOC.ID_CIUDAD_ZONA_URBA = ZU.ID_CIUDAD AND DOC.ID_TIPO_ZONA_URBA = ZU.ID_TIPO_ZONA_URBA AND DOC.ID_ZONA_URBA = ZU.ID_ZONA_URBA  
WHERE 
G.ID_PAIS_UBICACION =          1 -- 
--G.ID_CIUDAD_UBICACION =         10 AND 
--AND SEG.FECHA_HORA_MOVIMIENTO BETWEEN '20220101' AND '20230830'----->PARAMETROS
--AND G.ID_ESTADOENVIO NOT IN (3,4)
--AND LEN(G.NUMERO_GUIA)>7
--AND 
--G.NUMERO_GUIA IN(SELECT NUMERO_GUIA FROM @TABLA_GUIAS_TEMPORALES)
)
SELECT 
#ROW,
X,
DIVISION_UBICACION,
NOMBRE_DIVISION_UBICACION,
NUMERO_GUIA,
ID_CIUDAD_UBICACION,
NOMBRE_CIUDAD_UBICACION,
CIUDAD_ORIGEN,
NOMBRE_CIUDAD_ORIGEN,
CIUDAD_DESTINO,
NOMBRE_CIUDAD_DEST,
CLIENTE,
NOMBRE_CLIENTE,
DIRECCION_DEPENDENCIA,
CANAL,
NOMBRE_CANAL,
PESO_VOLU_OPERA,
PESO_FISICO_OPERA,
LARGO_ENV_OPERA,
ANCHO_ENV_OPERA,
ALTO_ENV_OPERA,
NUMERO_PIEZAS,
ID_PROCESO,
NOMBRE_PROCESO_LOG,
NOMBRE_TIPOENVIO,
FECHA_ENVIO,
FECHA_MODIFICACION,
HORA_MODIFICACION,
NUMMANIF,
CONS_MANIFIESTO,
NOMBRE_EMPLEADO,
CODPRO,
NOMPRO,
CODSUBPRO,
NOMSUBPRO,
ID_MEDTRANS,
TIMEID,
ID_ZONA_URBA,
NOMBRE_ZONA_URBA
FROM CIL WITH(NOLOCK)
WHERE #ROW = 1 
AND 
DIVISION_UBICACION IN (9304,9308,9310,9311,9316,9319,9362,9364,9365,9366,9367,9368,9373,9374,9710,9711,9764,9765,9313,9318,9312,9317,9321,9375,9377) ----PARAMETROS


