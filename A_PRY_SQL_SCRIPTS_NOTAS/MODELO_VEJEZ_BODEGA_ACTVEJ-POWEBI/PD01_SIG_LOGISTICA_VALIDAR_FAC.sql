USE SIG_LOGISTICA_DM;

DECLARE @TIMEPO_INI INT = CONVERT(INT,DATEADD(mm,-1,DATEADD(mm,DATEDIFF(mm,0,GETDATE()),0)))

SELECT TIME_ID_ULT_MOV = CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,FAC.[FEC_ULT_MOV_LOGISTICO]))))
      ,TIME_ID_EV = CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,FAC.[FEC_ULT_MOV_LOGISTICO]))))
      ,FAC.[NUMERO_GUIA]
      ,FAC.[NOMBRE_CLIENTE]
      ,FAC.[ID_CIUDAD_UBICACION]
      ,FAC.[NOMBRE_CIUDAD_ORIGEN]
      ,FAC.[NOMBRE_CIUDAD_DEST]
      ,FAC.[NUMERO_PIEZAS]
      ,FAC.[ULT_MOV_LOGISTICO]
      ,FAC.[FECHA_ENVIO]
      ,FAC.[FEC_ULT_MOV_LOGISTICO]
      ,FAC.[PRODUCTO]
      ,FAC.[ID_VEJEZ_CF]
      ,[ID_VEJEZ_SF] =  IIF(FAC.[ID_VEJEZ_SF] = 0 AND FAC.[ID_VEJEZ_CF] = -888, FAC.[ID_VEJEZ_SF], FAC.[ID_VEJEZ_CF])
      ,FAC.[BODEGA]
      ,[NOMBRE_BODEGA] =
                      CASE WHEN FAC.[NOMBRE_BODEGA] = 'SINIESROS' THEN 'SINIESTROS'
                            WHEN FAC.[NOMBRE_BODEGA] = 'GUIAS REEMPLAZO' THEN 'GUIAS DE REEMPLAZO'
                            WHEN FAC.[NOMBRE_BODEGA] = 'GUIAS  REEMPLAZO' THEN 'GUIAS DE REEMPLAZO'
                            WHEN FAC.[NOMBRE_BODEGA] = 'GUIAS DE REMPLAZO' THEN 'GUIAS DE REEMPLAZO'
                            ELSE FAC.NOMBRE_BODEGA
                            END
      ,FAC.[TIPO_BODEGA]         
      ,FAC.[ID_ESTADOENVIO]
      ,FAC.[NOMBRE_ESTADOENVIO]
      ,FAC.[ID_ESTADOGUIA]
      ,FAC.[NOMBRE_ESTADOGUIA]
      ,FAC.[ID_FECHA_EV]
      ,FAC.[ID_FECHA_RE]
      ,FAC.[ID_FECHA_RRE]
      ,FAC.[TELEFONO_DESTINA_GUIA]
      ,FAC.[NOMBRE_DESTINA_GUIA]
      ,FAC.[TELEFONO_REMITE_GUIA]
      ,FAC.[NOMBRE_REMITE_GUIA]
      ,FAC.[ID_VEJEZ_CF_DIAS]
      ,FAC.[ID_VEJEZ_SF_DIAS]
      ,ULT_DEVOLUCION = FAC.[ULT_PROC_DEVUL]---->el campo aparecia con el nombre en la etl y se ajusto
      ,FAC.[ID_ULT_PROC_DEVUL]
      ,FAC.[ID_ULT_PROC_CONC_DEVUL]
      ,FAC.[ID_FECHA_EZU]
      ,FAC.[SE_FECHA_EZU]
      ,FAC.[SE_ID_ULTI]
      ,FAC.[FECHA_EXTRACCION_DM]
  FROM [SIG_LOGISTICA_DM].[FAC].[VEJEZ_BODEGAS] FAC WITH(NOLOCK)
  WHERE
  CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,FAC.[FEC_ULT_MOV_LOGISTICO]))))
  >= @TIMEPO_INI




