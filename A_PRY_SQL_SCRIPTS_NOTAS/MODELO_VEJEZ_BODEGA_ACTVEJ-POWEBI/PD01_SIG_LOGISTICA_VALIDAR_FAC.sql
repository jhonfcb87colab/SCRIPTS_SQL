USE SIG_COLOMBIA_DW;
  WITH CTE 
(
	 ID 
	,[NUMERO_GUIA]
	,[NOMBRE_CLIENTE] 
	,[ID_CIUDAD_UBICACION]
	,[NOMBRE_CIUDAD_ORIGEN] 
	,[NOMBRE_CIUDAD_DEST]
	,[NUMERO_PIEZAS]
	,[ULT_MOV_LOGISTICO]
	,[FECHA_ENVIO]
	,[FEC_ULT_MOV_LOGISTICO]
	,[PRODUCTO]
	,[BODEGA]
	,[NOMBRE_BODEGA]
)
AS
	(
		SELECT
			 ROW_NUMBER() OVER(PARTITION BY NUMERO_GUIA ORDER BY [FECHA_ENVIO] DESC ) ID 
			,[NUMERO_GUIA]
			,[NOMBRE_CLIENTE] 
			,[ID_CIUDAD_UBICACION]
			,[NOMBRE_CIUDAD_ORIGEN] 
			,[NOMBRE_CIUDAD_DEST]
			,[NUMERO_PIEZAS]
			,[NOMBRE_PROCESO_LOG] AS ULT_MOV_LOGISTICO
			,[FECHA_ENVIO]
			,[FECHA_MODIFICACION] AS  FEC_ULT_MOV_LOGISTICO
			,[NOMPRO] AS PRODUCTO
			,[DIVISION_UBICACION] AS BODEGA
			,[NOMBRE_DIVISION_UBICACION] AS NOMBRE_BODEGA
		FROM 
			[TMP].[VEJEZ_BODEGAS_01] WITH (NOLOCK)
	)/*
INSERT INTO [TMP].[VEJEZ_BODEGAS]
(
	 [NUMERO_GUIA]
	,[NOMBRE_CLIENTE]
	,[ID_CIUDAD_UBICACION]
	,[NOMBRE_CIUDAD_ORIGEN]
	,[NOMBRE_CIUDAD_DEST]
	,[NUMERO_PIEZAS]
	,[ULT_MOV_LOGISTICO]
	,[FECHA_ENVIO]
	,[FEC_ULT_MOV_LOGISTICO]
	,[PRODUCTO]
	,[BODEGA]
	,[NOMBRE_BODEGA]
	,[TIPO_BODEGA]
)*/
SELECT
	 NUMERO_GUIA
	,CASE WHEN NOMBRE_CLIENTE = ' THEN 'NO DISPONIBLE' ELSE ISNULL(NOMBRE_CLIENTE,'NO DISPONIBLE') END NOMBRE_CLIENTE
	,ISNULL(ID_CIUDAD_UBICACION,-888) ID_CIUDAD_UBICACION
	,CASE WHEN NOMBRE_CIUDAD_ORIGEN = ' THEN 'NO DISPONIBLE' ELSE ISNULL(NOMBRE_CIUDAD_ORIGEN,'NO DISPONIBLE') END NOMBRE_CIUDAD_ORIGEN
	,CASE WHEN NOMBRE_CIUDAD_DEST = ' THEN 'NO DISPONIBLE' ELSE ISNULL(NOMBRE_CIUDAD_DEST,'NO DISPONIBLE') END NOMBRE_CIUDAD_DEST
	,CASE WHEN NUMERO_PIEZAS = 0 THEN 1 ELSE  NUMERO_PIEZAS END NUMERO_PIEZAS
	,ULT_MOV_LOGISTICO
	,FECHA_ENVIO
	,FEC_ULT_MOV_LOGISTICO
	,PRODUCTO
	,BODEGA
	,NOMBRE_BODEGA
	,CASE WHEN BODEGA IN(9304,9308,9310,9311,9312,9313,9710,9711,9317,9367,9373,9374/* BODEGAS OTRAS*/ ,9311,9406,9304,9711,9310,9308,9710) THEN 'BODEGAS PRIMARIAS'
		  WHEN BODEGA IN(9321,9364,9365,9375,9377,9764,9765,9319  /* BODEGAS OTRAS*/,9312,9365,9765,9364,9364,9764,9377,9377,9319,9367,9368,9374,9373, /* se agregan dos bodegas  */ 9321,9313)					  THEN 'BODEGAS SECUNDARIAS'
		  WHEN BODEGA IN(9316,9318,9362,9366)										  THEN 'BODEGAS CONTROL'
	  ELSE 'OTRAS' 
	END TIPO_BODEGA
FROM 
	CTE
WHERE 
	CTE.ID = 1






