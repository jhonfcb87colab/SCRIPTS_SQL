WITH CTE AS(
SELECT 
ROW_NUMBER ( )   OVER ( PARTITION BY SE.NUMERO_GUIA order by SE.FECHA_HORA_MOVIMIENTO desc )  #ROW_ID, 
SE.NUMERO_GUIA
,SE.ID_PROCESO
,SE.FECHA_HORA_MOVIMIENTO
,TIME_ID = CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,SE.FECHA_HORA_MOVIMIENTO))))
FROM TMP.GUIAS_FAC_VEJEZ_BODEGAS FAC WITH(NOLOCK)
INNER JOIN LOG.SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
ON FAC.NUMERO_GUIA=SE.NUMERO_GUIA
WHERE SE.ID_PROCESO IN(5,6,14)
-----and se.NUMERO_GUIA IN(2173288738,21681079)
)
SELECT
NUMERO_GUIA,
ID_PROCESO,
TIME_ID
FECHA_HORA_MOVIMIENTO,
CASE WHEN CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,FECHA_HORA_MOVIMIENTO)))=CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,GETDATE()))) THEN 0
		ELSE LOG.UFN_COUNT_DAYS_RANGE(FECHA_HORA_MOVIMIENTO,convert(datetime,convert(date,GETDATE()-1)),'DIA DOMINICAL,DIA FESTIVO')
		END DIAS_SIN_FEST_DOMINICAL_VEJEZ,
DATEDIFF(DAY,CONVERT(DATE,FECHA_HORA_MOVIMIENTO),GETDATE()) DIAS_CON_FEST_DOMINICAL_VEJEZ
FROM CTE WHERE #ROW_ID=1




