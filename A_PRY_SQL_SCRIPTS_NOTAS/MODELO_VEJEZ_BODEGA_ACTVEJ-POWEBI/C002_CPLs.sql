USE PARAMETROS;
SELECT
    CONCAT(BOD.ID_PAIS,'-',BOD.ID_CIUDAD,'-',BOD.ID_DIVISION) AS ID_CPL,
    CELO.CENTRO_LOGISTICO,
    BOD.ID_PAIS, 
	CD.NOMBRE_CIUDAD,
    BOD.ID_CIUDAD,   
    BOD.ID_CENTRO_LOGISTICO,   
    BOD.ID_DIVISION    ID_BODEGA,   
    BOD.LOGIN_EMPLEADO_CREACION,   
    BOD.FECHA_CREACION,
    BOD.LOGIN_EMPLEADO_MODIFICACION,   
    BOD.FECHA_MODIFICACION
FROM CENTROS_LOGISTICOS CELO WITH(NOLOCK)
INNER JOIN CENTROS_LOGISTICOS_BODEGAS BOD WITH(NOLOCK)
ON CELO.ID_PAIS= BOD.ID_PAIS
AND CELO.ID_CIUDAD=BOD.ID_CIUDAD
AND CELO.ID_CENTRO_LOGISTICO= BOD.ID_CENTRO_LOGISTICO
LEFT JOIN CIUDADES CD WITH(NOLOCK)
ON CD.ID_CIUDAD=CELO.ID_CIUDAD




