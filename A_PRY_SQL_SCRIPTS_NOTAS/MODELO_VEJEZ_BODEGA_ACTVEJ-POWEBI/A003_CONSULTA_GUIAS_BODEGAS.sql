USE SIG_COLOMBIA_DW;


DECLARE @FECHA_INI DATETIME,@FECHA_FIN DATETIME;
SET @FECHA_INI = CONVERT(DATETIME,'20230501');
SET @FECHA_FIN = CONVERT(DATETIME,'20230511');

DROP TABLE IF EXISTS #TABLA_BODEGAS_ACTVEJ_202305101433;
CREATE TABLE #TABLA_BODEGAS_ACTVEJ_202305101433
(
	ID_PAIS INT
	,ID_CIUDAD INT
	,ID_DIVISION INT
	,ID_TIPO_DIVISION INT 
	,NOMBRE_DIVISION VARCHAR(40)
	,TIPO_BODEGA INT
);


WITH CTE AS (
			SELECT
				ID_PAIS,ID_CIUDAD,ID_DIVISION,ID_TIPO_DIVISION,NOMBRE_DIVISION, 
				TIPO_BODEGA =	CASE WHEN ID_DIVISION IN (9311,9406,9304,9711,9310,9308,9710) THEN 1		--9314,
									 WHEN ID_DIVISION IN (9312,9365,9765,9364,9364,9764,9377,9377,9319,9367,9368,9374,9373) THEN 2   ---9363,
									 ELSE 0 END
				FROM PAR.DIVISIONES DIV WITH(NOLOCK) WHERE ID_EST_DIVISION=1
			)
			INSERT INTO  #TABLA_BODEGAS_ACTVEJ_202305101433
				SELECT 
				DISTINCT 
				ID_PAIS,ID_CIUDAD,ID_DIVISION,ID_TIPO_DIVISION,NOMBRE_DIVISION,TIPO_BODEGA
				FROM CTE 
				WHERE TIPO_BODEGA <> 0;
				

--select * from  #TABLA_BODEGAS_ACTVEJ_202305101433



WITH CIL AS (
			SELECT 
			ROW_NUMBER() OVER(PARTITION BY G.NUMERO_GUIA ORDER BY SEG.FECHA_HORA_MOVIMIENTO DESC) as #ROW,
			1 AS X,
			G.ID_DIVISION_UBICACION AS DIVISION_UBICACION
			,DIV.NOMBRE_DIVISION AS NOMBRE_DIVISION_UBICACION
			,G.NUMERO_GUIA
			,ISNULL(G.ID_CIUDAD_UBICACION,0) AS ID_CIUDAD_UBICACION
			,ISNULL(G.ID_CIUDAD_ORIGEN,0) AS CIUDAD_ORIGEN
			,ISNULL(CIUORI.NOMBRE_CIUDAD,' ) AS NOMBRE_CIUDAD_ORIGEN
			,ISNULL(G.ID_CIUDAD_DESTINO,0) AS CIUDAD_DESTINO
			,ISNULL(CIUDEST.NOMBRE_CIUDAD,' ) AS NOMBRE_CIUDAD_DEST
			,ISNULL(G.ID_CLIENTE, ' ) AS CLIENTE,ISNULL(CLI.NOMBRE_CLIENTE,' ) AS NOMBRE_CLIENTE
			,ISNULL(DEP.DIRECCION_PRINCIPAL_DEPENDEN,' ) AS DIRECCION_DEPENDENCIA,ISNULL(G.ID_CANAL,' ) AS CANAL
			,ISNULL(CAN.NOMBRE_DIVISION,' ) AS NOMBRE_CANAL,
			G.PESO_VOLU_OPERA,G.PESO_FISICO_OPERA,G.LARGO_ENV_OPERA,G.ANCHO_ENV_OPERA,G.ALTO_ENV_OPERA,G.NUMERO_PIEZAS,
			ISNULL(PR.NOMBRE_PROCESO_LOG,' ) AS NOMBRE_PROCESO_LOG ,
			ISNULL(TIPENV.NOMBRE_TIPO_ENVIO,' ) AS NOMBRE_TIPOENVIO, G.FECHA_ENVIO,
			LEFT(CAST(SEG.FECHA_HORA_MOVIMIENTO AS VARCHAR(20)),11) AS FECHA_MODIFICACION,
			SUBSTRING(CAST(SEG.FECHA_HORA_MOVIMIENTO AS VARCHAR(20)),13,8) AS HORA_MODIFICACION,
			ISNULL(G.NU_DOCU_ULT_MOVI,' ) AS NUMMANIF,
			ISNULL(G.CONS_DOCU_ULT_MOVI, 0) As CONS_MANIFIESTO,
			ISNULL(EMP.NOMBRE_EMPLEADO,' )  + ' '  +  ISNULL(EMP.APELLIDO_EMPLEADO,' ) AS NOMBRE_EMPLEADO,
			ISNULL(G.ID_PRODUCTO, 0) AS CODPRO, 
			RTRIM(ISNULL(PROD.NOMBRE_PRODUCTO, ')) AS NOMPRO,
			ISNULL(G.ID_SUBPRODUCTO, 0) AS CODSUBPRO, 
			RTRIM(ISNULL(SPROD.NOMBRE_SUBPRODUCTO, ')) AS NOMSUBPRO   ---,
			----TMPBODEGA.TIPO_BODEGA
			FROM log.GUIAS AS G WITH (NOLOCK) 
			LEFT JOIN  PAR.DIVISIONES AS DIV WITH (NOLOCK) ON G.ID_PAIS_UBICACION = DIV.ID_PAIS AND G.ID_CIUDAD_UBICACION = DIV.ID_CIUDAD AND G.ID_DIVISION_UBICACION = DIV.ID_DIVISION 
			LEFT JOIN  PAR.CIUDADES AS CIUORI WITH (NOLOCK) ON G.ID_PAIS_ORIGEN = CIUORI.ID_PAIS AND G.ID_CIUDAD_ORIGEN = CIUORI.ID_CIUDAD 
			LEFT JOIN  PAR.CIUDADES AS CIUDEST WITH (NOLOCK) ON G.ID_PAIS_DESTINO = CIUDEST.ID_PAIS AND G.ID_CIUDAD_DESTINO = CIUDEST.ID_CIUDAD 
			LEFT JOIN  PAR.CLIENTES AS CLI WITH (NOLOCK) ON G.ID_CLIENTE = CLI.ID_CLIENTE 
			LEFT JOIN  PAR.CLIENTES_SUCURSALES_DEPENDEN AS DEP WITH (NOLOCK) ON G.ID_CLIENTE = DEP.ID_CLIENTE AND G.ID_1 = DEP.ID_SUCURSAL AND G.ID_2 = DEP.ID_DEPENDEN 
			LEFT JOIN  PAR.DIVISIONES AS CAN WITH (NOLOCK) ON G.ID_1 = CAN.ID_PAIS AND G.ID_2 = CAN.ID_CIUDAD AND G.ID_CANAL = CAN.ID_DIVISION 
			LEFT JOIN  par.PROCESOS AS PR WITH (NOLOCK) ON PR.ID_PROCESO =  G.ID_DOCU_ULT_MOVI 
			LEFT JOIN  LOG.SEGUIMIENTO_ENVIO AS SEG WITH (NOLOCK) ON SEG.ID_PROCESO = G.ID_DOCU_ULT_MOVI AND SEG.NUMERO_MOVIMI = G.NU_DOCU_ULT_MOVI AND SEG.CONSECUT_MOVIMI = G.CONS_DOCU_ULT_MOVI AND SEG.NUMERO_GUIA = G.NUMERO_GUIA 
			LEFT JOIN  SIG_COL_LOGISTICA_DW.DIM.TIPO_ENVIO AS TIPENV WITH (NOLOCK) ON SEG.ID_TIPOENVIO = TIPENV.ID_TIPO_ENVIO 
			LEFT JOIN  PAR.EMPLEADOS AS EMP WITH (NOLOCK) ON SEG.ID_EMPLEADO = EMP.ID_EMPLEADO 
			LEFT JOIN  PAR.PRODUCTOS  AS PROD WITH (NOLOCK) ON G.ID_PRODUCTO = PROD.ID_PRODUCTO 
			LEFT JOIN  PAR.SUBPRODUCTOS AS SPROD WITH (NOLOCK) ON G.ID_PRODUCTO = SPROD.ID_PRODUCTO AND G.ID_SUBPRODUCTO = SPROD.ID_SUBPRODUCTO
			INNER JOIN  #TABLA_BODEGAS_ACTVEJ_202305101433 AS TMPBOD WITH(NOLOCK) ON  TMPBOD.ID_DIVISION=G.ID_CANAL  
			WHERE 
			G.ID_PAIS_UBICACION =          1 --AND 
			--G.ID_CIUDAD_UBICACION =         10 AND 
			AND G.ID_DIVISION_UBICACION IN (SELECT DISTINCT ID_DIVISION FROM #TABLA_BODEGAS_ACTVEJ_202305101433)										------>9304,9308,9310,9311,9316,9319,9362,9364,9365,9366,9367,9368,9373,9374,9710,9711,9764,9765,9313,9318,9312,9317,9321,9375,9377
			AND SEG.FECHA_HORA_MOVIMIENTO BETWEEN @FECHA_INI AND @FECHA_FIN
)
