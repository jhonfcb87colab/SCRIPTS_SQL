USE SIG_COL_LOGISTICA_DW;

-------------------------
--Ingreso Tiempo Oferta
-------------------------

SELECT * FROM DIM.RED_OPERATIVA_TIEMPO_TAB_F WITH(NOLOCK) 
WHERE NOMBRE_CIUDAD_ORIGEN LIKE'%BOGO%' AND NOMBRE_CIUDAD_DESTINO LIKE'%duita%' 

WITH CLIENTE_CORPORATIVO_RED_OPERATIVA AS(
SELECT	DISTINCT EM.ID_CIUDAD_ORIGEN, 
		EM.ID_CIUDAD_DESTINO, 
		TIEMPO_EN_ENTREGA,
		TIEMPO_ENTREGA_COMERCIAL AS T_CIAL
		--------------INTO #CLIENTE_CORPORATIVO_RED_OPERATIVA 
FROM	FAC.GUIAS_ENTREG_TIEMPO_PROMESA_ENVIOS_MOV  AS EM WITH(NOLOCK)
		INNER JOIN DIM.RED_OPERATIVA_TIEMPO_TAB_F AS RED WITH(NOLOCK) ON 
	EM.TIME_ID >= CONVERT(NUMERIC(18,0),GETDATE()-15) AND
	EM.ID_CIUDAD_ORIGEN = RED.ID_CIUDAD_ORIGEN 
	AND EM.ID_CIUDAD_DESTINO = RED.ID_CIUDAD_DESTINO
)

----------CREATE INDEX IDX_ENVIOS_MOVILIZADOS1 ON #CLIENTE_CORPORATIVO_RED_OPERATIVA
----------(ID_CIUDAD_ORIGEN,ID_CIUDAD_DESTINO,TIEMPO_EN_ENTREGA)

------------UPDATE	FAC.GUIAS_ENTREG_TIEMPO_PROMESA_ENVIOS_MOV
------------SET		
SELECT
		TIEMPO_OFERTA = ISNULL(T_CIAL,36) * CANT_GUIAS
FROM	FAC.GUIAS_ENTREG_TIEMPO_PROMESA_ENVIOS_MOV AS EM WITH(NOLOCK)
		INNER JOIN CLIENTE_CORPORATIVO_RED_OPERATIVA ON	
	EM.TIME_ID >= CONVERT(NUMERIC(18,0),GETDATE()-15) AND
	EM.ID_CIUDAD_ORIGEN = CLIENTE_CORPORATIVO_RED_OPERATIVA.ID_CIUDAD_ORIGEN
	AND EM.ID_CIUDAD_DESTINO = CLIENTE_CORPORATIVO_RED_OPERATIVA.ID_CIUDAD_DESTINO
	AND EM.TIEMPO_EN_ENTREGA = CLIENTE_CORPORATIVO_RED_OPERATIVA.TIEMPO_EN_ENTREGA


--------DROP TABLE #CLIENTE_CORPORATIVO_RED_OPERATIVA




		      
