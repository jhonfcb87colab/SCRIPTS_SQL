
USE Mece_Logistico;


/********************************EJECUCION EN DIRECCION GENERAL MECE_LOGISTICO         LSTSSDGN    ******************************************************/

WITH CTE AS(
SELECT 
ROW_NUMBER ( )   OVER ( PARTITION BY SE.[NUMERO_GUIA] order by SE.FECHA_HORA_MOVIMIENTO DESC )  #ROW_ID_SE,  
ROW_NUMBER ( )   OVER ( PARTITION BY SE.[NUMERO_GUIA] order by DO.FECHA_HORA_MOVIMI DESC )  #ROW_ID_DO 
,SE.NUMERO_GUIA
,SE.FECHA_HORA_MOVIMIENTO SEGUI_ENV_FECHA_HORA_MOVIMIENTO
,DO.FECHA_HORA_MOVIMI DOCUMENTOS_FECHA_HORA_MOVIMIENTO
,PR.ID_PROCESO
,PR.NOMBRE_PROCESO_LOG
,DO.ID_DIVISION_DESTINO
,DO.ID_DIVISION_ORIGEN
,DIV_DEST.NOMBRE_DIVISION DIV_DEST_NOMBRE_DIVISION
,DIV_ORIG.NOMBRE_DIVISION DIV_ORIG_NOMBRE_DIVISION
,CIUD_ORIG.NOMBRE_CIUDAD CIUD_ORIG_NOMBRE_CIUDAD
,CIUD_DEST.NOMBRE_CIUDAD CIUD_DEST_NOMBRE_CIUDAD
,REGIO_DESTI.NOMBRE_REGIONAL REGIO_DESTI_NOMBRE_REGIONAL
,REGIO_ORIG.NOMBRE_REGIONAL  REGIO_ORIG_NOMBRE_REGIONAL
----,do.FECHA_MODIFICACION DO_FECHA_MODIFICACION
,DO.ID_CIUDAD_DESTINO
,ID_CIUDAD_DIVISION_ORIGEN
,SE_FECHA_MODIFICACION = SE.FECHA_MODIFICACION
,DO_FECHA_MODIFICACION = DO.FECHA_MODIFICACION
FROM Mece_Logistico..SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
INNER JOIN  MECE_LOGISTICO..DOCUMENTOS DO WITH (NOLOCK) 
ON SE.ID_PROCESO=DO.ID_PROCESO 
AND SE.NUMERO_MOVIMI=DO.NUMERO_MOVIMI 
AND SE.CONSECUT_MOVIMI=DO.CONSECUT_MOVIMI
LEFT JOIN PARAMETROS..PROCESOS PR ON SE.ID_PROCESO=PR.ID_PROCESO

	-------------->CIUDAD DESTINO
	LEFT JOIN PARAMETROS..CIUDADES CIUD_DEST ON CIUD_DEST.ID_CIUDAD=DO.ID_CIUDAD_DESTINO
	LEFT JOIN PARAMETROS..REGIONALES_PAIS REGIO_DESTI ON REGIO_DESTI.ID_REGIONAL=CIUD_DEST.ID_REGIONAL
	LEFT JOIN PARAMETROS..DIVISIONES DIV_DEST WITH (NOLOCK)
	ON DIV_DEST.ID_DIVISION=DO.ID_DIVISION_DESTINO AND DO.ID_CIUDAD_DESTINO=DIV_DEST.ID_CIUDAD 

	-------------->CIUDAD ORIGEN
	LEFT JOIN PARAMETROS..CIUDADES CIUD_ORIG ON CIUD_ORIG.ID_CIUDAD=DO.ID_CIUDAD_DIVISION_ORIGEN
	LEFT JOIN PARAMETROS..REGIONALES_PAIS REGIO_ORIG ON REGIO_ORIG.ID_REGIONAL=CIUD_ORIG.ID_REGIONAL
	LEFT JOIN PARAMETROS..DIVISIONES DIV_ORIG WITH (NOLOCK)
	ON DIV_ORIG.ID_DIVISION=DO.ID_DIVISION_ORIGEN AND DO.ID_CIUDAD_DIVISION_ORIGEN=DIV_ORIG.ID_CIUDAD 

WHERE NUMERO_GUIA in(			---279661986
351650322

)---ORDER BY DO.FECHA_HORA_MOVIMI DESC
)
SELECT 
CT.NUMERO_GUIA	
,CT.ID_PROCESO	
,NOMBRE_PROCESO_LOG
,ID_DIVISION_UBICACION = CASE WHEN CT.ID_PROCESO IN(7,12,9) THEN CT.ID_DIVISION_ORIGEN
								WHEN CT.ID_PROCESO IN(5,6,8,10,14,15,17,19,20,21) THEN CT.ID_DIVISION_DESTINO
								ELSE CT.ID_DIVISION_DESTINO END
,DIVISION_UBICACION = CASE WHEN CT.ID_PROCESO IN(7,12,9) THEN CT.DIV_ORIG_NOMBRE_DIVISION
								WHEN CT.ID_PROCESO IN(5,6,8,10,14,15,17,19,20,21) THEN CT.DIV_DEST_NOMBRE_DIVISION
								ELSE CT.DIV_DEST_NOMBRE_DIVISION END
,ID_CIUDAD_UBICACION =  CASE WHEN CT.ID_PROCESO IN(7,12,9) THEN CT.ID_CIUDAD_DIVISION_ORIGEN
								WHEN CT.ID_PROCESO IN(5,6,8,10,14,15,17,19,20,21) THEN CT.ID_CIUDAD_DESTINO
								ELSE CT.ID_CIUDAD_DESTINO END	
,CIUDAD_UBICACION =  CASE WHEN CT.ID_PROCESO IN(7,12,9) THEN CT.CIUD_ORIG_NOMBRE_CIUDAD
								WHEN CT.ID_PROCESO IN(5,6,8,10,14,15,17,19,20,21) THEN CT.CIUD_DEST_NOMBRE_CIUDAD
								ELSE CT.CIUD_DEST_NOMBRE_CIUDAD END	
,REGIONAL_UBICACION =  CASE WHEN CT.ID_PROCESO IN(7,12,9) THEN CT.REGIO_ORIG_NOMBRE_REGIONAL
								WHEN CT.ID_PROCESO IN(5,6,8,10,14,15,17,19,20,21) THEN CT.REGIO_DESTI_NOMBRE_REGIONAL
								ELSE CT.REGIO_DESTI_NOMBRE_REGIONAL END	
,CT.SEGUI_ENV_FECHA_HORA_MOVIMIENTO	
,CT.DOCUMENTOS_FECHA_HORA_MOVIMIENTO
,CT.SE_FECHA_MODIFICACION
,CT.DO_FECHA_MODIFICACION
FROM CTE  CT
WHERE
--#ROW_ID_SE BETWEEN 1 AND 10
#ROW_ID_DO BETWEEN 1 AND 10
--AND NOMBRE_PROCESO_LOG  like '%salida%' 
---and DIV_DEST_NOMBRE_DIVISION in('AJUSTES','TABLAS DE INVESTIGACION')


SELECT PR.NOMBRE_PROCESO_LOG,SE.* FROM Mece_Logistico..SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
INNER JOIN PARAMETROS..PROCESOS PR WITH(NOLOCK) ON PR.ID_PROCESO=SE.ID_PROCESO
WHERE SE.NUMERO_GUIA=351650322
ORDER BY FECHA_HORA_MOVIMIENTO DESC

