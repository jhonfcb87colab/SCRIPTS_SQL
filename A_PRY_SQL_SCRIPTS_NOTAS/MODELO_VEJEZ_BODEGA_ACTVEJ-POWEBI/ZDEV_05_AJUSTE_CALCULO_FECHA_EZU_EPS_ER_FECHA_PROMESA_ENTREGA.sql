WITH CTE_ULTIMO_MOV_EZU_EPS AS(
		SELECT
		ROW_NUMBER ( )   OVER ( PARTITION BY TMP.NUMERO_GUIA order by SE.FECHA_HORA_MOVIMIENTO,SE.ID_PROCESO ASC )  ROWid, 
		TMP.NUMERO_GUIA,
		SE.ID_PROCESO,
		PR.NOMBRE_PROCESO_LOG,
		SE.FECHA_HORA_MOVIMIENTO
		FROM [TMP].[GUIAS_FAC_VEJEZ_BODEGAS] TMP WITH(NOLOCK)
		INNER JOIN LOG.SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
		ON TMP.NUMERO_GUIA=SE.NUMERO_GUIA
		INNER JOIN PAR.PROCESOS PR WITH(NOLOCK)
		ON PR.ID_PROCESO=SE.ID_PROCESO
		WHERE SE.ID_PROCESO IN(5,6,14)
)SELECT * 
FROM CTE_ULTIMO_MOV_EZU_EPS WITH(NOLOCK) WHERE ROWid=1

-----PRUEBAS
WITH CTE_ULTIMO_MOV_EZU_EPS_ER AS(
		SELECT
		ROW_NUMBER ( )   OVER ( PARTITION BY TMP.NUMERO_GUIA order by SE.FECHA_HORA_MOVIMIENTO ASC )  ROWid, 
		TMP.NUMERO_GUIA,
		SE.ID_PROCESO,
		PR.NOMBRE_PROCESO_LOG,
		SE.FECHA_HORA_MOVIMIENTO
		FROM [TMP].[GUIAS_FAC_VEJEZ_BODEGAS] TMP WITH(NOLOCK)
		INNER JOIN LOG.SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
		ON TMP.NUMERO_GUIA=SE.NUMERO_GUIA
		LEFT JOIN PAR.PROCESOS PR WITH(NOLOCK)
		ON (PR.ID_PROCESO=SE.ID_PROCESO AND SE.ID_PROCESO IN(5,6))
)SELECT * 
FROM CTE_ULTIMO_MOV_EZU_EPS_ER WITH(NOLOCK) WHERE ROWid=1
AND NOMBRE_PROCESO_LOG IS NULL
