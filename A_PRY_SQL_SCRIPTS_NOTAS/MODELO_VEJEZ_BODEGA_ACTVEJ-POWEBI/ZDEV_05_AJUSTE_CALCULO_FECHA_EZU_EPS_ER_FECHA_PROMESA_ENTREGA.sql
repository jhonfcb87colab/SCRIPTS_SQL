WITH GUIAS_SIN_EZU_EPS AS(
		SELECT
		ROW_NUMBER ( )   OVER ( PARTITION BY TMP.NUMERO_GUIA order by SE.FECHA_HORA_MOVIMIENTO ASC )  ROWid, 
		TMP.NUMERO_GUIA,
		SE.ID_PROCESO
		FROM [TMP].[GUIAS_FAC_VEJEZ_BODEGAS] TMP WITH(NOLOCK)
		LEFT JOIN LOG.SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
		ON TMP.NUMERO_GUIA=SE.NUMERO_GUIA AND SE.ID_PROCESO NOT IN(5,6)
		WHERE SE.ID_PROCESO = 14
)
SELECT * FROM GUIAS_SIN_EZU_EPS SIN_EZU_EPS WHERE SIN_EZU_EPS.ROWid IN(1,2,3) -----AND SIN_EZU_EPS.ID_PROCESO = 14
, CTE_CON_SALIDA_ER AS ( 
SELECT 
		ROW_NUMBER ( )   OVER ( PARTITION BY SIN_EZU_EPS.NUMERO_GUIA order by SEG.FECHA_HORA_MOVIMIENTO ASC )  ROWid, 
		SIN_EZU_EPS.NUMERO_GUIA,
		SEG.ID_PROCESO,
		PR.NOMBRE_PROCESO_LOG,
		SEG.FECHA_HORA_MOVIMIENTO
FROM LOG.SEGUIMIENTO_ENVIO SEG WITH(NOLOCK)
INNER JOIN GUIAS_SIN_EZU_EPS SIN_EZU_EPS
ON SIN_EZU_EPS.NUMERO_GUIA=SEG.NUMERO_GUIA
INNER JOIN PAR.PROCESOS PR WITH(NOLOCK)
ON PR.ID_PROCESO=SEG.ID_PROCESO
WHERE SIN_EZU_EPS.ROWid=1
)
SELECT * FROM CTE_CON_SALIDA_ER ER WHERE ER.ROWid=1


