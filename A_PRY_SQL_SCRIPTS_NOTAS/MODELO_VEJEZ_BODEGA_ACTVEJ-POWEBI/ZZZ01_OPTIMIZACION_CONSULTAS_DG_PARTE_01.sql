		ULT_ID_CONCEPTO
FROM CIL CIL WITH(NOLOCK) 
LEFT JOIN  PARAMETROS..DIVISIONES AS DIV WITH (NOLOCK) ON 1 = DIV.ID_PAIS AND CIL.ID_CIUDAD_UBICACION = DIV.ID_CIUDAD AND CIL.DIVISION_UBICACION = DIV.ID_DIVISION
LEFT JOIN  PARAMETROS..CIUDADES AS CIUUBICA WITH (NOLOCK) ON 1 = CIUUBICA.ID_PAIS AND CIL.ID_CIUDAD_UBICACION = CIUUBICA.ID_CIUDAD 
LEFT JOIN  PARAMETROS..ZONASURBANAS ZU WITH(NOLOCK) ON ZU.ID_PAIS = 1 AND CIL.ID_CIUDAD_UBICACION = ZU.ID_CIUDAD AND CIL.ID_TIPO_ZONA_URBA = ZU.ID_TIPO_ZONA_URBA AND CIL.ID_ZONA_URBA = ZU.ID_ZONA_URBA  
WHERE #ROW = 1 
AND DIVISION_UBICACION IN(SELECT BODEGA FROM @BODEGAS ) ----PARAMETROS
AND CIL.ID_PROCESO NOT IN(9,24,25,30,31,32,33,34)
