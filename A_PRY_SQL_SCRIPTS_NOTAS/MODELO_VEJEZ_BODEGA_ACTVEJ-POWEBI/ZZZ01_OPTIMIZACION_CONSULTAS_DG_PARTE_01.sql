		CIL.NOMBRE_CIUDAD_DEST,
		CIL.CLIENTE,
		CIL.NOMBRE_CLIENTE,
		CIL.DIRECCION_DEPENDENCIA,
		CIL.CANAL,
		CIL.NOMBRE_CANAL,
		CIL.PESO_VOLU_OPERA,
