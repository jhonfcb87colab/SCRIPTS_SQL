		CIL.LARGO_ENV_OPERA,
		CIL.ANCHO_ENV_OPERA,
		CIL.ALTO_ENV_OPERA,
		CIL.NUMERO_PIEZAS,
		CIL.ID_PROCESO,
		CIL.NOMBRE_PROCESO_LOG,
		CIL.NOMBRE_TIPOENVIO,
		CIL.FECHA_ENVIO,
		CIL.FECHA_MODIFICACION,
		CIL.HORA_MODIFICACION,
		CIL.NUMMANIF,
		CIL.CONS_MANIFIESTO,
		CIL.NOMBRE_EMPLEADO,
		CIL.CODPRO,
		CIL.NOMPRO,
		CIL.CODSUBPRO,
		CIL.NOMSUBPRO,
