/******************************EXTRAER IFNORMACION DEL MODELO *******************************************/

;WITH CIL AS (
SELECT 
	ROW_NUMBER() OVER(PARTITION BY SEG.NUMERO_GUIA ORDER BY SEG.FECHA_HORA_MOVIMIENTO DESC) as #ROW,
	1 AS X
	
	---,DIV.NOMBRE_DIVISION AS NOMBRE_DIVISION_UBICACION
	,DIVISION_UBICACION = CASE WHEN SEG.ID_PROCESO IN(7,12,9) THEN DOC.ID_DIVISION_ORIGEN
								WHEN SEG.ID_PROCESO IN(5,6,8,10,14,15,17,19,20,21) THEN DOC.ID_DIVISION_DESTINO
								ELSE DOC.ID_DIVISION_DESTINO END
	,G.NUMERO_GUIA	
	
	--,ISNULL(CIUUBICA.NOMBRE_CIUDAD,'NA') AS NOMBRE_CIUDAD_UBICACION   ---ISNULL(DOC.ID_CIUDAD_DESTINO,0) 
	,ID_CIUDAD_UBICACION =  CASE WHEN SEG.ID_PROCESO IN(7,12,9) THEN DOC.ID_CIUDAD_DIVISION_ORIGEN
								WHEN SEG.ID_PROCESO IN(5,6,8,10,14,15,17,19,20,21) THEN DOC.ID_CIUDAD_DESTINO
								ELSE DOC.ID_CIUDAD_DESTINO END	

	,ISNULL(G.ID_CIUDAD_ORIGEN,0) AS CIUDAD_ORIGEN
	,ISNULL(CIUORI.NOMBRE_CIUDAD,'' ) AS NOMBRE_CIUDAD_ORIGEN
	,ISNULL(G.ID_CIUDAD_DESTINO,0) AS CIUDAD_DESTINO
	,ISNULL(CIUDEST.NOMBRE_CIUDAD,'' ) AS NOMBRE_CIUDAD_DEST
	,ISNULL(G.ID_CLIENTE, '' ) AS CLIENTE,ISNULL(CLI.NOMBRE_CLIENTE,'' ) AS NOMBRE_CLIENTE
	,ISNULL(DEP.DIRECCION_PRINCIPAL_DEPENDEN,'' ) AS DIRECCION_DEPENDENCIA,ISNULL(G.ID_CANAL,'' ) AS CANAL
	,ISNULL(CAN.NOMBRE_DIVISION,'' ) AS NOMBRE_CANAL,
	G.PESO_VOLU_OPERA,G.PESO_FISICO_OPERA,G.LARGO_ENV_OPERA,G.ANCHO_ENV_OPERA,G.ALTO_ENV_OPERA,G.NUMERO_PIEZAS,
	ISNULL(PR.ID_PROCESO,'')AS ID_PROCESO,
	ISNULL(PR.NOMBRE_PROCESO_LOG,'' ) AS NOMBRE_PROCESO_LOG ,
	ISNULL(TIPENV.NOMBRE_TIPOENVIO,'' ) AS NOMBRE_TIPOENVIO, G.FECHA_ENVIO,
	LEFT(CAST(SEG.FECHA_HORA_MOVIMIENTO AS VARCHAR(20)),11) AS FECHA_MODIFICACION,
	SUBSTRING(CAST(SEG.FECHA_HORA_MOVIMIENTO AS VARCHAR(20)),13,8) AS HORA_MODIFICACION,
	SEG.NUMERO_MOVIMI AS NUMMANIF,
	SEG.CONSECUT_MOVIMI As CONS_MANIFIESTO,
	ISNULL(EMP.NOMBRE_EMPLEADO,'' )  + ' '  +  ISNULL(EMP.APELLIDO_EMPLEADO,'' ) AS NOMBRE_EMPLEADO,
	ISNULL(G.ID_PRODUCTO, 0) AS CODPRO, 
	RTRIM(ISNULL(PROD.NOMBRE_PRODUCTO, '')) AS NOMPRO,
	ISNULL(G.ID_SUBPRODUCTO, 0) AS CODSUBPRO, 
	RTRIM(ISNULL(SPROD.NOMBRE_SUBPRODUCTO, '')) AS NOMSUBPRO,
	G.ID_MEDTRANS,
	G.ID_TIEMPO AS TIMEID,
	DOC.ID_ZONA_URBA,
	DOC.ID_TIPO_ZONA_URBA,
	SEG.ID_CONCEPTO AS ULT_ID_CONCEPTO
FROM #LOG_GUIAS_TABLA_TEMPORAL AS G WITH (NOLOCK) 
	INNER JOIN  #LOG_SEGUIMIENTO_ENVIO_TABLA_TEMPORAL_02 AS SEG WITH (NOLOCK) ON SEG.NUMERO_GUIA = G.NUMERO_GUIA 
	INNER JOIN  #LOG_DOCUMENTOS_TABLA_TEMPORAL_02 AS DOC WITH(NOLOCK) ON SEG.ID_PROCESO = DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI = DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI = DOC.CONSECUT_MOVIMI
	LEFT JOIN  PARAMETROS..CIUDADES AS CIUORI WITH (NOLOCK) ON G.ID_PAIS_ORIGEN = CIUORI.ID_PAIS AND G.ID_CIUDAD_ORIGEN = CIUORI.ID_CIUDAD 
	LEFT JOIN  PARAMETROS..CIUDADES AS CIUDEST WITH (NOLOCK) ON G.ID_PAIS_DESTINO = CIUDEST.ID_PAIS AND G.ID_CIUDAD_DESTINO = CIUDEST.ID_CIUDAD 
	LEFT JOIN  PARAMETROS..CLIENTES AS CLI WITH (NOLOCK) ON G.ID_CLIENTE = CLI.ID_CLIENTE 
	LEFT JOIN  PARAMETROS..CLIENTES_SUCURSALES_DEPENDEN AS DEP WITH (NOLOCK) ON G.ID_CLIENTE = DEP.ID_CLIENTE AND G.ID_1 = DEP.ID_SUCURSAL AND G.ID_2 = DEP.ID_DEPENDEN 
	LEFT JOIN  PARAMETROS..DIVISIONES AS CAN WITH (NOLOCK) ON 1 = DOC.ID_PAIS_DESTINO AND DOC.ID_CIUDAD_DESTINO = CAN.ID_CIUDAD AND DOC.ID_DIVISION_DESTINO = CAN.ID_DIVISION 
	LEFT JOIN  PARAMETROS..PROCESOS AS PR WITH (NOLOCK) ON PR.ID_PROCESO =  SEG.ID_PROCESO
	LEFT JOIN  PARAMETROS..TIPO_ENVIO AS TIPENV WITH (NOLOCK) ON SEG.ID_TIPOENVIO = TIPENV.ID_TIPOENVIO 
	LEFT JOIN  PARAMETROS..EMPLEADOS AS EMP WITH (NOLOCK) ON SEG.ID_EMPLEADO = EMP.ID_EMPLEADO 
	LEFT JOIN  PARAMETROS..PRODUCTOS  AS PROD WITH (NOLOCK) ON G.ID_PRODUCTO = PROD.ID_PRODUCTO 
	LEFT JOIN  PARAMETROS..SUBPRODUCTOS AS SPROD WITH (NOLOCK) ON G.ID_PRODUCTO = SPROD.ID_PRODUCTO AND G.ID_SUBPRODUCTO = SPROD.ID_SUBPRODUCTO 
)
