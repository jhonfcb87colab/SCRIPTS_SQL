USE SIG_COLOMBIA_DW;

SELECT TOP 1000 * FROM  [FAC].[MOXP_BASE0] WITH(NOLOCK)

---------------->DIMENSION UEN
SELECT 
	ID_UEN	
	, CLAVE_DIM = right('00' + convert(varchar,id_producto),2) + right( '0000' +  convert(varchar, id_subproducto),4)
	,NOMBRE_UEN	
	,ID_PRODUCTO	
	,NOMBRE_PRODUCTO	
	,ID_SUBPRODUCTO	
	,NOMBRE_SUBPRODUCTO
FROM DIM.UEN_PROD_SUBP WITH(NOLOCK)


-----------> UPDATE SOBRE LA TABLA BASE 
SELECT 
TOP 1000 
G.NUMERO_GUIA,
G.ID_PRODUCTO,
P.NOMBRE_PRODUCTO,
G.ID_SUBPRODUCTO,
SP.NOMBRE_SUBPRODUCTO
FROM SIG_COLOMBIA_DW.LOG.GUIAS G WITH(NOLOCK)
LEFT JOIN SIG_COLOMBIA_DW.PAR.PRODUCTOS P WITH(NOLOCK)
ON G.ID_PRODUCTO=P.ID_PRODUCTO
LEFT JOIN SIG_COLOMBIA_DW.PAR.SUBPRODUCTOS SP WITH(NOLOCK)
ON G.ID_SUBPRODUCTO=SP.ID_SUBPRODUCTO

SELECT * FROM SIG_COLOMBIA_DW.PAR.PRODUCTOS
