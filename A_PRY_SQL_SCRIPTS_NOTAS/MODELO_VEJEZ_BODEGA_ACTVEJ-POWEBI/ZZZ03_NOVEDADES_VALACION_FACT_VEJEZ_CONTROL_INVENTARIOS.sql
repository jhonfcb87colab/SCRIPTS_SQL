WITH CTE1 AS (
SELECT NUMERO_GUIA,
DATEDIFF(DAY,CONVERT(DATE,FEC_ULT_MOV_LOGISTICO),GETDATE()) AS DIAS_DIF_CON_FES --9165511338
FROM FAC.VEJEZ_BODEGAS WITH(NOLOCK)
),
CTE2 AS(
SELECT NUMERO_GUIA,
		SUM(VB3.DIA_FESTIVO) TOTAL_DIAS_FES
FROM SIG_COLOMBIA_DW.TMP.VEJEZ_BODEGAS_03 VB3 WITH(NOLOCK)
LEFT JOIN FAC.VEJEZ_BODEGAS VB WITH(NOLOCK)
ON CONVERT(DATE,VB3.FECHA) BETWEEN CONVERT(DATE,VB.FEC_ULT_MOV_LOGISTICO) AND GETDATE()
GROUP BY NUMERO_GUIA
)SELECT   
----------UPDATE FAC.VEJEZ_BODEGAS SET 
DIAS_VEJEZ_02 = CTE1.DIAS_DIF_CON_FES - CTE2.TOTAL_DIAS_FES
FROM FAC.VEJEZ_BODEGAS VB WITH(NOLOCK)
INNER JOIN CTE1 WITH(NOLOCK)
ON VB.NUMERO_GUIA = CTE1.NUMERO_GUIA
INNER JOIN CTE2 WITH(NOLOCK)
ON VB.NUMERO_GUIA = CTE2.NUMERO_GUIA
WHERE VB.NUMERO_GUIA=2208802612
