DROP TABLE IF EXISTS #GUIAS_CALCULO_TIEMPO_PROMESA_P01;
DROP TABLE IF EXISTS #GUIAS_CALCULO_TIEMPO_PROMESA_P02;
SELECT *
INTO #GUIAS_CALCULO_TIEMPO_PROMESA_P01
FROM (
	SELECT 
		NUMERO_GUIA,
		ID_MEDTRANS,
		ID_TIEMPO,
		ID_CIUDAD_ORIGEN AS ID_CIUDAD_ORIGEN,
		ID_CIUDAD_DESTINO AS ID_CIUDAD_DESTINO
	FROM SIG_COLOMBIA_DW.[TMP].[VEJEZ_BODEGAS_SZU] WITH(NOLOCK)
	WHERE TIEMPO_OFERTA IS NULL
UNION ALL
	SELECT 
		NUMERO_GUIA,
		ID_MEDTRANS,
		TIMEID,
		CIUDAD_ORIGEN AS ID_CIUDAD_ORIGEN,
		CIUDAD_DESTINO AS ID_CIUDAD_DESTINO
	FROM SIG_COLOMBIA_DW.[TMP].[VEJEZ_BODEGAS] WITH(NOLOCK)
	WHERE TIEMPO_OFERTA IS NULL
) T
GROUP BY 
T.NUMERO_GUIA	
,T.ID_MEDTRANS	
,T.ID_TIEMPO	
,T.ID_CIUDAD_ORIGEN	
,T.ID_CIUDAD_DESTINO

;WITH CTE AS (
SELECT 
ROW_NUMBER ( )   OVER ( PARTITION BY TMP.[NUMERO_GUIA] order by CONVERT(INT,RA.TIEMPO_ENTREGA_COMERCIAL_DIA) desc )  #ROW_ID  
,TMP.NUMERO_GUIA	
,TMP.ID_MEDTRANS	
,TMP.ID_TIEMPO	
,TMP.ID_CIUDAD_ORIGEN	
,TMP.ID_CIUDAD_DESTINO 
,CONVERT(INT,RA.TIEMPO_ENTREGA_COMERCIAL_DIA) SE_ID_DIAS_PROMESA
FROM #GUIAS_CALCULO_TIEMPO_PROMESA_P01 TMP
	INNER JOIN
		[SERV-DBI01,9971].SIG_COL_LOGISTICA_DW.DIM.RED_OPERATIVA_RUTA RA WITH(NOLOCK) 
	ON
		TMP.ID_CIUDAD_ORIGEN = RA.ID_CIUDAD_ORIGEN
	AND
		TMP.ID_CIUDAD_DESTINO = RA.ID_CIUDAD_DESTINO
	AND
		CASE WHEN ISNULL(TMP.ID_TIEMPO,0) <> 0 THEN TMP.ID_TIEMPO ELSE 1 END = RA.ID_TIEMPO
	AND
		CASE WHEN ISNULL(TMP.ID_MEDTRANS,0) <> 0 THEN TMP.ID_MEDTRANS ELSE 1 END = RA.ID_MEDTRANS
)
SELECT 
NUMERO_GUIA
,ID_MEDTRANS	
,ID_TIEMPO	
,ID_CIUDAD_ORIGEN	
,ID_CIUDAD_DESTINO	
,SE_ID_DIAS_PROMESA
INTO #GUIAS_CALCULO_TIEMPO_PROMESA_P02
FROM CTE WHERE #ROW_ID=1;


------UPDATE TMP
------SET
SELECT C.NUMERO_GUIA,TMP.TIEMPO_OFERTA,
	TIEMPO_OFERTA = C.SE_ID_DIAS_PROMESA
FROM
	SIG_COLOMBIA_DW.TMP.VEJEZ_BODEGAS TMP
INNER JOIN #GUIAS_CALCULO_TIEMPO_PROMESA_P02 C
	ON 	TMP.NUMERO_GUIA = C.NUMERO_GUIA;


----------UPDATE TMP
----------SET
SELECT C.NUMERO_GUIA,TMP.TIEMPO_OFERTA,
	TIEMPO_OFERTA = C.SE_ID_DIAS_PROMESA
FROM
	SIG_COLOMBIA_DW.TMP.VEJEZ_BODEGAS_SZU TMP
INNER JOIN #GUIAS_CALCULO_TIEMPO_PROMESA_P02 C
	ON 	TMP.NUMERO_GUIA = C.NUMERO_GUIA;



