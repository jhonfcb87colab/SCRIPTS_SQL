SELECT 
[ESTADO_TRANSMISION],
[VERSION_FE],
[ESTADO_TRANSMISION_CL] =
					CASE WHEN [VERSION_FE]=2 THEN [ESTADO_TRANSMISION] ELSE
					 ( CASE
					   WHEN ([ESTADO_REPORTADO_DIAN]= 1 AND [ESTADO_TRANSACCION_DIAN]=1)  THEN 2						------ESTADO_TRSNMISION=2
					   WHEN ([ESTADO_REPORTADO_DIAN] IS NULL AND [ESTADO_TRANSACCION_DIAN] IS NULL) THEN 0			------ESTADO_TRSNMISION=0
					   WHEN ([ESTADO_REPORTADO_DIAN] = 1 AND [ESTADO_TRANSACCION_DIAN] IS NULL)  THEN 3				------ESTADO_TRSNMISION=3
					   WHEN ([ESTADO_REPORTADO_DIAN] = 0 AND [ESTADO_TRANSACCION_DIAN] IS NULL) THEN 0				------ESTADO_TRSNMISION=1
					   WHEN ([ESTADO_REPORTADO_DIAN] = 0 AND [ESTADO_TRANSACCION_DIAN] = 0)	THEN  0                 ------ESTADO_TRSNMISION=1
					ELSE 
				0 END )
			END
FROM FAC.DIAN_NOTAS_CREDITO_REGISTRADAS WITH (NOLOCK)
