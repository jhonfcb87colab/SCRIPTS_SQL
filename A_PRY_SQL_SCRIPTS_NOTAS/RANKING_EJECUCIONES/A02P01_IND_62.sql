INSERT INTO #TMP_PQR_RANKING_INDICADOR_ID_62_PASO_1
SELECT  
TIM.[YEAR]*100+TIM.MONTH_OF_YEAR AS ID_MES,
Id_indicador=62,
TEMP_GEO.ID_REGIONAL,
TEMP_GEO.NOMBRE_REGIONAL,
SUM(PQR.VALOR_RESPONSABILIDAD) AS VALOR_RESPONSABILIDAD,
count(PQR.VALOR_RESPONSABILIDAD) AS NUMERO_PQR_INDEM
--INTO [COGNOS_STG_V3].DBO.TMP_PQR_RANKING_INDICADOR_ID_62_PASO_1
FROM SIG_COL_LOGISTICA_DW.FAC.PQR_RESPONSABILIDAD_INDEM PQR WITH(NOLOCK)
INNER JOIN #PQR_GEOGRAFIA_20230417 TEMP_GEO WITH(NOLOCK) 
ON PQR.ID_CIUDAD_RESP=TEMP_GEO.ID_CIUDAD AND TEMP_GEO.ID_PAIS=PQR.ID_PAIS_RESP
INNER JOIN SIG_COL_LOGISTICA_DW.DIM.TIEMPO TIM WITH(NOLOCK) ON TIM.TIME_ID=PQR.TIME_ID_FECHA_PROCESO_INDEM
INNER JOIN SIG_COL_LOGISTICA_DW.DIM.PQR_ESTADOS_INDEMNIZACION ESTADO WITH(NOLOCK) 
ON PQR.ID_ESTADO_INDEMNIZACION_PQR=ESTADO.ID_ESTADO_INDEMNIZACION_PQR
WHERE TIM.[YEAR]*100+TIM.MONTH_OF_YEAR=@ID_MES
AND ESTADO.NOMBRE_ESTADO_INDEMNIZACION_PQR='INDEMNIZADO'
GROUP BY 
TIM.[YEAR]*100+TIM.MONTH_OF_YEAR,
TEMP_GEO.ID_REGIONAL,
TEMP_GEO.NOMBRE_REGIONAL
order by 1,3

