SELECT 
	A.AÑO * 100 + MES as id_mes
	, c.id_regional
	--      ,ID_CIUDAD_ORIGEN
	--      ,ID_CIUDAD_DESTINO]
	--      ,[ID_CLIENTE]
	, sum(a.CANT_GUIAS) CANT_GUIAS 
	, sum(a.CANT_PIEZAS) CANT_PIEZAS
	, sum(a.TIEMPO_OFERTA) TIEMPO_OFERTA 
	, sum(a.TIEMPO_EN_ENTREGA) TIEMPO_EN_ENTREGA
	, sum(a.TIEMPO_PROMESA_CUMPLE_D) TIEMPO_PROMESA_CUMPLE_D
	, sum(CASE    WHEN (a.TIEMPO_EN_ENTREGA/24) <= a.TIEMPO_OFERTA THEN a.CANT_GUIAS
		ELSE 0
	END) CANTIDAD_GUIAS_T_PROMESA
	, sum(CASE 
		WHEN (a.TIEMPO_EN_ENTREGA/24) <= a.TIEMPO_OFERTA THEN a.CANT_PIEZAS
		ELSE 0
	END) CANTIDAD_PIEZAS_T_PROMESA
FROM SIG_COL_LOGISTICA_DW.FAC.ENVIOS_MOVILIZADOS A WITH(NOLOCK) 
INNER JOIN  SIG_COL_LOGISTICA_DW.DIM.TIEMPO B WITH(NOLOCK) ON a.time_id = b.time_id AND YEAR(B.date) * 100 + month(B.date) = 202301
INNER JOIN 	SIG_COL_LOGISTICA_DW.DIM.CIUDADES_MOVIMIENTOS C WITH(NOLOCK)
	ON  --where a.time_id = b.time_id
		--and a.ID_CIUDAD_ORIGEN = c.id_ciudad and
		 A.ID_CIUDAD_DESTINO = C.id_ciudad
		AND C.id_regional <> 0
GROUP BY 
A.AÑO * 100 + A.MES
, C.ID_REGIONAL






