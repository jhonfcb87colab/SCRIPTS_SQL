WITH PQR_RESPON_INDEM AS (
	SELECT 
	YEAR(A.FECHA_PROCESO_INDEM)*100+MONTH(A.FECHA_PROCESO_INDEM) AS ID_PERIODO,
	C.ID_REGIONAL,
	A.ID_ESTADO_INDEMNIZACION_PQR,
	A.ID_TIPO_SOLICITUD_FINAL_PQR,
	A.ID_PQR,
	A.PORCENTAJE_RESPONSABILIDAD
	FROM 
	SIG_COL_LOGISTICA_DW.FAC.PQR_RESPONSABILIDAD_INDEM A 
	INNER JOIN 
	SIG_COL_LOGISTICA_DW.DIM.CIUDADES C
	ON 
	A.ID_CIUDAD_RESP = C.ID_CIUDAD
	--AND A.ID_PROCESO_PQR =2 -- INVESTIGACIONES
	WHERE 
	 A.ID_ESTADO_INDEMNIZACION_PQR = 2  -- EL VALOR 2 ES "INDEMNIZADO"
	--AND A.ID_TIPO_SOLICITUD_FINAL_PQR = 2  -- EL VALOR 2 ES "PERDIDA"
	---AND C.ID_REGIONAL <> 0 
	AND C.ID_REGIONAL=8
	AND YEAR(A.FECHA_PROCESO_INDEM)*100+MONTH(A.FECHA_PROCESO_INDEM) = 202301
	AND A.ID_TIPO_SOLICITUD_FINAL_PQR=3
), VALORES_PQR_INDEM AS (
SELECT  
ID_PERIODO, ID_REGIONAL , ID_TIPO_SOLICITUD_FINAL_PQR
,(SUM(PORCENTAJE_RESPONSABILIDAD)/100) AS PORC_PQR_RESPON
FROM PQR_RESPON_INDEM AS PQR
GROUP BY ID_PERIODO, ID_REGIONAL , ID_TIPO_SOLICITUD_FINAL_PQR
)
SELECT 
ID_PERIODO, ID_REGIONAL,ID_TIPO_SOLICITUD_FINAL_PQR
,SUM(PORC_PQR_RESPON) AS CANTIDAD_TOTAL,
SUM(CASE WHEN ID_TIPO_SOLICITUD_FINAL_PQR = 2 THEN PORC_PQR_RESPON ELSE 0 END)  CANTIDAD_ENVIOS_PERDIDOS,
SUM(CASE WHEN ID_TIPO_SOLICITUD_FINAL_PQR = 3 THEN PORC_PQR_RESPON ELSE 0 END)  CANTIDAD_ENVIOS_ESPOLIADOS,
SUM(CASE WHEN ID_TIPO_SOLICITUD_FINAL_PQR = 1 THEN PORC_PQR_RESPON ELSE 0 END)  CANTIDAD_ENVIOS_AVERIADOS,
SUM(CASE WHEN ID_TIPO_SOLICITUD_FINAL_PQR  NOT IN (1,2,3) OR ID_TIPO_SOLICITUD_FINAL_PQR IS NULL 
	THEN PORC_PQR_RESPON ELSE 0 END) /50 CANTIDAD_OTROS
FROM VALORES_PQR_INDEM
GROUP BY ID_PERIODO, ID_REGIONAL,ID_TIPO_SOLICITUD_FINAL_PQR

