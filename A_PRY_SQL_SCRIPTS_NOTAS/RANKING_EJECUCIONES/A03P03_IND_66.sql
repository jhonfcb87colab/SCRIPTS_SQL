SELECT 
	YEAR(A.FECHA_PROCESO_INDEM)*100+MONTH(A.FECHA_PROCESO_INDEM) AS ID_PERIODO
    ,C.ID_REGIONAL
	,REG.NOMBRE_REGIONAL
	,CANTIDAD_ENVIOS_INEFICIENTES = ROUND(SUM(PORCENTAJE_RESPONSABILIDAD)/100,2) 
	INTO  [TMP_BORRAR].[dbo].[TEMP_CALCULO_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO02]
	FROM 
	SIG_COL_LOGISTICA_DW.FAC.PQR_RESPONSABILIDAD_INDEM A WITH(NOLOCK) 
	INNER JOIN 
	SIG_COL_LOGISTICA_DW.DIM.CIUDADES C WITH(NOLOCK)
	ON 
	A.ID_CIUDAD_RESP = C.ID_CIUDAD	
	INNER JOIN 
	SIG_COL_LOGISTICA_DW.DIM.REGIONALES_PAIS REG WITH(NOLOCK)
	ON REG.ID_REGIONAL_PAIS=C.ID_REGIONAL
	INNER JOIN DIM_INDICADOR_RANKING DIM_IND WITH(NOLOCK)
	ON DIM_IND.id_indicador=@ID_INDICADOR
	WHERE 
	 A.ID_ESTADO_INDEMNIZACION_PQR = 2  -- EL VALOR 2 ES "INDEMNIZADO"
	AND C.ID_REGIONAL <> 0
	AND YEAR(A.FECHA_PROCESO_INDEM)*100+MONTH(A.FECHA_PROCESO_INDEM) = @ID_MES
	AND A.ID_TIPO_SOLICITUD_FINAL_PQR NOT IN (5,17)
	GROUP BY 
	YEAR(A.FECHA_PROCESO_INDEM)*100+MONTH(A.FECHA_PROCESO_INDEM)
    ,C.ID_REGIONAL,REG.NOMBRE_REGIONAL
	ORDER BY C.ID_REGIONAL



