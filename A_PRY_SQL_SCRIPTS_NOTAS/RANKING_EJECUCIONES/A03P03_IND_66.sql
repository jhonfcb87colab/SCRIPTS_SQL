DECLARE @ID_INDICADOR INT,@ID_MES INT,@ANIO INT;
SET @ID_INDICADOR = 66;
SET @ID_MES= (SELECT ID_PERIODO FROM PRM_PROCESO_RAN where Estado_Proceso = 0)
SET @ANIO=LEFT(@ID_MES,4) 
--SELECT @ID_INDICADOR,@ID_MES,@ANIO

