----INSERTAR  ENVIOS MOVILIZADOS CON Geografia destino 
INSERT INTO #TEMP_CALCULO_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO01
SELECT 
id_mes,id_regional, 
CANT_PIEZAS AS CANT_MOVILIZADOS 
FROM [EXTR_ENVIOS_MOV_DESTINO] WHERE id_mes=202301
ORDER BY 2


-------TABLA PQR'S con la dimesion de PQR_TIPO_SOLICITUD_FINAL.Tipo Solicitud   "retirando siniestro externo y prueba"
INSERT INTO #TEMP_CALCULO_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO02
SELECT 
	YEAR(A.FECHA_PROCESO_INDEM)*100+MONTH(A.FECHA_PROCESO_INDEM) AS ID_PERIODO
    ,C.ID_REGIONAL
	,REG.NOMBRE_REGIONAL
	,CANTIDAD_ENVIOS_INEFICIENTES = ROUND(SUM(PORCENTAJE_RESPONSABILIDAD)/100,2) 
	FROM 
	SIG_COL_LOGISTICA_DW.FAC.PQR_RESPONSABILIDAD_INDEM A WITH(NOLOCK) 
	INNER JOIN 
	SIG_COL_LOGISTICA_DW.DIM.CIUDADES C WITH(NOLOCK)
	ON 
	A.ID_CIUDAD_RESP = C.ID_CIUDAD	
	INNER JOIN 
	SIG_COL_LOGISTICA_DW.DIM.REGIONALES_PAIS REG WITH(NOLOCK)
	ON REG.ID_REGIONAL_PAIS=C.ID_REGIONAL
	INNER JOIN DIM_INDICADOR_RANKING DIM_IND WITH(NOLOCK)
	ON DIM_IND.id_indicador=@ID_INDICADOR
	WHERE 
	 A.ID_ESTADO_INDEMNIZACION_PQR = 2  -- EL VALOR 2 ES "INDEMNIZADO"
	AND C.ID_REGIONAL <> 0
	AND YEAR(A.FECHA_PROCESO_INDEM)*100+MONTH(A.FECHA_PROCESO_INDEM) = @ID_MES
	AND A.ID_TIPO_SOLICITUD_FINAL_PQR NOT IN (5,17)
	GROUP BY 
	YEAR(A.FECHA_PROCESO_INDEM)*100+MONTH(A.FECHA_PROCESO_INDEM)
    ,C.ID_REGIONAL,REG.NOMBRE_REGIONAL
	ORDER BY C.ID_REGIONAL

	INSERT INTO #TEMP_CALCULO_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO02
	SELECT 
	TMP.ID_PERIODO	
	,ID_REGIONAL= REG.ID_REGIONAL
	,NOMBRE_REGIONAL = REG.NOMBRE_REGIONAL	
	,CANTIDAD_ENVIOS_INEFICIENTES = SUM(CANTIDAD_ENVIOS_INEFICIENTES)
	FROM #TEMP_CALCULO_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO02 TMP
	INNER JOIN SIG_COL_LOGISTICA_DW.DIM.REGIONALES_PAIS REG WITH(NOLOCK)
	ON REG.ID_REGIONAL=99
	GROUP BY TMP.ID_PERIODO,REG.ID_REGIONAL,REG.NOMBRE_REGIONAL


-----CREAR CONSOLIDADO PARA CALCULAR EL VALOR REAL	
INSERT INTO #TEMP_CALCULO_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO03
SELECT 
	TMP02.ID_PERIODO	
	,TMP02.ID_REGIONAL	
	,TMP02.NOMBRE_REGIONAL	
	,TMP02.CANTIDAD_ENVIOS_INEFICIENTES
	,CANT_MOVILIZADOS= TMP01.CANT_MOVILIZADOS
	,VALOR_REAL = CASE 
					WHEN TMP02.CANTIDAD_ENVIOS_INEFICIENTES=0 OR TMP01.CANT_MOVILIZADOS = 0 THEN 0
					ELSE TMP02.CANTIDAD_ENVIOS_INEFICIENTES / ( TMP01.CANT_MOVILIZADOS /50000)
					END
FROM #TEMP_CALCULO_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO02 TMP02
INNER JOIN #TEMP_CALCULO_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO01 TMP01
ON TMP02.ID_PERIODO=TMP01.id_mes AND TMP02.ID_REGIONAL=TMP01.id_regional


--- CALCULO VALOR CUMPLIMIENTO 
INSERT INTO #EXTR_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO01
SELECT
ID_MES = TMP01.ID_PERIODO	
,ID_REGIONAL = TMP01.ID_REGIONAL	
,NOMBRE_REGIONAL = TMP01.NOMBRE_REGIONAL
,Id_indicador = DIM_RAN.id_indicador
,Nombre_Indicador = DIM_RAN.Nombre_Indicador
,Marca_meta = DIM_RAN.Marca_meta
,Puntos = DIM_RAN.Puntos
,LIMITE_SUP = METAS.VALOR_LIMITE_SUPERIOR
,LIMITE_INF = METAS.VALOR_LIMITE_INFERIOR
,VALOR_REAL = TMP01.VALOR_REAL
,VALOR_CUMPLIMIENTO = IIF(
						(DIM_RAN.Marca_meta - TMP01.VALOR_REAL) / (METAS.VALOR_LIMITE_SUPERIOR-METAS.VALOR_LIMITE_INFERIOR)>=0,
						1+(DIM_RAN.Marca_meta - TMP01.VALOR_REAL ) / (METAS.VALOR_LIMITE_SUPERIOR-METAS.VALOR_LIMITE_INFERIOR),
						(DIM_RAN.Marca_meta - TMP01.VALOR_REAL) / ( METAS.VALOR_LIMITE_SUPERIOR-METAS.VALOR_LIMITE_INFERIOR )
						)
,PUNTAJE_MES = 0
,PORC_PUNTOS = 0
FROM #TEMP_CALCULO_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO03 TMP01
INNER JOIN DBO.DIM_INDICADOR_RANKING DIM_RAN WITH(NOLOCK)
ON DIM_RAN.id_indicador=@ID_INDICADOR
INNER JOIN SIG_COL_LOGISTICA_DW.RAN.METAS_LIMITES METAS WITH(NOLOCK)
ON METAS.ID_INDICADOR=DIM_RAN.id_indicador


---CALCULO VALOR DELPUNTAJEMES Y PROCENTAJE PUNTOS
INSERT INTO #EXTR_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO02
SELECT 
TMP.ID_MES	
,TMP.ID_REGIONAL	
,TMP.NOMBRE_REGIONAL	
,TMP.Id_indicador	
,TMP.Nombre_Indicador	
,TMP.Marca_meta	
,TMP.Puntos	
,TMP.LIMITE_SUP	
,TMP.LIMITE_INF	
,TMP.VALOR_REAL	
,TMP.VALOR_CUMPLIMIENTO	
,PUNTAJE_MES	= IIF(TMP.VALOR_REAL <= TMP.Marca_meta,
										TMP.Puntos,
												IIF(
													(TMP.VALOR_REAL	- TMP.LIMITE_SUP)>0,
													0,
													(1-ABS(TMP.VALOR_CUMPLIMIENTO)*TMP.Puntos)
													)
					)
,TMP.PORC_PUNTOS
FROM #EXTR_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO01 TMP


