,TMP.VALOR_CUMPLIMIENTO	
,TMP.PUNTAJE_MES	
,PORC_PUNTOS = TMP.PUNTAJE_MES / TMP.Puntos	
FROM #EXTR_IND_66_Cant_ineficiencas_x_50MIL_movili_PASO02 TMP




