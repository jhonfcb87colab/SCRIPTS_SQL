TRUNCATE TABLE [dbo].[EXTR_IND_15_Indemnizaciones_de_PQR_Vs_Venta]
DECLARE @ID_INDICADOR INT,@ID_MES INT,@ANIO INT;
SET @ID_INDICADOR = 15;
SET @ID_MES= (SELECT ID_PERIODO FROM PRM_PROCESO_RAN where Estado_Proceso = 0)
SET @ANIO= LEFT(@ID_MES,4)

INSERT INTO [dbo].[EXTR_IND_15_Indemnizaciones_de_PQR_Vs_Venta]
SELECT 
		ID_MES = @ID_MES
		,ID_REGIONAL = GEO.ID_REGIONAL
		,NOMBRE_REGIONAL  = GEO.NOMBRE_REGIONAL
		,Id_indicador  = INDIC.id_indicador
		,Nombre_Indicador =  INDIC.Nombre_Indicador ---(SELECT INDIC.Nombre_Indicador FROM DBO.DIM_INDICADOR_RANKING INDIC WHERE id_indicador=@ID_INDICADOR)
		,Marca_meta  = INDIC.Marca_meta
		,Puntos  = INDIC.Puntos
		,LIMITE_SUP  = METAS.VALOR_LIMITE_SUPERIOR
		,LIMITE_INF  = METAS.VALOR_LIMITE_INFERIOR
		,VALOR_REAL  = 0
		,VALOR_CUMPLIMIENTO  = 0
		,PUNTAJE_MES  = 0
		,PORC_PUNTOS  = 0
FROM DBO.DIM_GEOGRAFIA_RANKING GEO WITH(NOLOCK)
INNER JOIN DBO.DIM_INDICADOR_RANKING INDIC WITH(NOLOCK)
ON INDIC.id_indicador=@ID_INDICADOR
INNER JOIN [SIG_COL_LOGISTICA_DW].RAN.METAS_LIMITES METAS WITH(NOLOCK)
ON METAS.AÑO=@ANIO AND METAS.ID_INDICADOR=@ID_INDICADOR
WHERE GEO.ID_REGIONAL>=1
ORDER BY 2




