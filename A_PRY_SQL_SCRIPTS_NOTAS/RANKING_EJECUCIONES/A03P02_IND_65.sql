DECLARE @ID_INDICADOR INT,@ID_MES INT,@ANIO INT;
SET @ID_INDICADOR = 65;
SET @ID_MES= (SELECT ID_PERIODO FROM PRM_PROCESO_RAN where Estado_Proceso = 0)
SET @ANIO=LEFT(@ID_MES,4) 
INSERT INTO #EXTR_IND_65_Cumpl_Ppto_Total_de_Ingresos_PASO_01
SELECT 
		ID_MES = @ID_MES
		,ID_REGIONAL = GEO.ID_REGIONAL
		,NOMBRE_REGIONAL  = GEO.NOMBRE_REGIONAL
		,Id_indicador  = @ID_INDICADOR
		,Nombre_Indicador  = (SELECT INDIC.Nombre_Indicador FROM DBO.DIM_INDICADOR_RANKING INDIC WHERE id_indicador=@ID_INDICADOR)
		,Marca_meta  = CONVERT(FLOAT,METAS.VALOR_META)
		,Puntos  = (SELECT INDIC.Puntos FROM DBO.DIM_INDICADOR_RANKING INDIC WHERE id_indicador=@ID_INDICADOR)
		,LIMITE_SUP  = METAS.VALOR_LIMITE_SUPERIOR
		,LIMITE_INF  = METAS.VALOR_LIMITE_INFERIOR
		,VALOR_REAL  = PRESUP.PORCENTAJE_VENTAS_TOTALES
		,VALOR_CUMPLIMIENTO  = PRESUP.PORCENTAJE_VENTAS_TOTALES / CONVERT(FLOAT,METAS.VALOR_META) 
		,PUNTAJE_MES  = 0 
		,PORC_PUNTOS  = 0
FROM DBO.DIM_GEOGRAFIA_RANKING GEO WITH(NOLOCK)
INNER JOIN	[SIG_COL_LOGISTICA_DW].[RAN].[METAS_LIMITES] METAS WITH(NOLOCK)	
ON @ID_INDICADOR=METAS.ID_INDICADOR 
AND METAS.AÑO=@ANIO 
--------AND GEO.ID_REGIONAL=METAS.ID_REGIONAL_PAIS
INNER JOIN [SIG_COL_LOGISTICA_DW].RAN.EJECUCION_PRESUPUESTAL PRESUP WITH(NOLOCK)	
ON PRESUP.ID_PERIODO=@ID_MES AND PRESUP.ID_REGIONAL_PAIS=GEO.ID_REGIONAL
WHERE GEO.ID_REGIONAL IN(1,2,3,4,5,6,8,9,10,11,99)
ORDER BY 2



INSERT INTO #EXTR_IND_65_Cumpl_Ppto_Total_de_Ingresos_PASO_02
SELECT [ID_MES]
      ,[ID_REGIONAL]
      ,[NOMBRE_REGIONAL]
      ,[Id_indicador]
      ,[Nombre_Indicador]
      ,[Marca_meta]
      ,[Puntos]
      ,[LIMITE_SUP]
      ,[LIMITE_INF]
      ,[VALOR_REAL]
      ,[VALOR_CUMPLIMIENTO]
      ,[PUNTAJE_MES] =   
				CASE	WHEN [VALOR_REAL]>=[Marca_meta] THEN CONVERT(FLOAT,[Puntos])
						WHEN VALOR_CUMPLIMIENTO<LIMITE_INF THEN 0
				ELSE ((VALOR_CUMPLIMIENTO-LIMITE_INF)*5)*CONVERT(FLOAT,Puntos)
				END
      ,[PORC_PUNTOS]
  FROM #EXTR_IND_65_Cumpl_Ppto_Total_de_Ingresos_PASO_01 B
  
  


