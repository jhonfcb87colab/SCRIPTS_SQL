INSERT INTO #MEM_EXTRACCION_GUIA_MASIVA(
G_NUMERO_GUIA
,G_ID_FECHA
,G_FECHA
,G_NUMERO_PIEZAS
,G_ID_TIEMPO_ENTREGA
,G_ID_PRODUCTO
,G_DIRE_DESTINO
,G_ID_CIUDAD_ORIGEN
,G_ID_CIUDAD_DESTINO
,G_ID_CLIENTE
,G_ID_ESTADO_ENVIO
,G_ID_PAIS_UBICACION
,G_ID_CIUDAD_UBICACION
,G_ID_DIVISION_UBICACION
,G_VALOR_DECLARADO
,G_ID_BODEGA_ULTM_MOVI
,G_FECHA_MODIFICACION_DG
)
SELECT
MGM.G_NUMERO_GUIA
,ISNULL(G.FECHA_ENVIO,'1900-01-01')AS FECHA_ENVIO
,ISNULL(CONVERT(VARCHAR, G.FECHA_ENVIO, 21),'NO DISPONIBLE') AS FECHA
,ISNULL(CASE WHEN G.NUMERO_PIEZAS = 0 THEN NULL ELSE G.NUMERO_PIEZAS END, 1) AS NUMERO_PIEZAS
,ISNULL(CONVERT(INT, CASE WHEN G.ID_TIEMPO = 0 THEN NULL ELSE G.ID_TIEMPO END), -888) AS ID_TIEMPO
,ISNULL(CASE WHEN G.ID_PRODUCTO = 0 THEN NULL ELSE G.ID_PRODUCTO END, -888) AS ID_PRODUCTO
,ISNULL(CASE WHEN G.DIRECCION_DESTINA_GUIA = '' THEN NULL ELSE G.DIRECCION_DESTINA_GUIA END, 'NO DISPONIBLE') AS DIRECCION_DESTINA_GUIA
,ISNULL(CASE WHEN G.ID_CIUDAD_ORIGEN = 0 THEN NULL ELSE G.ID_CIUDAD_ORIGEN END, -888) AS ID_CIUDAD_ORIGEN
,ISNULL(CASE WHEN G.ID_CIUDAD_DESTINO = 0 THEN NULL ELSE G.ID_CIUDAD_DESTINO END, -888) AS ID_CIUDAD_DESTINO
,ISNULL(CASE WHEN G.ID_CLIENTE = '' THEN NULL ELSE G.ID_CLIENTE END, '-888') AS ID_CLIENTE
,ISNULL(CONVERT(INT, CASE WHEN G.ID_ESTADOENVIO = 0 THEN NULL ELSE G.ID_ESTADOENVIO END), -888) AS ID_ESTADOENVIO
,ISNULL(CASE WHEN G.ID_PAIS_UBICACION = 0 THEN NULL ELSE G.ID_PAIS_UBICACION END, -888) AS ID_PAIS_UBICACION
,ISNULL(CASE WHEN G.ID_CIUDAD_UBICACION = 0 THEN NULL ELSE G.ID_CIUDAD_UBICACION END, -888) AS ID_CIUDAD_UBICACION
,ISNULL(CASE WHEN G.ID_DIVISION_UBICACION = 0 THEN NULL ELSE G.ID_DIVISION_UBICACION END, -888) AS ID_DIVISION_UBICACION
,ISNULL(G.VALOR_DECLARADO_GUIA, 0) AS VALOR_DECLARADO_GUIA
,CONVERT(VARCHAR, ISNULL(G.ID_PAIS_UBICACION, '-888')) + '-' + CONVERT(VARCHAR, ISNULL(G.ID_CIUDAD_UBICACION, '-888')) + '-' + CONVERT(VARCHAR, ISNULL(G.ID_DIVISION_UBICACION, '-888')) AS P_ID_BODEGA
,G.FECHA_MODIFICACION_DG
FROM #MEM_GUIA_MASIVA MGM WITH(NOLOCK)
LEFT JOIN DBO.GUIAS G WITH(NOLOCK)
ON MGM.G_NUMERO_GUIA = G.NUMERO_GUIA
OPTION(RECOMPILE, OPTIMIZE FOR UNKNOWN, MAXDOP 4)
