/*
Con el siguiente código se busca la información contenida en los campos de la tabla SEGUIMIENTO_ENVIO y se insertan en la tabla
#MEM_SEG_ENV_GUIA_MASIVA para ser procesados luego e insertados en los campos correspondientes en la tabla #MEM_GUIA_MASIVA
*/

DROP TABLE IF EXISTS #MEM_SEG_ENV_GUIA_MASIVA;

--#MEM_SEG_ENV_GUIA_MASIVA = TMP.GUIA_MASIVA_07
CREATE TABLE #MEM_SEG_ENV_GUIA_MASIVA(
	[ID] [int] IDENTITY(1,1) NOT NULL,
	[NUMERO_GUIA] [numeric](20, 0) NOT NULL,
	[ID_PROCESO] [int] NULL,
	[ID_CONCEPTO] [int] NULL,
	[FECHA_HORA_MOVIMIENTO] [datetime] NULL,
	[NUMERO_MOVIMI] [char](30) NULL,
	[CONSECUT_MOVIMI] [numeric](7, 0) NULL
) 
CREATE NONCLUSTERED INDEX [idx_N_GUIA] ON #MEM_SEG_ENV_GUIA_MASIVA
(
[NUMERO_GUIA] ASC
)WITH (PAD_INDEX = OFF, 
STATISTICS_NORECOMPUTE = OFF, 
SORT_IN_TEMPDB = OFF, 
DROP_EXISTING = OFF, 
ONLINE = OFF, 
ALLOW_ROW_LOCKS = ON, 
ALLOW_PAGE_LOCKS = ON) 
ON [PRIMARY];

INSERT INTO #MEM_SEG_ENV_GUIA_MASIVA(
NUMERO_GUIA
,ID_PROCESO
,ID_CONCEPTO
,FECHA_HORA_MOVIMIENTO
,NUMERO_MOVIMI
,CONSECUT_MOVIMI)
SELECT
MGM.G_NUMERO_GUIA
,SE.ID_PROCESO
,SE.ID_CONCEPTO
,SE.FECHA_HORA_MOVIMIENTO
,SE.NUMERO_MOVIMI
,SE.CONSECUT_MOVIMI
FROM #MEM_GUIA_MASIVA MGM WITH(NOLOCK)
INNER JOIN DBO.SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
ON MGM.G_NUMERO_GUIA = SE.NUMERO_GUIA
OPTION(RECOMPILE, OPTIMIZE FOR UNKNOWN, MAXDOP 4);

WITH CTE
(
G_NUMERO_GUIA
,SE_ID_FECHA_EZU
,SE_FECHA_EZU
,SE_ID_FECHA_ULTI_MOVI
,SE_FECHA_ULTI_MOVI
,SE_CANT_SZU
,SE_ID_FECHA_SZU
,SE_FECHA_SZU
,SE_ID_CONC_SZU
,SE_ID_DZU
,SE_ID_ULTI
) AS (
SELECT 
NUMERO_GUIA G_NUMERO_GUIA
,ISNULL(MIN(CASE WHEN ID_PROCESO IN (5,6) THEN FECHA_HORA_MOVIMIENTO ELSE NULL END  ),'1900-01-01' ) SE_ID_FECHA_EZU
,ISNULL(CONVERT(VARCHAR, MIN(CASE WHEN ID_PROCESO IN (5,6) THEN FECHA_HORA_MOVIMIENTO ELSE NULL END  ),21),'NO DISPONIBLE' ) SE_FECHA_EZU
,ISNULL(MAX(FECHA_HORA_MOVIMIENTO),'1900-01-01') SE_ID_FECHA_ULTI_MOVI
,ISNULL(CONVERT(VARCHAR,MAX(FECHA_HORA_MOVIMIENTO),21),'NO DISPONIBLE') SE_FECHA_ULTI_MOVI
,ISNULL(COUNT(CASE WHEN ID_PROCESO = 9 THEN ID_PROCESO ELSE NULL END),0) SE_CANT_SZU
,ISNULL(MAX(CASE WHEN ID_PROCESO = 9 THEN FECHA_HORA_MOVIMIENTO ELSE NULL END  ),'1900-01-01' ) SE_ID_FECHA_SZU
,ISNULL(CONVERT(VARCHAR, MAX(CASE WHEN ID_PROCESO = 9 THEN FECHA_HORA_MOVIMIENTO ELSE NULL END  ),21),'NO DISPONIBLE' ) SE_FECHA_SZU
,ISNULL(MAX(CASE WHEN ID_PROCESO = 9 THEN ID_CONCEPTO ELSE NULL END  ),-888 ) SE_ID_CONC_SZU	 
,ISNULL(COUNT(CASE WHEN ID_PROCESO = 10 THEN ID_PROCESO ELSE NULL END),0) SE_ID_DZU
,ISNULL(MAX(ID),-888) SE_ID_ULTI
FROM  #MEM_SEG_ENV_GUIA_MASIVA WITH(NOLOCK)
GROUP BY  NUMERO_GUIA
)
UPDATE MGM
SET
SE_ID_FECHA_EZU   = CTE.SE_ID_FECHA_EZU
,SE_FECHA_EZU = CTE.SE_FECHA_EZU
,SE_ID_FECHA_ULTI_MOVI   = CTE.SE_ID_FECHA_ULTI_MOVI
,SE_FECHA_ULTI_MOVI = CTE.SE_FECHA_ULTI_MOVI
,SE_CANT_SZU   = CTE.SE_CANT_SZU
,SE_ID_FECHA_SZU = CTE.SE_ID_FECHA_SZU
,SE_FECHA_SZU = CTE.SE_FECHA_SZU
,SE_ID_CONC_SZU = CTE.SE_ID_CONC_SZU
,SE_ID_CANT_DZU = CTE.SE_ID_DZU
,SE_ID_ULTI = CTE.SE_ID_ULTI
FROM  #MEM_GUIA_MASIVA AS MGM WITH (NOLOCK)
INNER JOIN  CTE
ON MGM.G_NUMERO_GUIA = CTE.G_NUMERO_GUIA
OPTION(RECOMPILE, OPTIMIZE FOR UNKNOWN, MAXDOP 4)
GO

UPDATE #MEM_GUIA_MASIVA
SET SE_ID_SZU = CASE WHEN SE_CANT_SZU > 0 THEN 'SI' ELSE SE_ID_SZU END

DROP TABLE IF EXISTS #MEM_SEG_ENV_GUIA_MASIVA;
GO







