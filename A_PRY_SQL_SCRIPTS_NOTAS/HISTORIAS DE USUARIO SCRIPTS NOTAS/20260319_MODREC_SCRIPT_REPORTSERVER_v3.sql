DROP TABLE IF EXISTS #DIM_CLIENTES
SELECT * 
INTO #DIM_CLIENTES
FROM(
SELECT
ID_CLIENTE='TODOS'
,NOMBRE_CLIENTE='TODOS' 
,ID_TIPO_CLIENTE=0	
,TIPO_CLIENTE=0	
UNION ALL
SELECT
ID_CLIENTE='0'
,NOMBRE_CLIENTE='NO DISPONIBLE' 
,ID_TIPO_CLIENTE=0	
,TIPO_CLIENTE=0	
UNION ALL
SELECT 
   LTRIM(RTRIM(CL.ID_CLIENTE)) AS ID_CLIENTE	
  ,CONCAT(LTRIM(RTRIM(CL.ID_CLIENTE)),'-',RAZON_SOCIAL_CORTA) AS NOMBRE_CLIENTE	
  ,ID_TIPO_CLIENTE	
  ,TIPO_CLIENTE	
FROM DIM.CLIENTES CL WITH(NOLOCK)
INNER join [FAC].[MODREC_LPC_COD_GUIAS] FAC WITH(NOLOCK)
ON FAC.ID_CLIENTE = CL.ID_CLIENTE
--WHERE RAZON_SOCIAL_CORTA LIKE '%TEMU%'
--ORDER BY RAZON_SOCIAL_CORTA ASC
GROUP BY 
CL.ID_CLIENTE
,RAZON_SOCIAL_CORTA 
,ID_TIPO_CLIENTE	
,TIPO_CLIENTE
) AS CTE


