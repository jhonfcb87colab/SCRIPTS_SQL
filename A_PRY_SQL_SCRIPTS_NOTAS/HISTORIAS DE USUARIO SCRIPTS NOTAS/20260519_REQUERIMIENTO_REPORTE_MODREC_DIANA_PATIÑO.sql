AND ISNULL(CPR.NUMERO_ORDEN_SERVICIO,'')='' -- NO TIENE ORDEN DE RECAUDO DE EFECTY
AND ISNULL(CPR.ESTA_ANULADO,0)=0 -- NO DEBE ESTAR ANULADA
AND isnull(G.ID_DIVISION_PROV,0) = 0
AND CPR.FECHA_CREACION BETWEEN convert(datetime,@FECH_INI) AND convert(datetime,@FECH_FIN)
AND  CPR.ID_AUXILIAR = @ID_AUXILIAR     

