------------------- PRIMER BARRIDO EN  BASE DE INFORMACION CONTADOS Y RECAUDOS

WITH CTE_CONTADOS_Y_RECAUDOS AS(
			SELECT 
					ROW_NUMBER() OVER(PARTITION BY CG.NUMERO_GUIA ORDER BY GR.FECHA_CREACION, GRIR.FECHA_MODIFICACION_TRANSMISION DESC ) AS  ROW_id,
					CG.[NUMERO_GUIA]
					,GRIR.ID_FORMA_PAGO
					,GR.ID_TIPO_COBRO
				FROM SIG_LOGISTICA_DM.FAC.CONFIRMACIONES_GUIA CG WITH(NOLOCK)
				INNER JOIN SIG_COLOMBIA_DW.LOG.GUIA_RECAUDO GR WITH(NOLOCK)
				ON CG.NUMERO_GUIA=GR.NUMERO_GUIA
				INNER JOIN SIG_COLOMBIA_DW.LOG.GUIA_RECAUDO_INFORMACION_RECAUDO GRIR WITH(NOLOCK)
				ON CG.NUMERO_GUIA=GRIR.NUMERO_GUIA
				WHERE (CG.ID_TIPO_COBRO IS NULL OR CG.ID_FORMA_PAGO IS NULL)
)
SELECT 
		CT.NUMERO_GUIA,
		CT.ID_FORMA_PAGO,
		CT.ID_TIPO_COBRO
--UPDATE CGFAC_UPDATE
--SET 
--	ID_FORMA_PAGO=CT.ID_FORMA_PAGO,
--	ID_TIPO_COBRO=CT.ID_TIPO_COBRO
FROM CTE_CONTADOS_Y_RECAUDOS CT
INNER JOIN SIG_LOGISTICA_DM.FAC.CONFIRMACIONES_GUIA CGFAC_UPDATE WITH(NOLOCK) ON CT.NUMERO_GUIA=CGFAC_UPDATE.NUMERO_GUIA
WHERE  CT.ROW_id=1 

GO
------------------- SEGUNDO BARRIDO EN BASE DE INFORMACION DE PREFACTURACION  DEL MERF

WITH CTE_MERF AS (
			SELECT 
			ROW_NUMBER ( )   OVER ( PARTITION BY CG.NUMERO_GUIA order by GR.FECHA_EXTRACCION_DW desc )  ROW_id,  
			CG.NUMERO_GUIA,
			CASE WHEN GR.ID_FORMAPAGO_GUIA IS NULL OR GR.ID_FORMAPAGO_GUIA = 0 THEN GR.ID_FORMAPAGO_OPER ELSE GR.ID_FORMAPAGO_GUIA END ID_FORMAPAGO,
			--ISNULL(GR.ID_FORMAPAGO_GUIA,GR.ID_FORMAPAGO_OPER) ID_FORMAPAGO_GUIA,
			FP.NOMBRE_FORMAPAGO,
			GR.FECHA_EXTRACCION_DW
				FROM SIG_LOGISTICA_DM.FAC.CONFIRMACIONES_GUIA CG WITH(NOLOCK)
				INNER JOIN SIG_COLOMBIA_DW.PRF.MECE_LOGISTICO_GUIAS_INF_ADICIONAL GR WITH(NOLOCK)
				ON CG.NUMERO_GUIA=GR.NUMERO_GUIA	
				INNER JOIN SIG_COLOMBIA_DW.PAR.FORMAPAGO FP WITH(NOLOCK) 
				ON FP.ID_FORMAPAGO=(CASE WHEN GR.ID_FORMAPAGO_GUIA IS NULL OR GR.ID_FORMAPAGO_GUIA = 0 THEN GR.ID_FORMAPAGO_OPER ELSE GR.ID_FORMAPAGO_GUIA END)
				WHERE (CG.ID_FORMA_PAGO IS NULL)
				AND FP.NOMBRE_FORMAPAGO IS NOT NULL
				)
SELECT 
CT.NUMERO_GUIA,
CT.ID_FORMAPAGO,
CT.NOMBRE_FORMAPAGO
--UPDATE CGFAC_UPDATE
--SET
--	ID_FORMA_PAGO=CT.ID_FORMAPAGO
FROM CTE_MERF CT 
INNER JOIN SIG_LOGISTICA_DM.FAC.CONFIRMACIONES_GUIA CGFAC_UPDATE WITH(NOLOCK) ON CT.NUMERO_GUIA=CGFAC_UPDATE.NUMERO_GUIA
WHERE CT.ROW_id=1 

GO
------------------- TERCER BARRIDO EN BASE DE INFORMACION DE RETAIL WEB

WITH CTE_RETAIL AS(
				SELECT 
				    ROW_NUMBER ( )   OVER ( PARTITION BY RTWG.Number order by RTWG.FECHA_EXTRACCION_DW  desc )  ROW_id,  
					RTWG.Number AS NUMERO_GUIA,
					INVOICEDETAIL.PaymentFormId AS ID_FORMAPAGO
				FROM SIG_LOGISTICA_DM.FAC.CONFIRMACIONES_GUIA CG WITH(NOLOCK)
				INNER JOIN SIG_COLOMBIA_DW.RTW.GUIDE RTWG WITH(NOLOCK) ON RTWG.Number=CG.NUMERO_GUIA
				INNER JOIN SIG_COLOMBIA_DW.RTW.INVOICEDETAIL INVOICEDETAIL WITH(NOLOCK) 
				ON RTWG.InvoiceDetailId=INVOICEDETAIL.Id
				WHERE (CG.ID_FORMA_PAGO IS NULL)   ---CG.ID_TIPO_COBRO IS NULL OR 
				)
SELECT 
		CT.NUMERO_GUIA,
		CT.ID_FORMAPAGO
--UPDATE CGFAC_UPDATE
--SET
--	ID_FORMA_PAGO=CT.ID_FORMAPAGO
FROM CTE_RETAIL CT
INNER JOIN SIG_LOGISTICA_DM.FAC.CONFIRMACIONES_GUIA CGFAC_UPDATE WITH(NOLOCK) ON CT.NUMERO_GUIA=CGFAC_UPDATE.NUMERO_GUIA
WHERE CT.ROW_id=1





