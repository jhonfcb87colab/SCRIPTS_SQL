USE SIG_LOGISTICA_DM;

SELECT 
		CNF.[NUMERO_GUIA]
		,CNF.[ID_ESTADO]
		,CNF.[ESTADO]
		--,CNF.[ID_EMPLEADO]
		--,CNF.[NOMBRE_EMPLEADO]
		--,CNF.[ID_FECHA_CREACION]   
		,CONVERT(DATETIME,CONVERT(DATE,CNF.[ID_FECHA_CREACION])) FECHA_CREACION
		,CNF.[ID_FECHA_CONFIRMACION]
		,CNF.[FECHA_CONFIRMACION]
		,CNF.[FECHA_EXTRACCION_DM]
		,CNF.[ID_CLIENTE]
		,CLM.NOMBRE_CLIENTE
		,CNF.[ID_PRODUCTO]
		,CNF.[ID_FORMA_PAGO]
		,FPG.FORMA_DE_PAGO
		--,CNF.OFRECIMIENTO_ENVIO
		--,CNF.CONFIRMACION_ENVIO
		--,CNF.FECHA_SALIDA_BODEGA_LOCAL
FROM [FAC].[CONFIRMACIONES_GUIA] CNF WITH(NOLOCK)
LEFT JOIN SIG_COLOMBIA_DW.DIM.FORMADEPAGO FPG WITH(NOLOCK)
ON CNF.ID_FORMA_PAGO=FPG.ID_FORMAPAGO
LEFT JOIN [DIM].[CLIENTES_MOVIMIENTO] CLM WITH(NOLOCK)
ON CLM.ID_CLIENTE=CNF.ID_CLIENTE
WHERE --CONVERT(DATE,[ID_FECHA_CONFIRMACION])>=CONVERT(DATE,DATEADD(MONTH,-24,GETDATE()))AND
CLM.NOMBRE_CLIENTE LIKE '%FALABELL%'
AND FPG.FORMA_DE_PAGO LIKE '%C.O.D%'
 

