----------------------CREATE PROCEDURE  [dbo].[EXTRACCION_DATA_TABLERO_CONTADOS]    
     
----------------------@FECHA_CREACION DATETIME,    
----------------------@FEC_EXTRACCION DATETIME,    
----------------------@TIPO_RECAUDO int,    
----------------------@CODIGO_RECAUDO VARCHAR(16) = NULL,    
----------------------@NIT varchar(20),    
----------------------@ID_CLIENTE varchar(20),    
----------------------@CODIGO_SER varchar(15),    
----------------------@NUM_MOVIMIENTO_DIARIO int,    
----------------------@NUMERO_GUIA bigint,    
----------------------@REGIONAL_ORIGEN VARCHAR(MAX),    
----------------------@REGIONAL_DESTINO VARCHAR(MAX),    
----------------------@FECHA_INI_ULTIMO_MOV DATETIME = NULL,    
----------------------@FECHA_FIN_ULTIMO_MOV DATETIME = NULL    
  
----------------------AS    
    
DECLARE     
@FECHA_CREACION DATETIME = null,    
@FEC_EXTRACCION DATETIME = null,    
@TIPO_RECAUDO int = NULL,    
@CODIGO_RECAUDO VARCHAR(16) = NULL,    
@NIT varchar(20) = null,    
@ID_CLIENTE varchar(20) = null ,    
@CODIGO_SER varchar(15)=null,    
@NUM_MOVIMIENTO_DIARIO int = NULL,    
@NUMERO_GUIA bigint = 2239088545,    
@REGIONAL_ORIGEN VARCHAR(MAX) = NULL,    
@REGIONAL_DESTINO VARCHAR(MAX) = NULL,    
@FECHA_INI_ULTIMO_MOV DATETIME = NULL,    
@FECHA_FIN_ULTIMO_MOV DATETIME = NULL    
    
    
BEGIN    
SET DATEFORMAT ymd    
    
DECLARE @IDENTIFICACION varchar(20)    
DECLARE @FECHA_INICIAL DATETIME    
SET @FECHA_INICIAL = dateadd(YY,-1,getdate())    
    
IF @NIT IS NOT NULL    
BEGIN    
 SET @IDENTIFICACION = @NIT    
END    
    
IF @ID_CLIENTE IS NOT NULL    
BEGIN    
 SET @IDENTIFICACION = @ID_CLIENTE    
END    
    
 IF(OBJECT_ID('#TCIUDADES','u') IS NOT NULL)    
  DROP TABLE #TCIUDADES    
    
 CREATE TABLE #TCIUDADES    
 (    
  ID_CIUDAD int,    
  NOMBRE_CIUDAD varchar(40),    
  ID_REGIONAL tinyint,    
  NOMBRE_REGIONAL varchar(40)    
 )    
     
    
 print 'crea #TCIUDADES' + convert(varchar, GETDATE())    
 INSERT INTO #TCIUDADES    
 SELECT C.ID_CIUDAD, C.NOMBRE_CIUDAD, R.ID_REGIONAL, R.NOMBRE_REGIONAL     
 FROM Parametros.DBO.CIUDADES C (NOLOCK)     
 INNER JOIN Parametros.dbo.REGIONALES_PAIS R (NOLOCK) ON C.id_pais = R.id_pais and C.ID_REGIONAL = R.ID_REGIONAL    
 WHERE C.ID_PAIS = 1  AND C.ID_EST_CIUDAD = 1    
    
    
 CREATE NONCLUSTERED INDEX ix_TCiudades ON #TCIUDADES ([ID_CIUDAD]);    
    
    
 SELECT ROW_NUMBER() over (partition by GR.NUMERO_GUIA order by MR.ID_MOVIMIENTO_REINTEGRO desc) as 'Consecutivo',     
 GR.NUMERO_GUIA,    
 MR.FECHA_CREACION,    
 MR.VALOR_MOVIMIENTO,    
 MR.ESTADO_PAGO,    
 MR.FECHA_MOVIMIENTO,    
 MR.VALOR_PAGO,    
 MR.ID_MOVIMIENTO_REINTEGRO,    
 MR.NUMERO_MOVIMIENTO,    
 EA.ESTADO_DE_PAGO,    
 MR.NUMERO_COMPROBANTE_CAUSACION,    
 MR.MENSAJE_INTEGRACION    
 INTO #REINTEGRO    
 FROM [LOGISTICA_COBRO].[dbo].[GUIA_REINTEGRO] GR (nolock)    
 INNER JOIN [LOGISTICA_COBRO].[dbo].MOVIMIENTO_REINTEGRO MR (nolock) ON MR.ID_MOVIMIENTO_REINTEGRO = GR.ID_MOVIMIENTO_REINTEGRO AND MR.ESTADO_PAGO <> 4    
 INNER JOIN [LOGISTICA_COBRO].[dbo].ESTADO_REINTEGRO EA (NOLOCK) ON EA.ID_PAGO = MR.ESTADO_PAGO    
 WHERE MR.NUMERO_COMPROBANTE_CAUSACION IS NOT NULL    
    
 DELETE FROM #REINTEGRO WHERE Consecutivo >= 2   
    
 CREATE NONCLUSTERED INDEX iNUMERO_GUIA ON #REINTEGRO (NUMERO_GUIA);    
     
 IF @CODIGO_RECAUDO IS NOT NULL    
 BEGIN    
 print 'opcion ingresada por @CODIGO_RECAUDO IS NOT NULL'    
  SELECT DISTINCT    
   GR.NUMERO_GUIA,    
   GR.ID_CLIENTE_PS AS CODIGO_SER,    
   CONVERT(VARCHAR(19),GR.FECHA_CREACION,121) AS FECHA_GENERACION_ENVIO,    
   CONVERT(VARCHAR(19),GIT.FECHA_HORA_MOVIMIENTO,121) AS FECHA_HORA_MOVIMIENTO,    
   GR.ID_CLIENTE,    
   CASE WHEN CLI.NOMBRE_CLIENTE IS NULL THEN CLIP.NOMBRE_EMPRESA ELSE CLI.NOMBRE_CLIENTE END AS NOMBRE_CLIENTE,    
   GR.ID_CLIENTE_REMITENTE,    
   GR.NOMBRE_CLIENTE_REMITENTE,    
   CI_O.NOMBRE_REGIONAL AS REGIONAL_ORIGEN,    
   CI_O.NOMBRE_CIUDAD AS CIUDAD_ORIGEN,    
   CI_O.ID_CIUDAD AS ID_CIUDAD_ORIGEN, --LTMD    
   CI_D.NOMBRE_REGIONAL AS REGIONAL_DESTINO,    
   CI_D.NOMBRE_CIUDAD AS NOMBRE_CIUDAD_DESTINO,    
   CI_D.ID_CIUDAD AS ID_CIUDAD_DESTINO,--LTMD    
   LPTC.NOMBRE_TIPO_COBRO,    
   CASE     
    WHEN LPEC.NOMBRE_ESTADO_COD = 'Recaudado' THEN 'Recaudado'    
    WHEN LPEC.NOMBRE_ESTADO_COD = 'Venta anulada' THEN 'Venta anulada'    
    WHEN  LPEC.NOMBRE_ESTADO_COD = 'Devol. destinatario' THEN 'Devolucion al remitente'    
    ELSE 'Pendiente por recaudar'    
   END AS ESTADO_DEL_RECAUDO,    
   CASE     
    WHEN GR.ID_TIPO_COBRO = 1 THEN GRIR.VALOR_FLETE + VALOR_SOBREFLETE - VALOR_DESCUENTO    
    WHEN GR.ID_TIPO_COBRO = 2 THEN GRIR.VALOR_PRODUCTO    
    WHEN GR.ID_TIPO_COBRO = 3 THEN GRIR.VALOR_FLETE + VALOR_SOBREFLETE - VALOR_DESCUENTO + GRIR.VALOR_PRODUCTO     
    ELSE 0     
   END AS VALOR_RECAUDAR,    
   GRIR.VALOR_RECAUDADO AS VALOR_RECAUDADO,    
   CASE     
    WHEN GR.ID_TIPO_COBRO = 1 THEN ISNULL(GRIR.VALOR_RECAUDADO,0) - (GRIR.VALOR_FLETE + VALOR_SOBREFLETE - VALOR_DESCUENTO)    
    WHEN GR.ID_TIPO_COBRO = 2 THEN ISNULL(GRIR.VALOR_RECAUDADO,0) - GRIR.VALOR_PRODUCTO    
    WHEN GR.ID_TIPO_COBRO = 3 THEN ISNULL(GRIR.VALOR_RECAUDADO,0) - (GRIR.VALOR_FLETE + VALOR_SOBREFLETE - VALOR_DESCUENTO + GRIR.VALOR_PRODUCTO)    
    ELSE 0     
   END AS SALDO,    
   GRIR.NUMERO_ORDEN_SERVICIO,    
   GR.ID_MOVIMIENTO AS NUMERO_MOVIMIENTO_DIARIO,    
   GRIR.NUMERO_CODIGO_EFECTY AS CODIGO_DE_PROYECTO,    
   CASE WHEN GRIE.PAP IS NULL THEN CTR.ID_PUNTO_RECAUDO ELSE GRIE.PAP END AS 'EFECTY-PAP',    
   CASE WHEN GRIE.PROYECTO IS NULL THEN CTR.CODIGO_PROYECTO ELSE GRIE.PROYECTO END AS 'EFECTY-PROYECTO',    
   CASE WHEN GRIE.FECHA_RECAUDO IS NULL THEN CONVERT(VARCHAR(19),CTR.FECHA_RECAUDO,121) ELSE CONVERT(VARCHAR(19),GRIE.FECHA_RECAUDO,121) END AS 'EFECTY-FECHA RECAUDO',    
   CASE WHEN GRIE.ORDEN_SERVICIO IS NULL THEN CTR.NUMERO_ORDEN_SERVICIO ELSE GRIE.ORDEN_SERVICIO END AS 'EFECTY-ORDEN SERVICIO',    
   GRIE.NIT_CLIENTE AS 'EFECTY-NIT CLIENTE',    
   GRIE.NOMBRE_CLIENTE AS 'EFECTY-NOMBRE CLIENTE',    
   CASE WHEN GRIE.VALOR IS NULL THEN CTR.VALOR_TOTAL ELSE GRIE.VALOR END AS 'EFECTY-VALOR',    
   MOP.NOMBRE_MODALPAGO AS MODALIDAD_PAGO,    
   GRIR.NUMERO_APROBACION AS NUMERO_APROBACION,    
   EE.NOMBRE_ESTADOENVIO AS ESTADO_ENVIO,    
   EG.NOMBRE_ESTADOGUIA AS ESTADO_DE_LA_GUIA,    
   P.NOMBRE_PROCESO_LOG AS ULTIMO_MOVIMIENTO_LOGISTICO,    
   ZU.NOMBRE_ZONA_URBA AS NOMBRE_ZONA_ULTIMO_MOVIMIENTO, --LTMD    
   CZU.NOMBRE_CATEGORIA AS CATEGORIA_ZONA_ULTIMO_MOVIMIENTO,--LTMD    
   TI.NOMBRE_TIPO_IDENTIFIC AS NOMBRE_TIPO_IDENTIFIC_DESTINATARIO,    
   GRID.NUMERO_IDENTIFICACION_DESTINATARIO,      
   GRID.NOMBRE_DESTINATARIO    
   ,GIT.CIUDAD_ULTIMO_MOVIMIENTO    
   ,CI_UM.ID_CIUDAD AS ID_CIUDAD_ULTIMO_MOVIMIENTO --LTMD    
   ,GIT.BODEGA    
   ,GIT.OPERATIVO    
   ,GIT.CIUDAD_DESTINO_OPERATIVO    
   ,GIT.NOMBRE_CONCEPTO    
   ,'LPC' + CONVERT(VARCHAR,MR.ID_MOVIMIENTO_REINTEGRO) AS REFERENCIA    
   ,MR.NUMERO_COMPROBANTE_CAUSACION    
   ,MR.NUMERO_MOVIMIENTO    
   ,EA.ESTADO_DE_PAGO AS ESTATUS_PAGO    
   ,CASE WHEN MR.ESTADO_PAGO IN (1,2) THEN MR.FECHA_MOVIMIENTO ELSE MR.FECHA_CREACION END AS FECHA_ESTATUS_PAGO    
   ,CASE WHEN MR.ESTADO_PAGO IN (1,2) THEN MR.VALOR_PAGO ELSE MR.VALOR_MOVIMIENTO END AS MONTO_PAGO    
   ,MR.MENSAJE_INTEGRACION    
   INTO #GUIA1    
   FROM GUIA_RECAUDO GR (NOLOCK)       
   INNER JOIN GUIA_RECAUDO_INFORMACION_RECAUDO GRIR (NOLOCK) ON GR.NUMERO_GUIA = GRIR.NUMERO_GUIA    
   INNER JOIN GUIA_RECAUDO_INFORMACION_DESTINATARIO GRID (NOLOCK) ON GR.NUMERO_GUIA = GRID.NUMERO_GUIA    
   INNER JOIN GUIA_RECAUDO_INFORMACION_EFECTY GRIE (NOLOCK) ON GRIE.NUMERO_GUIA = GR.NUMERO_GUIA    
   INNER JOIN #TCIUDADES CI_O (NOLOCK) ON GR.ID_CIUDAD_ORIGEN = CI_O.ID_CIUDAD     
   INNER JOIN #TCIUDADES CI_D (NOLOCK) ON GR.ID_CIUDAD_DESTINO = CI_D.ID_CIUDAD     
   LEFT JOIN GUIA_INFORMACION_ADICIONAL_TABLERO_CONTROL GIT (NOLOCK) ON gr.NUMERO_GUIA = GIT.NUMERO_GUIA    
   LEFT JOIN LPC_TIPO_COBRO LPTC (NOLOCK) ON GR.ID_TIPO_COBRO = LPTC.ID    
   LEFT JOIN PARAMETROS.DBO.ESTADOSGUIA EG (NOLOCK) ON GIT.ID_ESTADOGUIA = EG.ID_ESTADOGUIA    
   LEFT JOIN PARAMETROS_MDM.DBO.ESTADOSENVIO EE (NOLOCK) ON GIT.ID_ESTADOENVIO = EE.ID_ESTADOENVIO    
   LEFT JOIN PARAMETROS_MDM.DBO.PROCESOS P (NOLOCK) ON P.ID_PROCESO =  GIT.ID_PROCESO     
   LEFT JOIN PARAMETROS.DBO.TIPOSIDENTIFIC TI (NOLOCK) ON TI.ID_TIPO_IDENTIFIC = GRID.ID_TIPO_IDENTIFIC    
   LEFT JOIN LPC_ESTADO_COD LPEC (NOLOCK) ON GR.ID_ESTADO_COD = LPEC.ID    
   LEFT JOIN Mece_logistico.DBO.COD_CONTROL_TRANSMISION_RECAUDO CTR (NOLOCK) ON CTR.NUMERO_GUIA = GR.NUMERO_GUIA    
   LEFT JOIN PARAMETROS.DBO.CLIENTES CLI (NOLOCK) ON CLI.ID_CLIENTE = GR.ID_CLIENTE AND CLI.ID_PAIS = 1    
   LEFT JOIN PARAMETROS.PYMES.CLIENTES_PYMES CLIP (NOLOCK) ON CLIP.ID_CLIENTE = GR.ID_CLIENTE AND CLIP.ID_PAIS = 1    
   LEFT JOIN PARAMETROS.DBO.MODALIDADPAGO MOP (NOLOCK) ON MOP.ID_MODALPAGO = GRIR.ID_MODALPAGO    
   --LEFT JOIN [LOGISTICA_COBRO].[dbo].[GUIA_REINTEGRO] REI (nolock) ON REI.NUMERO_GUIA = GR.NUMERO_GUIA     
   LEFT JOIN #REINTEGRO MR (nolock) ON MR.NUMERO_GUIA = GR.NUMERO_GUIA    
   LEFT JOIN ESTADO_REINTEGRO EA (NOLOCK) ON EA.ID_PAGO = MR.ESTADO_PAGO    
   LEFT JOIN #TCIUDADES CI_UM (NOLOCK) ON GIT.CIUDAD_ULTIMO_MOVIMIENTO = CI_UM.NOMBRE_CIUDAD AND CI_UM.ID_CIUDAD = CASE WHEN ISNULL(GIT.ID_CIUDAD_ZONA_URBANA,0) = 0 THEN CI_UM.ID_CIUDAD ELSE GIT.ID_CIUDAD_ZONA_URBANA END  --LTMD    
   LEFT JOIN [PARAMETROS].[dbo].[ZONASURBANAS] ZU WITH(NOLOCK) ON ZU.ID_ZONA_URBA=GIT.ID_ZONA_URBA AND ZU.ID_CIUDAD=GIT.ID_CIUDAD_ZONA_URBANA AND ZU.ID_PAIS=GIT.ID_PAIS_ZONA_URBANA AND ZU.ID_TIPO_ZONA_URBA=GIT.ID_TIPO_ZONA_URBA --LTMD    
   LEFT JOIN [PARAMETROS].[dbo].[CATEGORIAZONASURBANAS] CZU WITH(NOLOCK) ON CZU.Id_Categoria=ZU.CATEGORIA_ZONA_URBA --LTMD    
   LEFT JOIN [CONTADOS].[dbo].[CONSIGNACIONES_AUTOMATICAS] CA WITH(NOLOCK) ON CA.FACTURAORDENSERVICIO=GR.NUMERO_GUIA--LTMD    
   WHERE     
   GRIE.ORDEN_SERVICIO = @CODIGO_RECAUDO    
   
  SELECT     
   G.NUMERO_GUIA,    
   G.CODIGO_SER,    
   G.FECHA_GENERACION_ENVIO,    
   G.FECHA_HORA_MOVIMIENTO,    
   G.ID_CLIENTE,    
   G.NOMBRE_CLIENTE,    
   G.ID_CLIENTE_REMITENTE,    
   G.NOMBRE_CLIENTE_REMITENTE,    
   G.REGIONAL_ORIGEN,    
   G.CIUDAD_ORIGEN,    
   G.ID_CIUDAD_ORIGEN, --LTMD    
   G.REGIONAL_DESTINO,    
   G.NOMBRE_CIUDAD_DESTINO,    
   G.ID_CIUDAD_DESTINO,--LTMD    
   G.NOMBRE_TIPO_COBRO,    
   G.ESTADO_DEL_RECAUDO,    
   G.VALOR_RECAUDAR,    
   G.VALOR_RECAUDADO,    
   G.SALDO,    
   G.NUMERO_ORDEN_SERVICIO,    
   G.NUMERO_MOVIMIENTO_DIARIO,    
   G.CODIGO_DE_PROYECTO,    
   G.[EFECTY-PAP],    
   G.[EFECTY-PROYECTO],    
   G.[EFECTY-FECHA RECAUDO],    
   G.[EFECTY-ORDEN SERVICIO],    
   G.[EFECTY-NIT CLIENTE],    
   G.[EFECTY-NOMBRE CLIENTE],    
   G.[EFECTY-VALOR],       
   G.MODALIDAD_PAGO,    
   G.NUMERO_APROBACION,    
   G.ESTADO_ENVIO,    
   G.ESTADO_DE_LA_GUIA,    
   G.ULTIMO_MOVIMIENTO_LOGISTICO,    
   G.NOMBRE_ZONA_ULTIMO_MOVIMIENTO, --LTMD    
   G.CATEGORIA_ZONA_ULTIMO_MOVIMIENTO,--LTMD    
   G.NOMBRE_TIPO_IDENTIFIC_DESTINATARIO,    
   G.NUMERO_IDENTIFICACION_DESTINATARIO,      
   G.NOMBRE_DESTINATARIO    
   ,G.CIUDAD_ULTIMO_MOVIMIENTO    
   ,G.ID_CIUDAD_ULTIMO_MOVIMIENTO --LTMD    
   ,G.BODEGA    
   ,G.OPERATIVO    
   ,G.CIUDAD_DESTINO_OPERATIVO    
   ,G.NOMBRE_CONCEPTO    
   ,G.REFERENCIA    
   ,G.NUMERO_COMPROBANTE_CAUSACION    
   ,G.NUMERO_MOVIMIENTO    
   ,G.ESTATUS_PAGO    
   ,G.FECHA_ESTATUS_PAGO    
   ,G.MONTO_PAGO    
   ,G.MENSAJE_INTEGRACION      
      FROM #GUIA1 AS G WITH(NOLOCK)    
   LEFT JOIN [CONTADOS].[dbo].[CONSIGNACIONES_AUTOMATICAS] CA WITH(NOLOCK) ON CA.FACTURAORDENSERVICIO=G.NUMERO_GUIA--LTMD    
   DROP TABLE #GUIA1    
   RETURN    
 END     
    
 IF(@FECHA_INI_ULTIMO_MOV IS NULL AND @FECHA_FIN_ULTIMO_MOV IS NULL)    
 BEGIN    
  print 'opcion ingresada por @FECHA_INI_ULTIMO_MOV IS NULL AND @FECHA_INI_ULTIMO_MOV IS NULL' + convert(varchar, GETDATE())    
  DECLARE @REGIONALES_ORIGEN TABLE (ID INT IDENTITY(1,1), ID_REGIONAL_ORIGEN NUMERIC(20,0))     
  IF @REGIONAL_ORIGEN IS NOT NULL    
  BEGIN    
   DECLARE @POSICION_ORIGEN INT      
       
   SET @REGIONAL_ORIGEN = LTRIM(RTRIM(@REGIONAL_ORIGEN))    
   SET @POSICION_ORIGEN = CHARINDEX(',',@REGIONAL_ORIGEN,1)    
   WHILE @POSICION_ORIGEN > 0    
    BEGIN    
     INSERT INTO @REGIONALES_ORIGEN VALUES ( CONVERT(NUMERIC(20,0),SUBSTRING(@REGIONAL_ORIGEN,1,@POSICION_ORIGEN-1)) )    
     SET @REGIONAL_ORIGEN = SUBSTRING(@REGIONAL_ORIGEN,@POSICION_ORIGEN+1,8000)    
     SET @POSICION_ORIGEN = CHARINDEX(',',@REGIONAL_ORIGEN,1)    
    END    
   IF LEN(@REGIONAL_ORIGEN) > 0    
    BEGIN    
     INSERT INTO @REGIONALES_ORIGEN VALUES ( CONVERT(NUMERIC(20,0),@REGIONAL_ORIGEN) )    
    END    
      
  END    
  ELSE     
  BEGIN      
   INSERT INTO @REGIONALES_ORIGEN     
   SELECT ID_REGIONAL FROM PARAMETROS.DBO.REGIONALES_PAIS WHERE ID_PAIS = 1    
  END    
    
  DECLARE @REGIONALES_DESTINO TABLE (ID INT IDENTITY(1,1), ID_REGIONAL_DESTINO NUMERIC(20,0))    
  IF @REGIONAL_DESTINO IS NOT NULL    
  BEGIN    
   DECLARE @POSICION_DESTINO INT    
      
    
   SET @REGIONAL_DESTINO = LTRIM(RTRIM(@REGIONAL_DESTINO))    
   SET @POSICION_DESTINO = CHARINDEX(',',@REGIONAL_DESTINO,1)    
   WHILE @POSICION_DESTINO > 0    
    BEGIN    
     INSERT INTO @REGIONALES_DESTINO VALUES ( CONVERT(NUMERIC(20,0),SUBSTRING(@REGIONAL_DESTINO,1,@POSICION_DESTINO-1)) )    
     SET @REGIONAL_DESTINO = SUBSTRING(@REGIONAL_DESTINO,@POSICION_DESTINO+1,8000)    
     SET @POSICION_DESTINO = CHARINDEX(',',@REGIONAL_ORIGEN,1)    
    END    
   IF LEN(@REGIONAL_DESTINO) > 0    
    BEGIN    
     INSERT INTO @REGIONALES_DESTINO VALUES ( CONVERT(NUMERIC(20,0),@REGIONAL_DESTINO) )    
    END    
       
  END    
  ELSE    
  BEGIN    
   INSERT INTO @REGIONALES_DESTINO     
   SELECT ID_REGIONAL FROM PARAMETROS.DBO.REGIONALES_PAIS (NOLOCK) WHERE ID_PAIS = 1    
  END    
  print 'Inicia select' + convert(varchar, GETDATE())    
  SET @FECHA_CREACION = @FECHA_CREACION + ' 00:00:00.000 '     
  SET @FEC_EXTRACCION = @FEC_EXTRACCION + ' 23:59:59.999'    
      
  ------------------    
    
  SELECT    
  GR.NUMERO_GUIA,    
  GR.ID_CLIENTE_PS AS CODIGO_SER,    
  CONVERT(VARCHAR(19),GR.FECHA_CREACION,121) AS FECHA_GENERACION_ENVIO,    
  GR.ID_CLIENTE,    
  GR.ID_CLIENTE_REMITENTE,    
  GR.NOMBRE_CLIENTE_REMITENTE,    
  CI_O.NOMBRE_REGIONAL AS REGIONAL_ORIGEN,    
  CI_O.NOMBRE_CIUDAD AS CIUDAD_ORIGEN,    
  CI_O.ID_CIUDAD AS ID_CIUDAD_ORIGEN, --LTMD    
  CI_D.NOMBRE_REGIONAL AS REGIONAL_DESTINO,    
  CI_D.NOMBRE_CIUDAD AS NOMBRE_CIUDAD_DESTINO,    
  CI_D.ID_CIUDAD AS ID_CIUDAD_DESTINO,--LTMD    
  LPTC.NOMBRE_TIPO_COBRO,    
  CASE     
   WHEN GR.ID_ESTADO_COD = 3 THEN 'Recaudado'    
   WHEN GR.ID_ESTADO_COD = 6 THEN 'Venta anulada'     
   WHEN  GR.ID_ESTADO_COD = 5 THEN 'Devolucion al remitente'    
   ELSE 'Pendiente por recaudar'    
  END AS ESTADO_DEL_RECAUDO,       
  CASE     
   WHEN GR.ID_TIPO_COBRO = 1 THEN GRIR.VALOR_FLETE + VALOR_SOBREFLETE - VALOR_DESCUENTO    
   WHEN GR.ID_TIPO_COBRO = 2 THEN GRIR.VALOR_PRODUCTO    
   WHEN GR.ID_TIPO_COBRO = 3 THEN GRIR.VALOR_FLETE + VALOR_SOBREFLETE - VALOR_DESCUENTO + GRIR.VALOR_PRODUCTO     
   ELSE 0     
  END AS VALOR_RECAUDAR,    
  GRIR.VALOR_RECAUDADO AS VALOR_RECAUDADO,    
  CASE     
   WHEN GR.ID_TIPO_COBRO = 1 THEN ISNULL(GRIR.VALOR_RECAUDADO,0) - (GRIR.VALOR_FLETE + VALOR_SOBREFLETE - VALOR_DESCUENTO)    
   WHEN GR.ID_TIPO_COBRO = 2 THEN ISNULL(GRIR.VALOR_RECAUDADO,0) - GRIR.VALOR_PRODUCTO    
   WHEN GR.ID_TIPO_COBRO = 3 THEN ISNULL(GRIR.VALOR_RECAUDADO,0) - (GRIR.VALOR_FLETE + VALOR_SOBREFLETE - VALOR_DESCUENTO + GRIR.VALOR_PRODUCTO)    
   ELSE 0     
  END AS SALDO,    
  GRIR.NUMERO_ORDEN_SERVICIO,    
  GR.ID_MOVIMIENTO AS NUMERO_MOVIMIENTO_DIARIO,    
  GRIR.NUMERO_CODIGO_EFECTY AS CODIGO_DE_PROYECTO,    
  MOP.NOMBRE_MODALPAGO AS MODALIDAD_PAGO,    
  GRIR.NUMERO_APROBACION AS NUMERO_APROBACION,    
  TI.NOMBRE_TIPO_IDENTIFIC AS NOMBRE_TIPO_IDENTIFIC_DESTINATARIO,    
  GRID.NUMERO_IDENTIFICACION_DESTINATARIO,      
  GRID.NOMBRE_DESTINATARIO    
  ,CASE WHEN ID_PRODUCTO = 86 THEN 1 ELSE 2 END AS TIPO_CLIENTE    
  INTO #GUIA    
  FROM     
  (SELECT * FROM  GUIA_RECAUDO (NOLOCK) WHERE FECHA_CREACION >= ISNULL(@FECHA_CREACION, @FECHA_INICIAL) AND FECHA_CREACION <= ISNULL(@FEC_EXTRACCION,  GETDATE())) GR       
  INNER JOIN GUIA_RECAUDO_INFORMACION_RECAUDO GRIR (NOLOCK) ON GRIR.NUMERO_GUIA = GR.NUMERO_GUIA    
  INNER JOIN GUIA_RECAUDO_INFORMACION_DESTINATARIO GRID (NOLOCK) ON GRID.NUMERO_GUIA = GR.NUMERO_GUIA       
  INNER JOIN #TCIUDADES CI_O (NOLOCK) ON CI_O.ID_CIUDAD = GR.ID_CIUDAD_ORIGEN    
  INNER JOIN #TCIUDADES CI_D (NOLOCK) ON CI_D.ID_CIUDAD = GR.ID_CIUDAD_DESTINO    
  INNER JOIN @REGIONALES_ORIGEN RO ON RO.ID_REGIONAL_ORIGEN = CI_O.ID_REGIONAL    
  INNER JOIN @REGIONALES_DESTINO RD ON RD.ID_REGIONAL_DESTINO = CI_D.ID_REGIONAL    
  INNER JOIN LPC_TIPO_COBRO LPTC (NOLOCK) ON LPTC.ID = GR.ID_TIPO_COBRO    
  LEFT JOIN PARAMETROS.DBO.MODALIDADPAGO MOP (NOLOCK) ON MOP.ID_MODALPAGO = GRIR.ID_MODALPAGO AND MOP.ID_PAIS = 1    
  LEFT JOIN PARAMETROS.DBO.TIPOSIDENTIFIC TI (NOLOCK) ON TI.ID_TIPO_IDENTIFIC = GRID.ID_TIPO_IDENTIFIC AND TI.ID_PAIS = 1    
