SELECT 
CPR.ESTADO_COD,
CPR.*,G.ID_CLIENTE,G.ID_REMITE,G.NOMBRE_REMITE_GUIA,G.ID_PRODUCTO AS ID_PRODUCTO_GUIA,G.ID_ESTADOENVIO,G.ID_ESTADOGUIA,ISNULL(G.VALOR_SEG_MAN_GUIAS,0)+ISNULL(G.VALOR_FLETES_GUIAS,0) AS VALOR_ENVIO_GUIA,ISNULL(GIA.VALOR_RECAUDAR_PRODUCTO,0) AS VALOR_RECAUDAR_PRODUCTO_GUIA
,CAST('' AS nvarchar(50)) AS NOMBRE_ESTADOENVIO,G.FECHA_ENVIO
,TCAN.NOMBRE_TIPO_CANAL
,CTCAN.NOMBRE_CLASE_TIPO_CANAL
,G.[ID_CIUDAD_ORIGEN]			AS G_ID_CIUDAD_ORIGEN
,G.[ID_CIUDAD_DESTINO]			AS G_ID_CIUDAD_DESTINO
FROM [Mece_Logistico].[dbo].[COD_PENDIENTE_POR_RECAUDO] CPR (NOLOCK)
INNER JOIN [Mece_Logistico].[dbo].[GUIAS] G (nolock) ON G.NUMERO_GUIA=CPR.NUMERO_GUIA
LEFT JOIN [Mece_Logistico].[dbo].[GUIAS_INF_ADICIONAL] GIA (nolock) ON GIA.NUMERO_GUIA=CPR.NUMERO_GUIA
--LEFT JOIN [tmp_borrar_local].dbo.LPC_GUIAS_SOLUCIONADAS LGS (NOLOCK) ON LGS.NUMERO_GUIA=CPR.NUMERO_GUIA
LEFT JOIN [Mece_Logistico].[dbo].[CANALES] CAN (NOLOCK) ON CAN.id_pais=G.ID_1 and CAN.id_ciudad=G.ID_2 and CAN.[ID_DIVISION]=G.ID_CANAL
LEFT JOIN [Mece_Logistico].[dbo].[TIPOS_CANAL] TCAN (NOLOCK) ON TCAN.ID_TIPO_CANAL=CAN.ID_TIPO_CANAL AND TCAN.ID_EST_TIPO_CANAL=1
LEFT JOIN PARAMETROS.[dbo].[CLASE_TIPO_CANAL] CTCAN (NOLOCK) ON CTCAN.ID_CLASE_TIPO_CANAL=TCAN.CLASE_TIPO_CANAL
WHERE --LGS.NUMERO_GUIA IS NULL 
--AND ISNULL(CPR.ESTADO_COD,1)=1-- RECAUDO ESTA ACTIVO
 ISNULL(CPR.ESTA_RECAUDADO,0)=0 -- NO ESTA RECAUDADO
AND ISNULL(CPR.NUMERO_ORDEN_SERVICIO,'')='' -- NO TIENE ORDEN DE RECAUDO DE EFECTY
AND ISNULL(CPR.ESTA_ANULADO,0)=0 -- NO DEBE ESTAR ANULADA
AND G.ID_DIVISION_PROV IS NULL
---AND CPR.FECHA_CREACION BETWEEN convert(datetime,?) AND convert(datetime,?)
AND CPR.NUMERO_GUIA=2239088545




