DROP TABLE IF EXISTS #BORRAR_GUIAS_SOLICITUD_MARTIN_20260123_P01
SELECT CONVERT(NUMERIC(18,0),[NUMERO GUIA]) AS [NUMERO GUIA]
INTO #BORRAR_GUIAS_SOLICITUD_MARTIN_20260123_P01
   FROM [tmp_borrar_local].[dbo].[BORRAR_GUIAS_SOLICITUD_MARTIN_20260123]

DROP TABLE IF EXISTS #BORRAR_GUIAS_SOLICITUD_MARTIN_20260123_P02
;WITH CTE AS (
SELECT 
ROWID = ROW_NUMBER() OVER(PARTITION BY SEG.NUMERO_GUIA ORDER BY SEG.FECHA_HORA_MOVIMIENTO DESC)
,SEG.NUMERO_GUIA
,SEG.FECHA_HORA_MOVIMIENTO
,SEG.ID_PROCESO
,PR.NOMBRE_PROCESO_LOG
,REGIO_DESTI.NOMBRE_REGIONAL	AS NOMBRE_REGIONAL_DEST 
,REGIO_ORIG.NOMBRE_REGIONAL		AS NOMBRE_REGIONAL_ORG 
,DIV_DEST.NOMBRE_DIVISION		AS BODEGA_DESTINO
,DIV_ORIG.NOMBRE_DIVISION		AS BODEGA_ORIGEN
FROM #BORRAR_GUIAS_SOLICITUD_MARTIN_20260123_P01 T01
LEFT JOIN Mece_Logistico..SEGUIMIENTO_ENVIO SEG WITH(NOLOCK)
ON T01.[NUMERO GUIA]=SEG.NUMERO_GUIA
LEFT JOIN  MECE_LOGISTICO..DOCUMENTOS DOC WITH (NOLOCK) 
ON SEG.ID_PROCESO=DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI
LEFT JOIN PARAMETROS..PROCESOS PR ON SEG.ID_PROCESO=PR.ID_PROCESO
	-------------->CIUDAD DESTINO
	LEFT JOIN PARAMETROS..CIUDADES CIUD_DEST ON CIUD_DEST.ID_CIUDAD=DOC.ID_CIUDAD_DESTINO
	LEFT JOIN PARAMETROS..REGIONALES_PAIS REGIO_DESTI ON REGIO_DESTI.ID_REGIONAL=CIUD_DEST.ID_REGIONAL
	LEFT JOIN PARAMETROS..DIVISIONES DIV_DEST WITH (NOLOCK)
	ON DIV_DEST.ID_DIVISION=DOC.ID_DIVISION_DESTINO AND DOC.ID_CIUDAD_DESTINO=DIV_DEST.ID_CIUDAD 
	-------------->CIUDAD ORIGEN
	LEFT JOIN PARAMETROS..CIUDADES CIUD_ORIG ON CIUD_ORIG.ID_CIUDAD=DOC.ID_CIUDAD_DIVISION_ORIGEN
	LEFT JOIN PARAMETROS..REGIONALES_PAIS REGIO_ORIG ON REGIO_ORIG.ID_REGIONAL=CIUD_ORIG.ID_REGIONAL
	LEFT JOIN PARAMETROS..DIVISIONES DIV_ORIG WITH (NOLOCK)
	ON DIV_ORIG.ID_DIVISION=DOC.ID_DIVISION_ORIGEN AND DOC.ID_CIUDAD_DIVISION_ORIGEN=DIV_ORIG.ID_CIUDAD 
)SELECT 
 CT.NUMERO_GUIA
 ,G.FECHA_ENVIO
,CT.FECHA_HORA_MOVIMIENTO
,CT.ID_PROCESO
,CT.NOMBRE_PROCESO_LOG
,CT.NOMBRE_REGIONAL_DEST 
,CT.NOMBRE_REGIONAL_ORG 
,CT.BODEGA_DESTINO
,CT.BODEGA_ORIGEN
,G.ID_ESTADOENVIO
,EEV.NOMBRE_ESTADOENVIO
,G.ID_ESTADOGUIA
,EEG.NOMBRE_ESTADOGUIA
INTO #BORRAR_GUIAS_SOLICITUD_MARTIN_20260123_P02
FROM CTE CT 
INNER JOIN Mece_Logistico..GUIAS G WITH(NOLOCK)
ON G.NUMERO_GUIA=CT.NUMERO_GUIA
INNER JOIN Mece_Logistico..ESTADOSENVIO EEV WITH(NOLOCK) ON EEV.ID_ESTADOENVIO=G.ID_ESTADOGUIA
INNER JOIN Mece_Logistico..ESTADOSGUIA	EEG WITH(NOLOCK) ON EEG.ID_ESTADOGUIA =G.ID_ESTADOGUIA
WHERE ROWID=1


DROP TABLE IF EXISTS #BORRAR_GUIAS_SOLICITUD_MARTIN_20260123_P03
SELECT NUMERO_GUIA,MIN(FECHA_HORA_MOVIMIENTO) AS FECHA_EZU_EPS
INTO #BORRAR_GUIAS_SOLICITUD_MARTIN_20260123_P03 
FROM Mece_Logistico..SEGUIMIENTO_ENVIO SEG WITH(NOLOCK)
WHERE ID_PROCESO IN(5,6)
AND NUMERO_GUIA IN(SELECT NUMERO_GUIA FROM #BORRAR_GUIAS_SOLICITUD_MARTIN_20260123_P02 GROUP BY NUMERO_GUIA)
GROUP BY NUMERO_GUIA


SELECT 
	 T01.NUMERO_GUIA
	,T01.FECHA_ENVIO
	,T01.FECHA_HORA_MOVIMIENTO
	,T01.ID_PROCESO
	,T01.NOMBRE_PROCESO_LOG
	,T01.NOMBRE_REGIONAL_DEST
	,T01.NOMBRE_REGIONAL_ORG
	,T01.BODEGA_DESTINO
	,T01.BODEGA_ORIGEN
	,T01.ID_ESTADOENVIO
	,T01.NOMBRE_ESTADOENVIO
	,T01.ID_ESTADOGUIA
	,T01.NOMBRE_ESTADOGUIA
	,T02.FECHA_EZU_EPS
FROM #BORRAR_GUIAS_SOLICITUD_MARTIN_20260123_P02 T01
LEFT JOIN #BORRAR_GUIAS_SOLICITUD_MARTIN_20260123_P03 T02
ON T01.NUMERO_GUIA=T02.NUMERO_GUIA



