USE Mece_Logistico;

DROP TABLE IF EXISTS #REQ_DARWIN_20251212;

;WITH CTE AS (
SELECT 
ROW_ID = ROW_NUMBER() OVER(PARTITION BY NUMERO_GUIA ORDER BY FECHA_HORA_MOVIMIENTO ASC),
* FROM SEGUIMIENTO_ENVIO WITH(NOLOCK)
WHERE ID_PROCESO IN(5,6)
AND FECHA_HORA_MOVIMIENTO BETWEEN '2025-12-08' AND '2025-12-12'
)
SELECT * 
INTO #REQ_DARWIN_20251212
FROM CTE WHERE ROW_ID=1

drop table IF EXISTS  #guias_REQ_DARWIN_20251212
select distinct NUMERO_GUIA 
INTO #guias_REQ_DARWIN_20251212
from #REQ_DARWIN_20251212


ALTER TABLE #guias_REQ_DARWIN_20251212 ADD  CONSTRAINT [ZZZZIDX20251212_GUIAS] UNIQUE NONCLUSTERED 
(
NUMERO_GUIA ASC)
WITH (PAD_INDEX = OFF, STATISTICS_NORECOMPUTE = OFF, SORT_IN_TEMPDB = OFF, IGNORE_DUP_KEY = OFF, ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON, FILLFACTOR = 80) ON [PRIMARY]



DROP TABLE IF EXISTS #TABLA_guias_REQ_DARWIN_20251212
SELECT 
GUI.* 
INTO #TABLA_guias_REQ_DARWIN_20251212
FROM #guias_REQ_DARWIN_20251212 GTMP
INNER JOIN Mece_Logistico..GUIAS GUI WITH(NOLOCK)
ON GTMP.NUMERO_GUIA=GUI.NUMERO_GUIA
WHERE ID_PRODUCTO=6



SELECT 
G.NUMERO_GUIA,
NOMBRE_CLIENTE = CASE WHEN CL.NOMBRE_CLIENTE IS NULL THEN CONCAT(G.NOMBRE_REMITE_GUIA,' ',G.APELLIDO_REMITE_GUIA)
					ELSE CL.NOMBRE_CLIENTE
					END,
CANAL = CASE 
				WHEN  CL.NOMBRE_CLIENTE LIKE '%SEVIENTRE%' THEN 'GUIA SERVIENTREGA'
				WHEN ISNULL(G.ID_DIVISION_PROV,'0')<>'0' THEN 'GUIA INTERNA'
				WHEN ISNULL(G.ID_CANAL,'0')<>'0' AND ISNULL(G.ID_CLIENTE,'0')='0' THEN 'RETAIL'
				WHEN ISNULL(G.ID_CANAL,'0')='0' AND ISNULL(G.ID_CLIENTE,'0')<>'0' THEN 'CORPORATIVO'
				ELSE 'DESCONOCIDO'
				END,
G.PESO_FISICO_GUIA AS G_PESO_FISICO_GUIA,
G.PESO_FISICO_OPERA AS G_PESO_FISICO_OPERA,
G.PESO_VOLU_GUIA AS G_PESO_VOLU_GUIA,
G.PESO_VOLU_OPERA AS G_PESO_VOLU_OPERA,
S.FECHA_HORA_MOVIMIENTO,
S.ID_PRODUCTO,
G.ID_CLIENTE,
G.ID_CANAL,
G.ID_DIVISION_PROV
FROM #TABLA_guias_REQ_DARWIN_20251212 G
INNER JOIN #REQ_DARWIN_20251212 S 
ON S.NUMERO_GUIA=G.NUMERO_GUIA
LEFT JOIN PARAMETROS..CLIENTES CL WITH(NOLOCK)
ON G.ID_CLIENTE=CL.ID_CLIENTE
