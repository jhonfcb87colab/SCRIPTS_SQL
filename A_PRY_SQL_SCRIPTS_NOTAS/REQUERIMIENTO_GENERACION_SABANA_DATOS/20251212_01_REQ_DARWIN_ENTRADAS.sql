,TMP.FECHA_ENVIO	
,TMP.FECHA_HORA_MOV_ENTREGA_PR_11	
,TMP.NOMBRE_ZONA_URBA	
,TMP.NOMBRE_CIUDAD_ORG_GUIA	
,TMP.NOMBRE_CIUDAD_DEST	
,TMP.NOMBRE_REGIONAL_DEST	
,TMP.CIUDAD_ZONA_URBANA
ORDER BY COUNT_SZU DESC


