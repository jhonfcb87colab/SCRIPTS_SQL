USE [SIG_COL_LOGISTICA_DW];
GO
WITH CTE_PROMEDIO_TIEMPO_RESPUESTA_TAREAS
(
	TIME_ID	
	,NUMERO_GUIA	
	,PROM_TIEMPO_RESPUESTA	
	,PROM_TIEMPO_ASIGNACION	
	,PROM_TIEMPO_MODIFICACION	
	,PROM_TIEMPO_CORRIDO	
	,PROM_TIEMPO_TOTAL	
	,NUM_TAREAS
) AS (
SELECT 
	MIN(TR.[TIME_ID]) [TIME_ID]
	,TR.[NUMERO_DOC_PROBLEMA] AS NUMERO_GUIA
	,SUM(TR.[TIEMPO_RESPUESTA])/SUM(TR.[NUM_TAREAS]) [PROM_TIEMPO_RESPUESTA]
	,SUM(TR.[TIEMPO_ASIGNACION])/SUM(TR.[NUM_TAREAS]) [PROM_TIEMPO_ASIGNACION]
	,SUM(TR.[TIEMPO_MODIFICACION])/SUM(TR.[NUM_TAREAS]) [PROM_TIEMPO_MODIFICACION]
	,SUM(TR.[TIEMPO_CORRIDO])/SUM(TR.[NUM_TAREAS]) [PROM_TIEMPO_CORRIDO]
	,SUM(TR.[TIEMPO_TOTAL])/SUM(TR.[NUM_TAREAS]) [PROM_TIEMPO_TOTAL]
	,SUM(TR.[NUM_TAREAS]) [NUM_TAREAS]
FROM [FAC].[ATENCION_CLIENTE_ESTADO_TAREAS] TR WITH (NOLOCK)
INNER JOIN DIM.ESTADO_RESPUESTA DM WITH (NOLOCK) ON TR.ID_RESPUESTA_TAREA=DM.ID_ESTADO_RESPUESTA
WHERE NUMERO_DOC_PROBLEMA = '3039359950' AND
DM.NOMBRE_ESTADORESPUESTA <> 'CANCELADA'
GROUP BY [NUMERO_DOC_PROBLEMA]
)
SELECT
	TIME_ID	
	,NUMERO_GUIA	
	,PROM_TIEMPO_RESPUESTA	
	,PROM_TIEMPO_CORRIDO	
	,PROM_TIEMPO_TOTAL	
	,NUM_TAREAS
	FROM CTE_PROMEDIO_TIEMPO_RESPUESTA_TAREAS

