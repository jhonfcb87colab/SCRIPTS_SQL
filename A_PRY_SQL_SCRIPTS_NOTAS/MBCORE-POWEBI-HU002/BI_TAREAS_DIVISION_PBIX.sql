		,AÑO
		,NUMERO_GUIA = CONVERT([numeric](20, 0),SIG_COLOMBIA_DW.[dbo].[Limpiar_Carcateres](TAR.NUMERO_DOC_PROBLEMA, '^0-9')) 	
		,DV.NOMBRE_DIVISION
		,TAR.ID_TIPO_IDP
		,TAR.ID_EST_TAREA
		,TAR.ID_EMPLEADO
		,TAR.ID_EMPLEADO_ASIGNADO
		,TAR.ID_PAIS
		,TAR.ID_TIPO_SERVICIO
		,TAR.ID_CIUDAD
		,TAR.ID_CIUDAD_PERTENECE
		,TAR.ID_DIVISION
		,TAR.ID_TIPO_TAREA
		,TAR.ID_RESPUESTA_TAREA
		,TAR.RESPONSABLE_TIPO_IDP
		,TAR.RESPONSABLE_PAIS
		,TAR.RESPONSABLE_CIUDAD
		,TAR.RESPONSABLE_TIPO
		,TAR.RESPONSABLE_CODIGO
		,TAR.ID_PAIS_CONTACTO
