		,TAR.FECHA_MODIFICACION
		,TAR.FECHA_CREACION_TAREA
		,TAR.NUM_TAREAS_CON_RESPUESTA
 FROM FAC.ATENCION_CLIENTE_ESTADO_TAREAS TAR
 INNER JOIN DIM.DIVISIONES DV ON DV.ID_CIUDAD=TAR.ID_CIUDAD AND DV.ID_DIVISION=TAR.ID_DIVISION
 WHERE ISNUMERIC(TAR.NUMERO_DOC_PROBLEMA)=1
 AND CONVERT(DATETIME,TIME_ID)>=DATEADD(yy,-5,DATEADD(yy,DATEDIFF(yy,0,GETDATE()),0))










 WITH CTE_DIM_PROCESO_TAREAS
 (
 ID
 ,FECHA	
 ,NUMERO_GUIA
 ,ID_DIVISION
 ,NOMBRE_DIVISION
 )
 AS (
	 SELECT  
	 ROW_NUMBER ( )   OVER ( PARTITION BY TAR.NUMERO_DOC_PROBLEMA order by FECHA desc ) ID
	 ,FECHA
			,NUMERO_GUIA = CONVERT([numeric](20, 0),SIG_COLOMBIA_DW.[dbo].[Limpiar_Carcateres](TAR.NUMERO_DOC_PROBLEMA, '^0-9')) 	
			,TAR.ID_DIVISION
			,DV.NOMBRE_DIVISION
	 FROM FAC.ATENCION_CLIENTE_ESTADO_TAREAS TAR
	 INNER JOIN DIM.DIVISIONES DV ON DV.ID_CIUDAD=TAR.ID_CIUDAD AND DV.ID_DIVISION=TAR.ID_DIVISION
	 WHERE ISNUMERIC(TAR.NUMERO_DOC_PROBLEMA)=1
	 AND CONVERT(DATETIME,TIME_ID)>=DATEADD(yy,-5,DATEADD(yy,DATEDIFF(yy,0,GETDATE()),0))
)
SELECT  
FECHA	
 ,NUMERO_GUIA
 ,ID_DIVISION
 ,NOMBRE_DIVISION
FROM CTE_DIM_PROCESO_TAREAS
WHERE ID=1