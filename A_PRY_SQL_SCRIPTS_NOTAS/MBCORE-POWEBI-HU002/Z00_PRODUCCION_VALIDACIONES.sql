DECLARE  @TABLA VARCHAR(100) = 'MBCORE'; 
DECLARE @TABLA_QDINAM NVARCHAR(MAX); 
SET @TABLA_QDINAM = CONCAT('%',@TABLA,'%')  

SELECT * FROM (  
SELECT *   
FROM [SIG_COL_LOGISTICA_DW].INFORMATION_SCHEMA.TABLES   
WHERE TABLE_NAME LIKE @TABLA_QDINAM  
UNION ALL  
SELECT *   
FROM [SIG_COLOMBIA_DW].INFORMATION_SCHEMA.TABLES   
WHERE TABLE_NAME LIKE @TABLA_QDINAM  
UNION ALL  
SELECT *   
FROM [SIG_LOGISTICA_DM].INFORMATION_SCHEMA.TABLES   
WHERE TABLE_NAME LIKE @TABLA_QDINAM 
) AS TABLE_AUX  
ORDER BY 1,3  

