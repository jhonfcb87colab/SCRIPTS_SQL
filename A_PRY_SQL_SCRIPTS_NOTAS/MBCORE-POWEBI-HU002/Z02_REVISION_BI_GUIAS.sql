WITH CTE_MBCORE
(
id,
nOMBRE_DIVISION_destino,
nOMBRE_DIVISION_origen,
NOMBRE_PROCESO_LOG,
NUMERO_GUIA,
FECHA_HORA_MOVIMIENTO,
NOMBRE_REGIONAL,
FECHA_EXTRACCION_DW,
FECHA_CREACION,
FECHA_MODIFICACION_DG
)
AS(
	SELECT ROW_NUMBER ( )   OVER ( PARTITION BY GUI.[NUMERO_GUIA] order by SEG.FECHA_HORA_MOVIMIENTO desc )  id,  
		 DIV.[NOMBRE_DIVISION] as nOMBRE_DIVISION_destino,
		 DIV_org.[NOMBRE_DIVISION] as nOMBRE_DIVISION_origen
		,PR.NOMBRE_PROCESO_LOG 
		,GUI.[NUMERO_GUIA]
		,SEG.FECHA_HORA_MOVIMIENTO
		,REGIO.NOMBRE_REGIONAL
		,DOC.FECHA_EXTRACCION_DW
		,DOC.FECHA_CREACION
		,GUI.FECHA_MODIFICACION_DG
	FROM LOG.GUIAS GUI WITH(NOLOCK)
	LEFT JOIN  LOG.SEGUIMIENTO_ENVIO SEG WITH (NOLOCK)
	ON GUI.NUMERO_GUIA=SEG.NUMERO_GUIA
	INNER JOIN  LOG.DOCUMENTOS DOC WITH (NOLOCK) 
	ON SEG.ID_PROCESO=DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI
	INNER JOIN PAR.DIVISIONES DIV WITH (NOLOCK)
	ON DIV.ID_DIVISION=DOC.ID_DIVISION_DESTINO AND DOC.ID_CIUDAD_DESTINO=DIV.ID_CIUDAD 

	INNER JOIN PAR.DIVISIONES DIV_org WITH (NOLOCK)
	ON DIV_org.ID_DIVISION=DOC.ID_DIVISION_ORIGEN AND DOC.ID_CIUDAD_DIVISION_ORIGEN=DIV_org.ID_CIUDAD 

	INNER JOIN PAR.PROCESOS PR ON SEG.ID_PROCESO=PR.ID_PROCESO
	INNER JOIN PAR.CIUDADES CIUD ON CIUD.ID_CIUDAD=DOC.ID_CIUDAD_DESTINO
	INNER JOIN PAR.REGIONALES_PAIS REGIO ON REGIO.ID_REGIONAL=CIUD.ID_REGIONAL
