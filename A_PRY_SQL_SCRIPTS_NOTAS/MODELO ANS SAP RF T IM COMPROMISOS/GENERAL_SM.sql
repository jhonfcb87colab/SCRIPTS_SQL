INSERT INTO [#DATOSGENERAESSAP]
		SELECT DISTINCT
		IM.NUMBER							AS [NUMBER],
		IM.PROBLEM_STATUS					AS [ESTADO INCIDENTE],
		IM.ASSIGNEE_NAME					AS [OPERADOR ACTUALMENTE ASIGNADO], 
		IM.ASSIGNMENT						AS [GRUPO ACTUAL SOPORTE],
		IM.CURRENT_PHASE					AS [FASE SERVICIO],
		DATEADD(HOUR,-5,IM.OPEN_TIME)		AS [FECHA APERTURA],
		DATEADD(HOUR,-5,IM.RESOLVED_TIME)	AS [FECHA RESOLUCION], 
		DATEADD(HOUR,-5,IM.CLOSE_TIME)		AS [FECHA CIERRE],
		IM.PRIORITY_CODE					AS [PRIORIDAD],
		IM.OPENED_BY 						AS [ABIERTO POR]
		FROM PROBSUMMARYM1 AS IM (NOLOCK)
		INNER JOIN SLORESPONSEHISTM1 AS SL (NOLOCK) ON IM.NUMBER = SL.FOREIGN_KEY
		WHERE 
		Sl.AGREEMENT_ID ='176' 
		AND SL.SLO_ID BETWEEN '1168' AND '1183'  
		AND SL.ASSIGNMENT IS NOT NULL 
		AND IM.RESOLVED_TIME IS NOT NULL 
		/*FILTRO DE FECHAS A CONSULTAS CASOS SAP*/
		AND DATEADD(HOUR,-5,IM.RESOLVED_TIME)>='2022-08-01'
		AND DATEADD(HOUR,-5,IM.RESOLVED_TIME)<'2022-09-01'
	UNION ALL
		SELECT DISTINCT
		IM.NUMBER							AS [NUMBER],
		IM.[STATUS]							AS [ESTADO INCIDENTE],
		IM.ASSIGNED_TO						AS [OPERADOR ACTUALMENTE ASIGNADO], 
		IM.ASSIGNED_GROUP					AS [GRUPO ACTUAL SOPORTE],
		IM.CURRENT_PHASE					AS [FASE SERVICIO],
		DATEADD(HOUR,-5,IM.SUBMIT_DATE)		AS [FECHA APERTURA],
		DATEADD(HOUR,-5,IM.RESOLVED_TIME)	AS [FECHA RESOLUCION], 
		DATEADD(HOUR,-5,IM.CLOSE_DATE)		AS [FECHA CIERRE],
		IM.[PRIORITY]						AS [PRIORIDAD],
		IM.OPENED_BY 						AS [ABIERTO POR]
		FROM REQUESTM1 AS IM (NOLOCK)
		INNER JOIN SLORESPONSEHISTM1 AS SL (NOLOCK) ON IM.NUMBER = SL.FOREIGN_KEY
		WHERE 
		Sl.AGREEMENT_ID ='176' 
		AND SL.SLO_ID BETWEEN '1168' AND '1183'  
		AND SL.ASSIGNMENT IS NOT NULL 
		AND IM.RESOLVED_TIME IS NOT NULL 
		/*FILTRO DE FECHAS A CONSULTAS CASOS SAP*/
		AND DATEADD(HOUR,-5,IM.RESOLVED_TIME)>='2022-08-01'
		AND DATEADD(HOUR,-5,IM.RESOLVED_TIME)<'2022-09-01'
