	 (CONVERT(VARCHAR(12),DATEDIFF(DAY,'4000-01-01 00:00:00.000',[TIME]),8)
	 +'  '+CONVERT(VARCHAR(12),[TIME],8)) AS [TIEMPOTOTAL],
	(CONVERT(INT,DATEDIFF(SECOND,'4000-01-01 00:00:00.000',[TIME]),8)) AS [SEGUNDOS]
