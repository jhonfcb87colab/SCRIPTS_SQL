USE SM;
DECLARE @FE_INI INT = 20220801;
DECLARE @FE_FIN INT = 20220901;	
WITH CTE_DATOSGENERAESSAP
(
ID,
NUMBER,
ESTADO_INCIDENTE,
OPERADOR_ACTUALMENTE_ASIGNADO,
GRUPO_ACTUAL_SOPORTE,
FASE_SERVICIO,
FECHA_APERTURA,
FECHA_RESOLUCION,
FECHA_CIERRE,
PRIORIDAD,
ABIERTO_POR
)
AS 
(
	SELECT 		 ROW_NUMBER ( )   OVER ( PARTITION BY NUMBER order by [FECHA_CIERRE] desc )  ID, *
		FROM (
				SELECT
					IM.NUMBER							AS [NUMBER],
					IM.PROBLEM_STATUS					AS [ESTADO_INCIDENTE],
					IM.ASSIGNEE_NAME					AS [OPERADOR_ACTUALMENTE_ASIGNADO], 
					IM.ASSIGNMENT						AS [GRUPO_ACTUAL_SOPORTE],
					IM.CURRENT_PHASE					AS [FASE_SERVICIO],
					DATEADD(HOUR,-5,IM.OPEN_TIME)		AS [FECHA_APERTURA],
					DATEADD(HOUR,-5,IM.RESOLVED_TIME)	AS [FECHA_RESOLUCION], 
					DATEADD(HOUR,-5,IM.CLOSE_TIME)		AS [FECHA_CIERRE],
					IM.PRIORITY_CODE					AS [PRIORIDAD],
					IM.OPENED_BY 						AS [ABIERTO_POR]
					FROM PROBSUMMARYM1 AS IM (NOLOCK)
					INNER JOIN SLORESPONSEHISTM1 AS SL (NOLOCK) ON IM.NUMBER = SL.FOREIGN_KEY
					WHERE 
					Sl.AGREEMENT_ID ='176' 
					AND SL.SLO_ID BETWEEN '1168' AND '1183'  
					AND SL.ASSIGNMENT IS NOT NULL 
					AND IM.RESOLVED_TIME IS NOT NULL 
					/*FILTRO DE FECHAS A CONSULTAS CASOS SAP*/
					AND 
					(YEAR(DATEADD(HOUR,-5,IM.RESOLVED_TIME))*100+MONTH(DATEADD(HOUR,-5,IM.RESOLVED_TIME)))*100+DAY(DATEADD(HOUR,-5,IM.RESOLVED_TIME))
					>=@FE_INI
					AND
					(YEAR(DATEADD(HOUR,-5,IM.RESOLVED_TIME))*100+MONTH(DATEADD(HOUR,-5,IM.RESOLVED_TIME)))*100+DAY(DATEADD(HOUR,-5,IM.RESOLVED_TIME))
					<@FE_FIN
				UNION ALL
				SELECT
					IM.NUMBER							AS [NUMBER],
					IM.[STATUS]							AS [ESTADO_INCIDENTE],
					IM.ASSIGNED_TO						AS [OPERADOR_ACTUALMENTE ASIGNADO], 
					IM.ASSIGNED_GROUP					AS [GRUPO_ACTUAL_SOPORTE],
					IM.CURRENT_PHASE					AS [FASE_SERVICIO],
					DATEADD(HOUR,-5,IM.SUBMIT_DATE)		AS [FECHA_APERTURA],
					DATEADD(HOUR,-5,IM.RESOLVED_TIME)	AS [FECHA_RESOLUCION], 
					DATEADD(HOUR,-5,IM.CLOSE_DATE)		AS [FECHA_CIERRE],
					IM.[PRIORITY]						AS [PRIORIDAD],
					IM.OPENED_BY 						AS [ABIERTO_POR]
					FROM REQUESTM1 AS IM (NOLOCK)
					INNER JOIN SLORESPONSEHISTM1 AS SL (NOLOCK) ON IM.NUMBER = SL.FOREIGN_KEY
					WHERE 
					Sl.AGREEMENT_ID ='176' 
					AND SL.SLO_ID BETWEEN '1168' AND '1183'  
					AND SL.ASSIGNMENT IS NOT NULL 
					AND IM.RESOLVED_TIME IS NOT NULL 
					/*FILTRO DE FECHAS A CONSULTAS CASOS SAP*/
					AND
					(YEAR(DATEADD(HOUR,-5,IM.RESOLVED_TIME))*100+MONTH(DATEADD(HOUR,-5,IM.RESOLVED_TIME)))*100+DAY(DATEADD(HOUR,-5,IM.RESOLVED_TIME))
					>=@FE_INI
					AND
					(YEAR(DATEADD(HOUR,-5,IM.RESOLVED_TIME))*100+MONTH(DATEADD(HOUR,-5,IM.RESOLVED_TIME)))*100+DAY(DATEADD(HOUR,-5,IM.RESOLVED_TIME))
					<@FE_FIN
			) CTE_AUX
)
SELECT 
NUMBER,
ESTADO_INCIDENTE,
OPERADOR_ACTUALMENTE_ASIGNADO,
GRUPO_ACTUAL_SOPORTE,
FASE_SERVICIO,
FECHA_APERTURA,
FECHA_RESOLUCION,
FECHA_CIERRE,
PRIORIDAD,
ABIERTO_POR
FROM CTE_DATOSGENERAESSAP WHERE ID=1
AND NUMBER
 IN(
'IM122703'--,
--'IM125002',
--'IM125998',
--'IM126476',
--'IM126913'
)
ORDER BY NUMBER ASC
