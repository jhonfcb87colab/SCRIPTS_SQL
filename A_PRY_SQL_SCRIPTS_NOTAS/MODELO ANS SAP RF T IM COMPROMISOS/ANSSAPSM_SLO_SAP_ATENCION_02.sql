USE SM;
DECLARE @FE_INI INT = 20220801;
DECLARE @FE_FIN INT = 20220901;	
--DECLARE @FE_INI INT = 0;
--DECLARE @FE_FIN INT = 0;	


WITH CTE_SLO_SAP_ATENCION
(
	NUMERO_CASO,
	GRUPO_SOPORTE,
	ESTADO_INICIO_MEDICION,
	ESTADO_FINAL_MEDICION,
	FECHA_INICIO_MEDICION,
	FECHA_FINAL_MEDICION,
	FECHA_DE_MODIFICACION,
	TIEMPO_TOTAL,
	TIEMPO_TOTAL_DESENCRIPTADO,
	TIEMPO_TOTAL_GRUPO,
	TIEMPO_TOTAL_GRUPO_DESENCRIPTADO,
	NOMBRE_ACUERDO,
	ACTIVO,
	CUMPLIMIENTO_SAP,
	ESTADO_CASO_SLO,
	NUMERO_ACUERDO,
	MACROPROCESO,
	PROCESO,
	SUBPROCESO,
	CATEGORIA,
	TIPO_ACUERDO,
	PAIS,
	REGIONAL,
	CIUDAD,
	TIEMPO_EN_SEGUNDOS,
	TIPO_MEDICION
)
AS
(
	SELECT 
		SL.FOREIGN_KEY												AS [NUMERO_CASO],
		SL.ASSIGNMENT 												AS [GRUPO_SOPORTE],
		SL.INITIAL_STATE 											AS [ESTADO_INICIO_MEDICION],
		SL.FINAL_STATE 												AS [ESTADO_FINAL_MEDICION],
		DATEADD(HOUR,-5,SL.START_TIME) 								AS [FECHA_INICIO_MEDICION],
		DATEADD(HOUR,-5,SL.END_TIME)  								AS [FECHA_FINAL_MEDICION],
		DATEADD(HOUR,-5,SL.sysmodtime) 								AS [FECHA_DE_MODIFICACION],
		('+SL.TOTAL_TIME+')										AS [TIEMPO_TOTAL],
		(CONVERT(VARCHAR(12),
		DATEDIFF(DAY,'4000-01-01 00:00:00.000',TOTAL_TIME),8) 
		+ '  ' + CONVERT(VARCHAR(12), TOTAL_TIME,8)) 				AS [TIEMPO_TOTAL_DESENCRIPTADO],
		SL.TOTAL_TIME_GROUP 										AS [TIEMPO_TOTAL_GRUPO],
		(CONVERT(VARCHAR(12),
		DATEDIFF(DAY,'4000-01-01 00:00:00.000',TOTAL_TIME_GROUP),8) 
		+ '  ' + CONVERT(VARCHAR(12), TOTAL_TIME_GROUP,8)) 			AS [TIEMPO_TOTAL_GRUPO_DESENCRIPTADO],
		SL.SLO_NAME 												AS [NOMBRE_ACUERDO],
		SL.BREACHED 												AS [ACTIVO],
			CASE SL.BREACHED
			WHEN 'f' THEN 'CUMPLIDO'
			WHEN 't' THEN 'INCUMPLIDO'
			END 
		AS [CUMPLIMIENTO_SAP],
			CASE SL.active
			WHEN 'f' THEN 'ABIERTO'
			WHEN 't' THEN 'CERRADO'
			END
		AS [ESTADO_CASO_SLO],
		SL.SLO_ID 													AS [NUMERO_ACUERDO],
		SL.M_PROCESO 												AS [MACROPROCESO],
		SL.P_PROCESO 												AS [PROCESO],
		SL.S_PROCESO 												AS [SUBPROCESO],
		CASE SL.FOREIGN_FILENAME
			WHEN'request' 		THEN 'REQUERIMIENTOS'
			WHEN'probsummary' 	THEN 'INCIDENTES'
		END 
		AS [CATEGORIA],
		SL.AGREEMENT_ID 											AS [TIPO_ACUERDO],
		SL.PAIS 													AS [PAIS],
		SL.REGIONAL 												AS [REGIONAL],
		SL.CIUDAD 													AS [CIUDAD],
		CASE 
			WHEN TOTAL_TIME IS NULL THEN '0'
			ELSE
		(CONVERT(INT,DATEDIFF(SECOND,'4000-01-01 00:00:00.000',TOTAL_TIME),8)) 
		END AS [TIEMPO_EN_SEGUNDOS],
		'ATENCIÓN IM' AS [TIPO_MEDICION]
		FROM SLORESPONSEHISTM1 AS SL (NOLOCK)
		INNER JOIN PROBSUMMARYM1 AS IM (NOLOCK) ON IM.NUMBER = SL.FOREIGN_KEY
		WHERE 
		Sl.AGREEMENT_ID ='176' 
		AND SL.SLO_ID BETWEEN '1168' AND '1171'  
		AND SL.ASSIGNMENT IS NOT NULL
		AND IM.RESOLVED_TIME IS NOT NULL
		/*FILTRO DE FECHAS A CONSULTAS NIVEL DE ATENCIÓN*/
		-- AND DATEADD(HOUR,-5,IM.RESOLVED_TIME)>='2022-08-01'
		-- AND DATEADD(HOUR,-5,IM.RESOLVED_TIME) <'2022-09-01'
		AND
		(YEAR(DATEADD(HOUR,-5,IM.RESOLVED_TIME))*100+MONTH(DATEADD(HOUR,-5,IM.RESOLVED_TIME)))*100+DAY(DATEADD(HOUR,-5,IM.RESOLVED_TIME))
		>=@FE_INI
		AND
		(YEAR(DATEADD(HOUR,-5,IM.RESOLVED_TIME))*100+MONTH(DATEADD(HOUR,-5,IM.RESOLVED_TIME)))*100+DAY(DATEADD(HOUR,-5,IM.RESOLVED_TIME))
		<@FE_FIN
	UNION ALL
		SELECT 
		SL.FOREIGN_KEY												AS [NUMERO_CASO],
		SL.ASSIGNMENT 												AS [GRUPO_SOPORTE],
		SL.INITIAL_STATE 											AS [ESTADO_INICIO_MEDICION],
		SL.FINAL_STATE 												AS [ESTADO_FINAL_MEDICION],
		DATEADD(HOUR,-5,SL.START_TIME) 								AS [FECHA_INICIO_MEDICION],
		DATEADD(HOUR,-5,SL.END_TIME)  								AS [FECHA_FINAL_MEDICION],
		DATEADD(HOUR,-5,SL.sysmodtime) 								AS [FECHA_DE_MODIFICACION],
		('+SL.TOTAL_TIME+')										AS [TIEMPO_TOTAL],
		(CONVERT(VARCHAR(12),
		DATEDIFF(DAY,'4000-01-01 00:00:00.000',TOTAL_TIME),8) 
		+ '  ' + CONVERT(VARCHAR(12), TOTAL_TIME,8)) 				AS [TIEMPO_TOTAL_DESENCRIPTADO],
		SL.TOTAL_TIME_GROUP 										AS [TIEMPO_TOTAL_GRUPO],
		(CONVERT(VARCHAR(12),
		DATEDIFF(DAY,'4000-01-01 00:00:00.000',TOTAL_TIME_GROUP),8) 
		+ '  ' + CONVERT(VARCHAR(12), TOTAL_TIME_GROUP,8)) 			AS [TIEMPO_TOTAL_GRUPO_DESENCRIPTADO],
		SL.SLO_NAME 												AS [NOMBRE_ACUERDO],
		SL.BREACHED 												AS [ACTIVO],
			CASE SL.BREACHED
			WHEN 'f' THEN 'CUMPLIDO'
			WHEN 't' THEN 'INCUMPLIDO'
			END 
		AS [CUMPLIMIENTO_SAP],
			CASE SL.active
			WHEN 'f' THEN 'ABIERTO'
			WHEN 't' THEN 'CERRADO'
			END
		AS [ESTADO_CASO_SLO],
		SL.SLO_ID 													AS [NUMERO_ACUERDO],
		SL.M_PROCESO 												AS [MACROPROCESO],
		SL.P_PROCESO 												AS [PROCESO],
		SL.S_PROCESO 												AS [SUBPROCESO],
		CASE SL.FOREIGN_FILENAME
			WHEN'request' 		THEN 'REQUERIMIENTOS'
			WHEN'probsummary' 	THEN 'INCIDENTES'
		END 
		AS [CATEGORIA],
		SL.AGREEMENT_ID 											AS [TIPO_ACUERDO],
		SL.PAIS 													AS [PAIS],
		SL.REGIONAL 												AS [REGIONAL],
		SL.CIUDAD 													AS [CIUDAD],
		CASE 
			WHEN TOTAL_TIME IS NULL THEN '0'
			ELSE
		(CONVERT(INT,DATEDIFF(SECOND,'4000-01-01 00:00:00.000',TOTAL_TIME),8)) 
		END AS [TIEMPO_EN_SEGUNDOS],
		'ATENCIÓN RF' AS [TIPO_MEDICION]
		FROM SLORESPONSEHISTM1 AS SL (NOLOCK)
		INNER JOIN REQUESTM1 AS IM (NOLOCK) ON IM.NUMBER = SL.FOREIGN_KEY
		WHERE 
		Sl.AGREEMENT_ID ='176' 
		AND SL.SLO_ID BETWEEN '1176' AND '1179'  
		AND SL.ASSIGNMENT IS NOT NULL
		AND IM.RESOLVED_TIME IS NOT NULL
		/*FILTRO DE FECHAS A CONSULTAS NIVEL DE ATENCIÓN*/
		-- AND DATEADD(HOUR,-5,IM.RESOLVED_TIME)>='2022-08-01'
		-- AND DATEADD(HOUR,-5,IM.RESOLVED_TIME) <'2022-09-01'
		AND
		(YEAR(DATEADD(HOUR,-5,IM.RESOLVED_TIME))*100+MONTH(DATEADD(HOUR,-5,IM.RESOLVED_TIME)))*100+DAY(DATEADD(HOUR,-5,IM.RESOLVED_TIME))
		>=@FE_INI
		AND
		(YEAR(DATEADD(HOUR,-5,IM.RESOLVED_TIME))*100+MONTH(DATEADD(HOUR,-5,IM.RESOLVED_TIME)))*100+DAY(DATEADD(HOUR,-5,IM.RESOLVED_TIME))
		<@FE_FIN
)
SELECT * FROM CTE_SLO_SAP_ATENCION
WHERE  NUMERO_CASO
 IN(
