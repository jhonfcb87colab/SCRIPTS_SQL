WITH CTE_IMS_RF
(
id,
TIME_ID_FECHA_RESOLUCION,
NUMERO_CASO,
LLAVE_CASO,
GRUPO_SOPORTE,
ESTADO_INICIO_MEDICION,
ESTADO_FINAL_MEDICION,
FECHA_INICIO_MEDICION,
FECHA_FINAL_MEDICION,
FECHA_DE_MODIFICACION,
TIEMPO_TOTAL_TRANSCURRIDO,
TIEMPO_TOTAL_GRUPO,
NOMBRE_ACUERDO,
ACTIVO,
CUMPLIMIENTO,
ESTADO_CASO_SLO,
ESTADO_INCIDENTE,
NUMERO_ACUERDO,
CATEGORIA,
ACUERDO_SLO,
OPERADOR_ACTUALMENTE_ASIGNADO,
GRUPO_ACTUAL_SOPORTE,
FASE_SERVICIO,
FECHA_APERTURA,
FECHA_RESOLUCION,
FECHA_CIERRE,
PRIORIDAD,
ANOS,
MESES,
DIAS,
HORAS,
MINUTOS,
SEGUNDOS,
TIEMPO_EN_SEGUNDOS,
SLO_SEG,
ID_SAP,
TIEMPO_CONTRATO_SAP,
MEDICION,
[ITEM CONTRATO],
ABIERTO_POR,
ID_AREA_PROCESO,
ID_CIUDAD,
CIUDAD,
PAIS,
REGIONAL,
MACROPROCESO,
PROCESO,
SUBPROCESO,
ID_DEPARTAMENTO,
ID_REGIONAL,
FECHA_EXTRACCION
)
AS(
SELECT 
ROW_NUMBER ( )   OVER ( PARTITION BY [NUMERO_CASO],[MEDICION] order by [FECHA_DE_MODIFICACION] desc )  id, 
[TIME_ID_FECHA_RESOLUCION]
      ,[NUMERO_CASO]
      ,LLAVE_CASO = CONCAT([NUMERO_CASO],'-',[MEDICION])
      ,[GRUPO_SOPORTE]
      ,[ESTADO_INICIO_MEDICION]
      ,[ESTADO_FINAL_MEDICION]
      ,[FECHA_INICIO_MEDICION]
      ,[FECHA_FINAL_MEDICION]
      ,[FECHA_DE_MODIFICACION]
      ,[TIEMPO_TOTAL_TRANSCURRIDO]
      ,[TIEMPO_TOTAL_GRUPO]
      ,[NOMBRE_ACUERDO]
      ,[ACTIVO]
      ,[CUMPLIMIENTO]
      ,[ESTADO_CASO_SLO]
      ,[ESTADO_INCIDENTE]
      ,[NUMERO_ACUERDO]
      ,[CATEGORIA]
      ,[ACUERDO_SLO]
      ,[OPERADOR_ACTUALMENTE_ASIGNADO]
      ,[GRUPO_ACTUAL_SOPORTE]
      ,[FASE_SERVICIO]
      ,[FECHA_APERTURA]
      ,[FECHA_RESOLUCION]
      ,[FECHA_CIERRE]
      ,[PRIORIDAD]
      ,[ANOS]
      ,[MESES]
      ,[DIAS]
      ,[HORAS]
      ,[MINUTOS]
      ,[SEGUNDOS]
      ,[TIEMPO_EN_SEGUNDOS]
      ,[SLO_SEG]
      ,[ID_SAP]
      ,[TIEMPO_CONTRATO_SAP]
      ,[MEDICION]
      ,[ITEM CONTRATO]
      ,[ABIERTO_POR]
      ,[ID_AREA_PROCESO]
      ,[ID_CIUDAD]
      ,[CIUDAD]
      ,[PAIS]
      ,[REGIONAL]
      ,[MACROPROCESO]
      ,[PROCESO]
      ,[SUBPROCESO]
      ,[ID_DEPARTAMENTO]
      ,[ID_REGIONAL]
      ,[FECHA_EXTRACCION]
  FROM [FAC].[ANSSAP_IM_RF] (NOLOCK)
)
SELECT * FROM CTE_IMS_RF WHERE ID=1
AND TIME_ID_FECHA_RESOLUCION 
BETWEEN CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,'2022-08-01')))) AND CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,'2022-08-31'))))
AND CATEGORIA = 'REQUERIMIENTOS'