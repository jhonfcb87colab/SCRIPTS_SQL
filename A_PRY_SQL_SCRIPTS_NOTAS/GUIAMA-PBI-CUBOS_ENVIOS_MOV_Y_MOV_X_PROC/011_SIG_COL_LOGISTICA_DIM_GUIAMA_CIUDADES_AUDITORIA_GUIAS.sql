CREATE VIEW [DIM].[DIM_GUIAMA_CIUDADES_AUDITORIA_GUIAS]
AS
	SELECT 
	T1.ID_CIUDAD, 
	CD.ID_REGIONAL,
	CD.NOMBRE_CIUDAD
	FROM(
		SELECT ID_CIUDAD,ID_PAIS 
		FROM SIG_COLOMBIA_DW.PAR.CIUDADES_ANEXAS 
		GROUP BY ID_CIUDAD,ID_PAIS  --ORDER BY 1
	) AS T1
	INNER JOIN SIG_COLOMBIA_DW.PAR.CIUDADES CD WITH(NOLOCK)
	ON T1.ID_CIUDAD=CD.ID_CIUDAD AND T1.ID_PAIS=CD.ID_PAIS
	WHERE T1.ID_PAIS=1
--AND CD.ID_REGIONAL=1
GO


