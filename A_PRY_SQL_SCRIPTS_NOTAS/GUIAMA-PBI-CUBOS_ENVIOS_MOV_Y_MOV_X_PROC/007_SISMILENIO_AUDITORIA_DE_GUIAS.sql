USE Seguridad;



SELECT * FROM DBO.GUIAS_AUDITORIA_WEB WITH(NOLOCK)



DECLARE @FECHA_INICIAL DATETIME = CONVERT(DATETIME,'20231201') 
DECLARE @FECHA_FINAL DATETIME = CONVERT(DATETIME,'20231222')

SELECT [ID_AUDITORIA_WEB]
      ,[NUMERO_GUIA]
      ,[FECHA_AUDITORIA_WEB]
      ,[HORA_AUDITORIA_WEB]
      ,[MODO_ENTREGA]
      ,[ID_REGIONAL]
      ,[ID_CIUDAD]
      ,[NOMBRE_ZONA] = RTRIM(LTRIM(CONVERT(VARCHAR(40),[NOMBRE_ZONA])))
      ,[CATEGORIA_ZONA] = RTRIM(LTRIM(CONVERT(tinyint,[CATEGORIA_ZONA])))
      ,[ID_EMPLEADO_O_ZONA]
      ,[NOMBRE_EMPLEADO]
      ,[ESTADO_AUDITORIA]
      ,[AUDITADO]
      ,[CAPTURA_NOMBRE]
      ,[CAPTURA_CEDULA]
      ,[SOPORTE_FIRMAS]
      ,[FOTO_SELLO]
      ,[FECHA_CREACION]
      ,[FECHA_MODIFICACION]
      ,[USUARIO_CREACION]
      ,[USUARIO_MODIFICACION]
  FROM [Seguridad].[dbo].[GUIAS_AUDITORIA_WEB] WITH(NOLOCK)
  WHERE FECHA_MODIFICACION BETWEEN @FECHA_INICIAL AND   @FECHA_FINAL

