USE SIG_COLOMBIA_DW;
DROP TABLE IF EXISTS #FORMATOS_IMPRESION_TESMPORAL_01;
with CTE as ( 
SELECT 
[ID_TIPOGUIA] AS ID_FORMATO
,[NOMBRE_TIPOGUIA] AS NOMBRE_FORMATO
,'Cadena Contado' [CADENA_CANAL]
 FROM  [PAR].[RTW_RETAIL_FORMATOS_IMPRESION_TIPOGUIA] WITH(NOLOCK)

 UNION ALL
SELECT 
	Id	AS ID_FORMATO
	,NombreFormato AS NOMBRE_FORMATO
	,'Cadena Credito' [CADENA_CANAL]
FROM  [PAR].[SIS_SISCLINET_FORMATOS_IMPRESION] WITH(NOLOCK)

)
SELECT 
C.ID_FORMATO
,C.NOMBRE_FORMATO
,C.CADENA_CANAL
INTO #FORMATOS_IMPRESION_TESMPORAL_01 
FROM CTE C
INNER JOIN [PAR].[FORMATOS_IMPRESION_DISPONIBLES] T WITH(NOLOCK)
ON C.ID_FORMATO = T.ID_FORMATO AND T.CADENA_CANAL=C.CADENA_CANAL
ORDER BY 1 ASC



USE SIG_COL_LOGISTICA_DW;
TRUNCATE TABLE DIM.FORMATOS_IMPRESION

INSERT INTO DIM.FORMATOS_IMPRESION 
SELECT 
ID_FORMATO	
,NOMBRE_FORMATO	
,CADENA_CANAL
FROM #FORMATOS_IMPRESION_TESMPORAL_01



