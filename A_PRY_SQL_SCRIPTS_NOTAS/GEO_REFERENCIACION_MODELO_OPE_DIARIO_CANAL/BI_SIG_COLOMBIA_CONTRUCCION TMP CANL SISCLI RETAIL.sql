USE SIG_COLOMBIA_DW;
SELECT
		T.*
		,CASE WHEN G_ID_TIEMPO_ENTREGA IN(2,3) THEN
		CASE WHEN T.[ZONA_TE] = ZT.ID_ZONA THEN 
			ZT.ID_ZONA
		ELSE 
			'N/A'
		END
	 ELSE
		CASE WHEN T.[ZONA_PRODUCTO] = Z.ID_ZONA THEN 
			Z.ID_ZONA
		ELSE 
			'N/A'
		END
	 END ZONA

FROM
(
SELECT        
      ROW_NUMBER() OVER(PARTITION BY G.Id ORDER BY RTW.SHIPPING.GuideId ASC) ROW#
	 ,RTW.SHIPPING.Id
	 ,CTE.ID_TIEMPO
	 ,CTE.ID_GEOGRAFIA_SERV
	 ,RTW.SHIPPING.ReceiverCityId ID_GEOGRAFIA_SERV_DEST
	 ,CTE.ID_ICLENTE_SCN
	 ,CTE.ID_CLIENTE_RTW
	 ,CTE.ID_UEN_PROD_SUBP	  
	,ISNULL(CONVERT(INT, G.DeliveryTimeId), - 888) AS G_ID_TIEMPO_ENTREGA    	
	,ISNULL(CONVERT(INT, G.MeanTransportId), - 888) AS G_ID_MEDIO_TRANSPORTE	    
	,CTE.ID_CANAL	
	,ISNULL(G.Number, - 888) AS G_NUMERO_GUIA
	,1 CANTIDAD_PIEZAS
	,CTE.VL_RECAUDO
	,CTE.FECHA_IMPRESION
	,CASE WHEN (RTW.SHIPPING.[ZONE] IS NULL OR RTW.SHIPPING.[ZONE] = ' ') THEN 'N/A' ELSE RTW.SHIPPING.[ZONE] END ID_ZONA  
	,CONVERT(VARCHAR(50),CONVERT(VARCHAR,RTW.SHIPPING.ReceiverCityId) + '-PD-' + CONVERT(VARCHAR,CTE.ID_UEN_PROD_SUBP) + '-' + CONVERT(VARCHAR,RTW.SHIPPING.[ZONE])) ZONA_PRODUCTO	  
	,CONVERT(VARCHAR(50),CONVERT(VARCHAR,RTW.SHIPPING.ReceiverCityId) + '-TE-' + CONVERT(VARCHAR,G.DeliveryTimeId) + '-' + CONVERT(VARCHAR,RTW.SHIPPING.[ZONE])) ZONA_TE	  
                   ,CTE.ID_TIPO_LOGISTICA

FROM            RTW.GUIDE AS G WITH (NOLOCK) INNER JOIN                        
                         RTW.SHIPPING WITH (NOLOCK) ON G.Id = RTW.SHIPPING.GuideId INNER JOIN
						 TMP.CANAL_RETAIL CTE  WITH (NOLOCK) ON  G.InvoiceDetailId = CTE.id
) T
	LEFT JOIN
			TMP.ZONAS_GEOREFERENCIADAS Z WITH (NOLOCK)
ON
	Z.ID_ZONA = T.ZONA_PRODUCTO 

	LEFT JOIN
			TMP.ZONAS_GEOREFERENCIADAS ZT WITH (NOLOCK)
ON
	ZT.ID_ZONA = T.ZONA_TE

WHERE T.ROW# = 1





