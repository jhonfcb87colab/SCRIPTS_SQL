SELECT 
		D.Id
	   ,CONVERT(INT, CONVERT(NUMERIC, CONVERT(DATETIME, CONVERT(CHAR(11), V.InvoiceDate)))) ID_TIEMPO
	   ,S.CityId ID_GEOGRAFIA_SERV
	   ,'-888' ID_ICLENTE_SCN
	   ,CASE WHEN (S.CountryId IS NULL OR S.CityId IS NULL OR S.SolutionCenterId IS NULL) THEN CONVERT(VARCHAR(20), '-888') ELSE CONVERT(VARCHAR(20), CONVERT(VARCHAR, S.CountryId) + '-' + 
	   CONVERT(VARCHAR, S.CityId) + '-' + CONVERT(VARCHAR,S.SolutionCenterId)) END ID_CLIENTE_RTW
	   ,1 ID_CANAL
	   ,CASE WHEN (D .FilialId IS NULL OR D .FilialId <> 1 OR D .ProductId IS NULL OR D .ByProductId IS NULL) THEN  '-888' ELSE (CONVERT(VARCHAR, D .ProductId) + '-' + CONVERT(VARCHAR, D .ByProductId))  END ID_UEN_PROD_SUBP
	   ,CASE 
			WHEN PaymentFormId = 4 THEN 1
	        ELSE CASE WHEN ProductId = 52 THEN 2 
				ELSE 4 
				END
		 END ID_TIPO_LOGISTICA
	   ,D.TotalValue VL_RECAUDO
	   ,V.InvoiceDate FECHA_IMPRESION
FROM RTW.INVOICEDETAIL AS D WITH (NOLOCK)
	  INNER JOIN
				 RTW.INVOICE AS V WITH (NOLOCK) ON D.InvoiceId = V.Id 
      INNER JOIN
				RTW.CASHREGISTER AS C WITH (NOLOCK) ON V.CashRegisterId = C.Id 
	  INNER JOIN
                RTW.SOLUTIONCENTER AS S WITH (NOLOCK) ON C.SolutionCenterId = S.Id 
WHERE  V.InvoiceDate  >= '20230510'
       AND 
	   V.InvoiceDate < DATEADD(DAY,+1, '20230516')
AND V.State = 1


