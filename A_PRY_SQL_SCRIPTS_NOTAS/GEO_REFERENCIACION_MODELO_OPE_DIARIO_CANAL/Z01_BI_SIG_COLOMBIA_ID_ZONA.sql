USE SIG_COLOMBIA_DW;
SELECT 
	T.*	
	,CASE WHEN ID_TIEMPO_ENTREGA IN(10) THEN
		CASE WHEN T.[ZONA_TE] = ZT.ID_ZONA THEN 
			ZT.ID_ZONA
		ELSE 
			'N/A'
		END
	 ELSE
		CASE WHEN T.[ZONA_PRODUCTO] = Z.ID_ZONA THEN 
			Z.ID_ZONA
		ELSE 
			'N/A'
		END
	 END ZONA
 FROM

(
SELECT 
    
       CONVERT(INT, CONVERT(NUMERIC, CONVERT(DATETIME, CONVERT(CHAR(11), [FEC_CREACION])))) ID_TIEMPO	    
	  ,CASE WHEN [DES_CIUDADREMITENTE] IS NULL THEN '-888' ELSE [DES_CIUDADREMITENTE] END ID_GEOGRAFIA_SERV
	  ,CASE WHEN [DES_CIUDAD] IS NULL THEN '-888' ELSE [DES_CIUDAD] END ID_GEOGRAFIA_SERV_DEST
	  ,CASE WHEN [IDE_CODFACTURACION] IS NULL THEN '-888' ELSE[IDE_CODFACTURACION] END  ID_ICLENTE_SCN
	  ,'-888' ID_CLIENTE_RTW
	  ,CASE WHEN IDE_PRODUCTO IS NULL THEN '-888' ELSE CONVERT(VARCHAR,IDE_PRODUCTO)+'-1' END ID_UEN_PROD_SUBP
	  ,ISNULL(CONVERT(INT,DES_TIPODURACIONTRAYECTO), -888) ID_TIEMPO_ENTREGA
	  ,ISNULL(CONVERT(INT,DES_MEDIOTRANSPORTE), -888) ID_MEDIO_TRANSPORTE
	  ,2 ID_CANAL
	  ,NUM_GUIA NUMERO_GUIA
	  ,NUM_PIEZAS CANTIDAD_PIEZAS
	  ,CASE WHEN [DES_FORMAPAGO] = 4 AND (ISNULL([NUM_RECAUDO],0) <> 0) THEN 5
			ELSE CASE WHEN  [DES_FORMAPAGO] = 4 THEN 1
				ELSE CASE WHEN (ISNULL([NUM_RECAUDO], 0) <> 0) THEN 3
					ELSE CASE WHEN IDE_PRODUCTO = 52 THEN 2 ELSE 4
					END
				END
			END
		END ID_TIPO_LOGISTICA	
	  ,CONVERT(VARCHAR(50),CONVERT(VARCHAR,[DES_CIUDAD]) + '-PD-' + CONVERT(VARCHAR,IDE_PRODUCTO) +'-1' + '-' + CONVERT(VARCHAR,ID_ZONIFICACION)) ZONA_PRODUCTO	  
	  ,CONVERT(VARCHAR(50),CONVERT(VARCHAR,[DES_CIUDAD]) + '-TE-' + CONVERT(VARCHAR,DES_TIPODURACIONTRAYECTO) + '-' + CONVERT(VARCHAR,ID_ZONIFICACION)) ZONA_TE	  
	  ,CASE WHEN (ID_ZONIFICACION IS NULL OR ID_ZONIFICACION = ' ') THEN 'N/A' ELSE ID_ZONIFICACION END ID_ZONA
	  ,FEC_CREACION FECHA_IMPRESION
	  ,NUM_VALORLIQUIDADO VL_RECAUDO
	  ,NUM_VLRSOBREFLETE VL_SOBREFLETE--------
	  ,NUM_VLRFLETE VL_FLETE--------
  FROM [SIG_COLOMBIA_DW].[SCN].[SERT_ENVIO] WITH (NOLOCK)
  INNER JOIN
			[SIG_COLOMBIA_DW].[SCN].[SERT_CLIENTE_CODSER] F WITH (NOLOCK)
ON
	[SCN].[SERT_ENVIO].IDE_CODFACTURACION = F.ID_CODFACTURACION

WHERE NUM_GUIA in(2090863732,2160542932)
  AND [SCN].[SERT_ENVIO].EST_CANCELACION = 0 AND F.ID_ESTADO_DEPE = 1
)T
	LEFT JOIN
			TMP.ZONAS_GEOREFERENCIADAS Z WITH (NOLOCK)
ON
	Z.ID_ZONA = T.ZONA_PRODUCTO 

	LEFT JOIN
			TMP.ZONAS_GEOREFERENCIADAS ZT WITH (NOLOCK)
ON
	ZT.ID_ZONA = T.ZONA_TE

