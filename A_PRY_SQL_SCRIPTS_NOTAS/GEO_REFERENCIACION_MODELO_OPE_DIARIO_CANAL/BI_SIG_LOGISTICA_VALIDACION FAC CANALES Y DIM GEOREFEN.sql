SELECT * FROM
(
SELECT 
	 CONVERT(VARCHAR(50),T.ID_GEOGRAFIA) ID_GEOGRAFIA
	,T.NOMBRE_ZONA
	,T.TIPO_ZONA
	,ROW_NUMBER() OVER(PARTITION BY T.ID_GEOGRAFIA ORDER BY CIUDAD_DES  ASC) R    

  FROM
(
SELECT  
        Z.CIUDAD_DES
	   ,Z.ZONA
	   ,Z.CODIGO_ZONA
	   ,Z.NOMBRE_ZONA
	   ,Z.TIPO_ZONA
	   ,Z.ID_TIPO
	   ,Z.ID_PRODUCTO 
	   ,Z.ID_ENTREGA
	   ,CASE WHEN Z.CODIGO_ZONA = 'N/A' OR (ID_TIPO = 'PD' AND ID_PRODUCTO = '0') THEN 'N/A' 	  
			 WHEN ID_TIPO = 'PD' THEN CONCAT(Z.CIUDAD_DES,'-',Z.ID_TIPO,'-',ID_PRODUCTO,'-',CODIGO_ZONA) 
	         ELSE CONCAT(Z.CIUDAD_DES,'-',Z.ID_TIPO,'-',ID_ENTREGA,'-',CODIGO_ZONA) END ID_GEOGRAFIA 
FROM [TMP].[CIUDADES_ZONAS2] Z WITH (NOLOCK) 
) T WHERE ID_GEOGRAFIA <> 'N/A' 
) Z WHERE Z.R = 1






