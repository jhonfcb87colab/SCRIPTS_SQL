/****** Script for SelectTopNRows command from SSMS  ******/
USE SIG_COLOMBIA_DW;
SELECT
	CIU.ID_CIUDAD
	,CIU.NOMBRE_CIUDAD
      ,PROD.[ID_PRODUCTO]
      ,PROD.[NOMBRE_PRODUCTO]
      ,PROD.[DESCRIP_PRODUCTO]
      ,PROD.[DESCRIP_LIQUI_PRODUCTO]
      ,PROD.[DESCRIP_NORMAS_PRODUCTO]
  FROM [SIG_COLOMBIA_DW].[PAR.].[PRODUCTOS] PROD WITH(NOLOCK), PAR.CIUDADES CIU WITH(NOLOCK)
  WHERE PROD.[ID_PRODUCTO] IN(1,2,65,9)
  --AND CIU.ID_CIUDAD IN(10)
  SELECT * FROM PAR.CIUDADES WHERE ID_CIUDAD = 281
