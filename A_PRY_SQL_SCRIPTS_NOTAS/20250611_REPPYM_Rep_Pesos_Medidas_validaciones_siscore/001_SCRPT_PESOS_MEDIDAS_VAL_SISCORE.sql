DROP TABLE IF EXISTS #TEMP_SEGUIMIENTO_ENVIO;
SELECT SEG.*
INTO #TEMP_SEGUIMIENTO_ENVIO
FROM SEGUIMIENTO_ENVIO SEG WITH(NOLOCK) 
WHERE SEG.FECHA_HORA_MOVIMIENTO BETWEEN @FECHA_INI AND @FECHA_FIN 
AND ID_PROCESO IN(6,5,8,14)
OPTION(FAST 1)

