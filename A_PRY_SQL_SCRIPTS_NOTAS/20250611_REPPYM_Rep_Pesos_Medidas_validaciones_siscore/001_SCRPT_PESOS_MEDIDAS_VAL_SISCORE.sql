DECLARE @FECHA_INI DATETIME = DATEADD(DAY,-5,DATEADD(DAY,DATEDIFF(DAY,0,GETDATE()),0))
DECLARE @FECHA_FIN DATETIME = DATEADD(DAY,1,CONVERT(DATE,GETDATE()))
