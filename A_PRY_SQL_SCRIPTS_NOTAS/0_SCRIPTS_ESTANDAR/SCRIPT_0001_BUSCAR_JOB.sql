--[LOG].[PRUEBAS_ENTREGA]
DECLARE  @TABLA VARCHAR(100) = '%SISCL TIPO TRAYECTO%'; --'EXTRACCION TABLAS ORIGEN.dtsx' ---'CLIENTES_SUCURSALES_DEPENDEN';  --'CLIENTE_VENDEDOR'
DECLARE @TABLA_QDINAM NVARCHAR(MAX);  
SET @TABLA_QDINAM = CONCAT('%',@TABLA,'%')   
SELECT  
     NAME,  
STEP_ID AS ORDEN_EJECUCION,  
     STEP_NAME--,  
     --REPLACE(COMMAND,'/ISSERVER "\"\SSISDB\DATA WAREHOUSE\PPES\','')  
FROM  
    MSDB.DBO.SYSJOBS JOB  
INNER JOIN  
    MSDB.DBO.SYSJOBSTEPS STEPS          
ON  
    JOB.JOB_ID = STEPS.JOB_ID  
WHERE  
JOB.ENABLED = 1 AND  
(NAME                LIKE @TABLA_QDINAM OR  
COMMAND        LIKE @TABLA_QDINAM OR  
STEP_NAME  LIKE @TABLA_QDINAM )  
ORDER BY NAME  
