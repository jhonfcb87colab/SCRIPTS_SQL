USE Mece_Logistico;
SELECT SE.* FROM .SEGUIMIENTO_ENVIO AS SE WITH(NOLOCK)
INNER JOIN .Guias_Temu AS TEMU WITH(NOLOCK)
ON SE.NUMERO_GUIA = TEMU.NumeroGuia
WHERE SE.FECHA_HORA_MOVIMIENTO BETWEEN '2024-11-26' AND '2024-11-27'
AND SE.ID_PROCESO in (6, 29, 28)

