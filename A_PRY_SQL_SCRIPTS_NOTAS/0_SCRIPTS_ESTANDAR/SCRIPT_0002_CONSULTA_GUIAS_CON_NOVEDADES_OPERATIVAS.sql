
USE MECE_LOGISTICO
SELECT  
SEG.NUMERO_GUIA,[TIPN].[NOMBRE_TIPO_NOVEDAD]
FROM [DBO].[SEGUIMIENTO_ENVIO] SEG WITH(NOLOCK)
INNER JOIN [DBO].[DOCUMENTOS_NOVEDAD_DIARIA] DOCND WITH(NOLOCK)
	ON  [DOCND].[ID_PROCESO] = [SEG].[ID_PROCESO]
		AND [DOCND].[NUMERO_MOVIMI] = [SEG].[NUMERO_MOVIMI]
		AND [DOCND].[CONSECUT_MOVIMI] = [SEG].[CONSECUT_MOVIMI]
INNER JOIN  [DBO].[NOVEDAD_DIARIA] ND WITH(NOLOCK)
	ON [DOCND].[ID_PAIS_UNO] = [ND].[ID_PAIS_UNO]
		AND [DOCND].[ID_CIUDAD_UNO] = [ND].[ID_CIUDAD_UNO]
		AND [DOCND].[FECHA_NOVEDAD] = [ND].[FECHA_NOVEDAD]
INNER JOIN  [PARAMETROS].[DBO].[TIPOSNOVEDADESOPERATIVAS] TIPN WITH (NOLOCK)
	ON  [ND].[ID_TIPO_NOVEDAD] = [TIPN].[ID_TIPO_NOVEDAD]
LEFT JOIN  [DBO].[DETALLE_NOVEDAD_DIARIA] DETND WITH(NOLOCK)
	ON  [DOCND].[ID_PAIS_UNO] = [DETND].[ID_PAIS_UNO]
		AND [DOCND].[ID_CIUDAD_UNO] = [DETND].[ID_CIUDAD_UNO]
		AND [DOCND].[FECHA_NOVEDAD] = [DETND].[FECHA_NOVEDAD]
LEFT JOIN  [PARAMETROS].[DBO].[SUBTIPOS_NOVEDADES_OPERATIVAS] PAR WITH (NOLOCK)
	ON  [TIPN].[ID_TIPO_NOVEDAD] = [PAR].[ID_TIPO_NOVEDAD]
		AND [DETND].[ID_SUBTIPO_NOVEDAD] = [PAR].[ID_SUBTIPO_NOVEDAD]
WHERE SEG.NUMERO_GUIA IN(22812708335)
