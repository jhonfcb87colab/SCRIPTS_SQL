DROP TABLE IF EXISTS #GEOGRAFIAS_VALIDACION_PR_E;
SELECT 
CD.ID_CIUDAD,
CD.NOMBRE_CIUDAD,
CD.ID_REGIONAL,
RG.NOMBRE_REGIONAL
INTO #GEOGRAFIAS_VALIDACION_PR_E
FROM PARAMETROS..CIUDADES CD (NOLOCK)
INNER JOIN PARAMETROS..REGIONALES_PAIS RG (NOLOCK)
ON CD.ID_REGIONAL=RG.ID_REGIONAL

DROP TABLE IF EXISTS #PROCESOS_LOG;
SELECT 
PR.ID_PROCESO,
PR.NOMBRE_PROCESO_LOG
INTO #PROCESOS_LOG
FROM PARAMETROS..PROCESOS PR (NOLOCK)




SELECT 
--TMP.PR_E_NUMERO_GUIA	
TMP.NUMERO_GUIA
,RESPONSABLE_ENTREGA = CASE WHEN ZU.NOMBRE_ZONA_URBA LIKE '%RAPIGO%' OR ZU.NOMBRE_ZONA_URBA LIKE '%ALIADO%' THEN 'RAPIGO'
					WHEN ZU.NOMBRE_ZONA_URBA LIKE '%CLICO%' THEN 'CLICOH' 
					ELSE 'SERVIENTREGA'
					END
,ID_FECHA_ENVIO = CONVERT(varchar,TMP.FECHA_ENVIO,112)
,ID_FECHA_ENVIO_ANIO_MES = YEAR(TMP.FECHA_ENVIO)*100 + MONTH(TMP.FECHA_ENVIO)
,ID_FECHA_HORA_MOVIMIENTO_SE = CONVERT(varchar,TMP.FECHA_HORA_MOVIMIENTO,112)
,ID_FECHA_HORA_MOVIMIENTO_SE_ANIOMES = YEAR(TMP.FECHA_HORA_MOVIMIENTO)*100 + MONTH(TMP.FECHA_HORA_MOVIMIENTO)
,TMP.NUMERO_MOVIMI	
,TMP.CONSECUT_MOVIMI	
,TMP.ID_PROCESO	
,PR.NOMBRE_PROCESO_LOG
,TMP.FECHA_ENVIO	
,TMP.FECHA_HORA_MOVIMIENTO	
,TMP.ID_ESTADOENVIO	
,TMP.ID_ESTADOGUIA	
,TMP.ID_ZONA_URBA	
,TMP.ID_TIPO_ZONA_URBA	
,TMP.ID_CIUDAD_ZONA_URBA	
,ZU.NOMBRE_ZONA_URBA
,GEO_ZU.NOMBRE_CIUDAD as NOMBRE_CIUDAD_ZU
,GEO_ZU.NOMBRE_REGIONAL as NOMBRE_REGIONAL_ZU
,TMP.ID_DIVISION_ORIGEN	
,TMP.ID_DIVISION_DESTINO	
,TMP.ID_CIUDAD_DIVISION_ORIGEN	
,TMP.ID_CIUDAD_DESTINO
,GEO_1.NOMBRE_CIUDAD as NOMBRE_CIUDAD_DEST
,GEO_1.NOMBRE_REGIONAL as NOMBRE_REGIONAL_DEST
,TMP.PR_E_FECHA_CREACION	
,TMP.PR_E_FECHA_DIGITALIZACION	
,TMP.PR_E_TIPO_PRUEBA_ENTREGA	
