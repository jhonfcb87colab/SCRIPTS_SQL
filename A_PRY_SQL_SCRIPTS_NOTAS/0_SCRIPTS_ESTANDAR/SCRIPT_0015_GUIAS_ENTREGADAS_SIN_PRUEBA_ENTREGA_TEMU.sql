ON ZU.ID_ZONA_URBA=TMP.ID_ZONA_URBA AND ZU.ID_TIPO_ZONA_URBA=TMP.ID_TIPO_ZONA_URBA AND ZU.ID_CIUDAD=TMP.ID_CIUDAD_ZONA_URBA
LEFT JOIN #GEOGRAFIAS_VALIDACION_PR_E GEO_1 ON TMP.ID_CIUDAD_DESTINO=GEO_1.ID_CIUDAD
LEFT JOIN #GEOGRAFIAS_VALIDACION_PR_E GEO_zu ON TMP.ID_CIUDAD_ZONA_URBA=GEO_zu.ID_CIUDAD
LEFT JOIN #PROCESOS_LOG PR ON TMP.ID_PROCESO=PR.ID_PROCESO





