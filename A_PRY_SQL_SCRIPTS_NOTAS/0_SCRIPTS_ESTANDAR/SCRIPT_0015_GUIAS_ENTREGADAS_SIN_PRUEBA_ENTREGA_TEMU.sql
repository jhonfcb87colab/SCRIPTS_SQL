INSERT INTO #GUIAS_NECESARIAS_A_EVALUAR
SELECT NUMERO_GUIA,ID_ESTADOENVIO,ID_ESTADOGUIA,FECHA_ENVIO 
FROM Mece_Logistico..GUIAS (NOLOCK) WHERE ID_REMITE = '2970299'
AND FECHA_ENVIO >= '2024-01-01' AND ID_ESTADOENVIO IN(3,4) AND ID_ESTADOGUIA >=3



SELECT TMP.NUMERO_GUIA,TMP.ID_ESTADOENVIO,TMP.ID_ESTADOGUIA,TMP.FECHA_ENVIO
,PR_E.NUMERO_GUIA AS PR_E_NUMERO_GUIA
,PR_E.FECHA_CREACION AS PR_E_FECHA_CREACION
,PR_E.FECHA_DIGITALIZACION AS PR_E_FECHA_DIGITALIZACION
,PR_E.TIPO_PRUEBA_ENTREGA AS PR_E_TIPO_PRUEBA_ENTREGA
INTO #GUIAS_ENTREGADAS_NO_DIGITALIZADAS
FROM #GUIAS_NECESARIAS_A_EVALUAR TMP
LEFT JOIN [dbo].[PRUEBAS_ENTREGA_BI] PR_E (NOLOCK)
ON TMP.NUMERO_GUIA=PR_E.NUMERO_GUIA
WHERE PR_E.NUMERO_GUIA IS NULL


