

USE SIG_COLOMBIA_DW;

DROP TABLE IF EXISTS #TMP_CIUDADES_ANEXAS;
DROP TABLE IF EXISTS #TMP_CIUDADES_ANEXAS_CPL;
SELECT CAD.* 
INTO #TMP_CIUDADES_ANEXAS 
FROM PAR.CIUDADES_ANEXAS CAD (NOLOCK) 
WHERE CAD.ID_PAIS=1 AND CAD.RECOLECCION=1
 
INSERT INTO #TMP_CIUDADES_ANEXAS
SELECT CAD.* FROM PAR.CIUDADES_ANEXAS CAD (NOLOCK) 
LEFT JOIN #TMP_CIUDADES_ANEXAS TCAD ON TCAD.ID_CIUDAD_ANEXA=CAD.ID_CIUDAD_ANEXA
WHERE CAD.ID_PAIS=1 AND CAD.RECOLECCION=0 AND TCAD.ID_CIUDAD_ANEXA IS NULL
 
DELETE T FROM (
SELECT *, DupRank = ROW_NUMBER() OVER (PARTITION BY ID_CIUDAD_ANEXA ORDER BY FECHA_CREACION DESC
) FROM #TMP_CIUDADES_ANEXAS) AS T
WHERE DupRank > 1

----truncate table [TMP].[KPI_TIEMPOS_ENTREGA_13]

SELECT 
T01.ID_CIUDAD_ANEXA AS  ID_CIUDAD_ANEXA
,CD_ANX.NOMBRE_CIUDAD AS NOMBRE_CIUDAD_ANEXA
,RG_ANX.ID_REGIONAL AS ID_REGIONAL_ANEXA
,RG_ANX.NOMBRE_REGIONAL AS NOMBRE_REGIONAL_ANEXA
,T01.ID_CIUDAD AS ID_CIUDAD_CABECERA
,CD.NOMBRE_CIUDAD AS  NOMBRE_CIUDAD_CABECERA
,RG_PRIN.ID_REGIONAL AS ID_REGIONAL_PRINCIPAL
,RG_PRIN.NOMBRE_REGIONAL AS NOMBRE_REGIONAL_PRINCIPAL
,CPL = CONVERT(VARCHAR(50),'')
INTO #TMP_CIUDADES_ANEXAS_CPL
FROM #TMP_CIUDADES_ANEXAS T01
INNER JOIN PAR.CIUDADES CD_ANX WITH(NOLOCK)
ON CD_ANX.ID_CIUDAD=T01.ID_CIUDAD_ANEXA
AND CD_ANX.ID_PAIS=1
INNER JOIN PAR.REGIONALES_PAIS RG_ANX WITH(NOLOCK)
ON RG_ANX.ID_REGIONAL=CD_ANX.ID_REGIONAL
AND RG_ANX.ID_PAIS=1
INNER JOIN PAR.CIUDADES CD WITH(NOLOCK)
ON CD.ID_CIUDAD=T01.ID_CIUDAD
AND CD.ID_PAIS=1
INNER JOIN PAR.REGIONALES_PAIS RG_PRIN WITH(NOLOCK)
ON CD.ID_REGIONAL=RG_PRIN.ID_REGIONAL

---where T01.ID_CIUDAD_ANEXA = 253--460
---CD.NOMBRE_CIUDAD like '%QUEREMAL%'
ORDER BY 1 ASC

UPDATE CPL SET
CPL.CPL = CL.CENTRO_LOGISTICO 
FROM  #TMP_CIUDADES_ANEXAS_CPL CPL 
INNER JOIN PAR.CENTROS_LOGISTICOS CL WITH(NOLOCK)
ON CPL.ID_CIUDAD_CABECERA=CL.ID_CIUDAD AND CL.ID_ESTADO=1


--TRUNCATE TABLE [dbo].[MPCCO_PAR_CPL]
--INSERT INTO [dbo].[MPCCO_PAR_CPL]
SELECT 
ID_CIUDAD_ANEXA	
,NOMBRE_CIUDAD_ANEXA	
,ID_REGIONAL_ANEXA	
,NOMBRE_REGIONAL_ANEXA	
,ID_CIUDAD_CABECERA	
,NOMBRE_CIUDAD_CABECERA	
,ID_REGIONAL_PRINCIPAL	
,NOMBRE_REGIONAL_PRINCIPAL	
,CPL
----INTO [dbo].[MPCCO_PAR_CPL]
FROM #TMP_CIUDADES_ANEXAS_CPL
UNION  ALL 
SELECT 
ID_CIUDAD_ANEXA=CD.ID_CIUDAD	
,NOMBRE_CIUDAD_ANEXA=CD.NOMBRE_CIUDAD	
,ID_REGIONAL_ANEXA=RG.ID_REGIONAL	
,NOMBRE_REGIONAL_ANEXA=RG.NOMBRE_REGIONAL
,ID_CIUDAD_CABECERA=NULL	
,NOMBRE_CIUDAD_CABECERA=NULL	
,ID_REGIONAL_PRINCIPAL=NULL	
,NOMBRE_REGIONAL_PRINCIPAL=NULL	
,CPL='ERROR - NO EXISTE EN PARAMETROS CENTRO LOGISTICO'
----INTO [dbo].[MPCCO_PAR_CPL]
FROM PAR.CIUDADES CD WITH(NOLOCK)
INNER JOIN PAR.REGIONALES_PAIS RG WITH(NOLOCK)
ON CD.ID_REGIONAL=RG.ID_REGIONAL
WHERE CD.ID_CIUDAD NOT IN(SELECT ID_CIUDAD_ANEXA FROM #TMP_CIUDADES_ANEXAS_CPL WITH(NOLOCK) GROUP BY ID_CIUDAD_ANEXA)
AND CD.ID_PAIS=1
AND RG.ID_PAIS=1

DROP TABLE IF EXISTS #TMP_CIUDADES_ANEXAS;
DROP TABLE IF EXISTS #TMP_CIUDADES_ANEXAS_CPL;

