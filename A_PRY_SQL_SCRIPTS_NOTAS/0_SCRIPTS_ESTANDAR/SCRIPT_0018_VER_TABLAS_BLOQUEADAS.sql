-- 2. Variables de control
DECLARE @LOTE INT = 5000;
DECLARE @FILAS INT = 1;

-- 3. Bucle de actualización por lotes
WHILE @FILAS > 0
BEGIN
    -- Ejecutar el UPDATE acotado al lote actual
    UPDATE FAC
    SET
         FAC.UBIC_ID_PROCESO                = TMP.UBIC_ID_PROCESO
        ,FAC.UBIC_NOMBRE_PROCESO_LOG        = TMP.UBIC_NOMBRE_PROCESO_LOG
        ,FAC.UBIC_FECHA_HORA_MOVIMI         = TMP.UBIC_FECHA_HORA_MOVIMI
        ,FAC.UBIC_ID_DIV_BODEGA_UBICACION   = TMP.UBIC_ID_DIV_BODEGA_UBICACION
        ,FAC.UBIC_BODEGA_UBICACION          = TMP.UBIC_BODEGA_UBICACION
        ,FAC.UBIC_ID_CIUDAD_UBICACION       = TMP.UBIC_ID_CIUDAD_UBICACION
        ,FAC.UBIC_CIUDAD_UBICACION          = TMP.UBIC_CIUDAD_UBICACION
        ,FAC.UBIC_ID_REGIONAL_UBICACION     = TMP.UBIC_ID_REGIONAL_UBICACION
        ,FAC.UBIC_NOMBRE_REGIONAL_UBICACION = TMP.UBIC_NOMBRE_REGIONAL_UBICACION
        ,FAC.ULT_ID_ZONA_URBA               = TMP.DOC_ID_ZONA_URBA
        ,FAC.ULT_ID_CIUDAD_ZONA_URBA        = TMP.DOC_ID_CIUDAD_ZONA_URBA
        ,FAC.ULT_ID_TIPO_ZONA_URBA          = TMP.DOC_ID_TIPO_ZONA_URBA
        ,FAC.ULT_SEG_NUMERO_PIEZAS          = TMP.ULT_SEG_NUMERO_PIEZAS
    FROM [SIG_CCM_DM].[FAC].[DIGGUICCM_DIGITALIZACION_FINAL_ULTIMO_PROCESO_LOG] FAC WITH (ROWLOCK)
    INNER JOIN (
        SELECT TOP (@LOTE) NUMERO_GUIA 
        FROM #GUIAS_PENDIENTES
    ) GP ON GP.NUMERO_GUIA = FAC.NUMERO_GUIA
    INNER JOIN #TABLA_TEMPORAL_COMPLEMENTAR_ULT_PROCESO_NULL TMP 
       ON TMP.NUMERO_GUIA = FAC.NUMERO_GUIA;

    -- Eliminar del buffer exactamente el número de guías procesadas
    DELETE TOP (@LOTE) FROM #GUIAS_PENDIENTES;

    -- Actualizar el contador con las filas eliminadas de la cola
    SET @FILAS = @@ROWCOUNT;

    RAISERROR('Lote procesado exitosamente...', 0, 1) WITH NOWAIT;
END;

DROP TABLE IF EXISTS #GUIAS_PENDIENTES;
DROP TABLE IF EXISTS #TABLA_TEMPORAL_COMPLEMENTAR_ULT_PROCESO_NULL;


