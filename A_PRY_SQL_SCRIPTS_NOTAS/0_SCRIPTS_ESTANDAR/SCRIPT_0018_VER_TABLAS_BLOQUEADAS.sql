-- ════════════════════════════════════════════════════════════════════
-- PASO 4: UPDATE por lotes optimizado (Sin re-crear tablas temporales)
-- ════════════════════════════════════════════════════════════════════
DROP TABLE IF EXISTS #GUIAS_PENDIENTES;
SELECT TOP 0
FAC.NUMERO_GUIA
,dell = 0 
INTO #GUIAS_PENDIENTES
FROM [SIG_CCM_DM].[FAC].[DIGGUICCM_DIGITALIZACION_FINAL_ULTIMO_PROCESO_LOG] FAC WITH (NOLOCK)
INNER JOIN #TABLA_TEMPORAL_COMPLEMENTAR_ULT_PROCESO_NULL TMP WITH (NOLOCK)
   ON TMP.NUMERO_GUIA = FAC.NUMERO_GUIA
WHERE FAC.UBIC_FECHA_HORA_MOVIMI IS NULL
   OR ISNULL(FAC.UBIC_FECHA_HORA_MOVIMI, '1900-01-01') <> ISNULL(TMP.UBIC_FECHA_HORA_MOVIMI, '1900-01-01');
CREATE CLUSTERED INDEX CIX_GP ON #GUIAS_PENDIENTES (NUMERO_GUIA);

-- Filtra solo las guías de la tabla final que necesitan actualización
INSERT INTO #GUIAS_PENDIENTES
SELECT 
FAC.NUMERO_GUIA
,UBIC_FECHA_HORA_MOVIMI = CASE 
        WHEN TMP.UBIC_FECHA_HORA_MOVIMI>ISNULL(FAC.UBIC_FECHA_HORA_MOVIMI, '1900-01-01') THEN 0
        WHEN TMP.UBIC_FECHA_HORA_MOVIMI = ISNULL(FAC.UBIC_FECHA_HORA_MOVIMI, '1900-01-01') THEN 1
        ELSE 2 END
FROM [SIG_CCM_DM].[FAC].[DIGGUICCM_DIGITALIZACION_FINAL_ULTIMO_PROCESO_LOG] FAC WITH (NOLOCK)
INNER JOIN #TABLA_TEMPORAL_COMPLEMENTAR_ULT_PROCESO_NULL TMP WITH (NOLOCK)
   ON TMP.NUMERO_GUIA = FAC.NUMERO_GUIA
OPTION(RECOMPILE);

DELETE #GUIAS_PENDIENTES where dell>=1

