SET NOCOUNT ON;
SET XACT_ABORT ON;

-- ════════════════════════════════════════════════════════════════════
-- PASO 1: Snapshot de parámetros
-- ════════════════════════════════════════════════════════════════════
DROP TABLE IF EXISTS #PAR_PROCESOS;
SELECT ID_PROCESO, NOMBRE_PROCESO_LOG
INTO #PAR_PROCESOS 
FROM SIG_COLOMBIA_DW.PAR.PROCESOS WITH (NOLOCK);
CREATE CLUSTERED INDEX CIX_PR ON #PAR_PROCESOS (ID_PROCESO);

DROP TABLE IF EXISTS #PAR_CIUDADES;
SELECT ID_CIUDAD, NOMBRE_CIUDAD, ID_REGIONAL
INTO #PAR_CIUDADES 
FROM SIG_COLOMBIA_DW.PAR.CIUDADES WITH (NOLOCK);
CREATE CLUSTERED INDEX CIX_CI ON #PAR_CIUDADES (ID_CIUDAD);

DROP TABLE IF EXISTS #PAR_REGIONALES;
SELECT ID_REGIONAL, NOMBRE_REGIONAL
INTO #PAR_REGIONALES 
FROM SIG_COLOMBIA_DW.PAR.REGIONALES_PAIS WITH (NOLOCK);
CREATE CLUSTERED INDEX CIX_RE ON #PAR_REGIONALES (ID_REGIONAL);

DROP TABLE IF EXISTS #PAR_DIVISIONES;
SELECT ID_DIVISION, ID_CIUDAD, NOMBRE_DIVISION
INTO #PAR_DIVISIONES 
FROM SIG_COLOMBIA_DW.PAR.DIVISIONES WITH (NOLOCK);
CREATE CLUSTERED INDEX CIX_DI ON #PAR_DIVISIONES (ID_DIVISION, ID_CIUDAD);

-- ════════════════════════════════════════════════════════════════════
-- PASO 2: Pre-materializar DOCUMENTOS filtrado
-- ════════════════════════════════════════════════════════════════════
DROP TABLE IF EXISTS #DOC;
SELECT distinct
     D.ID_PROCESO
    ,D.NUMERO_MOVIMI
    ,D.CONSECUT_MOVIMI
    ,D.ID_DIVISION_ORIGEN
    ,D.ID_DIVISION_DESTINO
    ,D.ID_CIUDAD_DIVISION_ORIGEN
    ,D.ID_CIUDAD_DESTINO
    ,D.ID_ZONA_URBA
    ,D.ID_CIUDAD_ZONA_URBA
    ,D.ID_TIPO_ZONA_URBA
INTO #DOC
FROM SIG_CCM_DM.[TMP].[DIGGUICCM_ULTIMO_PROCESO_LOG] U WITH (NOLOCK)
INNER JOIN SIG_CCM_DM.[TMP].[DIGGUICCM_ULTIMO_DOCUMENTO_MANIFIESTO] D WITH (NOLOCK)
   ON  D.ID_PROCESO      = U.ID_PROCESO
  AND  D.NUMERO_MOVIMI   = U.NUMERO_MOVIMI COLLATE SQL_Latin1_General_CP850_CI_AI
  AND  D.CONSECUT_MOVIMI = U.CONSECUT_MOVIMI;

CREATE CLUSTERED INDEX CIX_DOC ON #DOC (ID_PROCESO, NUMERO_MOVIMI, CONSECUT_MOVIMI);

-- ════════════════════════════════════════════════════════════════════
-- PASO 3: Enriquecer
-- ════════════════════════════════════════════════════════════════════
DROP TABLE IF EXISTS #TABLA_TEMPORAL_COMPLEMENTAR_ULT_PROCESO_NULL;
SELECT TOP 0
     U.NUMERO_GUIA
    ,UBIC_ID_PROCESO               = U.ID_PROCESO
    ,UBIC_NOMBRE_PROCESO_LOG       = PR.NOMBRE_PROCESO_LOG
    ,UBIC_FECHA_HORA_MOVIMI        = U.FECHA_HORA_MOVIMIENTO
    ,UBIC_ID_DIV_BODEGA_UBICACION  = CASE
        WHEN U.ID_PROCESO IN (7,12,9)                      THEN DOC.ID_DIVISION_ORIGEN
        WHEN U.ID_PROCESO IN (5,6,8,10,14,15,17,19,20,21) THEN DOC.ID_DIVISION_DESTINO
        ELSE DOC.ID_DIVISION_DESTINO END
    ,UBIC_BODEGA_UBICACION         = CASE
        WHEN U.ID_PROCESO IN (7,12,9)                      THEN DIV_ORIG.NOMBRE_DIVISION
        WHEN U.ID_PROCESO IN (5,6,8,10,14,15,17,19,20,21) THEN DIV_DEST.NOMBRE_DIVISION
        ELSE DIV_DEST.NOMBRE_DIVISION END
    ,UBIC_ID_CIUDAD_UBICACION      = CASE
        WHEN U.ID_PROCESO IN (7,12,9)                      THEN DOC.ID_CIUDAD_DIVISION_ORIGEN
        WHEN U.ID_PROCESO IN (5,6,8,10,14,15,17,19,20,21) THEN DOC.ID_CIUDAD_DESTINO
        ELSE DOC.ID_CIUDAD_DESTINO END
    ,UBIC_CIUDAD_UBICACION         = CASE
        WHEN U.ID_PROCESO IN (7,12,9)                      THEN CIUD_ORIG.NOMBRE_CIUDAD
        WHEN U.ID_PROCESO IN (5,6,8,10,14,15,17,19,20,21) THEN CIUD_DEST.NOMBRE_CIUDAD
        ELSE CIUD_DEST.NOMBRE_CIUDAD END
    ,UBIC_ID_REGIONAL_UBICACION    = CASE
        WHEN U.ID_PROCESO IN (7,12,9)                      THEN CIUD_ORIG.ID_REGIONAL
        WHEN U.ID_PROCESO IN (5,6,8,10,14,15,17,19,20,21) THEN CIUD_DEST.ID_REGIONAL
        ELSE CIUD_DEST.ID_REGIONAL END
    ,UBIC_NOMBRE_REGIONAL_UBICACION = CASE
        WHEN U.ID_PROCESO IN (7,12,9)                      THEN REGIO_ORIG.NOMBRE_REGIONAL
        WHEN U.ID_PROCESO IN (5,6,8,10,14,15,17,19,20,21) THEN REGIO_DESTI.NOMBRE_REGIONAL
        ELSE REGIO_DESTI.NOMBRE_REGIONAL END
    ,ULT_SEG_NUMERO_PIEZAS         = U.GUI_NUMERO_PIEZAS
    ,DOC_ID_ZONA_URBA              = DOC.ID_ZONA_URBA
    ,DOC_ID_CIUDAD_ZONA_URBA       = DOC.ID_CIUDAD_ZONA_URBA
    ,DOC_ID_TIPO_ZONA_URBA         = DOC.ID_TIPO_ZONA_URBA
INTO #TABLA_TEMPORAL_COMPLEMENTAR_ULT_PROCESO_NULL
FROM SIG_CCM_DM.[TMP].[DIGGUICCM_ULTIMO_PROCESO_LOG] U WITH (NOLOCK)
LEFT JOIN #DOC DOC ON DOC.ID_PROCESO = U.ID_PROCESO AND DOC.NUMERO_MOVIMI = U.NUMERO_MOVIMI AND DOC.CONSECUT_MOVIMI = U.CONSECUT_MOVIMI
LEFT JOIN #PAR_PROCESOS PR ON PR.ID_PROCESO = U.ID_PROCESO
LEFT JOIN #PAR_CIUDADES CIUD_DEST ON CIUD_DEST.ID_CIUDAD = DOC.ID_CIUDAD_DESTINO
LEFT JOIN #PAR_REGIONALES REGIO_DESTI ON REGIO_DESTI.ID_REGIONAL = CIUD_DEST.ID_REGIONAL
LEFT JOIN #PAR_DIVISIONES DIV_DEST ON DIV_DEST.ID_DIVISION = DOC.ID_DIVISION_DESTINO AND DIV_DEST.ID_CIUDAD = DOC.ID_CIUDAD_DESTINO
LEFT JOIN #PAR_CIUDADES CIUD_ORIG ON CIUD_ORIG.ID_CIUDAD = DOC.ID_CIUDAD_DIVISION_ORIGEN
LEFT JOIN #PAR_REGIONALES REGIO_ORIG ON REGIO_ORIG.ID_REGIONAL = CIUD_ORIG.ID_REGIONAL
LEFT JOIN #PAR_DIVISIONES DIV_ORIG ON DIV_ORIG.ID_DIVISION = DOC.ID_DIVISION_ORIGEN AND DIV_ORIG.ID_CIUDAD = DOC.ID_CIUDAD_DIVISION_ORIGEN;

CREATE CLUSTERED INDEX CIX_TMP ON #TABLA_TEMPORAL_COMPLEMENTAR_ULT_PROCESO_NULL (NUMERO_GUIA);
INSERT INTO #TABLA_TEMPORAL_COMPLEMENTAR_ULT_PROCESO_NULL
SELECT 
     U.NUMERO_GUIA
    ,UBIC_ID_PROCESO                = U.ID_PROCESO
    ,UBIC_NOMBRE_PROCESO_LOG        = PR.NOMBRE_PROCESO_LOG
    ,UBIC_FECHA_HORA_MOVIMI         = U.FECHA_HORA_MOVIMIENTO
    ,UBIC_ID_DIV_BODEGA_UBICACION    = MAP.ID_DIVISION
    ,UBIC_BODEGA_UBICACION          = DIV.NOMBRE_DIVISION
    ,UBIC_ID_CIUDAD_UBICACION       = MAP.ID_CIUDAD
    ,UBIC_CIUDAD_UBICACION          = CIUD.NOMBRE_CIUDAD
    ,UBIC_ID_REGIONAL_UBICACION     = CIUD.ID_REGIONAL
    ,UBIC_NOMBRE_REGIONAL_UBICACION  = REGIO.NOMBRE_REGIONAL
    ,ULT_SEG_NUMERO_PIEZAS          = U.GUI_NUMERO_PIEZAS
    ,DOC_ID_ZONA_URBA               = DOC.ID_ZONA_URBA
    ,DOC_ID_CIUDAD_ZONA_URBA        = DOC.ID_CIUDAD_ZONA_URBA
    ,DOC_ID_TIPO_ZONA_URBA          = DOC.ID_TIPO_ZONA_URBA
FROM SIG_CCM_DM.[TMP].[DIGGUICCM_ULTIMO_PROCESO_LOG] U WITH (NOLOCK)
LEFT JOIN #DOC DOC 
    ON  DOC.ID_PROCESO      = U.ID_PROCESO 
    AND DOC.NUMERO_MOVIMI   = U.NUMERO_MOVIMI 
    AND DOC.CONSECUT_MOVIMI = U.CONSECUT_MOVIMI

-- 1. Evaluamos la lógica Origen/Destino UNA sola vez por fila en lugar de repetir CASEs
CROSS APPLY (
    SELECT 
        ID_DIVISION = CASE WHEN U.ID_PROCESO IN (7,12,9) THEN DOC.ID_DIVISION_ORIGEN ELSE DOC.ID_DIVISION_DESTINO END,
        ID_CIUDAD   = CASE WHEN U.ID_PROCESO IN (7,12,9) THEN DOC.ID_CIUDAD_DIVISION_ORIGEN ELSE DOC.ID_CIUDAD_DESTINO END
) MAP
-- 2. JOINs unificados (se reducen de 8 a solo 4 JOINs)
LEFT JOIN #PAR_PROCESOS PR    ON PR.ID_PROCESO  = U.ID_PROCESO
LEFT JOIN #PAR_CIUDADES CIUD   ON CIUD.ID_CIUDAD = MAP.ID_CIUDAD
LEFT JOIN #PAR_REGIONALES REGIO ON REGIO.ID_REGIONAL = CIUD.ID_REGIONAL
LEFT JOIN #PAR_DIVISIONES DIV  ON DIV.ID_DIVISION = MAP.ID_DIVISION 
                              AND DIV.ID_CIUDAD   = MAP.ID_CIUDAD
                              OPTION(RECOMPILE);



