WHILE @COUNT_SET<=@COUNTER_ALL
 BEGIN 
	SET @COUNT_SET = @COUNT_SET + 1

		SET @USUARIOS_BCCLINE = (SELECT EMAIL FROM PAR.ENVIO_CORREO_REPORTES_VARIOS WHERE ESTADO_FAC_PDTE_TEMU = 1 AND TIPO_ENVIO_FAC_PDTE_TEMU = 'BCCLINE' AND PK=@COUNT_SET);
		IF LEN(@USUARIOS_BCCLINE)>1   
				SET @USUARIOS_FINAL_BCCLINE = CONCAT(@USUARIOS_BCCLINE,';',@USUARIOS_FINAL_BCCLINE)

		SET @USUARIOS_CCLINE = (SELECT EMAIL FROM PAR.ENVIO_CORREO_REPORTES_VARIOS WHERE ESTADO_FAC_PDTE_TEMU = 1 AND TIPO_ENVIO_FAC_PDTE_TEMU = 'CCLINE' AND PK=@COUNT_SET);
		IF LEN(@USUARIOS_CCLINE)>1   
				SET @USUARIOS_FINAL_CCLINE = CONCAT(@USUARIOS_CCLINE,';',@USUARIOS_FINAL_CCLINE)
 
		SET @USUARIOS_TOLINE = (SELECT EMAIL FROM PAR.ENVIO_CORREO_REPORTES_VARIOS WHERE ESTADO_FAC_PDTE_TEMU = 1 AND TIPO_ENVIO_FAC_PDTE_TEMU = 'TOLINE' AND PK=@COUNT_SET);
		IF LEN(@USUARIOS_TOLINE)>1   
				SET @USUARIOS_FINAL_TOLINE = CONCAT(@USUARIOS_TOLINE,';',@USUARIOS_FINAL_TOLINE)
 
 
 END

SELECT 
 CONVERT(VARCHAR(MAX),@USUARIOS_FINAL_BCCLINE) AS USUARIOS_BCCLINE
,CONVERT(VARCHAR(MAX),@USUARIOS_FINAL_CCLINE) AS USUARIOS_CCLINE
,CONVERT(VARCHAR(MAX),@USUARIOS_FINAL_TOLINE) AS USUARIOS_TOLINE




 
