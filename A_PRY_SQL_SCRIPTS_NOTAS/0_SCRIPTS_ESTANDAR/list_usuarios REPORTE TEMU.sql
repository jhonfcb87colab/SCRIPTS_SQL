DECLARE @COUNTER_ALL INT = (SELECT MAX(PK) FROM PAR.ENVIO_CORREO_REPORTES_VARIOS);
DECLARE @COUNT_SET INT = 0;
DECLARE @USUARIOS_BCCLINE VARCHAR(MAX);
DECLARE @USUARIOS_FINAL_BCCLINE VARCHAR(MAX);

DECLARE @USUARIOS_CCLINE VARCHAR(MAX);
DECLARE @USUARIOS_FINAL_CCLINE VARCHAR(MAX);

DECLARE @USUARIOS_TOLINE VARCHAR(MAX);
DECLARE @USUARIOS_FINAL_TOLINE VARCHAR(MAX);

