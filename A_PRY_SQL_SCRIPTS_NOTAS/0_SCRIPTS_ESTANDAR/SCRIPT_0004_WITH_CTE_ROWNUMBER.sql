( 
id 
,fecha_cargue 
,[Computer_name] 
) 
as 
( 
SELECT  
ROW_NUMBER ( )   OVER ( PARTITION BY [Computer_name] order by fecha_cargue desc )  ROWid  
,fecha_cargue 
,[Computer_name] 
  FROM [LICENCIAMIENTO_FLEXERA].[dbo].[TbServientrega_Hardware] 
where Computer_name = 'serv-pisap' 
) 
select  * from cte  where ROWid = 1  

 

   ------TABLA TEMPORAL CON CTE    

 

WITH CTE 
AS 
( 
SELECT T.[YEAR],T.[MONTH_OF_YEAR], 
CONVERT(VARCHAR(4),T.[YEAR]) + ' ' + CONVERT(VARCHAR(20),CASE T.[MONTH_OF_YEAR] 
WHEN 1 THEN '01 Enero' 
WHEN 2 THEN '02 Febrero' 
WHEN 3 THEN '03 Marzo' 
WHEN 4 THEN '04 Abril' 
WHEN 5 THEN '05 Mayo' 
WHEN 6 THEN '06 Junio' 
WHEN 7 THEN '07 Julio' 
WHEN 8 THEN '08 Agosto' 
WHEN 9 THEN '09 Septiembre' 
WHEN 10 THEN '10 Octubre' 
WHEN 11 THEN '11 Noviembre' 
ELSE '12 Diciembre' 
END) ANIO_MES 
,SUM(RE.D_VALOR_VENTA) VALOR_VENTA_ACT 
,0 VALOR_VENTA_ANT 
FROM 
[FAC].[RETAIL_ENVIOS] RE WITH(NOLOCK) 
INNER JOIN 
DIM.TIEMPO T WITH(NOLOCK) 
ON 
RE.[V_TIME_ID_VENTA] = T.TIME_ID 
WHERE 
RE.[V_TIME_ID_VENTA] >= CONVERT(INT,(DATEADD(yy, DATEDIFF(yy, 0, DATEADD(YEAR, -1,GETDATE())), 0))) 
AND 
RE.S_ID_CLIENTE_REMITE = @ID_CLIENTE 
GROUP BY 
T.[YEAR] 
,T.MONTH_OF_YEAR 
UNION 
SELECT T.[YEAR],T.[MONTH_OF_YEAR], 
CONVERT(VARCHAR(4),T.[YEAR]) + ' ' + CONVERT(VARCHAR(20),CASE T.[MONTH_OF_YEAR] 
WHEN 1 THEN '01 Enero' 
WHEN 2 THEN '02 Febrero' 
WHEN 3 THEN '03 Marzo' 
WHEN 4 THEN '04 Abril' 
WHEN 5 THEN '05 Mayo' 
WHEN 6 THEN '06 Junio' 
WHEN 7 THEN '07 Julio' 
WHEN 8 THEN '08 Agosto' 
WHEN 9 THEN '09 Septiembre'
WHEN 10 THEN '10 Octubre' 
WHEN 11 THEN '11 Noviembre' 
ELSE '12 Diciembre' 
END) ANIO_MES 
,0 VALOR_VENTA_ACT 
,SUM(RE.D_VALOR_VENTA) VALOR_VENTA_ANT 
FROM 
[FAC].[RETAIL_ENVIOS] RE WITH(NOLOCK) 
INNER JOIN 
DIM.TIEMPO T WITH(NOLOCK) 
ON 
CONVERT(INT,DATEADD(MONTH,1,CONVERT(DATETIME,CONVERT(VARCHAR,YEAR(CONVERT(DATETIME,RE.[V_TIME_ID_VENTA]))) + '-' + CONVERT(VARCHAR,MONTH(CONVERT(DATETIME,RE.[V_TIME_ID_VENTA]))) + '-01'))) = T.TIME_ID 
WHERE 
RE.[V_TIME_ID_VENTA] >= CONVERT(INT,DATEADD(month,11,(DATEADD(yy, DATEDIFF(yy, 0, DATEADD(YEAR, -2,GETDATE())), 0)))) 
AND 
RE.S_ID_CLIENTE_REMITE = @ID_CLIENTE 
GROUP BY 
T.[YEAR] 
,T.MONTH_OF_YEAR 
) 
SELECT 
[YEAR] 
,[MONTH_OF_YEAR] 
,ANIO_MES 
,RIGHT(LEFT(ANIO_MES,11),3) AS MES_NAME 
,SUM(VALOR_VENTA_ACT) VALOR_VENTA_ACT 
,SUM(VALOR_VENTA_ANT) VALOR_VENTA_ANT 
, CASE 
WHEN SUM(VALOR_VENTA_ANT)=0 THEN 1 
ELSE ((SUM(VALOR_VENTA_ACT)-SUM(VALOR_VENTA_ANT))/SUM(VALOR_VENTA_ANT)) END AS VARIACION 
FROM 
CTE 
WHERE 
cast([YEAR] as int) = @ANIO_CONSULTA 
AND 
[MONTH_OF_YEAR]<=MONTH(GETDATE()) 
GROUP BY 
[YEAR] 
,[MONTH_OF_YEAR] 
,ANIO_MES 
ORDER BY 
1,2  

 

 