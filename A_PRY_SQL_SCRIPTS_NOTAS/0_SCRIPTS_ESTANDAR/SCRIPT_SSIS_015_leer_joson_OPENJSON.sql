DROP TABLE IF EXISTS #TABLAMETRICASUSERLOG;
DROP TABLE IF EXISTS [TMP_BORRAR].dbo.TABLATEMPORAL_METRICASUSER_LOG;
DECLARE @FECHA_INI DATETIME  = DATEADD(mm,DATEDIFF(mm,0,DATEADD(MONTH,-3,GETDATE())),0)
SELECT 
      NUMBER = ROW_NUMBER() OVER(PARTITION BY RecordType ORDER BY CONTROLDATE ASC)
	  ,[AuditData]
	  INTO #TABLAMETRICASUSERLOG
  FROM [SIG_MEVI_DM].[FAC].[REPORTE_USO_LOG] (nolock)
  WHERE CONVERT(DATETIME,CONTROLDATE) >= @FECHA_INI 

DECLARE	@return_value int
CREATE TABLE [TMP_BORRAR].dbo.TABLATEMPORAL_METRICASUSER_LOG(
WorkSpaceName VARCHAR(500)
,ItemName VARCHAR(500)
,UserId VARCHAR(500)
,CreationTime  VARCHAR(500)
)
DECLARE @MIN_ID INT = (SELECT MIN(NUMBER) FROM #TABLAMETRICASUSERLOG)
DECLARE @MAX_ID INT = (SELECT MAX(NUMBER) FROM #TABLAMETRICASUSERLOG)

WHILE @MIN_ID<=@MAX_ID
BEGIN 
	DECLARE @JSON_CONSULTA VARCHAR(MAX) = (SELECT [AuditData] FROM #TABLAMETRICASUSERLOG (nolock) WHERE NUMBER=@MIN_ID)
	INSERT INTO [TMP_BORRAR].dbo.TABLATEMPORAL_METRICASUSER_LOG
	EXEC @return_value = [FAC].[CONSUMIR_JSON_METRICAS_USO] 
		 @json_ENTER = @JSON_CONSULTA
	print(@MIN_ID);
