	,MOMENTO_DEL_DIA
	,HORA_DEL_DIA
	,OPERACION
	,DIA_DEL_MES
	,DIA_DEL_ANIO
	,DIA_DE_LA_SEMANA
	,DIA_NOMBRE
	,SEMANA
	,MES
	,MES_NOMBRE
	,TRIMESTRE
	,CUATRIMESTRE
	,ANIO
	,FIN_DE_SEMANA
	,SEMANA_DEL_MES
	,FESTIVO
FROM CTE_CALENDARIO


