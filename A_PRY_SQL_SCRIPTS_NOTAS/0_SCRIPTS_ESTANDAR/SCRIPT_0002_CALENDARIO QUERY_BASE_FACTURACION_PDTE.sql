;WITH CTE_CALENDARIO AS(
SELECT 
 ID_TIEMPO	
,FECHA_HORA
,FECHA_CADENA = NULL
,MOMENTO_DEL_DIA = CONVERT(VARCHAR(8), FECHA_HORA, 108)
,HORA_DEL_DIA = DATEPART(HOUR,FECHA_HORA)
,OPERACION = IIF(DATEPART(HOUR,FECHA_HORA)>12,'PM','AM')
,DIA_DEL_MES = DAY(FECHA_HORA)
,DIA_DEL_ANIO = DATEPART(DAYOFYEAR, FECHA_HORA)
,DIA_DE_LA_SEMANA = DATEPART(dw,FECHA_HORA )
,DIA_NOMBRE = CASE
					WHEN DATEPART(dw,FECHA_HORA )=1 THEN 'DOMINGO'
					WHEN DATEPART(dw,FECHA_HORA )=2 THEN 'LUNES'
					WHEN DATEPART(dw,FECHA_HORA )=3 THEN 'MARTES'
					WHEN DATEPART(dw,FECHA_HORA )=4 THEN 'MIERCOLES'
					WHEN DATEPART(dw,FECHA_HORA )=5 THEN 'JUEVES'
					WHEN DATEPART(dw,FECHA_HORA )=6 THEN 'VIERNES'
					WHEN DATEPART(dw,FECHA_HORA )=7 THEN 'SABADO'
					ELSE NULL 
				END
,SEMANA =  DATEPART(WEEK, FECHA_HORA)
,MES = MONTH(FECHA_HORA)
,MES_NOMBRE = CASE 
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=1 THEN 'ENERO'
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=2 THEN 'FEBRERO'
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=3 THEN 'MARZO'
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=4 THEN 'ABRIL'
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=5 THEN 'MAYO'
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=6 THEN 'JUNIO'
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=7 THEN 'JULIO'
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=8 THEN 'AGOSTO'
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=9 THEN 'SEPTIEMBRE'
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=10 THEN 'OCTUBRE'
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=11 THEN 'NOVIEMBRE'
					WHEN MONTH(CONVERT(DATETIME,FECHA_HORA))=12 THEN 'DICIEMBRE'
					ELSE NULL
				END
,TRIMESTRE = DATEPART(QUARTER, FECHA_HORA)
,CUATRIMESTRE =     CASE
						WHEN MONTH(FECHA_HORA) BETWEEN 1 AND 4 THEN 1
						WHEN MONTH(FECHA_HORA) BETWEEN 5 AND 8 THEN 2
						WHEN MONTH(FECHA_HORA) BETWEEN 9 AND 12 THEN 3
					END
,ANIO = YEAR(FECHA_HORA)
,FIN_DE_SEMANA = CASE WHEN  DATEPART(dw,FECHA_HORA ) IN (1,7) THEN 1 ELSE 0 END
,SEMANA_DEL_MES = DATEDIFF(WEEK, DATEADD(MONTH, DATEDIFF(MONTH, 0, FECHA_HORA), 0), FECHA_HORA) + 1
,FESTIVO = 0
FROM #LOCAL_TABLEVARIABLE_CALENDARIO_DIM_FACTURACION_SIG_COLOMBIA_20221115_1129
)
