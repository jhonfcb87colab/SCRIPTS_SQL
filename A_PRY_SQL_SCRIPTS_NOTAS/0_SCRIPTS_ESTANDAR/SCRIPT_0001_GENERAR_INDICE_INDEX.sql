    ALLOW_PAGE_LOCKS = ON, 
    FILLFACTOR = 100,              -- Usar 100 reduce la escritura inicial de páginas de disco
    MAXDOP = 8                     -- Grado de paralelismo (ajustar según cores libres en el servidor)
) 
