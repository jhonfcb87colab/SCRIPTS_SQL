-- 3. Bucle de inserción por Lotes basado en ID numérico (Evita borrar/volver a hacer JOINs)
DECLARE @LOTE INT = 1000; -- Incrementado a 50k para mejor rendimiento E/S
DECLARE @MIN_ID INT = 1;
DECLARE @MAX_ID_LOTE INT;
DECLARE @MAX_ID_TOTAL INT = (SELECT ISNULL(MAX(ID), 0) FROM #GUIAS_PROCESOS_LIQUIDACION_PAGO_PRODUCTIVIDAD_TERCEROS_PS01);

WHILE @MIN_ID <= @MAX_ID_TOTAL
BEGIN
    SET @MAX_ID_LOTE = @MIN_ID + @LOTE - 1;


    INSERT INTO [tmp_borrar_local].[dbo].[xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx]
    (
        NUMERO_GUIA,
        ID_PROCESO,
        CONSECUT_MOVIMI,
        NUMERO_MOVIMI,
		FECHA_HORA_MOVIMIENTO
    )
    SELECT 
        PS01.NUMERO_GUIA,
        SE.ID_PROCESO,
        SE.CONSECUT_MOVIMI,
        SE.NUMERO_MOVIMI,
		SE.FECHA_HORA_MOVIMIENTO
    FROM #yyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyy PS01 WITH (NOLOCK)
    INNER JOIN Mece_Logistico.DBO.SEGUIMIENTO_ENVIO SE WITH (NOLOCK)
        ON PS01.NUMERO_GUIA = SE.NUMERO_GUIA
        AND PS01.ID_PROCESO = SE.ID_PROCESO
        ---AND SE.FECHA_HORA_MOVIMIENTO=CONVERT(DATE,PS01.FECHA_HORA_MOVIMIENTO)
		AND SE.FECHA_HORA_MOVIMIENTO >= CAST(PS01.FECHA_HORA_MOVIMIENTO AS DATETIME)
        AND SE.FECHA_HORA_MOVIMIENTO < DATEADD(DAY, 1, CAST(PS01.FECHA_HORA_MOVIMIENTO AS DATETIME))
    WHERE PS01.ID BETWEEN @MIN_ID AND @MAX_ID_LOTE
	----WHERE PS01.ID BETWEEN 1 AND 1000
	OPTION(RECOMPILE);

	PRINT(CONCAT('INSERTCION REALIZADA DESDE - ',@MIN_ID,' / HASTA - ',@MAX_ID_LOTE))

    SET @MIN_ID = @MAX_ID_LOTE + 1;
END;