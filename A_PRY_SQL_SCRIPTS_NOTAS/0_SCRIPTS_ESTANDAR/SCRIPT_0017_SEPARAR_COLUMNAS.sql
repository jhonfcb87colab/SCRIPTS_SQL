
SELECT TOP 1000
	NOMBRE_CLIENTE_CDS
	,LTRIM(RTRIM(SUBSTRING([NOMBRE_CLIENTE_CDS]
	,1,CHARINDEX('-', [NOMBRE_CLIENTE_CDS])-1))) AS [CODIGO_CLIENTE_CDS]
	--,LTRIM(RTRIM(SUBSTRING([NOMBRE_CLIENTE_CDS],CHARINDEX('-', [NOMBRE_CLIENTE_CDS])+1,len([NOMBRE_CLIENTE_CDS])))) AS [NOMBRE_CLIENTE_CDS]
FROM [SIG_COLOMBIA_DW].[TMP].[COSTO_DARWIN_BASE_OPERACION_MES] (NOLOCK)

SELECT 
CODDIGO_CLIENTE = IIF([NOMBRE_CLIENTE_CDS] LIKE	'%-%', SUBSTRING([NOMBRE_CLIENTE_CDS],1,CHARINDEX('-', [NOMBRE_CLIENTE_CDS])-1), '000000') 
,NOMBRE_CLIENTE_CDS = IIF([NOMBRE_CLIENTE_CDS] LIKE	'%-%', SUBSTRING([NOMBRE_CLIENTE_CDS],CHARINDEX('-', [NOMBRE_CLIENTE_CDS])+1,LEN([NOMBRE_CLIENTE_CDS])), [NOMBRE_CLIENTE_CDS]) 
FROM [SIG_COLOMBIA_DW].[TMP].[COSTO_DARWIN_BASE_OPERACION_MES] (NOLOCK)
WHERE [NOMBRE_CLIENTE_CDS] NOT LIKE '%-%'



USE SIG_LOGISTICA_DM;

SELECT DISTINCT
CODDIGO_CLIENTE = CASE WHEN ISNUMERIC(IIF([NOMBRE_CLIENTE_CDS] LIKE	'%-%', SUBSTRING([NOMBRE_CLIENTE_CDS],1,CHARINDEX('-', [NOMBRE_CLIENTE_CDS])-1), '000000'))=1  THEN   IIF([NOMBRE_CLIENTE_CDS] LIKE	'%-%', SUBSTRING([NOMBRE_CLIENTE_CDS],1,CHARINDEX('-', [NOMBRE_CLIENTE_CDS])-1), '000000')
							ELSE '00' END
,NOMBRE_CLIENTE_CDS = CASE WHEN ISNUMERIC(IIF([NOMBRE_CLIENTE_CDS] LIKE	'%-%', SUBSTRING([NOMBRE_CLIENTE_CDS],1,CHARINDEX('-', [NOMBRE_CLIENTE_CDS])-1), '000000'))=1  THEN   IIF([NOMBRE_CLIENTE_CDS] LIKE	'%-%', SUBSTRING([NOMBRE_CLIENTE_CDS],CHARINDEX('-', [NOMBRE_CLIENTE_CDS])+1,LEN([NOMBRE_CLIENTE_CDS])), [NOMBRE_CLIENTE_CDS]) 
							ELSE [NOMBRE_CLIENTE_CDS] END
  FROM [SIG_LOGISTICA_DM].[FAC].[COSTO_DARWIN_BASE_OPERACION_MES_BASE_PLANA_COSTO_CROSS_POR_CLIENTE] (NOLOCK)
WHERE [PERIODO_EJECUCION] IN (SELECT PERIODO FROM [FAC].[COSTO_DARWIN_PERIODOS_DASBOARD] WITH(NOLOCK) GROUP BY PERIODO) 
AND DANE_ORIGEN_DESTINO <> '0'
AND PERIODO_EJECUCION=202508
