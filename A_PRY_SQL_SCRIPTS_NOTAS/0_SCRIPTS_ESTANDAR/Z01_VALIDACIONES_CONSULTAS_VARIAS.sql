SELECT SE.ID_PROCESO,
PR.NOMBRE_PROCESO_LOG,
SE.NUMERO_GUIA,
SE.ID_CONCEPTO,
SE.FECHA_HORA_MOVIMIENTO, 
PRCP.NOMBRE_CONCEPTO,
DOC.ID_DIVISION_DESTINO,
DOC.ID_CIUDAD_DESTINO,
DOC.ID_DIVISION_ORIGEN,
DOC.ID_CIUDAD_DIVISION_ORIGEN,
DOC.ID_CIUDAD_CANAL,
ID_CIUDAD_ZONA_URBA
FROM Mece_Logistico..SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
inner join Mece_Logistico..DOCUMENTOS DOC WITH(NOLOCK) ON (SE.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND SE.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI AND SE.ID_PROCESO=DOC.ID_PROCESO)
LEFT JOIN PARAMETROS..ITEM_CONCEPTO  PRCP WITH(NOLOCK)
ON SE.ID_PROCESO=PRCP.ID_PROCESO AND SE.ID_CONCEPTO=PRCP.ID_CONCEPTO
LEFT JOIN PARAMETROS..PROCESOS PR WITH(NOLOCK)
ON PR.ID_PROCESO=SE.ID_PROCESO
WHERE 
SE.NUMERO_GUIA=251066982
AND SE.ID_PROCESO IN(8,14)	
AND DOC.ID_DIVISION_DESTINO = 9209 
ORDER BY SE.FECHA_HORA_MOVIMIENTO DESC

