SELECT 
	KEY_FECHA = (YEAR([DATE])*100+MONTH([DATE]))*100+DAY([DATE])	
	  ,[TIME_ID]
      ,[DATE] AS FECHA
      ,[YEAR] AS NUM_AÑO
      ,[AÑOMES] = [YEAR]*100+[MONTH_OF_YEAR]
	  ,[DAY_OF_MONTH] AS NUM_DIA
      ,[WEEK_OF_YEAR] AS NUM_SEMANA 
      ,[MONTH_OF_YEAR] AS NUM_MES
      ,[QUARTER_OF_YEAR] AS CUATRIMESTRE
      ,[SEMESTER_OF_YEAR] AS NUM_SEMESTRE
      ,[SEMESTER] AS SEMESTRE
      ,[FECHA_CREACION_DW]
      ,[NOMBRE_MES] = CASE WHEN [DAY_OF_MONTH]=1 THEN 'ENERO'
							WHEN [DAY_OF_MONTH]=2 THEN 'FEBRERO'
							WHEN [DAY_OF_MONTH]=3 THEN 'MARZO'
							WHEN [DAY_OF_MONTH]=4 THEN 'ABRIL'
							WHEN [DAY_OF_MONTH]=5 THEN 'MAYO'
							WHEN [DAY_OF_MONTH]=6 THEN 'JUNIO'
							WHEN [DAY_OF_MONTH]=7 THEN 'JULIO'
							WHEN [DAY_OF_MONTH]=8 THEN 'AGOSTO'
							WHEN [DAY_OF_MONTH]=9 THEN 'SEPTIEMBRE'
							WHEN [DAY_OF_MONTH]=10 THEN 'OCTUBRE'
							WHEN [DAY_OF_MONTH]=11 THEN 'NOVIEMBRE'
							WHEN [DAY_OF_MONTH]=12 THEN 'DICIEMBRE'
							ELSE 'NO DISPONIBLE' END
      ,[NOMBRE_MES_CORTO] = CASE	WHEN [DAY_OF_MONTH]=1  THEN 'ENE'
									WHEN [DAY_OF_MONTH]=2  THEN 'FEB'
									WHEN [DAY_OF_MONTH]=3  THEN 'MAR'
									WHEN [DAY_OF_MONTH]=4  THEN 'ABR'
									WHEN [DAY_OF_MONTH]=5  THEN 'MAY'
									WHEN [DAY_OF_MONTH]=6  THEN 'JUN'
									WHEN [DAY_OF_MONTH]=7  THEN 'JUL'
									WHEN [DAY_OF_MONTH]=8  THEN 'AGO'
									WHEN [DAY_OF_MONTH]=9  THEN 'SEP'
									WHEN [DAY_OF_MONTH]=10 THEN 'OCT'
									WHEN [DAY_OF_MONTH]=11 THEN 'NOV'
									WHEN [DAY_OF_MONTH]=12 THEN 'DIC'
							ELSE 'NA' END
  FROM [SIG_LOGISTICA_DM].[DIM].[TIEMPO] (NOLOCK)
  WHERE [DATE] BETWEEN 
  DATEADD(mm,-6,DATEADD(mm,DATEDIFF(mm,0,GETDATE()),0))
  AND  DATEADD(DAY,1,CONVERT(DATETIME,CONVERT(DATE,GETDATE())))