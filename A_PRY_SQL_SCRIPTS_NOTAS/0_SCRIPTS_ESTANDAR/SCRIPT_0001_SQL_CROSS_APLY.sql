select  LG.* ,SCN.* , MBG.* 
from [TMP].[MBCORE_GUIAS] MBG
CROSS APPLY (
	select TOP 1   'CORPORATIVO' AS G_CANAL,    CASE WHEN [DES_CIUDADREMITENTE] IS NULL THEN -888 ELSE [DES_CIUDADREMITENTE] END ID_GEOGRAFIA_SERV_ORIG
				  ,CASE WHEN [DES_CIUDAD] IS NULL THEN -888 ELSE [DES_CIUDAD] END ID_GEOGRAFIA_SERV_DEST 
	from [SCN].[SERT_ENVIO]
	where NUM_GUIA = G_NUMERO_GUIA
) SCN
CROSS APPLY (
	select TOP 1
		CASE WHEN GUI.ID_CLIENTE IS NULL AND ISNULL(GUI.ID_CANAL,'0')<>'0' THEN 'RETAIL'
							WHEN GUI.ID_CLIENTE IS NOT NULL AND ISNULL(GUI.ID_CANAL,'0')='0' THEN 'CORPORATIVO'
							ELSE 'OTROS'
							END AS G_CANAL,
		ISNULL(GUI.ID_CIUDAD_DESTINO,-888) AS G_ID_CIUDAD_CANAL_ORIGEN,
		ISNULL(GUI.ID_CIUDAD_ORIGEN,-888) AS G_ID_CIUDAD_CANAL_DESTINO
	from [TMP].[MBCORE_MECE_LOGISTICO_GUIAS] AS GUI
	where NUMERO_GUIA = G_NUMERO_GUIA
) LG
WHERE  G_NUMERO_GUIA = 2287028808
