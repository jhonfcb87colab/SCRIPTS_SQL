

USE SIG_COL_LOGISTICA_DW;

DECLARE @FECHA_INICIAL DATETIME = CONVERT(DATETIME,CONVERT(DATE,DATEADD(mm,-1,DATEADD(mm,DATEDIFF(mm,0,GETDATE()),0))))
DECLARE @FECHA_FINAL DATETIME = CONVERT(DATETIME,CONVERT(DATE,DATEADD(ms,-3,DATEADD(mm,0,DATEADD(mm,DATEDIFF(mm,0,GETDATE()),0)))))
--SELECT @FECHA_INICIAL,@FECHA_FINAL
SELECT 
       [MOXP].[AÑO] Año
	  ,[MOXP].[DIA] Dia
      ,[TM].MONTH_OF_YEAR [MONTH OF YEAR]
	  ,[TM].MONTH MesDelAño
      ,[TM].[day] [Dia de la semana]
	  ,PR.NOMBRE_PROCESO_LOG [Nombre Proceso]
	  ,MOXP.PLACA_VEHICULO PLACA
	  ,F_PG.MODO_PAGO
	  ,CDURB.NOMBRE_ZONA_URBA [Descripcion Zona Urbana]
	  ,CD_OR.NOMBRE_CIUDAD [Dim_Geografia_Origen_Nombre Ciudad]
	  ,CD_OR.NOMBRE_CPL [Dim_Geografia_Origen_NOMBRE CPL]
	  ,RGI_OR.NOMBRE_REGIONAL [Dim_Geografia_Origen_Nombre Regional]
	  ,CD_DS.NOMBRE_CIUDAD [Dim_Geografia_Destino_Nombre Ciudad]
	  ,CD_OR.NOMBRE_CPL [Dim_Geografia_Destino_NOMBRE CPL]
	  ,RGI_DS.NOMBRE_REGIONAL [Dim_Geografia_Destino_Nombre Regional]
	  ,SUM(moxp.CANTIDAD_ENVIOS_SE) [Cantidad Envios]

  FROM [SIG_COL_LOGISTICA_DW].[FAC].[MOV_POR_PROCESO_PRODUCTO] MOXP WITH(NOLOCK)
  inner join SIG_COLOMBIA_DW.PAR.PROCESOS PR WITH(NOLOCK) ON PR.ID_PROCESO=MOXP.ID_PROCESO
  INNER JOIN DIM.CIUDADES_MOVIMIENTOS_ORIGEN_MOVILIZADOS CD_OR WITH(NOLOCK) ON CD_OR.ID_CIUDAD=MOXP.ID_CIUDAD_ORIGEN_G
  INNER JOIN DIM.CIUDADES_MOVIMIENTOS_DESTINO_MOVILIZADOS CD_DS WITH(NOLOCK) ON CD_DS.ID_CIUDAD=MOXP.ID_CIUDAD_ORIGEN_G
  INNER JOIN DIM.REGIONALES_PAIS RGI_OR WITH(NOLOCK) ON RGI_OR.ID_REGIONAL_PAIS=RGI_OR.ID_REGIONAL
  INNER JOIN DIM.REGIONALES_PAIS RGI_DS WITH(NOLOCK) ON RGI_DS.ID_REGIONAL_PAIS=RGI_DS.ID_REGIONAL
  INNER JOIN DIM.TIEMPO TM WITH(NOLOCK) ON TM.TIME_ID=MOXP.TIME_ID
  INNER JOIN DIM.VEHICULOS VH WITH(NOLOCK) ON VH.PLACA_VEHICULO=CONVERT(NVARCHAR(20), MOXP.PLACA_VEHICULO  )
  INNER JOIN DIM.MOXP_MODO_PAGO F_PG WITH(NOLOCK) ON F_PG.ID_MOXP_MODO_PADO=MOXP.ID_TIPO_COBRO
  inner join DIM.CIUDADES_ZONA_URBA CDURB WITH(NOLOCK) ON 
														right( '0000' +  CONVERT(varchar,CDURB.Id_ciudad),4) +
														CONVERT(varchar,CDURB.ID_TIPO_Zona_urba) +
														right( '000' +  CONVERT(varchar,CDURB.ID_Zona_Urba),3) = MOXP.ID_CIUDAD_ZONA_URBA

WHERE [MOXP].FECHA BETWEEN @FECHA_INICIAL AND @FECHA_FINAL
AND [MOXP].ID_PROCESO IN(6,9,10,11,15,44)
GROUP BY 
       [MOXP].[AÑO] 
	  ,[MOXP].[DIA] 
      ,[TM].MONTH_OF_YEAR 
	  ,[TM].MONTH 
      ,[TM].[day] 
	  ,PR.NOMBRE_PROCESO_LOG 
	  ,MOXP.PLACA_VEHICULO 
	  ,F_PG.MODO_PAGO
	  ,CDURB.NOMBRE_ZONA_URBA
	  ,CD_OR.NOMBRE_CIUDAD 
	  ,CD_OR.NOMBRE_CPL
	  ,RGI_OR.NOMBRE_REGIONAL 
	  ,CD_DS.NOMBRE_CIUDAD 
	  ,CD_OR.NOMBRE_CPL 
	  ,RGI_DS.NOMBRE_REGIONAL
