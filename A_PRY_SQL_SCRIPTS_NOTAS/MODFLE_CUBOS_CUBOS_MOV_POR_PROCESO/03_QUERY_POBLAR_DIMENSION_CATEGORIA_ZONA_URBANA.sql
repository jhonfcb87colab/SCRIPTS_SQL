USE SIG_COLOMBIA_DW;
DROP TABLE IF EXISTS #ZONASUBARNAS_MODELOS_FLEX_01;
DROP TABLE IF EXISTS #ZONASUBARNAS_MODELOS_FLEX_02;


SELECT  
	right( '0000' +  CONVERT(varchar,A.Id_ciudad),4) +
	CONVERT(varchar,A.ID_TIPO_Zona_urba) +
	right( '000' +  CONVERT(varchar,A.ID_Zona_Urba),3) as CLAVE_DIMENSION
	,A.ID_PAIS 
	,A.ID_CIUDAD  
	,A.ID_TIPO_ZONA_URBA  
	,A.ID_ZONA_URBA 
	,IIF(ISNULL(A.CATEGORIA_ZONA_URBA,1)=0,1,ISNULL(A.CATEGORIA_ZONA_URBA,1)) AS ID_CATEGORIA_ZONA_URBA 
	,NOMBRE_CATEGORIA_ZONA_URBA =  
							CASE 
								WHEN (ISNULL(A.CATEGORIA_ZONA_URBA,1) = 1 OR ISNULL(A.CATEGORIA_ZONA_URBA,1) = 0) THEN 'URBANA'   
								WHEN A.CATEGORIA_ZONA_URBA  = 2 THEN 'RURAL'   
								WHEN A.CATEGORIA_ZONA_URBA  = 3 THEN  'VOLANTE'  
								WHEN A.CATEGORIA_ZONA_URBA  = 4 THEN  'EMPRESARIO SATELITE' 
								WHEN A.CATEGORIA_ZONA_URBA  = 5 THEN  'NINGUNA' 
								WHEN A.CATEGORIA_ZONA_URBA  = 6 THEN  'OUTSOURCING PXP' 
								WHEN A.CATEGORIA_ZONA_URBA  = 7 THEN  'RAPIGO' 
								ELSE 'NINGUNA'
							END
	,FECHA_ACTUALLIZACION = FECHA_MODIFICACION 								
							INTO #ZONASUBARNAS_MODELOS_FLEX_01
	FROM PAR.ZONASURBANAS A WITH(NOLOCK)
	WHERE ID_PAIS=1;




SELECT 
	ROW_NUMBER ( )   OVER ( PARTITION BY CLAVE_DIMENSION order by FECHA_ACTUALLIZACION desc )  ROWid  
	,CLAVE_DIMENSION	
	,ID_PAIS	
	,ID_CIUDAD	
	,ID_TIPO_ZONA_URBA	
	,ID_ZONA_URBA	
	,ID_CATEGORIA_ZONA_URBA	
	,NOMBRE_CATEGORIA_ZONA_URBA	
	,FECHA_ACTUALLIZACION
	INTO #ZONASUBARNAS_MODELOS_FLEX_02
FROM  
	#ZONASUBARNAS_MODELOS_FLEX_01;

TRUNCATE TABLE SIG_COL_LOGISTICA_DW.DIM.CATEGORIA_ZONA_URBANA;
INSERT INTO SIG_COL_LOGISTICA_DW.DIM.CATEGORIA_ZONA_URBANA
SELECT 
	CLAVE_DIMENSION		
	,ID_CATEGORIA_ZONA_URBA	
	,NOMBRE_CATEGORIA_ZONA_URBA	
FROM  
	#ZONASUBARNAS_MODELOS_FLEX_02
WHERE ROWid=1


SELECT * FROM SIG_COL_LOGISTICA_DW.DIM.CATEGORIA_ZONA_URBANA WITH(NOLOCK)

