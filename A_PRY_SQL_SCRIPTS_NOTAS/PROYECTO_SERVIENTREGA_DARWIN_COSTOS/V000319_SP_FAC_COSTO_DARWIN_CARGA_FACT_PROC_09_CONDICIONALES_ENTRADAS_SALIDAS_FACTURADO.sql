ALTER PROCEDURE [FAC].[COSTO_DARWIN_CARGA_FACT_PROC_09_CONDICIONALES_ENTRADAS_SALIDAS_FACTURADO]
AS
BEGIN
     SET NOCOUNT ON;
*/
	DECLARE @PERIODO INT = 202602 		/*(SELECT TOP 1 MAX(PERIODO_EJECUCION) 
												FROM [SIG_COLOMBIA_DW].[TMP].[COSTO_DARWIN_BASE_OPERACION_MES] (NOLOCK)); 
												print(@PERIODO);*/

		/*CARGA TABLA BASE CON LAS GUIAS PRINCIPALES */
		--DECLARE @PERIODO INT = 202604	
		TRUNCATE TABLE [TMP].[COSTO_DARWIN_BASE_OPERACION_MES_CONDICIONES_CONTROL_ENTRADA];
		INSERT INTO [TMP].[COSTO_DARWIN_BASE_OPERACION_MES_CONDICIONES_CONTROL_ENTRADA]
		SELECT 
			NUMERO_GUIA
			,CANAL
			,MEDIO_DE_PAGO
			,FECHA_FACTURACION	= ISNULL(CONVERT(DATETIME,MAX(FECHA_FACTURACION)),'1900-01-01')			
			,FECHA_ENTRADA = CONVERT(DATETIME,'1900-01-01')
			,FECHA_REPORTADO_ENTREGADO =	CONVERT(DATETIME,'1900-01-01')
			,APLICA_CONDICIONAL	= CONVERT(VARCHAR(200),'')
			,CONDICION_ENTRADA_ENTREGADO = CONVERT(VARCHAR(200),'')
		--INTO [TMP].[COSTO_DARWIN_BASE_OPERACION_MES_CONDICIONES_CONTROL_ENTRADA]
		FROM SIG_LOGISTICA_DM.FAC.COSTO_DARWIN_BASE_OPERACION_MES (NOLOCK) 
		WHERE PERIODO_EJECUCION = @PERIODO
		GROUP BY NUMERO_GUIA,CANAL,MEDIO_DE_PAGO



		/*GUIAS CON ENTRADA A ZONA ENTREADA PUNTO DE SERVICIO*/
		--DECLARE @PERIODO INT = 202604
		DROP TABLE IF EXISTS #GUIAS_FECHA_ENTRADA_ESU_EPS
		SELECT 
		PERIODO_EJECUCION,
		NUMERO_GUIA,
		FECHA_HORA_MOVIMIENTO
		INTO #GUIAS_FECHA_ENTRADA_ESU_EPS
		FROM SIG_LOGISTICA_DM.FAC.COSTO_DARWIN_BASE_OPERACION_MES (NOLOCK) 
		WHERE PERIODO_EJECUCION = @PERIODO
		AND [ID_PROCESO] IN (5,6)   
		GROUP BY 
		PERIODO_EJECUCION,
		NUMERO_GUIA,
		FECHA_HORA_MOVIMIENTO

		/*GUIAS CON REPORTADO ENTREGADOP */
		--DECLARE @PERIODO INT = 202604
		DROP TABLE IF EXISTS #GUIAS_FECHA_REPORTADO_ENTREGADO
		SELECT 
		PERIODO_EJECUCION,
		NUMERO_GUIA,
		FECHA_HORA_MOVIMIENTO
		INTO #GUIAS_FECHA_REPORTADO_ENTREGADO
		FROM SIG_LOGISTICA_DM.FAC.COSTO_DARWIN_BASE_OPERACION_MES (NOLOCK) 
		WHERE PERIODO_EJECUCION = @PERIODO
		AND [ID_PROCESO] IN (24)   
		GROUP BY 
		PERIODO_EJECUCION,
		NUMERO_GUIA,
		FECHA_HORA_MOVIMIENTO
  
 		  
		UPDATE T1_PR
			SET 
				T1_PR.FECHA_ENTRADA = ISNULL(T2.FECHA_HORA_MOVIMIENTO,'1900-01-01'),
				T1_PR.FECHA_REPORTADO_ENTREGADO = ISNULL(T3.FECHA_HORA_MOVIMIENTO,'1900-01-01')
		FROM [TMP].[COSTO_DARWIN_BASE_OPERACION_MES_CONDICIONES_CONTROL_ENTRADA] T1_PR WITH(NOLOCK)
		LEFT JOIN #GUIAS_FECHA_ENTRADA_ESU_EPS T2 ON T1_PR.NUMERO_GUIA=T2.NUMERO_GUIA
		LEFT JOIN #GUIAS_FECHA_REPORTADO_ENTREGADO T3 ON T1_PR.NUMERO_GUIA=T3.NUMERO_GUIA		

       
        DROP TABLE IF EXISTS #TEMPORAL_VALIDAR_GUIAS_CODICIONALES

        ;WITH DatosConPeriodo AS (
            SELECT 
                NUMERO_GUIA
                ,CANAL
                ,MEDIO_DE_PAGO
                ,FECHA_FACTURACION
                ,FECHA_ENTRADA
                ,FECHA_REPORTADO_ENTREGADO,
                -- Convertimos cada fecha a formato numérico YYYYMM (Ej: 202606). 
                -- Si es '1900-01-01', su período será 190001.
                (YEAR(FECHA_ENTRADA) * 100 + MONTH(FECHA_ENTRADA)) AS P_ENTRADA,
                (YEAR(FECHA_REPORTADO_ENTREGADO) * 100 + MONTH(FECHA_REPORTADO_ENTREGADO)) AS P_ENTREGADO,
                (YEAR(FECHA_FACTURACION) * 100 + MONTH(FECHA_FACTURACION)) AS P_FACTURA
    	        FROM [TMP].[COSTO_DARWIN_BASE_OPERACION_MES_CONDICIONES_CONTROL_ENTRADA] T1_PR WITH(NOLOCK)
        )
        SELECT 
            NUMERO_GUIA,
            CANAL,
            MEDIO_DE_PAGO,    
            FECHA_ENTRADA,
            FECHA_REPORTADO_ENTREGADO,
            FECHA_FACTURACION,
           -- ----------------------------------------------------
            -- 1. CASE PARA CONDICION_ENTRADA_ENTREGADO
            -- ----------------------------------------------------
            CASE 
                -- REGLA 1: Todos los periodos son exactamente IGUALES (y válidos > 190001)
                WHEN P_ENTRADA > 190001 AND P_ENTRADA = P_ENTREGADO AND P_ENTRADA = P_FACTURA
                    THEN '01 - TIENE ENTRADA - FUE ENTREGADO - FACTURADO EN EL MES'
                 -- REGLA 2: Dos campos son IGUALES y uno es NULL / '1900-01-01' (190001)
                WHEN (P_ENTRADA > 190001 AND P_ENTRADA = P_ENTREGADO AND P_FACTURA = 190001)
                    THEN '03 - TIENE ENTRADA - FUE ENTREGADO - NO FACTURADO'
                WHEN (P_ENTRADA > 190001 AND P_ENTRADA = P_FACTURA AND P_ENTREGADO = 190001)
                    THEN '08 - TIENE ENTRADA - NO FUE ENTREGADO - FACTURADO EN EL MES'
                WHEN (P_ENTREGADO > 190001 AND P_ENTREGADO = P_FACTURA AND P_ENTRADA = 190001)
                    THEN '06 - NO TIENE ENTRADA - FUE ENTREGADO - FACTURADO EN EL MES'
                 -- REGLA 3: Dos campos son IGUALES y uno tiene una FECHA SUPERIOR (Mes posterior)
                WHEN P_ENTRADA > 190001 AND P_ENTREGADO > 190001 AND P_FACTURA > 190001 
                 AND P_ENTRADA = P_ENTREGADO AND P_FACTURA > P_ENTRADA
                    THEN '02 - TIENE ENTRADA - FUE ENTREGADO - FACTURADO EN OTRO MES'
                 WHEN P_ENTRADA = 190001 AND P_ENTREGADO > 190001 AND P_FACTURA > 190001 AND P_FACTURA > P_ENTREGADO
                    THEN '07 - NO TIENE ENTRADA - FUE ENTREGADO - FACTURADO EN OTRO MES'
                WHEN P_ENTRADA > 190001 AND P_ENTREGADO = 190001 AND P_FACTURA > 190001 AND P_FACTURA > P_ENTRADA
                    THEN '09 - TIENE ENTRADA - NO FUE ENTREGADO - FACTURADO EN OTRO MES'
                -- REGLA 3.1 (NUEVO) Condición 11: Facturado en el mes ANTERIOR (Fecha inferior)
                WHEN P_ENTRADA > 190001 AND P_ENTREGADO > 190001 AND P_FACTURA > 190001 
                 AND P_ENTRADA = P_ENTREGADO AND P_FACTURA < P_ENTRADA
                    THEN '11 - TIENE ENTRADA - FUE ENTREGADO - FACTURADO EN EL MES ANTERIOR'
                 -- REGLA 4: Solo un campo es válido (tiene fecha real) y los otros dos son '1900-01-01'
                WHEN P_ENTRADA > 190001 AND P_ENTREGADO = 190001 AND P_FACTURA = 190001
                    THEN '04 - TIENE ENTRADA - NO FUE ENTREGADO - NO FACTURADO'
                WHEN P_ENTRADA = 190001 AND P_ENTREGADO > 190001 AND P_FACTURA = 190001
                    THEN '05 - NO TIENE ENTRADA - FUE ENTREGADO - NO FACTURADO'
                -- Condición 10: Solo hay facturación, sin entrada ni entrega
                WHEN P_ENTRADA = 190001 AND P_ENTREGADO = 190001 AND P_FACTURA > 190001
                    THEN '10 - NO TIENE ENTRADA - NO FUE ENTREGADO - FACTURADO EN EL MES'
                 -- Si no cumple ninguna de estas lógicas
                ELSE 'NO EXISTE DENTRO DEL PERIODO'
            END AS CONDICION_ENTRADA_ENTREGADO,
             -- ----------------------------------------------------
            -- 2. CASE PARA APLICA_CONDICIONAL
            -- ----------------------------------------------------
            CASE
                -- Si los TRES periodos son válidos (>190001), sin importar si la factura es = , > o <
                -- Esto cubre automáticamente las condiciones 01, 02 y 11.
                WHEN P_ENTRADA > 190001 AND P_ENTREGADO > 190001 AND P_FACTURA > 190001
                    THEN 'LIQUIDADO-FACTURADO Y MOVILIZADO'
                -- Dos campos válidos e iguales, Factura es 190001 (Condición 03)
                WHEN P_ENTRADA > 190001 AND P_ENTREGADO > 190001 AND P_FACTURA = 190001
                    THEN 'LIQUIDADO - NO FACTURADO Y MOVILIZADO'
                -- Solo Entrada es válida, los demás 190001 (Condición 04)
                WHEN P_ENTRADA > 190001 AND P_ENTREGADO = 190001 AND P_FACTURA = 190001
                    THEN 'LIQUIDADO - NO FACTURADO Y NO MOVILIZADO'
                -- Entrada es 190001, Entrega es válida, Factura es 190001 (Condición 05)
                WHEN P_ENTRADA = 190001 AND P_ENTREGADO > 190001 AND P_FACTURA = 190001
                    THEN 'NO LIQUIDADO - NO FACTURADO Y NO MOVILIZADO'
                -- Entrada es 190001, Entrega y Factura son válidas (Condiciones 06 y 07)
                WHEN P_ENTRADA = 190001 AND P_ENTREGADO > 190001 AND P_FACTURA > 190001
                    THEN 'NO LIQUIDADO - FACTURADO Y NO MOVILIZADO'
                -- Entrada y Factura válidas, Entrega es 190001 (Condiciones 08 y 09)
                WHEN P_ENTRADA > 190001 AND P_FACTURA > 190001 AND P_ENTREGADO = 190001
                    THEN 'LIQUIDADO - FACTURADO Y NO MOVILIZADO'
                -- Condición 10: Solo Factura es válida, los demás 190001
                WHEN P_ENTRADA = 190001 AND P_ENTREGADO = 190001 AND P_FACTURA > 190001
                    THEN 'NO LIQUIDADO - FACTURADO Y NO MOVILIZADO'
                 ELSE 'NO EXISTE DENTRO DEL PERIODO'
            END AS APLICA_CONDICIONAL
          INTO #TEMPORAL_VALIDAR_GUIAS_CODICIONALES
        FROM DatosConPeriodo;

		/* UPDATE DE DATOS DE CON LAS CONDICIONES EN LA FAC  */
		--DECLARE @PERIODO INT = 202604	
        UPDATE FAC SET
         FAC.APLICA_CONDICIONAL = TMP.APLICA_CONDICIONAL
        ,FAC.CONDICION_ENTRADA_ENTREGADO = TMP.CONDICION_ENTRADA_ENTREGADO 
        FROM SIG_LOGISTICA_DM.FAC.COSTO_DARWIN_BASE_OPERACION_MES FAC (NOLOCK)
        INNER JOIN  #TEMPORAL_VALIDAR_GUIAS_CODICIONALES TMP
        ON TMP.NUMERO_GUIA=FAC.NUMERO_GUIA AND FAC.PERIODO_EJECUCION=@PERIODO

--END
