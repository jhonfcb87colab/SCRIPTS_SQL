	CONVERT(NUMERIC(20,2),Sum(T01.[TOTAL_COSTO])/SUM(T01.[PIEZAS])) AS COSTO_POR_PIEZA 
FROM #TBL_TMP01_1C_Detalle_Guias_Piezas_Facturadas_02 AS T01
