/******************************		CREACION NUEVAS VISTAS DASHBOARD DETALLE MES					**************/

Drop table if exists #Costo_Cross_Por_Mov_Esperados_REPORT_CROSS_MODA
	DECLARE @PERIODO INT = /*202503;*/ (SELECT TOP 1 MAX(PERIODO_EJECUCION) 
										FROM [SIG_COLOMBIA_DW].[TMP].[COSTO_DARWIN_BASE_OPERACION_MES] (NOLOCK)); 
										print(@PERIODO);
	DROP TABLE IF EXISTS #Costo_Cross_Por_Mov_Esperados_REPORT_CROSS_MODA;
	DECLARE @Colaboradores_Cross_Pais FLOAT = 1016
	DECLARE @Costo_Unitario_Cross	  FLOAT = 3170000
	DECLARE @Costo_Mes_Cross FLOAT = @Colaboradores_Cross_Pais * @Costo_Unitario_Cross
	;WITH CTE AS(
	SELECT 
	[PERIODO]
	,Mov_Cross_Esperados = sum([MOV_CROSS_ESPERADOS])
	,Costo_mes_Cross = @Costo_Mes_Cross
	FROM [SIG_LOGISTICA_DM].[FAC].[COSTOS_DARWIN_MODA_PROCESOS_CROSS] (NOLOCK)
	GROUP BY [PERIODO]
	)
	SELECT 
	PERIODO	
	,Mov_Cross_Esperados	
	,Costo_mes_Cross
	,Costo_Cross_Por_Mov_Esperados = ROUND([Costo_Mes_Cross] / [Mov_Cross_Esperados],2)
	INTO #Costo_Cross_Por_Mov_Esperados_REPORT_CROSS_MODA
	FROM CTE WHERE PERIODO=@PERIODO


drop table if exists #TBL_TMP01_1C_Detalle_Guias_Piezas_Facturadas
SELECT 
[BASE DATOS].PERIODO_EJECUCION,
[BASE DATOS].NOMBRE_CLIENTE_CDS, 
[BASE DATOS].NOMBRE_PRODUCTO, 
[BASE DATOS].NUMERO_GUIA, 
[BASE DATOS].NOMBRE_ESTADOENVIO, 
[BASE DATOS].NOMBRE_TIPOTRAY,
Min([BASE DATOS].NUMERO_PIEZAS) AS PIEZAS, 
Min([BASE DATOS].VALOR_FACTURADO) AS FACTURADO, 
Min([BASE DATOS].PESO_FISICO_GUIA) AS PESO_KG, 
Min([BASE DATOS].PESO_VOLU_GUIA) AS PESO_VOL, 
Sum(IIf([BASE DATOS].[NOMBRE_PRODUCTO]='MERCANCIA INDUSTRIAL',
			CONVERT(FLOAT,[COSTO_GUIA_MAS_AUXILIAR_POR_PESO]),
			CONVERT(FLOAT,[COSTO_GUIA_MAS_AUXILIAR_POR_PIEZA]))) AS COSTO_POR_PESO_O_PIEZAS, 
Min([BASE DATOS].MOVIMIENTOS_CROSS) AS [CROSS], 
MIN(CONVERT(FLOAT,[BASE DATOS].MOVIMIENTOS_CROSS)) AS MOVIMIENTOS_CROSS,
Sum(IIf([NOMBRE_PROCESO_LOG]='SALIDA A ZONA URBANA',1,0)) AS SZU, 
Sum(IIf([NOMBRE_PROCESO_LOG]='REPORTADO ENTREGADO',1,0)) AS RE
INTO #TBL_TMP01_1C_Detalle_Guias_Piezas_Facturadas
FROM [FAC].[COSTO_DARWIN_BASE_OPERACION_MES] AS [BASE DATOS] WITH(NOLOCK)
LEFT JOIN [ACCES_DARWIN].[dbo].[PRODUCTOS] [PRODUCTOS] WITH(NOLOCK)
ON [BASE DATOS].NOMBRE_PRODUCTO = PRODUCTOS.NOMBRE_PRODUCTO
WHERE (((PRODUCTOS.APLICA)=1))
AND [BASE DATOS].PERIODO_EJECUCION=@PERIODO
AND [BASE DATOS].ID_PROCESO > 1
GROUP BY 
[BASE DATOS].PERIODO_EJECUCION,
[BASE DATOS].NOMBRE_CLIENTE_CDS, 
[BASE DATOS].NOMBRE_PRODUCTO, 
[BASE DATOS].NUMERO_GUIA, 
[BASE DATOS].NOMBRE_ESTADOENVIO, 
[BASE DATOS].NOMBRE_TIPOTRAY--,
HAVING (((Min([BASE DATOS].VALOR_FACTURADO))>0))

DROP TABLE IF EXISTS #TBL_TMP01_1C_Detalle_Guias_Piezas_Facturadas_02;
SELECT 
	 [PERIODO_EJECUCION]
	,[NOMBRE_CLIENTE_CDS]	
	,[NOMBRE_PRODUCTO]	
	,[NUMERO_GUIA]	
	,[NOMBRE_ESTADOENVIO]	
	,[NOMBRE_TIPOTRAY]	
	,[PIEZAS]	
	,[FACTURADO]	
	,[PESO_KG]	
	,[PESO_VOL]	
	,[COSTO_POR_PESO_O_PIEZAS]	
	,[CROSS]	
	,[COSTO_CROSS_MES]	= (MOVIMIENTOS_CROSS) * MODA.Costo_Cross_Por_Mov_Esperados
	,[SZU]	
	,[RE]	
	,IIF([SZU] >= 1 AND [RE] >= 1,'Si','No') AS VD_APLICA_REVISION 
	,[TOTAL_COSTO] = ([COSTO_POR_PESO_O_PIEZAS]) + ((MOVIMIENTOS_CROSS) * MODA.Costo_Cross_Por_Mov_Esperados)
	INTO #TBL_TMP01_1C_Detalle_Guias_Piezas_Facturadas_02
FROM #TBL_TMP01_1C_Detalle_Guias_Piezas_Facturadas T01
LEFT JOIN #Costo_Cross_Por_Mov_Esperados_REPORT_CROSS_MODA MODA WITH(NOLOCK)
ON MODA.PERIODO=T01.PERIODO_EJECUCION

DELETE [FAC].[COSTO_DARWIN_2C_Datos_Finales_Ingreso_Y_Costo] WHERE [PERIODO_EJECUCION]=@PERIODO;

;WITH CTE AS(
SELECT 
	TB1C.[PERIODO_EJECUCION],
	TB1C.NOMBRE_CLIENTE_CDS, 
	TB1C.NOMBRE_PRODUCTO, 
	TB1C.NOMBRE_TIPOTRAY, 
	TB1C.NOMBRE_ESTADOENVIO, 
	CONVERT(NUMERIC(20,2),Sum(TB1C.PIEZAS)) AS [TOTAL PIEZAS], 
	CONVERT(NUMERIC(20,2),Sum(CONVERT(FLOAT,TB1C.PESO_KG))) AS [TOTAL KG], 
	CONVERT(NUMERIC(20,2),Sum(TB1C.PESO_VOL)) AS [TOTAL VOL], 
	CONVERT(NUMERIC(20,2),Sum(TB1C.FACTURADO)) AS [VALOR FACTURADO], 
	CONVERT(NUMERIC(20,2),Sum(TB1C.TOTAL_COSTO)) AS [TOTAL COSTO], 
	CONVERT(NUMERIC(20,2),SUM(TB1C.[FACTURADO])/SUM(TB1C.[PIEZAS])) AS INGRESO_POR_PIEZA, 
	CONVERT(NUMERIC(20,2),Sum(TB1C.[TOTAL_COSTO])/SUM(TB1C.[PIEZAS])) AS COSTO_POR_PIEZA--, 
FROM #TBL_TMP01_1C_Detalle_Guias_Piezas_Facturadas_02 TB1C
WHERE (((TB1C.VD_APLICA_REVISION)='Si'))
--AND TB1C.NOMBRE_CLIENTE_CDS='LOGYTECH MOBILE SAS' 
--AND TB1C.NOMBRE_PRODUCTO='DOCUMENTO UNITARIO'
--AND TB1C.NOMBRE_TIPOTRAY='NACIONAL' 
--AND TB1C.NOMBRE_ESTADOENVIO='ENTREGADO'
GROUP BY 
TB1C.[PERIODO_EJECUCION],
TB1C.NOMBRE_CLIENTE_CDS, 
TB1C.NOMBRE_PRODUCTO, 
TB1C.NOMBRE_TIPOTRAY, 
TB1C.NOMBRE_ESTADOENVIO
)	
