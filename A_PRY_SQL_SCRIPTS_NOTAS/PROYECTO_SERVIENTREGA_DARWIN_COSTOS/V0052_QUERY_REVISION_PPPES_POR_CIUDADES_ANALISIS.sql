DROP TABLE IF EXISTS #TABLA_DARWIN_PPES_MUNICIPIOS;
;WITH CTE AS(
select ---TOP 100
(year(PPES.FECHA_LIQUIDACION)*100)+month(PPES.FECHA_LIQUIDACION) as ANIOMES
,PPES.CODIGO_CDS_PPES_DISTRIBUCION
,PPES.MODO_ENTREGA_EMPRESARIO
,G.ID_CIUDAD_DESTINO AS ID_CIUDAD_GUIAS 
,count(distinct(PPES.NUMERO_GUIA)) as TOTALGUIAS
,SUM(PPES.COMISION_DISTRIBUCION_EMPRESARIO) TOTAL_COMISIONES 
,AVG(PPES.COMISION_DISTRIBUCION_EMPRESARIO) PROM_COMISIONES
from  [tmp_borrar_local].[dbo].[PPES_COMISION_DISTRIBUCION] PPES WITH(NOLOCK INDEX=[IX_NUMERO_GUIA_PPD])
INNER JOIN Mece_Logistico..GUIAS G WITH(NOLOCK INDEX=[UK_GUIA]) ON PPES.NUMERO_GUIA=G.NUMERO_GUIA
where 
year(PPES.FECHA_LIQUIDACION)=2025 AND G.ID_CIUDAD_DESTINO IN(265,53,7809,68,451,9150,186)
GROUP BY 
(year(FECHA_LIQUIDACION)*100)+month(FECHA_LIQUIDACION) 
,CODIGO_CDS_PPES_DISTRIBUCION
,MODO_ENTREGA_EMPRESARIO
,G.ID_CIUDAD_DESTINO
--OPTION(RECOMPILE)
UNION ALL 
select ---TOP 100
(year(FECHA_LIQUIDACION)*100)+month(FECHA_LIQUIDACION) as ANIOMES
,CODIGO_CDS_PPES_RECOLECCION
,MODO_ENTREGA_EMPRESARIO = 'RECOLECCIONES'
,G.ID_CIUDAD_ORIGEN AS ID_CIUDAD_GUIAS
,count(distinct(PPES.NUMERO_GUIA)) as TOTALGUIAS
,SUM(COMISION_RECOLECCION_EMPRESARIO) TOTAL_COMISIONES 
,AVG(COMISION_RECOLECCION_EMPRESARIO) PROM_COMISIONES
from  [tmp_borrar_local].[dbo].[PPES_COMISION_RECOLECCION] PPES WITH(NOLOCK INDEX=[IX_NUMERO_GUIA_PPR])
INNER JOIN Mece_Logistico..GUIAS G WITH(NOLOCK INDEX=[UK_GUIA]) ON PPES.NUMERO_GUIA=G.NUMERO_GUIA
where 
year(PPES.FECHA_LIQUIDACION)=2025 AND G.ID_CIUDAD_ORIGEN IN(265,53,7809,68,451,9150,186)
GROUP BY 
(year(FECHA_LIQUIDACION)*100)+month(FECHA_LIQUIDACION) 
,CODIGO_CDS_PPES_RECOLECCION
,G.ID_CIUDAD_ORIGEN
----,MODO_ENTREGA_EMPRESARIO
--OPTION(RECOMPILE)
)
SELECT 
 CT.ANIOMES
,CT.CODIGO_CDS_PPES_DISTRIBUCION
,CT.MODO_ENTREGA_EMPRESARIO
,CT.ID_CIUDAD_GUIAS
,CD.NOMBRE_CIUDAD
,DEPA.NOMBRE_DEPARTAMENTO
,CT.TOTALGUIAS
,CT.TOTAL_COMISIONES 
,CT.PROM_COMISIONES
INTO #TABLA_DARWIN_PPES_MUNICIPIOS
FROM CTE CT
LEFT JOIN PARAMETROS..CIUDADES CD WITH(NOLOCK) ON CD.ID_CIUDAD=CT.ID_CIUDAD_GUIAS AND CD.ID_PAIS=1
LEFT JOIN PARAMETROS..DEPARTAMENTOS DEPA WITH(NOLOCK) ON DEPA.ID_DEPARTAMENTO=CD.ID_DEPARTAMENTO AND DEPA.ID_PAIS=1


