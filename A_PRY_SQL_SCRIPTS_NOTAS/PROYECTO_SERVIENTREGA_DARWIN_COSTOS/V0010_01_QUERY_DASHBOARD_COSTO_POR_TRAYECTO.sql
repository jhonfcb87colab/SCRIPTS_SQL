
WITH CTE AS(
SELECT ---TOP 100000
CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,[FECHA_HORA_MOVIMIENTO])))) AS ID_TIMEID	
        ,PERIODO_EJECUCION
	,NUMERO_GUIA
	,CANAL
	,NOMBRE_PRODUCTO
	,MEDIO_DE_PAGO
	,VALOR_RECAUDO
	,VALOR_ENVIO
	,NOMBRE_ESTADOENVIO
	,ID_PROCESO
	,NOMBRE_PROCESO_LOG
	,PLACA_VEHICULO_DOCU
	,TOTAL_AUXILIARES
	,ID_CIUDAD
	,NOMBRE_CIUDAD
	,FECHA_HORA_MOVIMIENTO
	,TOTAL_GUIAS_RECOLECCION
	,TOTAL_GUIAS_DISTRIBUCION
	,TOTAL_DEVOLUCIONES
	,PESO_FISICO_GUIA
	,PESO_FISICO_OPERA_RECOLECCION
	,PESO_FISICO_OPERA_DISTRIBUCION
	,MOVIMIENTOS_CROSS
	,LLAVE_ORIGEN_DESTINO
	,NOMBRE_TIPOTRAY
	,NOMBRE_CLIENTE_CDS
	,IDENTIFICACION_MOTO_CARRO_CURRIER_AEREO
	,KEY_SZU_RE_COBRO_DOBLE
	,TOTAL_GUIAS
	,TOTAL_PESO
	,TIPO_OPERACION_VEHICULO
	,DANE_ORIGEN_DESTINO
        ,[GEO_CIU_DEPA]
	,PROPIETARIO_VEHICULO
	,MODELOS_DE_CONTRATACION_FLOTA
	,COMISION_DISTRIBUCION_EMPRESARIO
	,COMISION_RECOLECCION_EMPRESARIO
	,TIPO_VEHICULO_BASE_PLACAS
	,KEY_IN_SOURCING
	,KM_INSOURCING
	,COSTO_KM_IN_SOURCING
	,SZU
	,RE
	,VD_DOBLE_COBRO
        ,CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,[FECHA_HORA_MOVIMIENTO]))) AS FECHA	
        --,FECHA
	,COSTO_FINAL_POR_MODELO
	,COSTO_UNITARIO_POR_KILO_GUIA
	,COSTO_UNITARIO_POR_UNIDAD_GUIA
	,COSTO_CON_AUXILIAR_POR_GUIA
	,COSTO_GUIA_MAS_AUXILIAR_POR_PESO
	,COSTO_GUIA_MAS_AUXILIAR_POR_GUIA
	,PESO_FISICO_OPERA_DEVOLUCION
        ,FECHA_CARGA_FAC
        ,ID_PRODUCTO
        ,ID_REGIONAL
        ,NOMBRE_REGIONAL
        ,PROPIETARIO_VEHICULOF
        ,ID_AUXILIAR1_VEHICULO
        ,ID_AUXILIAR2_VEHICULO
        ,ID_COURIER_CONDUCTOR
        ,[NOMBRE_ORIGEN_DESTINO]
        ,[PESO_VOLU_GUIA]
        ,[NUMERO_PIEZAS]
        ,[VALOR_FACTURADO]
		,FILTRO_ERROR_VEHICULOS = CASE WHEN [COSTO_FINAL_POR_MODELO] IN (2222222222, 3333333333, 1010101010, 1111111111,1313131313) THEN 'PLACA CON ERROR'
										ELSE 'SIN NOVEDAD'
										END
				,KEY_PERIDO_ORIGEN_DESTINO_COSTO = CONCAT(PERIODO_EJECUCION,'-',LLAVE_ORIGEN_DESTINO)
				,NOMBRE_REGIONAL_DESTINO
				,FECHA_FACTURACION
				,FECHA_ENVIO
				,ISNULL(FECHA_ENVIO,CONVERT(DATETIME,'1900-01-01')) ky_FECHA_LIQUIDACION				
				,ISNULL(FECHA_FACTURACION,CONVERT(DATETIME,'1900-01-01')) ky_FECHA_FACTURACION
				,ISNULL([FECHA_HORA_MOVIMIENTO],CONVERT(DATETIME,'1900-01-01')) ky_FECHA_MOV_CROSS
FROM SIG_LOGISTICA_DM.FAC.COSTO_DARWIN_BASE_OPERACION_MES (NOLOCK) 
WHERE PERIODO_EJECUCION IN(SELECT PERIODO FROM [FAC].[COSTO_DARWIN_PERIODOS_DASBOARD] (NOLOCK))
)
SELECT 
*
,APLICA_MISMO_PERIODO = CASE 
							WHEN YEAR(ky_FECHA_LIQUIDACION)*100+MONTH(ky_FECHA_LIQUIDACION)=PERIODO_EJECUCION 
									AND YEAR(ky_FECHA_FACTURACION)*100+MONTH(ky_FECHA_FACTURACION)=PERIODO_EJECUCION 
									AND YEAR(ky_FECHA_MOV_CROSS)*100+MONTH(ky_FECHA_MOV_CROSS)=PERIODO_EJECUCION THEN 'LIQUIDADO-FACTURADO Y MOVILIZADO'
							
							WHEN YEAR(ky_FECHA_LIQUIDACION)*100+MONTH(ky_FECHA_LIQUIDACION)=PERIODO_EJECUCION 
									AND YEAR(ky_FECHA_FACTURACION)*100+MONTH(ky_FECHA_FACTURACION)=PERIODO_EJECUCION 
									AND YEAR(ky_FECHA_MOV_CROSS)*100+MONTH(ky_FECHA_MOV_CROSS)=190001 THEN 'LIQUIDADO-FACTURADO NO MOVILIZADO'
							
							WHEN YEAR(ky_FECHA_LIQUIDACION)*100+MONTH(ky_FECHA_LIQUIDACION)=PERIODO_EJECUCION 
									AND YEAR(ky_FECHA_FACTURACION)*100+MONTH(ky_FECHA_FACTURACION)=190001 
									AND YEAR(ky_FECHA_MOV_CROSS)*100+MONTH(ky_FECHA_MOV_CROSS)=190001 THEN 'LIQUIDADO-NO FACTURADO NO MOVILIZADO'
							
							WHEN YEAR(ky_FECHA_LIQUIDACION)*100+MONTH(ky_FECHA_LIQUIDACION)=PERIODO_EJECUCION 
									AND YEAR(ky_FECHA_FACTURACION)*100+MONTH(ky_FECHA_FACTURACION)=190001 
									AND YEAR(ky_FECHA_MOV_CROSS)*100+MONTH(ky_FECHA_MOV_CROSS)=PERIODO_EJECUCION THEN 'LIQUIDADO-NO FACTURADO-MOVILIZADO'
							
							WHEN YEAR(ky_FECHA_LIQUIDACION)*100+MONTH(ky_FECHA_LIQUIDACION)=190001 
									AND YEAR(ky_FECHA_FACTURACION)*100+MONTH(ky_FECHA_FACTURACION)=PERIODO_EJECUCION 
									AND YEAR(ky_FECHA_MOV_CROSS)*100+MONTH(ky_FECHA_MOV_CROSS)=PERIODO_EJECUCION THEN 'NO LIQUIDADO FACTURADO Y MOVILIZADO'
							
							WHEN YEAR(ky_FECHA_LIQUIDACION)*100+MONTH(ky_FECHA_LIQUIDACION)=190001 
									AND YEAR(ky_FECHA_FACTURACION)*100+MONTH(ky_FECHA_FACTURACION)=PERIODO_EJECUCION 
									AND YEAR(ky_FECHA_MOV_CROSS)*100+MONTH(ky_FECHA_MOV_CROSS)=190001 THEN 'NO LIQUIDADO-FACTURADO-NO MOVILIZADO'							
							
							WHEN YEAR(ky_FECHA_LIQUIDACION)*100+MONTH(ky_FECHA_LIQUIDACION)=190001 
									AND YEAR(ky_FECHA_FACTURACION)*100+MONTH(ky_FECHA_FACTURACION)=190001 
									AND YEAR(ky_FECHA_MOV_CROSS)*100+MONTH(ky_FECHA_MOV_CROSS)=PERIODO_EJECUCION THEN	'NO LIQUIDADO-NO FACTURADO Y MOVILIZADO'	

							WHEN YEAR(ky_FECHA_LIQUIDACION)*100+MONTH(ky_FECHA_LIQUIDACION)=190001 
									AND YEAR(ky_FECHA_FACTURACION)*100+MONTH(ky_FECHA_FACTURACION)=190001 
									AND YEAR(ky_FECHA_MOV_CROSS)*100+MONTH(ky_FECHA_MOV_CROSS)=190001 THEN	'NO EXISTE'								
							ELSE 'NO EXISTE DENTRO DEL PERIODO' END
FROM CTE 

