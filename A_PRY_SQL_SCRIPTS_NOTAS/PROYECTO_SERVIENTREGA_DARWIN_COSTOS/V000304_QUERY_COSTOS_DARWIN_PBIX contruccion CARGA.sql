							THEN [COSTO_FINAL_POR_MODELO]
						WHEN [MODELOS_DE_CONTRATACION_FLOTA] IN(1,2,3)
							THEN IIF([COSTO_FINAL_POR_MODELO]=0 OR ([TOTAL_PESO] - [PESO_FISICO_OPERA_DEVOLUCION])=0,0,
									([COSTO_FINAL_POR_MODELO] / ([TOTAL_PESO] - [PESO_FISICO_OPERA_DEVOLUCION])))
						WHEN ([MODELOS_DE_CONTRATACION_FLOTA] IN(4,5)) AND [ID_PROCESO] IN(5,6)
							THEN [COSTO_FINAL_POR_MODELO] / [TOTAL_GUIAS_RECOLECCION]
						WHEN [MODELOS_DE_CONTRATACION_FLOTA] IN(4,5) AND [ID_PROCESO] IN(9,24) AND [COSTO_FINAL_POR_MODELO]=0
