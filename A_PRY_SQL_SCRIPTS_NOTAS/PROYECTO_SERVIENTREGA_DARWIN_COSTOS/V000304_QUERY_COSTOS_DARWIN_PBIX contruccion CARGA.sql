						WHEN [MODELOS_DE_CONTRATACION_FLOTA]=10 THEN [COSTO_FINAL_POR_MODELO]
						WHEN [MODELOS_DE_CONTRATACION_FLOTA]=11 THEN [PAR].[VW_COSTOS_DARWIN_CALCULAR_Tarifas_COSTO_POR_RUTA_AEREA](LLAVE_ORIGEN_DESTINO,PERIODO_EJECUCION)
						WHEN [MODELOS_DE_CONTRATACION_FLOTA]=14 THEN IIF([COSTO_FINAL_POR_MODELO]=0 OR [TOTAL_GUIAS_DISTRIBUCION] - [TOTAL_DEVOLUCIONES]=0,0,
																		[COSTO_FINAL_POR_MODELO] / ([TOTAL_GUIAS_DISTRIBUCION] - [TOTAL_DEVOLUCIONES]))
						ELSE 0 END ) * [VD_DOBLE_COBRO])
	,COSTO_UNITARIO_POR_UNIDAD_GUIA = CONVERT(NUMERIC(20,1),
									CASE	WHEN [MODELOS_DE_CONTRATACION_FLOTA]=0 THEN [COSTO_FINAL_POR_MODELO]
											WHEN [MODELOS_DE_CONTRATACION_FLOTA] IN(1,2,3) 
												THEN IIF([COSTO_FINAL_POR_MODELO]=0 OR  ([TOTAL_GUIAS] - [TOTAL_DEVOLUCIONES]) = 0,0,
														([COSTO_FINAL_POR_MODELO] / ([TOTAL_GUIAS] - [TOTAL_DEVOLUCIONES])))
											WHEN [MODELOS_DE_CONTRATACION_FLOTA] IN(4,5) AND [ID_PROCESO] IN(5,6)
												THEN IIF([COSTO_FINAL_POR_MODELO]=0 OR [TOTAL_GUIAS_RECOLECCION]=0,0,
																([COSTO_FINAL_POR_MODELO] / [TOTAL_GUIAS_RECOLECCION]) )
											WHEN [MODELOS_DE_CONTRATACION_FLOTA] IN(4,5) AND [ID_PROCESO] IN(9,24) AND [COSTO_FINAL_POR_MODELO]=0
												THEN 0
											WHEN [MODELOS_DE_CONTRATACION_FLOTA] IN(4,5) AND [ID_PROCESO] IN(9,24) AND [COSTO_FINAL_POR_MODELO]>0
