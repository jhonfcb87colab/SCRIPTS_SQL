											WHEN  [MODELOS_DE_CONTRATACION_FLOTA]=6
												THEN IIF([COSTO_FINAL_POR_MODELO]=0 OR ([TOTAL_GUIAS_DISTRIBUCION] - [TOTAL_DEVOLUCIONES])=0,0,
													[COSTO_FINAL_POR_MODELO] / ([TOTAL_GUIAS_DISTRIBUCION] - [TOTAL_DEVOLUCIONES]))
											WHEN [MODELOS_DE_CONTRATACION_FLOTA] IN(7,8,9)
												THEN IIF([COSTO_FINAL_POR_MODELO]=0 OR ([TOTAL_GUIAS] - [TOTAL_DEVOLUCIONES])<=0,0,
														[COSTO_FINAL_POR_MODELO] / ([TOTAL_GUIAS] - [TOTAL_DEVOLUCIONES]))
											WHEN [MODELOS_DE_CONTRATACION_FLOTA]=10
												THEN [COSTO_FINAL_POR_MODELO]
											WHEN [MODELOS_DE_CONTRATACION_FLOTA]=11			-------->VR_KILO_Y_CORTE_GUIA
												THEN [PAR].[VW_COSTOS_DARWIN_CALCULAR_Tarifas_COSTO_POR_RUTA_AEREA](LLAVE_ORIGEN_DESTINO,PERIODO_EJECUCION)*PESO_FISICO_GUIA						
											WHEN [MODELOS_DE_CONTRATACION_FLOTA]=14
												THEN	IIF( [COSTO_FINAL_POR_MODELO]=0 OR [TOTAL_GUIAS_DISTRIBUCION] - [TOTAL_DEVOLUCIONES]=0,0,
													[COSTO_FINAL_POR_MODELO] / ([TOTAL_GUIAS_DISTRIBUCION] - [TOTAL_DEVOLUCIONES]))

										ELSE @VALOR_Costo_Co_Sourcing_Operativos_131 END ) * [VD_DOBLE_COBRO]
