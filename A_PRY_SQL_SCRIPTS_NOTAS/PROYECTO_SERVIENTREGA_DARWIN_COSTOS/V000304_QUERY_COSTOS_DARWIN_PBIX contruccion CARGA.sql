,COSTO_FINAL_POR_MODELO = 
	  CASE 
			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=0 AND /*([ID_PROCESO]=5 OR [ID_PROCESO]=6)---CORREGIR A */ [ID_PROCESO] in(5,6)
						THEN [COMISION_RECOLECCION_EMPRESARIO]
			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=0 AND [ID_PROCESO] IN(9,24) 
						THEN [COMISION_DISTRIBUCION_EMPRESARIO]
			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=1 AND [TIPO_VEHICULO_PLACAS_PROPIAS]='SIN INFORMACION' 
						THEN	1010101010			----
			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=1 THEN  [KM_INSOURCING] * [COSTO_KM_IN_SOURCING]
			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=2 
				THEN IIF([Costo_Co_Sourcing_Zonas] IS NULL,
						IIF([Costo_Co_Sourcing_Operativos] IS NULL,
							--2222222222
							@VALOR_Costo_Co_Sourcing_Operativos_222,
							[Costo_Co_Sourcing_Operativos]),[Costo_Co_Sourcing_Zonas])

			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=3 
				THEN IIF([Costo_Promedio_Flete_Año_Actual] IS NULL,						
							--3333333333
							@VALOR_Costo_Co_Sourcing_Operativos_333,
							[Costo_Promedio_Flete_Año_Actual])
			WHEN [MODELOS_DE_CONTRATACION_FLOTA] IN (4,5,6) 
				THEN [PAR].[VW_COSTOS_DARWIN_CALCULAR_Tarifas_Productos_Por_Periodo](
																					 [PERIODO_EJECUCION]									--@ID_PERIODO 
																					,[MODELOS_DE_CONTRATACION_FLOTA]						--@ID_MODELO_CONTRATACION 
																					,ID_REGIONAL											--@ID_REGIONAL 
																					,[ID_PROCESO]											--@ID_PROCESO_LOGISTICO  
																					,[ID_PRODUCTO]											--@ID_PRODUCTO 
																					,([TOTAL_GUIAS_DISTRIBUCION] - [TOTAL_DEVOLUCIONES])	--@ID_CANT 
																					)

			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=7 THEN @VALOR_COSTO_Aux_Camioneta
			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=8 THEN @VALOR_COSTO_Currier_Moto
			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=9 THEN @VALOR_COSTO_Aux_Camioneta
			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=10 THEN [COMISION_RECOLECCION_EMPRESARIO] + [COMISION_DISTRIBUCION_EMPRESARIO]
			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=11 THEN 
													IIF(VR_KILO_Y_CORTE_GUIA IS NULL /*OR VR_KILO_Y_CORTE_GUIA < 1*/,
													@VALOR_Costo_Co_Sourcing_Operativos_111,
													(VR_KILO_Y_CORTE_GUIA * [PESO_FISICO_OPERA_DISTRIBUCION]))
			WHEN [MODELOS_DE_CONTRATACION_FLOTA]=14 AND [ID_PROCESO]=24 
				THEN [PAR].[VW_COSTOS_DARWIN_CALCULAR_Tarifas_Productos_Por_Periodo](
																					 [PERIODO_EJECUCION]									--@ID_PERIODO 
																					,[MODELOS_DE_CONTRATACION_FLOTA]						--@ID_MODELO_CONTRATACION 
																					,ID_REGIONAL											--@ID_REGIONAL 
																					,[ID_PROCESO]											--@ID_PROCESO_LOGISTICO  
																					,[ID_PRODUCTO]											--@ID_PRODUCTO 
																					,([TOTAL_GUIAS_DISTRIBUCION] - [TOTAL_DEVOLUCIONES]) /**/		--@ID_CANT 
																				)
			ELSE 
			@VALOR_Costo_Co_Sourcing_Operativos_131
			END
into #validar_tabla_temporal_02
