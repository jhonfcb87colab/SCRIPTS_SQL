LEFT JOIN [ACCES_DARWIN].[dbo].[VW_3C_Costo_Flete_Por_Placa_Promedio_Año_Actual] VW_3C_Costo_Flete (NOLOCK) ON VW_3C_Costo_Flete.PLACA=TMP01.PLACA_VEHICULO_DOCU
