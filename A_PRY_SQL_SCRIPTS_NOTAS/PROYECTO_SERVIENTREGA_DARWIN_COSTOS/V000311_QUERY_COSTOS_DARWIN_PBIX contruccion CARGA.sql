,NOMBRE_REGIONAL_DESTINO = DIMGEO_DES.[NOMBRE_REGIONAL]
,COSTO_FINAL_POR_MODELO = 
	  CASE 
			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=0 AND (TMP01.[ID_PROCESO] in(5,6))
						THEN TMP01.[COMISION_RECOLECCION_EMPRESARIO]
			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=0 AND (TMP01.[ID_PROCESO] IN(9,24)) 
						THEN TMP01.[COMISION_DISTRIBUCION_EMPRESARIO]
			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=1 AND TMP01.[TIPO_VEHICULO_PLACAS_PROPIAS]='SIN INFORMACION' 
						THEN @VALOR_Costo_Co_Sourcing_Operativos_101	----1010101010			----
			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=1 THEN  TMP01.[KM_INSOURCING] * TMP01.[COSTO_KM_IN_SOURCING]
			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=2 
				THEN IIF(TMP01.[Costo_Co_Sourcing_Zonas] IS NULL,
						IIF(TMP01.[Costo_Co_Sourcing_Operativos] IS NULL,
							--2222222222
							@VALOR_Costo_Co_Sourcing_Operativos_222,
							TMP01.[Costo_Co_Sourcing_Operativos]),TMP01.[Costo_Co_Sourcing_Zonas])

			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=3 
				THEN IIF(TMP01.[Costo_Promedio_Flete_Año_Actual] IS NULL,						
							--3333333333
							@VALOR_Costo_Co_Sourcing_Operativos_333,
							TMP01.[Costo_Promedio_Flete_Año_Actual])
			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA] IN (4,5,6) 
				THEN [ACCCES_DARWIN].[PAR].[VW_COSTOS_DARWIN_CALCULAR_Tarifas_Productos_Por_Periodo](
																					 TMP01.[PERIODO_EJECUCION]									--@ID_PERIODO 
																					,TMP01.[MODELOS_DE_CONTRATACION_FLOTA]						--@ID_MODELO_CONTRATACION 
																					,TMP01.ID_REGIONAL											--@ID_REGIONAL 
																					,TMP01.[ID_PROCESO]											--@ID_PROCESO_LOGISTICO  
																					,TMP01.ID_PRODUCTO_CST											--@ID_PRODUCTO 
																					,(TMP01.[TOTAL_GUIAS_DISTRIBUCION] - TMP01.[TOTAL_DEVOLUCIONES])	--@ID_CANT 
																					)

			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=7 THEN @VALOR_COSTO_Aux_Camioneta
			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=8 THEN @VALOR_COSTO_Currier_Moto
			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=9 THEN @VALOR_COSTO_Aux_Camioneta
			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=10 THEN [COMISION_RECOLECCION_EMPRESARIO] + [COMISION_DISTRIBUCION_EMPRESARIO]
			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=11 THEN 
													IIF(TMP01.VR_KILO_Y_CORTE_GUIA IS NULL /*OR VR_KILO_Y_CORTE_GUIA < 1*/,
													@VALOR_Costo_Co_Sourcing_Operativos_111,
													(TMP01.VR_KILO_Y_CORTE_GUIA * TMP01.[PESO_FISICO_OPERA_DISTRIBUCION]))
			WHEN TMP01.[MODELOS_DE_CONTRATACION_FLOTA]=14 AND TMP01.[ID_PROCESO]=24 
				THEN [ACCCES_DARWIN].[PAR].[VW_COSTOS_DARWIN_CALCULAR_Tarifas_Productos_Por_Periodo](
																					 TMP01.[PERIODO_EJECUCION]									--@ID_PERIODO 
																					,TMP01.[MODELOS_DE_CONTRATACION_FLOTA]						--@ID_MODELO_CONTRATACION 
																					,TMP01.ID_REGIONAL											--@ID_REGIONAL 
																					,TMP01.[ID_PROCESO]											--@ID_PROCESO_LOGISTICO  
																					,TMP01.ID_PRODUCTO_CST											--@ID_PRODUCTO 
																					,(TMP01.[TOTAL_GUIAS_DISTRIBUCION] - TMP01.[TOTAL_DEVOLUCIONES]) /**/		--@ID_CANT 
																				)
			ELSE 
			@VALOR_Costo_Co_Sourcing_Operativos_131
			END
into #validar_tabla_temporal_02
FROM #validar_tabla_temporal_01 TMP01
LEFT JOIN [ACCCES_DARWIN].[PAR].[DIM_GEO_CIUDAD_MUNICIPIO_REGIONAL] DIMGEO_ORG (NOLOCK) ON TMP01.LL_ORG_=DIMGEO_ORG.[CODIGO_DANE] 
