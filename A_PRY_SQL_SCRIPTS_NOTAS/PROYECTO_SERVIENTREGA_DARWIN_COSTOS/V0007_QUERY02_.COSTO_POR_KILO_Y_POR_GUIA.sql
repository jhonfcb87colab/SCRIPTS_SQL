,T2.[COSTO POR 1 KG]
,T2.[COSTO POR GUIA]
,T3.[PESO PONDERADO]
INTO #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_04
FROM #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_03 T1
INNER JOIN #COSTO_POR_1_KG T2
ON T1.NOMBRE_PRODUCTO=T2.NOMBRE_PRODUCTO
   AND T1.CANAL=T2.CANAL
   AND T1.NOMBRE_PROCESO_LOG=T2.NOMBRE_PROCESO_LOG
   AND T1.[Año-Mes]=T2.[Año-Mes]
INNER JOIN #PESO_PONDERADO T3
ON T1.NOMBRE_PRODUCTO=T3.NOMBRE_PRODUCTO
   AND T1.CANAL=T3.CANAL
   AND T1.NOMBRE_PROCESO_LOG=T3.NOMBRE_PROCESO_LOG
   AND T1.[Año-Mes]=T3.[Año-Mes]

