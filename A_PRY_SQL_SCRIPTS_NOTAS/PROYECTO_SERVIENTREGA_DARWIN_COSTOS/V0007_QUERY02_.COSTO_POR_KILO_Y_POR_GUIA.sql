DROP TABLE IF EXISTS #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_01;
SELECT 
/*APLICA*/
/*NO*/		 CTA.PERIODO_EJECUCION
/*SI*/		,[NOMBRE_PRODUCTO] = CTA.NOMBRE_PRODUCTO	
/*SI*/		,[CANAL]	= CTA.CANAL
/*SI*/		,[NOMBRE_PROCESO_LOG] = CTA.NOMBRE_PROCESO_LOG
/*SI*/		,[MODELO_CONTRATACION_UTILIZADO] = CTA.PROPIETARIO_VEHICULO	
/*ok*/		,[REGISTROS_MES] = CONVERT(FLOAT,Registros_Evaluados_Sum)	
/*ok*/		,[PROMEDIO_PESO_GUIA] = CONVERT(FLOAT,CTA.PESO_FISICO_GUIA_Mean)
/*ok*/		,[DESVIACION_PESO_GUIA] = CONVERT(FLOAT,CTA.PESO_FISICO_GUIA_Std)
/*ok*/		,[Q3_CUARTIL_DE_PESO_GUIA] = CONVERT(FLOAT,CTA.PESO_FISICO_GUIA_Q75)
/*ok*/		,[COSTO_PROMEDIO_EN_KILOS] = CONVERT(FLOAT,CTA.COSTO_GUIA_MAS_AUXILIAR_POR_PESO_Mean)	
/*ok*/		,[DESVIACION_COSTO_EN_KILOS] = CONVERT(FLOAT,CTA.COSTO_GUIA_MAS_AUXILIAR_POR_PESO_Std)	
/*ok*/		,[Q3_CUARTIL_DE_COSTO_EN KILOS] = CONVERT(FLOAT,CTA.COSTO_GUIA_MAS_AUXILIAR_POR_PESO_Q75)	
/*ok*/		,[COSTO_PROMEDIO_POR_GUIA] = CONVERT(FLOAT,CTA.COSTO_GUIA_MAS_AUXILIAR_POR_GUIA_Mean)
/*ok*/		,[DESVIACION_COSTO_POR_GUIA] = CONVERT(FLOAT,CTA.COSTO_GUIA_MAS_AUXILIAR_POR_GUIA_Std)
/*ok*/		,[Q3_CUARTIL_DE_COSTO_POR_GUIA] = CONVERT(FLOAT,CTA.COSTO_GUIA_MAS_AUXILIAR_POR_GUIA_Q75)
/*ok*/		,[FECHA] = CONVERT(DATETIME,CONVERT(VARCHAR(15),(CTA.PERIODO_EJECUCION*100+1)))
/*OK*/		,[Año-Mes] = CONCAT(YEAR(CONVERT(DATETIME,CONVERT(VARCHAR(15),(CTA.PERIODO_EJECUCION*100+1)))),'',MONTH(CONVERT(DATETIME,CONVERT(VARCHAR(15),(CTA.PERIODO_EJECUCION*100+1)))))	
INTO #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_01
FROM [FAC].[COSTO_DARWIN_RESUMEN_ANALITICA]  CTA (NOLOCK)

DROP TABLE IF EXISTS #TOTALES_AGRUPADOS_PRODUCTO_CANAL_PROCESO_FECHA
SELECT 
        NOMBRE_PRODUCTO,
        CANAL,
        NOMBRE_PROCESO_LOG,
        [Año-Mes],
        SUM(REGISTROS_MES) AS TOTALES_AGRUPADOS_PRODUCTO_CANAL_PROCESO_FECHA
		INTO #TOTALES_AGRUPADOS_PRODUCTO_CANAL_PROCESO_FECHA
    FROM 
        #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_01
    GROUP BY 
        NOMBRE_PRODUCTO,
        CANAL,
        NOMBRE_PROCESO_LOG,
        [Año-Mes]



DROP TABLE IF EXISTS #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_02;
SELECT T1.*
,T2.TOTALES_AGRUPADOS_PRODUCTO_CANAL_PROCESO_FECHA
,[% PART] = ( T1.REGISTROS_MES / T2.TOTALES_AGRUPADOS_PRODUCTO_CANAL_PROCESO_FECHA)
INTO #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_02
FROM #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_01 T1
INNER JOIN #TOTALES_AGRUPADOS_PRODUCTO_CANAL_PROCESO_FECHA T2
ON T1.NOMBRE_PRODUCTO=T2.NOMBRE_PRODUCTO
   AND T1.CANAL=T2.CANAL
   AND T1.NOMBRE_PROCESO_LOG=T2.NOMBRE_PROCESO_LOG
   AND T1.[Año-Mes]=T2.[Año-Mes]

DROP TABLE IF EXISTS #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_03
SELECT T1.*
,COSTO_POR_PART_POR_KG	= ([Q3_CUARTIL_DE_COSTO_EN KILOS]  / [Q3_CUARTIL_DE_PESO_GUIA]) * [% PART]
,COSTO_POR_PART_POR_GUIA = ([Q3_CUARTIL_DE_COSTO_POR_GUIA] * [% PART])
,[PESO POR PART PONDERADO] = [Q3_CUARTIL_DE_PESO_GUIA] * [% PART]
INTO #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_03
FROM #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_02 T1


DROP TABLE IF EXISTS #COSTO_POR_1_KG
SELECT 
        NOMBRE_PRODUCTO
        ,CANAL
        ,NOMBRE_PROCESO_LOG
        ,[Año-Mes]
        ,[COSTO POR 1 KG] = (SUM([COSTO_POR_PART_POR_KG]))
		,[COSTO POR GUIA] = (SUM([COSTO_POR_PART_POR_GUIA])) 
		INTO #COSTO_POR_1_KG
    FROM #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_03
    GROUP BY 
        NOMBRE_PRODUCTO,
        CANAL,
        NOMBRE_PROCESO_LOG,
        [Año-Mes]


DROP TABLE IF EXISTS #PESO_PONDERADO
SELECT 
        NOMBRE_PRODUCTO
        ,CANAL
        ,NOMBRE_PROCESO_LOG
        ,[Año-Mes]
		,[PESO PONDERADO] = (SUM([PESO POR PART PONDERADO]))
		INTO #PESO_PONDERADO
    FROM #FAC_COSTO_DARWIN_RESUMEN_ANALITICA_03
    GROUP BY 
        NOMBRE_PRODUCTO,
        CANAL,
        NOMBRE_PROCESO_LOG,
        [Año-Mes]



