ALTER FUNCTION [PAR].[VW_COSTOS_DARWIN_CALCULAR_Tarifas_COSTO_POR_RUTA_AEREA]( 
 @LLAVE_ORIGEN_DESTINO VARCHAR(50),
 @PERIODO_ID INT
)RETURNS INT		 
AS 

BEGIN 

--DECLARE @LLAVE_ORIGEN_DESTINO VARCHAR(100) = '11001000 - 05001000';
--DECLARE @PERIODO_ID INT = 202412;
DECLARE @RESULT INT = 0;

	IF 	@LLAVE_ORIGEN_DESTINO <> '' OR @LLAVE_ORIGEN_DESTINO IS not NULL
	BEGIN 
		SET @RESULT	= (
			SELECT ISNULL(MAX([VR_KILO_Y_CORTE_GUIA]),0) FROM [ACCCES_DARWIN].[dbo].[COSTO POR RUTA AEREA] 
					WHERE [KEY_ORIGEN_DESTINO_AEREO]=@LLAVE_ORIGEN_DESTINO AND PERIODO_ID=@PERIODO_ID
					)

   END 
   --PRINT @RESULT 
/**/
   RETURN @RESULT 
END

