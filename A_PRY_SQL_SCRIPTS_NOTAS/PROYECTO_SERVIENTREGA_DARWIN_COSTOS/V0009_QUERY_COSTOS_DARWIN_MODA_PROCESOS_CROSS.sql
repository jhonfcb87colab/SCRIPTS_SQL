G.ID_CIUDAD_DESTINO
FROM MECE_LOGISTICO.DBO.GUIAS G (NOLOCK)
--LEFT JOIN [Mece_Logistico].[dbo].[GUIAS_INF_ANTICIPADA] GUI (NOLOCK) ON GUI.NUMERO_GUIA=G.NUMERO_GUIA
WHERE 
G.FECHA_ENVIO BETWEEN @FECHA_INI AND @FECHA_FIN
AND LEN(G.NUMERO_GUIA)>7
OPTION(RECOMPILE, OPTIMIZE FOR UNKNOWN, MAXDOP 4)
