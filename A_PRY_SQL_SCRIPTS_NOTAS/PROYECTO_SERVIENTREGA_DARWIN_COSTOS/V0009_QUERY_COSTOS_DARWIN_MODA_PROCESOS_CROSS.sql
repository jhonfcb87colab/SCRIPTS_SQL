DECLARE @PERIODO INT = 202412;
DECLARE @FECHA_INI DATETIME, @FECHA_FIN DATETIME;
SET @FECHA_INI = CONVERT(DATETIME,CONCAT(CONVERT(VARCHAR(6),@PERIODO),'01'))
SET @FECHA_FIN = CONVERT(DATETIME,DATEADD(MONTH,1,@FECHA_INI))

IF OBJECT_ID('tempdb..#TMP_INFORMACION_MODA_ORIGEN_DESTINO_BI') IS NOT NULL	
    DROP TABLE #TMP_INFORMACION_MODA_ORIGEN_DESTINO_BI

