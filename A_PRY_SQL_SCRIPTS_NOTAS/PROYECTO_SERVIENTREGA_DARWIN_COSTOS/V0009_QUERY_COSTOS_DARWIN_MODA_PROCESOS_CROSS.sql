CASE WHEN LEN(MONTH(G.FECHA_ENVIO))=1 THEN '0'+ CAST(MONTH(G.FECHA_ENVIO) AS VARCHAR) ELSE CAST(MONTH(G.FECHA_ENVIO) AS VARCHAR) END,
G.ID_ESTADOENVIO,
