DROP TABLE IF EXISTS #TMP_INFORMACION_GUIAS_MODA_PROCESOS_CROSS_BI; 
SELECT 
(CAST(TMPGUI.AÑO AS NVARCHAR) +'-' + CAST(CASE WHEN LEN(TMPGUI.MES) = 1 THEN '0' + CAST(TMPGUI.MES AS NVARCHAR) ELSE CAST(TMPGUI.MES  AS NVARCHAR) END  AS NVARCHAR)) AS AÑO_MES
--TMPGUI.NOMBRE_TIPOTRAY
,DANE_ORIGEN_DESTINO
,ODM.CANT_MOVI_CROSS AS MODA_MOVIMIENTOS_CROSS
--,SUM(ODM.CANT_MOVI_CROSS*COUNT(TMPGUI.NUMERO_GUIA)) AS MOV_CROSS_ESPERADOS
,SUM(TMPGUI.CANT_MOVI_CROSS) AS CANTIDAD_MOVIMIENTOS_CROSS
,COUNT(TMPGUI.NUMERO_GUIA) AS NUMERO_GUIAS
,SUM(TMPGUI.NUMERO_PIEZAS) AS NUMERO_PIEZAS
,TMPGUI.ID_CIUDAD_ORIGEN
,CIUORI.NOMBRE_CIUDAD AS NOMBRE_CIUDAD_ORIGEN
,TMPGUI.ID_CIUDAD_DESTINO
,CIUDES.NOMBRE_CIUDAD AS NOMBRE_CIUDAD_DESTINO
INTO #TMP_INFORMACION_GUIAS_MODA_PROCESOS_CROSS_BI
FROM #TMP_INFORMACION_GUIAS_BI TMPGUI
INNER JOIN PARAMETROS.DBO.CIUDADES CIUORI (NOLOCK) ON CIUORI.ID_PAIS = 1 AND CIUORI.ID_CIUDAD = TMPGUI.ID_CIUDAD_ORIGEN
INNER JOIN PARAMETROS.DBO.CIUDADES CIUDES (NOLOCK) ON CIUDES.ID_PAIS = 1 AND CIUDES.ID_CIUDAD = TMPGUI.ID_CIUDAD_DESTINO
LEFT JOIN #TMP_INFORMACION_MODA_ORIGEN_DESTINO_BI ODM (NOLOCK) ON ODM.ID_CIUDAD_ORIGEN=TMPGUI.ID_CIUDAD_ORIGEN AND ODM.ID_CIUDAD_DESTINO=TMPGUI.ID_CIUDAD_DESTINO
--WHERE TMPGUI.ID_CIUDAD_ORIGEN=10 AND TMPGUI.ID_CIUDAD_DESTINO=10
--WHERE TMPGUI.AÑO=12 AND TMPGUI.MES=12
GROUP BY TMPGUI.DANE_ORIGEN_DESTINO,TMPGUI.ID_CIUDAD_ORIGEN,TMPGUI.ID_CIUDAD_DESTINO,CIUORI.NOMBRE_CIUDAD,CIUDES.NOMBRE_CIUDAD,ODM.CANT_MOVI_CROSS
	,(CAST(TMPGUI.AÑO AS NVARCHAR) +'-' + CAST(CASE WHEN LEN(TMPGUI.MES) = 1 THEN '0' + CAST(TMPGUI.MES AS NVARCHAR) ELSE CAST(TMPGUI.MES  AS NVARCHAR) END  AS NVARCHAR))
ORDER BY (CAST(TMPGUI.AÑO AS NVARCHAR) +'-' + CAST(CASE WHEN LEN(TMPGUI.MES) = 1 THEN '0' + CAST(TMPGUI.MES AS NVARCHAR) ELSE CAST(TMPGUI.MES  AS NVARCHAR) END  AS NVARCHAR)),
TMPGUI.ID_CIUDAD_ORIGEN,TMPGUI.ID_CIUDAD_DESTINO ASC
OPTION(RECOMPILE, OPTIMIZE FOR UNKNOWN, MAXDOP 4)
