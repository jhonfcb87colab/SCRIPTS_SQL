NOMBRE_TIPOTRAY VARCHAR(40) DEFAULT '',
CANT_MOVI_CROSS INT  DEFAULT 0)

CREATE NONCLUSTERED INDEX IX_CIUDAD ON #TMP_INFORMACION_MODA_ORIGEN_DESTINO_BI (ID_CIUDAD_ORIGEN,ID_CIUDAD_DESTINO)


