USE Mece_Logistico;

DECLARE @FEC_INI	DATETIME	= CONVERT(DATETIME,'20241202');  
DECLARE @FEC_FIN	DATETIME	= DATEADD(DAY,1,@FEC_INI);--'2024-12-03' --'2024-12-04'

DROP TABLE IF EXISTS #TABLA_TEMPORAL_PRODUCTIVIDAD_PASO_01
DROP TABLE IF EXISTS #GUIAS_EVALUAR_PRODUCTIVIDAD_PASO2;
DROP TABLE IF EXISTS #GUIAS_EVALUAR_PRODUCTIVIDAD_PASO_03;
DROP TABLE IF EXISTS #GUIAS_EVALUAR_PRODUCTIVIDAD_EMPLEADO_PASO_04;
DROP TABLE IF EXISTS #GUIAS_EVALUAR_PRODUCTIVIDAD_CIUDAD_PASO_05;
DROP TABLE IF EXISTS #GUIAS_EVALUAR_PRODUCTIVIDAD_NOMBREZONA_PASO_06;

SELECT 
ID_EMPLEADO
,CONCAT(NOMBRE_EMPLEADO,' ',APELLIDO_EMPLEADO) AS NOMBRE_EMPLEADO
INTO #GUIAS_EVALUAR_PRODUCTIVIDAD_EMPLEADO_PASO_04
FROM PARAMETROS..EMPLEADOS (NOLOCK)

SELECT CD.ID_CIUDAD,CD.NOMBRE_CIUDAD,CD.ID_REGIONAL,RG.NOMBRE_REGIONAL 
INTO #GUIAS_EVALUAR_PRODUCTIVIDAD_CIUDAD_PASO_05
FROM PARAMETROS..CIUDADES CD (NOLOCK)
INNER JOIN PARAMETROS..REGIONALES_PAIS RG (NOLOCK) 
ON CD.ID_REGIONAL=RG.ID_REGIONAL

SELECT 
ID_PAIS	
,ID_CIUDAD	
,ID_TIPO_ZONA_URBA	
,ID_ZONA_URBA	
,NOMBRE_ZONA_URBA	
,CATEGORIA_ZONA_URBA
INTO #GUIAS_EVALUAR_PRODUCTIVIDAD_NOMBREZONA_PASO_06
FROM PARAMETROS.DBO.ZONASURBANAS (NOLOCK) WHERE ID_PAIS=1

;WITH CTE AS (
SELECT 
ROW_NUMBER ( )   OVER ( PARTITION BY SEG.[NUMERO_GUIA] order by SEG.FECHA_HORA_MOVIMIENTO desc )  #ROW_ID_SE
,DOC.ID_AUXILIAR1_VEHICULO
,DOC.ID_AUXILIAR2_VEHICULO
,DOC.ID_COURIER_CONDUCTOR
,SEG.NUMERO_GUIA 
,SEG.FECHA_HORA_MOVIMIENTO
,SEG.ID_PROCESO
,SEG.NUMERO_MOVIMI
,SEG.CONSECUT_MOVIMI
,DOC.ID_CIUDAD_DIVISION_ORIGEN
,DOC.ID_CIUDAD_ZONA_URBA
,DOC.ID_ZONA_URBA
,DOC.ID_TIPO_ZONA_URBA
,DOC.ID_TIPO_LOGISTICA
,SEG.NUMERO_PIEZAS
FROM Mece_Logistico.DBO.SEGUIMIENTO_ENVIO SEG (NOLOCK)
INNER JOIN  MECE_LOGISTICO.DBO.DOCUMENTOS DOC WITH (NOLOCK) 
ON SEG.ID_PROCESO=DOC.ID_PROCESO 
AND SEG.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI 
AND SEG.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI
WHERE 
SEG.ID_PROCESO=9 
AND SEG.ID_CONCEPTO NOT IN (7,8,9,10)----SE DESCARTA TODAS LAS SALIDA A EMPRESARIO SATELITE
--AND FECHA_HORA_MOVIMIENTO BETWEEN /*@FEC_INI AND @FEC_FIN   ---*/'2024-12-02' AND '2024-12-03'
AND (FECHA_HORA_MOVIMIENTO >= @FEC_INI AND FECHA_HORA_MOVIMIENTO < @FEC_FIN) 
--AND DOC.ID_CIUDAD_DIVISION_ORIGEN = 10
AND LEFT(SEG.[NUMERO_GUIA],1) NOT IN (5) ---SE TOMARA GUIAS DIFERENTES A 5 GUIAS INTERNAS
)
SELECT 
* 
INTO #TABLA_TEMPORAL_PRODUCTIVIDAD_PASO_01
FROM CTE WHERE #ROW_ID_SE=1

--SELECT * FROM #TABLA_TEMPORAL_PRODUCTIVIDAD_PASO_01

SELECT NUMERO_GUIA 
INTO #GUIAS_EVALUAR_PRODUCTIVIDAD_PASO2
FROM #TABLA_TEMPORAL_PRODUCTIVIDAD_PASO_01
GROUP BY NUMERO_GUIA

--SELECT * FROM #GUIAS_EVALUAR_PRODUCTIVIDAD_PASO2

;WITH CTE AS (
SELECT 
ROW_NUMBER ( )   OVER ( PARTITION BY TMP.[NUMERO_GUIA] order by SEG.FECHA_HORA_MOVIMIENTO desc )  #ROW_ID_SE
,SEG.NUMERO_GUIA
,SEG.FECHA_HORA_MOVIMIENTO 
,SEG.NUMERO_MOVIMI
,SEG.CONSECUT_MOVIMI
,SEG.ID_PROCESO
FROM MECE_LOGISTICO.DBO.SEGUIMIENTO_ENVIO SEG (NOLOCK)
INNER JOIN #GUIAS_EVALUAR_PRODUCTIVIDAD_PASO2 TMP ON TMP.NUMERO_GUIA=SEG.NUMERO_GUIA
WHERE SEG.ID_PROCESO=11 
AND (SEG.FECHA_HORA_MOVIMIENTO >= @FEC_INI AND SEG.FECHA_HORA_MOVIMIENTO < DATEADD(HOUR,7,@FEC_FIN))   --DATEADD('HOUR',4,@FEC_FIN)
)
SELECT CT.* 
INTO #GUIAS_EVALUAR_PRODUCTIVIDAD_PASO_03 
FROM CTE CT 
WHERE CT.#ROW_ID_SE=1

