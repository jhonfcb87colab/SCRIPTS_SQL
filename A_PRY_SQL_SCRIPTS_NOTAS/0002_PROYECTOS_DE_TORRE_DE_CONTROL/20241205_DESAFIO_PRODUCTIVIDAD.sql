,TBL_00.NUMERO_GUIA	
,TBL_00.FECHA_HORA_MOVIMIENTO	AS FECHA_HORA_MOVIMIENTO_SZU
,TBL_00.ID_PROCESO	
,TBL_00.NUMERO_MOVIMI	
,TBL_00.CONSECUT_MOVIMI	
,TBL_00.ID_CIUDAD_DIVISION_ORIGEN	AS ID_CIUDAD_ORG
,CIUD.NOMBRE_CIUDAD
,CIUD.ID_REGIONAL
,CIUD.NOMBRE_REGIONAL
,TBL_00.ID_ZONA_URBA
,TBL_00.ID_CIUDAD_ZONA_URBA
,TBL_00.ID_TIPO_ZONA_URBA
,ZURB.NOMBRE_ZONA_URBA
,TBL_00.ID_TIPO_LOGISTICA	
,TBL_00.NUMERO_PIEZAS
------------------------------------------
,TBL_01.FECHA_HORA_MOVIMIENTO as FECHA_ENTREGA_VERIFICADA
,TBL_01.CONSECUT_MOVIMI AS CONSECUT_MOVIMI_EV
,TBL_01.NUMERO_MOVIMI AS NUMERO_MOVIMI_EV
,TBL_01.ID_PROCESO AS ID_PROCESO_EV
,PRB.TIPO_PRUEBA_ENTREGA
,CASE WHEN PRB.TIPO_PRUEBA_ENTREGA=2 THEN 'VIRTUAL'
	WHEN PRB.TIPO_PRUEBA_ENTREGA=1 THEN 'FISICA'
	ELSE 'NO DISPONIBLE' END AS TIPO_PRUEBA_ENTREGA_GENERADA
	,CASE WHEN TBL_00.NUMERO_MOVIMI=TBL_01.NUMERO_MOVIMI THEN 'SI' ELSE 'NO' END AS CUMPLE_PRODUCTIVIDAD
	,GETDATE() FECHA_GENERACION_REP
	INTO #CONSOLIDADO_PRODUCTIVIDAD_FINAL_POR_DIA_BI
FROM #TABLA_TEMPORAL_PRODUCTIVIDAD_PASO_01 TBL_00
LEFT JOIN #GUIAS_EVALUAR_PRODUCTIVIDAD_PASO_03 TBL_01
ON TBL_00.NUMERO_GUIA=TBL_01.NUMERO_GUIA
LEFT JOIN [tmp_borrar_local].[dbo].[PRUEBAS_ENTREGA_BI] PRB ON PRB.NUMERO_GUIA=TBL_00.NUMERO_GUIA
LEFT JOIN #GUIAS_EVALUAR_PRODUCTIVIDAD_EMPLEADO_PASO_04 EMPL01 ON EMPL01.ID_EMPLEADO=TBL_00.ID_AUXILIAR1_VEHICULO
LEFT JOIN #GUIAS_EVALUAR_PRODUCTIVIDAD_EMPLEADO_PASO_04 EMPL02 ON EMPL02.ID_EMPLEADO=TBL_00.ID_AUXILIAR2_VEHICULO
LEFT JOIN #GUIAS_EVALUAR_PRODUCTIVIDAD_EMPLEADO_PASO_04 EMPL03 ON EMPL03.ID_EMPLEADO=TBL_00.ID_COURIER_CONDUCTOR
INNER JOIN #GUIAS_EVALUAR_PRODUCTIVIDAD_CIUDAD_PASO_05 CIUD ON CIUD.ID_CIUDAD=TBL_00.ID_CIUDAD_DIVISION_ORIGEN
LEFT JOIN #GUIAS_EVALUAR_PRODUCTIVIDAD_NOMBREZONA_PASO_06 ZURB 
			ON (ZURB.ID_CIUDAD=TBL_00.ID_CIUDAD_ZONA_URBA 
			AND ZURB.ID_ZONA_URBA=TBL_00.ID_ZONA_URBA 
			AND ZURB.ID_TIPO_ZONA_URBA=TBL_00.ID_TIPO_ZONA_URBA)
----WHERE TBL_00.NUMERO_MOVIMI=TBL_01.NUMERO_MOVIMI AND TBL_00.ID_AUXILIAR1_VEHICULO='80825271'


