SELECT 
(YEAR(TBL_00.FECHA_HORA_MOVIMIENTO)*100+MONTH(TBL_00.FECHA_HORA_MOVIMIENTO))*100+DAY(TBL_00.FECHA_HORA_MOVIMIENTO) DIA_PRODUCTIVIDAD
,TBL_00.#ROW_ID_SE	
