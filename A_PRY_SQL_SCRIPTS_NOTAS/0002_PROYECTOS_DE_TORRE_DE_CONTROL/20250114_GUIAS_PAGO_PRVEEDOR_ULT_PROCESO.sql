DROP TABLE IF EXISTS #GUIAS_ORLANDO_SOLICITUD;
DROP TABLE IF EXISTS #ULTIMO_PROCESO_LOG;
CREATE TABLE #GUIAS_ORLANDO_SOLICITUD([NUMERO_GUIA] [numeric](20, 0) )
CREATE NONCLUSTERED INDEX [IdxNUMGuia] ON #GUIAS_ORLANDO_SOLICITUD
(
	[NUMERO_GUIA] ASC
)WITH (PAD_INDEX = OFF, STATISTICS_NORECOMPUTE = OFF, SORT_IN_TEMPDB = OFF, DROP_EXISTING = OFF, ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON)
GO
INSERT INTO #GUIAS_ORLANDO_SOLICITUD
SELECT [NUMERO_GUIAS]  
  FROM [TMP_BORRAR].[TMP].[GUIAS_SOLICITUD_ORLANDO] (NOLOCK)

;WITH CTE AS(
SELECT 
ROW_ID = ROW_NUMBER() OVER(PARTITION BY SE.NUMERO_GUIA ORDER BY SE.FECHA_HORA_MOVIMIENTO DESC),
SE.NUMERO_GUIA,
SE.NUMERO_MOVIMI,
SE.ID_PROCESO,
SE.CONSECUT_MOVIMI,
SE.FECHA_HORA_MOVIMIENTO
FROM [SIG_COLOMBIA_DW].LOG.SEGUIMIENTO_ENVIO SE (NOLOCK)
INNER JOIN #GUIAS_ORLANDO_SOLICITUD TMP ON TMP.NUMERO_GUIA=SE.NUMERO_GUIA
)
SELECT * 
INTO #ULTIMO_PROCESO_LOG
FROM CTE WHERE ROW_ID=1

SELECT ult.*, 
DOC.ID_CIUDAD_CANAL,
DOC.ID_CIUDAD_ZONA_URBA,
DOC.ID_CIUDAD_DIVISION_ORIGEN,
DOC.ID_CIUDAD_DESTINO,
DOC.ID_DIVISION_ORIGEN,
DOC.ID_DIVISION_DESTINO,
DOC.PLACA_VEHICULO_DOCU,
DOC.ID_AUXILIAR1_VEHICULO,
DOC.ID_AUXILIAR2_VEHICULO,
DOC.ID_COURIER_CONDUCTOR
FROM #ULTIMO_PROCESO_LOG ult
	LEFT JOIN  SIG_COLOMBIA_DW.LOG.DOCUMENTOS DOC WITH (NOLOCK) 
	ON ult.ID_PROCESO=DOC.ID_PROCESO AND ult.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND ult.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI