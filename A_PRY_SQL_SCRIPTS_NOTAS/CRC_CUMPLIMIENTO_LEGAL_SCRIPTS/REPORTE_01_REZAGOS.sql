			iif((T.DOC_ID_CIUDAD_DESTINO_FINAL_SALIDA_CPL <> T.G_ID_CIUDAD_ORIGEN AND T.DOC_ID_CIUDAD_DESTINO_FINAL_SALIDA_CPL <> T.G_ID_CIUDAD_DESTINO),1,0) 
			ELSE 0 END AS INTENTOS_UBICACION_ERRONEA
,CASE 
		WHEN (T.G_ID_CIUDAD_DESTINO IS NULL OR  T.G_ID_CIUDAD_ORIGEN IS NULL OR  T.DOC_ID_CIUDAD_DESTINO_FINAL_SALIDA_CPL IS NULL)
			THEN 
			1
			ELSE 0 END AS INTENTOS_SIN_UBICACION

