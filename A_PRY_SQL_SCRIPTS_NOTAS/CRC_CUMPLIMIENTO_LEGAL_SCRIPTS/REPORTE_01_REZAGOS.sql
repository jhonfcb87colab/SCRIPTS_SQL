,INTENTOS_AL_REMITENTE	= CASE WHEN INTENTOS_LOCALES_CIUDAD>=1 THEN 
																		CASE 
																			WHEN CONTADOR__TOTAL_SZU = 1 THEN 0
																			WHEN CONTADOR__TOTAL_SZU = 2 THEN 1 ------ SE ASIGNA TAMBIEN 1 AL REMITENTE
																			WHEN CONTADOR__TOTAL_SZU >2 THEN CONTADOR__TOTAL_SZU-2  ----- EL RESTO SE LE ASIGNA AL REMITENTE
																			ELSE INTENTOS_AL_REMITENTE
																			END 
