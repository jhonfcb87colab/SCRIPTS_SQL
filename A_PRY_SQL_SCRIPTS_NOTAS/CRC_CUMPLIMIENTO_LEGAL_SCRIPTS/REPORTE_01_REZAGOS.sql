		WHEN (T.DOC_ID_CIUDAD_DESTINO_FINAL_SALIDA_CPL <> T.G_ID_CIUDAD_DESTINO OR T.DOC_ID_CIUDAD_DESTINO_FINAL_SALIDA_CPL <> T.G_ID_CIUDAD_ORIGEN OR T.G_ID_CIUDAD_DESTINO <> T.G_ID_CIUDAD_ORIGEN )
