,CASE 
		WHEN (T.G_ID_CIUDAD_DESTINO=T.DOC_ID_CIUDAD_DESTINO_FINAL_SALIDA_CPL) AND (T.G_ID_CIUDAD_ORIGEN <> T.DOC_ID_CIUDAD_DESTINO_FINAL_SALIDA_CPL)
