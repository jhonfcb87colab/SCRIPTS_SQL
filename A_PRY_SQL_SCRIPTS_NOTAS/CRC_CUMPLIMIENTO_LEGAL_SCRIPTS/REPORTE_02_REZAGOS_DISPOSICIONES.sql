/****** Script for SelectTopNRows command from SSMS  ******/
SELECT TOP (1000) [ANNO]
      ,[NUMERO_CONSECUTIVO_OPERACION]
      ,[NUM_PRUEBA_ADMISION_O_NUM_GUIA]
      ,[FECHA_IMPOSICION]
      ,[INTENTOS_ENTREGA_DESTINATARIO]
      ,[INTENTOS_DEVOLUCION_REMITENTE]
      ,[MOTIVO_NO_ENTREGA_DESTINATARIO]
      ,[FECHA_DECLARACION_REZAGO]
      ,[MODALIDAD_SERVICIO_POSTAL]
      ,[DESCRIPCION_OBJETO_REZAGO]
      ,[PENDIENTE_DISPOSICION_OBJETO_REZAGO]
      ,[PENDIENTE_ENTIDAD_BENEFICIADA]
      ,[*****SEPARADOR********]
      ,[NOVEDAD_INTENTOS_ENTREGA_DESTINATARIO]
      ,[NOVEDAD_INTENTOS_DEVOLUCION_REMITENTE]
      ,[TOTAL_SZU]
  FROM [SIG_COLOMBIA_DW].[TMP].[CRC_DATA_REZAGOS_FINAL_REPORTE_ANIO] WITH(NOLOCK)
  WHERE [NUM_PRUEBA_ADMISION_O_NUM_GUIA]=251066982


SELECT COUNT(1)
  FROM [SIG_COLOMBIA_DW].[TMP].[CRC_DATA_REZAGOS_FINAL_REPORTE_ANIO] T01 WITH(NOLOCK)
INNER JOIN [TMP].[CRC_CSV_DISPOSICION_REZAGOS] T02 WITH(NOLOCK)
ON T01.NUM_PRUEBA_ADMISION_O_NUM_GUIA=CONVERT(NUMERIC(13,0),T02.[GUIA])

