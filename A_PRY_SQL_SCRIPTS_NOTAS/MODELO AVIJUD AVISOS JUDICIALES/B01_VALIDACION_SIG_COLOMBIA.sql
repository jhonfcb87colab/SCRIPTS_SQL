WITH CTE AS(
			SELECT 
				ROW_NUMBER ( )   OVER ( PARTITION BY G.NUMERO_GUIA order by G.FECHA_MODIFICACION_DG desc )  ROWID,  
				G.NUMERO_GUIA,
				G.ID_CIUDAD_ORIGEN,
				C.ID_REGIONAL AS ID_REGIONAL_ORIGEN,
				C.NOMBRE_CIUDAD AS NOMBRE_CIUDAD_ORIGEN,R.NOMBRE_REGIONAL AS NOMBRE_REGIONAL_ORIGEN,
				G.ID_CIUDAD_DESTINO,
				C_DS.ID_REGIONAL AS ID_REGIONAL_DESTINO,
				C_DS.NOMBRE_CIUDAD AS NOMBRE_CIUDAD_DESTINO,R_DS.NOMBRE_REGIONAL AS NOMBRE_REGIONAL_DESTINO
			FROM LOG.GUIAS G WITH(NOLOCK  INDEX=IX_GUIAS_V2) 
			INNER JOIN TMP.BASE_AVISOS_JUDICIALES AVJ WITH(NOLOCK) ON AVJ.NUMERO_GUIA=G.NUMERO_GUIA
			INNER JOIN PAR.CIUDADES C WITH(NOLOCK) ON G.ID_CIUDAD_ORIGEN=C.ID_CIUDAD
			INNER JOIN PAR.REGIONALES_PAIS R WITH(NOLOCK) ON C.ID_REGIONAL=R.ID_REGIONAL
			INNER JOIN PAR.CIUDADES C_DS WITH(NOLOCK) ON G.ID_CIUDAD_DESTINO=C_DS.ID_CIUDAD
			INNER JOIN PAR.REGIONALES_PAIS R_DS WITH(NOLOCK) ON C_DS.ID_REGIONAL=R_DS.ID_REGIONAL
			WHERE 
			AVJ.ID_CIUDAD_ORIGEN IS NULL	
			OR AVJ.ID_REGIONAL_ORIGEN IS NULL	
			OR AVJ.NOMBRE_CIUDAD_ORIGEN IS NULL	
			OR AVJ.NOMBRE_REGIONAL_ORIGEN IS NULL	
			OR AVJ.ID_CIUDAD_DESTINO IS NULL	
			OR AVJ.ID_REGIONAL_DESTINO IS NULL	
			OR AVJ.NOMBRE_CIUDAD_DESTINO IS NULL	
			OR AVJ.NOMBRE_REGIONAL_DESTINO IS NULL
			)
UPDATE AVJ2 SET
--SELECT
