	AVJ2.ID_CIUDAD_ORIGEN	= CTE.ID_CIUDAD_ORIGEN
	,AVJ2.ID_REGIONAL_ORIGEN	= CTE.ID_REGIONAL_ORIGEN
	,AVJ2.NOMBRE_CIUDAD_ORIGEN	= CTE.NOMBRE_CIUDAD_ORIGEN
	,AVJ2.NOMBRE_REGIONAL_ORIGEN 	= CTE.NOMBRE_REGIONAL_ORIGEN
	,AVJ2.ID_CIUDAD_DESTINO	= CTE.ID_CIUDAD_DESTINO
	,AVJ2.ID_REGIONAL_DESTINO	= CTE.ID_REGIONAL_DESTINO
	,AVJ2.NOMBRE_CIUDAD_DESTINO	= CTE.NOMBRE_CIUDAD_DESTINO
	,AVJ2.NOMBRE_REGIONAL_DESTINO  = CTE.NOMBRE_REGIONAL_DESTINO
FROM CTE CTE 
INNER JOIN TMP.BASE_AVISOS_JUDICIALES AVJ2 WITH(NOLOCK) 
ON CTE.NUMERO_GUIA=AVJ2.NUMERO_GUIA
WHERE CTE.ROWID=1

	
