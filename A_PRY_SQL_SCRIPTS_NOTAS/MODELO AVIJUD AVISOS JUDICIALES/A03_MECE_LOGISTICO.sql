USE Mece_Logistico;

WITH CTE AS(
SELECT
ROW_NUMBER ( ) OVER ( PARTITION BY SE.NUMERO_GUIA order by SE.FECHA_HORA_MOVIMIENTO ASC )  ID,
GAJ.*,
DV.NOMBRE_DIVISION NOMBRE_CLIENTE,
CASE WHEN (DV.NOMBRE_DIVISION IS NULL) THEN DV.NOMBRE_DIVISION ELSE CONCAT(DV.ID_PAIS, '-', DV.ID_CIUDAD, '-', DV.ID_DIVISION) END AS ID_CLIENTE,
CASE WHEN (DV.NOMBRE_DIVISION IS NULL) THEN DV.NOMBRE_DIVISION ELSE 'PUNTO DE SERVICIO' END AS TIPO_CLIENTE
FROM DBO.GUIAS_AVISOS_JUDICIALES GAJ WITH(NOLOCK)
LEFT JOIN
DBO.SEGUIMIENTO_ENVIO SE WITH(NOLOCK) ON GAJ.NUMERO_GUIA = SE.NUMERO_GUIA
LEFT JOIN 
DBO.DOCUMENTOS DC  WITH(NOLOCK) ON
(DC.ID_PROCESO = SE.ID_PROCESO
AND    DC.NUMERO_MOVIMI = SE.NUMERO_MOVIMI
AND    DC.CONSECUT_MOVIMI = SE.CONSECUT_MOVIMI)
LEFT JOIN PAR.DIVISIONES DV WITH(NOLOCK)
ON DC.ID_DIVISION_ORIGEN = DV.ID_DIVISION
AND DC.ID_CIUDAD_DIVISION_ORIGEN = DV.ID_CIUDAD
WHERE CONVERT(DATE, GAJ.FECHA_ENVIO) BETWEEN '20230501' AND '20230503'
)
SELECT * FROM CTE WITH(NOLOCK) WHERE ID = 1






