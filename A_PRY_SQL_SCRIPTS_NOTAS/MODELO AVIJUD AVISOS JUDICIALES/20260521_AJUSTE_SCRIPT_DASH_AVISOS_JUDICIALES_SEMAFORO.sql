
USE SIG_LOGISTICA_DM;
WITH CTE_AVISOS_JUDICIALES AS(
SELECT --TOP 1000
		 NUMERO_GUIA
		,FECHA_ENVIO
		,ID_PAIS
		,ID_CIUDAD
		,ID_TIPO_CERTIFICADO
		,ID_TIPO_NOTIFICACION
		,NOMBRE_REMITENTE
		,NOMBRE_REMITENTE_COPIA
		,NOMBRE_DESTINATARIO
		,NOMBRE_RECIBE
		,ID_TIPO_DOCUMENTO_RECIBE
		,NUMERO_DOCUMENTO_RECIBE
		,FECHA_HORA_RECIBE
		,ID_VIVE_RESIDE_EN_DIRECCION
		,ID_CAUSAL_DEVOLUCION
		,DETALLE_DEVOLUCION
		,NOMBRE_COLABORADOR_ENTREGA
		,CARGO_COLABORADOR_ENTREGA
		,NOMBRE_COORDINADOR_PROCESO
		,NUMERO_GUIA_CERTIFICADO
		,NOMBRE_RECIBE_CERTIFICADO
		,CARGO_RECIBE_CERTIFICADO
		,FECHA_ENTREGA_CERTIFICADO
		,FECHA_CERTIFICACION
		,NUMERO_OBLIGACION
		,ID_ABOGADO
		,ID_CIUDAD_ORIGEN
		,ID_ANEXOS
		,PERTENECE_ARTICULO
		,LOGIN_EMPLEADO
		,FECHA_CREACION
		,FECHA_MODIFICACION
		,NUMERO_CERTIFICADO
		,NUMERO_GUIA_REVERSA
		,NOMBRE_ENTIDAD
		,NUMERO_REFERENCIA_PROCESO
		,LOGIN_MODIFICACION
		,TIPO_CLIENTE
		,ID_CLIENTE
		,NOMBRE_CLIENTE
		,NOMBRE_CIUDAD_ORIGEN
		,ID_REGIONAL_ORIGEN
		,NOMBRE_REGIONAL_ORIGEN
		,ID_CIUDAD_DESTINO
		,NOMBRE_CIUDAD_DESTINO
		,ID_REGIONAL_DESTINO
		,NOMBRE_REGIONAL_DESTINO
		,ID_CDS
		,NOMBRE_CDS
		,DEVUELTO
		,FECHA_DEVOLUCION
		,TIENE_CERTIFICADO
		,IMAGEN
		,FECHA_EXTRACCION
		,BASE_AJ
		,FECHA_ENTREGA_VERIFICADA 
		,FECHA_PRUEBA_ENTREGA
		,ID_TIPO_ENTREGA  = ISNULL(ID_TIPO_ENTREGA,999)
		,HORAS_CERTIFICADO = 
		CASE WHEN FECHA_CERTIFICACION IS NULL OR FECHA_PRUEBA_ENTREGA IS NULL THEN 0
			 WHEN FECHA_CERTIFICACION IS NOT NULL OR FECHA_PRUEBA_ENTREGA IS NOT NULL THEN DATEDIFF(HOUR,FECHA_PRUEBA_ENTREGA,FECHA_CERTIFICACION)
			 ELSE 0
			END	
		,DIAS_CERTIFICADO = 
		CASE WHEN FECHA_CERTIFICACION IS NULL OR FECHA_PRUEBA_ENTREGA IS NULL THEN 0
			 WHEN FECHA_CERTIFICACION IS NOT NULL OR FECHA_PRUEBA_ENTREGA IS NOT NULL THEN DATEDIFF(DAY,FECHA_PRUEBA_ENTREGA,FECHA_CERTIFICACION)
			 ELSE 0
			END	
FROM FAC.BASE_AVISOS_JUDICIALES WITH(NOLOCK)
WHERE YEAR(FECHA_ENVIO)>=YEAR(DATEADD(YEAR,-5,GETDATE()))
--OPTION(RECOMPILE)
)
SELECT 
*
,ID_CLASIFICACION_VEJEZ_CERTIFICACION= 
		CASE 
			WHEN (FECHA_CERTIFICACION IS NOT NULL OR FECHA_PRUEBA_ENTREGA IS NOT NULL )
				AND FECHA_CERTIFICACION >= FECHA_PRUEBA_ENTREGA
				AND HORAS_CERTIFICADO <= 48 
				THEN 1
			WHEN (FECHA_CERTIFICACION IS NOT NULL OR FECHA_PRUEBA_ENTREGA IS NOT NULL )
				AND FECHA_CERTIFICACION >= FECHA_PRUEBA_ENTREGA
				AND HORAS_CERTIFICADO > 48 
				THEN 2
			WHEN (FECHA_CERTIFICACION IS NOT NULL OR FECHA_PRUEBA_ENTREGA IS NOT NULL )
				AND FECHA_CERTIFICACION < FECHA_PRUEBA_ENTREGA
				THEN 3
			WHEN (FECHA_CERTIFICACION IS NULL AND FECHA_PRUEBA_ENTREGA IS NOT NULL ) 
				THEN 4
			WHEN (FECHA_CERTIFICACION IS NOT NULL AND FECHA_PRUEBA_ENTREGA IS NULL ) 
				THEN 5
			ELSE 6
			END	
,NOMBRE_CLASIFICACION_VEJEZ_CERTIFICACION= 
		CASE 
			WHEN (FECHA_CERTIFICACION IS NOT NULL OR FECHA_PRUEBA_ENTREGA IS NOT NULL )
				AND FECHA_CERTIFICACION >= FECHA_PRUEBA_ENTREGA
				AND HORAS_CERTIFICADO <= 48 
				THEN '1-CERTIFICADO A TIEMPO'
			WHEN (FECHA_CERTIFICACION IS NOT NULL OR FECHA_PRUEBA_ENTREGA IS NOT NULL )
				AND FECHA_CERTIFICACION >= FECHA_PRUEBA_ENTREGA
				AND HORAS_CERTIFICADO > 48 
				THEN '2-CERTIFICADO POR FUERA DEL LIMITE PERMITIDO'
			WHEN (FECHA_CERTIFICACION IS NOT NULL OR FECHA_PRUEBA_ENTREGA IS NOT NULL )
				AND FECHA_CERTIFICACION < FECHA_PRUEBA_ENTREGA
				THEN '3-CERTIFICADO ANTES DE LA ENTREGA'
			WHEN (FECHA_CERTIFICACION IS NULL AND FECHA_PRUEBA_ENTREGA IS NOT NULL ) 
				THEN '4-SIN CERTIFICADO / CON ENTREGA'
			WHEN (FECHA_CERTIFICACION IS NOT NULL AND FECHA_PRUEBA_ENTREGA IS NULL ) 
				THEN '5-CON CERTIFICADO / SIN ENTREGA'
			ELSE '6-EN PROCESAMIENTO'
			END	
FROM CTE_AVISOS_JUDICIALES  

