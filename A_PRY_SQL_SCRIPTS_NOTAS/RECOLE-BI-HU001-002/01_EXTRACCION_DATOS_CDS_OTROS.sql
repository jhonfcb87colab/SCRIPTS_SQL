WITH CTE_G_RECOLECCION AS(
   SELECT 
   ROW_NUMBER ( )   OVER ( PARTITION BY GR.NUMERO_GUIA order by G.FECHA_MODIFICACION_DG desc )  ROWid  
   ,GR.NUMERO_SOLICITUD AS GR_NUMERO_SOLICITUD
   ,GR.NUMERO_GUIA AS GR_NUMERO_GUIA
   ,G.FECHA_ENVIO AS G_FECHA_ENVIO 
   ,MVSRFECHA_CREACION AS SR_FECHA_CREACION
   ,MVSRFECHA_RECOLECCION AS SR_FECHA_RECOLECCION
   ,MVSRFECHA_SOLICITUD_REC AS SR_FECHA_SOLICITUD_REC
   ,MVSRFECHA_RECOLECCION_SALIDA AS SR_FECHA_RECOLECCION_SALIDA
   ,MVSRFECHA_RECOLECCION_LLEGADA  AS SR_FECHA_RECOLECCION_LLEGADA
   ,G.FECHA_ENTREGA AS G_FECHA_ENTREGA
   ,G.ID_ESTADOENVIO AS G_ID_ESTADOENVIO  
   ,MVSRID_CLIENTE AS SR_ID_CLIENTE
   ,G.ID_CLIENTE AS G_ID_CLIENTE
   ,MVSRID_FORMAPAGO AS SR_ID_FORMAPAGO
   ,MVSRID_TIEMPO	AS SR_ID_TIEMPO 
   ,MVSRID_TIPO_ZONA_URBA AS SR_ID_TIPO_ZONA_URBA	
   ,MVSRID_ZONA_URBA	AS SR_ID_ZONA_URBA
   ,MVSRID_PAIS AS SR_ID_PAIS
   ,MVSRID_CIUDAD AS SR_ID_CIUDAD	
   ,MVSRID_DIVISION AS SR_ID_DIVISION
   ,G.FECHA_MODIFICACION_DG AS G_FECHA_MODIFICACION_DG
	FROM [Mece_Logistico].[dbo].[RECOLECCIONES_GUIAS] GR WITH(NOLOCK) 
   INNER JOIN [dbo].[SOLICITUDRECOLECCION] SR ON GR.NUMERO_SOLICITUD=MVSRNUMERO_SOLICITUD
   INNER JOIN [dbo].GUIAS G WITH(NOLOCK) ON G.NUMERO_GUIA=GR.NUMERO_GUIA
  -------------- INNER JOIN [dbo].SEGUIMIENTO_ENVIO SG WITH(NOLOCK) ON SG.NUMERO_GUIA=GR.NUMERO_GUIA
  WHERE G.ID_CLIENTE IS NULL AND LEN(MVSRID_CLIENTE)<1 
  --------------AND SG.ID_PROCESO IN (2,6,9)
   )
   SELECT 
   CTE.* 
   ,DIV.NOMBRE_DIVISION
   FROM CTE_G_RECOLECCION CTE 
   INNER JOIN PARAMETROS..DIVISIONES DIV WITH(NOLOCK)
   ON (
		CTE.SR_ID_PAIS=DIV.ID_PAIS
		AND CTE.SR_ID_CIUDAD=DIV.ID_CIUDAD
		AND CTE.SR_ID_DIVISION=DIV.ID_DIVISION
	)	
   WHERE CTE.ROWid=1




