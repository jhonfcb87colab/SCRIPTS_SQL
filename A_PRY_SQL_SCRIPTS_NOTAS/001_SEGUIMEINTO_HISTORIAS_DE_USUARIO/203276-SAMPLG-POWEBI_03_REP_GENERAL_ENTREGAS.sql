USE SIG_LOGISTICA_DM;


DECLARE @ESTADO_ENVIO INT = 3;
DECLARE @PERIODO INT = 2;
DECLARE @CAMPANNA VARCHAR(50)='KIT INTENSO PRO FIRMEZA';



DECLARE @ESTADO_ENVIO_02 VARCHAR(50) = CASE WHEN @ESTADO_ENVIO=3 THEN 'POR ENTREGAR,ENTREGADO'
											WHEN @ESTADO_ENVIO=2 THEN 'POR ENTREGAR'
											WHEN @ESTADO_ENVIO=1 THEN 'ENTREGADO' END
DECLARE @TABLE AS TABLE(ESTADO_ENVIO VARCHAR(50))
INSERT INTO @TABLE
SELECT VALUE AS ESTADOENVIO FROM STRING_SPLIT(@ESTADO_ENVIO_02,',')

select * from @TABLE
--



IF (@PERIODO = 1)
SELECT [CONSECUTIVO_SOLICITUD]
      ,[CONSECUTIVO_PARTICIPANTE]
      ,[CONSECUTIVO_CAMPANNA_PRODUCTO]
      ,[FECHA_SOLICITUD]
      ,[CANTIDAD_PRODUCTO_SOLICITADO]
      ,[SOLICITUD_REALIZADA_SIN_EXISTENCIAS_PRODUCTO]
      ,[NUMERO_SALIDA]
      ,[NUMERO_DESPACHO]
      ,[NUMERO_GUIA]
      ,[ID_ESTADOENVIO]
      ,[FECHA_ENTREGA]
      ,[FECHA_EXTRACCION_DM]
      ,[ID_ULT_PROCESO]
      ,[ESTADO_ENTREGA]
      ,[NOMBRE_CAMPANNA_PRODUCTO]
		,FECHA_SOLICITUD_DIAMES
		,FECHA_ENTREGA_DIAMES = CASE WHEN LEN(FECHA_ENTREGA_DIAMES)=1 THEN FECHA_SOLICITUD_DIAMES ELSE FECHA_ENTREGA_DIAMES END
  FROM [FAC].[SOLICITUDES_CAMPANNA_PRODUCTOS] WITH(NOLOCK)
  WHERE NOMBRE_CAMPANNA_PRODUCTO = @CAMPANNA
  --AND FECHA_SOLICITUD >= DATEADD(DD,-7,GETDATE())
  --AND FECHA_SOLICITUD <= GETDATE()
AND [ESTADO_ENTREGA] IN(SELECT ESTADO_ENVIO FROM @TABLE)

ELSE
IF (@PERIODO = 2)
SELECT [CONSECUTIVO_SOLICITUD]
      ,[CONSECUTIVO_PARTICIPANTE]
      ,[CONSECUTIVO_CAMPANNA_PRODUCTO]
      ,[FECHA_SOLICITUD]
      ,[CANTIDAD_PRODUCTO_SOLICITADO]
      ,[SOLICITUD_REALIZADA_SIN_EXISTENCIAS_PRODUCTO]
      ,[NUMERO_SALIDA]
      ,[NUMERO_DESPACHO]
      ,[NUMERO_GUIA]
      ,[ID_ESTADOENVIO]
      ,[FECHA_ENTREGA]
      ,[FECHA_EXTRACCION_DM]
      ,[ID_ULT_PROCESO]
      ,[ESTADO_ENTREGA]
      ,[NOMBRE_CAMPANNA_PRODUCTO]
,FECHA_SOLICITUD_DIAMES
,FECHA_ENTREGA_DIAMES  = CASE WHEN LEN(FECHA_ENTREGA_DIAMES)=1 THEN FECHA_SOLICITUD_DIAMES ELSE FECHA_ENTREGA_DIAMES END
  FROM [FAC].[SOLICITUDES_CAMPANNA_PRODUCTOS] WITH(NOLOCK)
  WHERE NOMBRE_CAMPANNA_PRODUCTO = @CAMPANNA
  --AND FECHA_SOLICITUD >= DATEADD(DD,-30,GETDATE())
  --AND FECHA_SOLICITUD <= GETDATE()
AND [ESTADO_ENTREGA] IN(SELECT ESTADO_ENVIO FROM @TABLE)
ELSE
IF (@PERIODO = 3)
SELECT [CONSECUTIVO_SOLICITUD]
      ,[CONSECUTIVO_PARTICIPANTE]
      ,[CONSECUTIVO_CAMPANNA_PRODUCTO]
      ,[FECHA_SOLICITUD]
      ,[CANTIDAD_PRODUCTO_SOLICITADO]
      ,[SOLICITUD_REALIZADA_SIN_EXISTENCIAS_PRODUCTO]
      ,[NUMERO_SALIDA]
      ,[NUMERO_DESPACHO]
      ,[NUMERO_GUIA]
      ,[ID_ESTADOENVIO]
      ,[FECHA_ENTREGA]
      ,[FECHA_EXTRACCION_DM]
      ,[ID_ULT_PROCESO]
      ,[ESTADO_ENTREGA]
      ,[NOMBRE_CAMPANNA_PRODUCTO]
,FECHA_SOLICITUD_DIAMES
,FECHA_ENTREGA_DIAMES  = CASE WHEN LEN(FECHA_ENTREGA_DIAMES)=1 THEN FECHA_SOLICITUD_DIAMES ELSE FECHA_ENTREGA_DIAMES END
  FROM [FAC].[SOLICITUDES_CAMPANNA_PRODUCTOS] WITH(NOLOCK)
  WHERE NOMBRE_CAMPANNA_PRODUCTO = @CAMPANNA
  --AND FECHA_SOLICITUD >= CONVERT(DATE,DATEADD(DAY,-(DAY(DATEADD(MONTH,-1,GETDATE()))-1),DATEADD(MONTH,-1,GETDATE())))
  --AND FECHA_SOLICITUD <= CONVERT(DATE,DATEADD(DAY,-(DAY(GETDATE())),GETDATE()))
AND [ESTADO_ENTREGA] IN(SELECT ESTADO_ENVIO FROM @TABLE)


select FECHA_SOLICITUD FROM [FAC].[SOLICITUDES_CAMPANNA_PRODUCTOS] WITH(NOLOCK)  group by FECHA_SOLICITUD
select FECHA_SOLICITUD_DIAMES FROM [FAC].[SOLICITUDES_CAMPANNA_PRODUCTOS] WITH(NOLOCK) group by FECHA_SOLICITUD_DIAMES
