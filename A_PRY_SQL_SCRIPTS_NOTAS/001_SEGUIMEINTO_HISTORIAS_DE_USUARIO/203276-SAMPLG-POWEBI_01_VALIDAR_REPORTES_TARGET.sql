	SELECT 
		[CONSECUTIVO_PARTICIPANTE] 
	,[ID_TIPOINDETIFIC]
	,[ID_PARTICIPANTE] 
	,[NOMBRES_PARTICIPANTE]
	,[APELLIDOS_PARTICIPANTE] 
	,[ID_GENERO] 
	,[ID_PAIS] 
	,[ID_CIUDAD] 
	,[DIRECCION_PARTICIPANTE] 
	,[BARRIO_PARTICIPANTE]
	,[CONSECUTIVO_ESTRATO]
	,[CODIGO_POSTAL_PARTICIPANTE]
	,[TELEFONO_FIJO_PARTICIPANTE]
	,[TELEFONO_CELULAR_PARTICIPANTE]
	,[CORREO_ELECTRONICO_PARTICIPANTE]
	,[FECHA_NACIMIENTO_PARTICIPANTE]
	,[ID_ESTADOCIVIL]
	,[ID_NIVEL_ACADEMICO]
	,[CONSECUTIVO_SECTOR_TRABAJO]
	,[OTRO_SECTOR_TRABAJO]
	,[TIENE_HIJOS_PARTICIPANTE]
	,[TIENE_MASCOTAS_PARTICIPANTE]
	,[ACEPTO_ENVIO_MUESTRAS_PARTICIPANTE]
	,[CONSECUTIVO_USUARIO]
	,[CORREO_ELECTRONICO_USUARIO]
	,[CONTRASENNA_USUARIO]
	,[CAMBIAR_CONTRASENNA_USUARIO]
	,[CONSECUTIVO_ROL_USUARIO]
	,[ESTADO_USUARIO]
	FROM SAMPLING.PARTICIPANTES PAR (NOLOCK)
	INNER JOIN CONTROL.USUARIOS USU (NOLOCK) ON USU.CORREO_ELECTRONICO_USUARIO = PAR.CORREO_ELECTRONICO_PARTICIPANTE
	WHERE CHARINDEX(','+CONVERT(VARCHAR,PAR.ID_CIUDAD)+',',@CONSECUTIVO_CIUDAD) > 0
	AND (YEAR(GETDATE()) - YEAR(PAR.FECHA_NACIMIENTO_PARTICIPANTE)) BETWEEN @EDAD_MINIMA_AFILIADO AND @EDAD_MAXIMA_AFILIADO
	AND CHARINDEX(','+CONVERT(VARCHAR,PAR.ID_GENERO)+',',@CONSECUTIVO_GENERO) > 0
	AND CHARINDEX(','+CONVERT(VARCHAR,PAR.ID_ESTADOCIVIL)+',',@CONSECUTIVO_ESTADO_CIVIL) > 0
	AND CHARINDEX(','+CONVERT(VARCHAR,PAR.ID_NIVEL_ACADEMICO)+',',@CONSECUTIVO_NIVEL_ACADEMICO) > 0
	AND CHARINDEX(','+CONVERT(VARCHAR,PAR.CONSECUTIVO_SECTOR_TRABAJO)+',',@CONSECUTIVO_SECTOR_TRABAJO) > 0
	--AND CHARINDEX(','+CONVERT(VARCHAR,PAR.CONSECUTIVO_ESTRATO)+',',@CONSECUTIVO_ESTRATO) > 0
	--AND PAR.TIENE_HIJOS_PARTICIPANTE = @TIENE_HIJOS
	--AND PAR.TIENE_MASCOTAS_PARTICIPANTE = @TIENE_MASCOTAS
	AND USU.CONSECUTIVO_ROL_USUARIO = 1		-- Participante
	AND USU.ESTADO_USUARIO = 1		-- Activo

	select @CONSECUTIVO_ESTRATO,@TIENE_HIJOS,@TIENE_MASCOTAS

SELECT
	TIENE_MASCOTAS
	,TIENE_HIJOS
	,CONSECUTIVO_ESTRATO
	,CONSECUTIVO_MASCOTA
	FROM SAMPLING.TARGETS_PRODUCTOS (NOLOCK)
GROUP BY 
	TIENE_MASCOTAS
	,TIENE_HIJOS
	,CONSECUTIVO_ESTRATO
	,CONSECUTIVO_MASCOTA
	,CONSECUTIVO_MASCOTA




