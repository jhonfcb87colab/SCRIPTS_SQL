	DECLARE @PARTICIPANTES TABLE (
						[CONSECUTIVO_PARTICIPANTE] [bigint] NOT NULL,
						[ID_TIPOINDETIFIC] [tinyint] NOT NULL,
						[ID_PARTICIPANTE] [char](20) NOT NULL,
						[NOMBRES_PARTICIPANTE] [varchar](100) NOT NULL,
						[APELLIDOS_PARTICIPANTE] [varchar](100) NOT NULL,
						[ID_GENERO] [tinyint] NOT NULL,
						[ID_PAIS] [smallint] NOT NULL,
						[ID_CIUDAD] [int] NOT NULL,
						[DIRECCION_PARTICIPANTE] [varchar](400) NOT NULL,
						[BARRIO_PARTICIPANTE] [varchar](100) NOT NULL,
						[CONSECUTIVO_ESTRATO] [tinyint] NULL,
						[CODIGO_POSTAL_PARTICIPANTE] [varchar](20) NULL,
						[TELEFONO_FIJO_PARTICIPANTE] [varchar](20) NULL,
						[TELEFONO_CELULAR_PARTICIPANTE] [varchar](20) NULL,
						[CORREO_ELECTRONICO_PARTICIPANTE] [varchar](200) NOT NULL,
						[FECHA_NACIMIENTO_PARTICIPANTE] [date] NOT NULL,
						[ID_ESTADOCIVIL] [tinyint] NOT NULL,
						[ID_NIVEL_ACADEMICO] [tinyint] NULL,
						[CONSECUTIVO_SECTOR_TRABAJO] [smallint] NOT NULL,
						[OTRO_SECTOR_TRABAJO] [varchar](200) NULL,
						[TIENE_HIJOS_PARTICIPANTE] [bit] NOT NULL,
						[TIENE_MASCOTAS_PARTICIPANTE] [bit] NOT NULL,
						[ACEPTO_ENVIO_MUESTRAS_PARTICIPANTE] [bit] NOT NULL,
						[CONSECUTIVO_USUARIO] [bigint] NOT NULL,
						[CORREO_ELECTRONICO_USUARIO] [varchar](200) NOT NULL,
						[CONTRASENNA_USUARIO] [varchar](100) NOT NULL,
						[CAMBIAR_CONTRASENNA_USUARIO] [bit] NOT NULL,
						[CONSECUTIVO_ROL_USUARIO] [tinyint] NOT NULL,
						[ESTADO_USUARIO] [tinyint] NOT NULL
	)






	
	DECLARE @INTERESES TABLE (
	CONSECUTIVO_INTERES BIGINT)
	
	DECLARE @INTERESES_PARTICIPANTES TABLE (
	CONSECUTIVO_PARTICIPANTE BIGINT)

	DECLARE @HIJOS TABLE (
	CONSECUTIVO_PARTICIPANTE VARCHAR(MAX),
	CANTIDAD_HIJOS TINYINT)
	
	SELECT 
	@CONSECUTIVO_CIUDAD = ','+RTRIM(CONSECUTIVO_CIUDAD)+',',
	@CONSECUTIVO_INTERESES = CONSECUTIVO_INTERES,
	@EDAD_MINIMA_AFILIADO = EDAD_MINIMA_AFILIADO,
	@EDAD_MAXIMA_AFILIADO = EDAD_MAXIMA_AFILIADO,
	@CONSECUTIVO_GENERO = ','+RTRIM(CONSECUTIVO_GENERO)+',',
	@CONSECUTIVO_ESTADO_CIVIL = ','+RTRIM(CONSECUTIVO_ESTADO_CIVIL)+',',
	@CONSECUTIVO_NIVEL_ACADEMICO = ','+RTRIM(CONSECUTIVO_NIVEL_ACADEMICO)+',',
	@CONSECUTIVO_SECTOR_TRABAJO = ','+RTRIM(CONSECUTIVO_SECTOR_TRABAJO)+',',
	@TIENE_HIJOS = TIENE_HIJOS,
	@CANTIDAD_HIJOS = CANTIDAD_HIJOS,
	--@EDAD_MINIMA_HIJO = EDAD_MINIMA_HIJO,
	--@EDAD_MAXIMA_HIJO = EDAD_MAXIMA_HIJO,
	@TIENE_MASCOTAS = TIENE_MASCOTAS,
	@CONSECUTIVO_ESTRATO = ','+CONVERT(VARCHAR,CONSECUTIVO_ESTRATO)+','
--	@CONSECUTIVO_MASCOTA = CONSECUTIVO_MASCOTA
	FROM SAMPLING.TARGETS_PRODUCTOS (NOLOCK)
	WHERE CONSECUTIVO_TARGET_PRODUCTO = @CONSECUTIVO_TARGET_PRODUCTO

--SELECT * FROM SAMPLING.TARGETS_PRODUCTOS (NOLOCK)
--	WHERE CONSECUTIVO_TARGET_PRODUCTO = @CONSECUTIVO_TARGET_PRODUCTO




	-- Inserta los consecutivos de interes en la tabla temporal #INTERESES
	SET @POSICION = CHARINDEX(',',@CONSECUTIVO_INTERESES,1)
	WHILE @POSICION > 0
		BEGIN
			SET @CONSECUTIVO_INTERES = SUBSTRING(@CONSECUTIVO_INTERESES,1,@POSICION-1)
			INSERT INTO @INTERESES (CONSECUTIVO_INTERES) VALUES (@CONSECUTIVO_INTERES)
			
			SET @CONSECUTIVO_INTERESES = SUBSTRING(@CONSECUTIVO_INTERESES,@POSICION+1,LEN(@CONSECUTIVO_INTERESES))
			SET @POSICION = CHARINDEX(',',@CONSECUTIVO_INTERESES,1)
		END
	IF LEN(@CONSECUTIVO_INTERESES) > 0
		BEGIN
			SET @CONSECUTIVO_INTERES = @CONSECUTIVO_INTERESES
			INSERT INTO @INTERESES (CONSECUTIVO_INTERES) VALUES (@CONSECUTIVO_INTERES)
		END
	
	---- Selecciona los participantes
	--INSERT INTO @PARTICIPANTES (
