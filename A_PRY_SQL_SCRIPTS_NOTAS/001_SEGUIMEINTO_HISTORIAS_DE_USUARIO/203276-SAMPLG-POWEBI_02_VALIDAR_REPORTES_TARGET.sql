FROM [TMP].[SAMPLING_PATICIPANTE_TARGET_CAMPANIA_PRODUCTOS] TB01 WITH(NOLOCK) 
INNER JOIN PAR.CIUDADES CIU WITH(NOLOCK) ON CIU.ID_CIUDAD=TB01.ID_CIUDAD
