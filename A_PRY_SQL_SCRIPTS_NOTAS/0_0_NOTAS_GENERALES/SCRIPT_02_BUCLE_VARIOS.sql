DECLARE @FECH_INI DATETIME = '2022-01-01'
DECLARE @FECH_FIN DATETIME = '2026-10-31'

DECLARE @FECH_AUX DATETIME = '1900-01-01'
----DECLARE @VALOR INT = 0;

DECLARE @VALORES AS TABLE(DTMES INT, VALOR INT) 
DECLARE @VALOR INT = 20000;

SET @FECH_AUX = @FECH_INI

WHILE (YEAR(@FECH_AUX)*100)+MONTH(@FECH_AUX) <=  (YEAR(@FECH_FIN)*100)+MONTH(@FECH_FIN)
BEGIN
	INSERT INTO @VALORES(DTMES,VALOR)
	SELECT 
	(YEAR(@FECH_AUX)*100)+MONTH(@FECH_AUX),
	@VALOR 

	SET @FECH_AUX = DATEADD(MONTH,1,@FECH_AUX)
	PRINT(CONCAT('FECHA INSERTADA ',@FECH_AUX,'PERIODO ',(YEAR(@FECH_AUX)*100)+MONTH(@FECH_AUX),'VALOR ',@VALOR))
END

SELECT * FROM @VALORES

SELECT SUM(VALOR) FROM @VALORES
