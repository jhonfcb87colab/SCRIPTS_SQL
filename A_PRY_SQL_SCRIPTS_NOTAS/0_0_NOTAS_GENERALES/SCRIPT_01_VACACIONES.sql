USE SIG_COLOMBIA_DW;

DECLARE @FE_HOY DATETIME = CONVERT(DATETIME,CONVERT(DATE,GETDATE()));
DECLARE @FE_INI DATETIME = '2027-03-14';
DECLARE @FE_FIN DATETIME = @FE_INI;
DECLARE @NUM_DIAS INT = 15; 

-------------------------------------------------------------------------------------------------------------
DECLARE @DIAS_FESTIVOS_Y_DOMINGOS INT =0;
DECLARE @DIAS_SABADOS INT =0;
DECLARE @DIAS_RESULTADO INT =0;
DECLARE @DIAS_RESULTADO_HOY_TO_DIA_FINAL_HABIL INT =0;

SET @DIAS_RESULTADO_HOY_TO_DIA_FINAL_HABIL = (
	SELECT COUNT(1) FROM 
	[DIM].[VW_TIEMPO_CALENDARIO_Y_FESTIVOS]
	WHERE [DATE] BETWEEN @FE_HOY AND @FE_INI AND [DAY]<>'Sabado' AND TIPO_DIA NOT IN('DIA FESTIVO','DIA DOMINICAL'))



WHILE @DIAS_RESULTADO < @NUM_DIAS
BEGIN		
		SET @DIAS_RESULTADO = (
			SELECT COUNT(1) FROM 
			[DIM].[VW_TIEMPO_CALENDARIO_Y_FESTIVOS]
			WHERE [DATE] BETWEEN @FE_INI AND @FE_FIN AND [DAY]<>'Sabado' AND TIPO_DIA NOT IN('DIA FESTIVO','DIA DOMINICAL')
			);

		SET @DIAS_FESTIVOS_Y_DOMINGOS = (
			SELECT COUNT(1) FROM 
			[DIM].[VW_TIEMPO_CALENDARIO_Y_FESTIVOS]
			WHERE [DATE] BETWEEN @FE_INI AND @FE_FIN AND TIPO_DIA IN('DIA FESTIVO','DIA DOMINICAL')
			);

		SET @DIAS_SABADOS = (
			SELECT COUNT(1) FROM 
			[DIM].[VW_TIEMPO_CALENDARIO_Y_FESTIVOS]
			WHERE [DATE] BETWEEN @FE_INI AND @FE_FIN AND [DAY]='Sabado' 
			);
		SET @FE_FIN = DATEADD(DAY,IIF(@DIAS_RESULTADO < @NUM_DIAS,1,0),@FE_FIN)
		PRINT(@DIAS_RESULTADO)
		PRINT(@FE_INI)
		PRINT(@FE_FIN)

END

SELECT 
@FE_INI AS FECHA_INICIAL,
@FE_FIN AS FECHA_FINAL,
@DIAS_RESULTADO AS NUMERO_DIAS,
@DIAS_FESTIVOS_Y_DOMINGOS AS DIAS_FESTIVOS_Y_DOMINGOS, 
@DIAS_SABADOS AS DIAS_SABADOS,
DATEDIFF(DAY, @FE_INI, @FE_FIN)+1 AS DIAS_TOTALES,
@FE_HOY AS HOY,
DATEDIFF(DAY,@FE_HOY,@FE_INI) AS DIAS_FALTANTES,
@DIAS_RESULTADO_HOY_TO_DIA_FINAL_HABIL  AS DIAS_FALTANTES_HABILES
SELECT DATE, 
			TIPO_FECHA =
				CASE WHEN [DAY]='Sabado' THEN 'Sabado'
					 WHEN TIPO_DIA = 'DIA FESTIVO' THEN 'DIA FESTIVO' 
					 WHEN TIPO_DIA = 'DIA DOMINICAL' THEN 'DIA DOMINICAL'
					 ELSE 'NA' END
FROM 
[DIM].[VW_TIEMPO_CALENDARIO_Y_FESTIVOS]
WHERE [DATE] BETWEEN @FE_INI AND @FE_FIN 
order by TIME_ID

