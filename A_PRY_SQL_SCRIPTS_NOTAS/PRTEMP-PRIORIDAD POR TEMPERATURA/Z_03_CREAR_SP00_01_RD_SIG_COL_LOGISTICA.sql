CREATE PROCEDURE [FAC].[PRTEMP_RD]

@regionales VARCHAR(MAX),
@cpl VARCHAR(MAX),
@numero_guia VARCHAR(MAX)


AS

WITH CTE
(
	 [NUMERO_SOLICITUD]
	,[FECHA] 
	,AÑO
	,MES
	,DIA    
	,ID_CLIENTE
	,ID_TIEMPO_ENTREGA	  
	,GM_MARCA
	,FECHA_HORA_RECOLECCION
	,FECHA_HORA_REGISTRO
	,FECHA_HORA_ZONIFICACION
	,FECHA_HORA_ASIGNACION
	,FECHA_HORA_VERIFICACION
	,FECHA_HORA_CANCELACION	  	  
	,ID_ESTADO_VEJEZ
	,ID_ESTADO_ASIGNADA_EZU
	,ID_ESTADO_ASIGNADA_EZU_HOY
	,ID_ESTADO_ASIGNADA
	,OBSERVACIONES
	,OBSERVACIONES_GM
	,EVIDENCIA_FOTOGRAFICA
	,LOGIN_CREACION
	,EMAIL_CREACION
	,DIAS_NOVEDAD
	,ID_GEOGRAFIA
	,ID_CONFIRM_SOLICITUD
	,ID_TIPO_SOLICITUD
	,ID_MOTIVO_RECHAZO
	,ID_UEN_PROD_SUBPROD
	,ID_RANGO_VEJEZ
)
AS
	(
		SELECT 
			 F.[NUMERO_SOLICITUD]
			,F.[FECHA] 
			,F.AÑO
			,F.MES
			,F.DIA    
			,F.ID_CLIENTE
			,F.ID_TIEMPO_ENTREGA	  
			,F.GM_MARCA 
			,F.S_FECHA_HORA_RECOLECCION
			,F.FECHA_HORA_RECOLECCION_REGIS FECHA_HORA_REGISTRO
			,F.FECHA_HORA_RECOLECCION_ZONIF FECHA_HORA_ZONIFICACION
			,F.FECHA_HORA_RECOLECCION_ASIGN FECHA_HORA_ASIGNACION
			,F.FECHA_HORA_RECOLECCION_VERIF FECHA_HORA_VERIFICACION
			,F.FECHA_HORA_RECOLECCION_CANCEL FECHA_HORA_CANCELACION	  	  
			,F.ID_ESTADO_VEJEZ
			,F.ID_ESTADO_ASIGNADA_EZU
			,F.ID_ESTADO_ASIGNADA_EZU_HOY
			,F.ID_ESTADO_ASIGNADA
			,F.OBSERVACIONES
			,F.OBSERVACIONES_GM
			,F.EVIDENCIA_FOTOGRAFICA
			,F.LOGIN_CREACION
			,F.EMAIL_CREACION
			,F.DIAS_NOVEDAD
			,F.ID_GEOGRAFIA
			,F.ID_CONFIRM_SOLICITUD
			,F.ID_TIPO_SOLICITUD
			,F.ID_MOTIVO_RECHAZO
			,F.ID_UEN_PROD_SUBPROD
			,F.ID_RANGO_VEJEZ
		FROM 
			[FAC].[GM_RECOLECCION] F WITH (NOLOCK)
		WHERE
		CONVERT(DATE,F.S_FECHA_HORA_RECOLECCION)
		=
		CONVERT(DATE,
			(SELECT MAX(S_FECHA_HORA_RECOLECCION) FROM [FAC].[GM_RECOLECCION]))
)
SELECT 
	*
FROM  
	CTE 
GO

