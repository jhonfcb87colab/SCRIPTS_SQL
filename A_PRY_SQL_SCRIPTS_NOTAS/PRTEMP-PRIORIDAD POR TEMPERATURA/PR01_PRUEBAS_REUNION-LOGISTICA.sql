DECLARE @DATEFECHAACTUAL DATETIME = GETDATE();
	-- DECLARE @DATEFECHAACTUAL DATETIME = CONVERT(DATETIME,'2019-05-25 03:19:52.380');
	WITH CTE_VEJEZ_AP
	(
	TIME_ID,	
	NUMERO_GUIA,
	ID_PROCESO,
	FECHA_HORA_MOVIMIENTO,
	ID_BODEGA_ORGEN,
	ID_BODEGA_DESTINO,
	ID_BODEGA_VEJEZ,
	ID_PROCESO_PENULTIMO_PROC,
	FECHA_HORA_MOVIMIENTO_PENULTIMO_PROC,
	ID_BODEGA_VEJEZ_PENULTIMO_PROC,
	ID_BODEGA_ORGEN_PENULTIMO_PROC,
	ID_BODEGA_DESTINO_PENULTIMO_PROC,
	HORAS_VEJEZ_BODEGA,
	HORAS_VEJEZ_CREACION_A_ULTIMO_MOV,
	HORAS_VEJEZ_CREACION_A_HOY,
	ID_REGIONAL_DESTINO,
	LOGIN_EMPLEADO,
	LOGIN_EMPLEADO_PENULTIMO_PROC
	)
	AS
	(
	SELECT      
		[TIME_ID],
		[NUMERO_GUIA],
		[ID_PROCESO],
		[FECHA_HORA_MOVIMIENTO],
		[ID_BODEGA_ORGEN],
		[ID_BODEGA_DESTINO],
		[ID_BODEGA_VEJEZ],
		[ID_PROCESO_PENULTIMO_PROC],
		[FECHA_HORA_MOVIMIENTO_PENULTIMO_PROC],
		[ID_BODEGA_VEJEZ_PENULTIMO_PROC],
		[ID_BODEGA_ORGEN_PENULTIMO_PROC],
		[ID_BODEGA_DESTINO_PENULTIMO_PROC],
		[HORAS_VEJEZ_BODEGA],
		[HORAS_VEJEZ_CREACION_A_ULTIMO_MOV],
		[HORAS_VEJEZ_CREACION_A_HOY],
		[ID_REGIONAL_DESTINO],
		[LOGIN_EMPLEADO],
		[LOGIN_EMPLEADO_PENULTIMO_PROC]
		FROM [TMP].[PRTEMP_PS_08] WITH (NOLOCK)
	)
	SELECT * FROM(
			SELECT
				ROW_NUMBER ( )   OVER ( PARTITION BY HS.NUMERO_GUIA order by HS.FECHA_HORA_MOVIMIENTO desc )  ID, 
						HS.NUMERO_GUIA,
						HS.ID_CLIENTE AS ID_CLIENTE,
						HS.NOMBRE_REMITE_GUIA AS NOMBRE_CLIENTE,
						HS.FECHA_CREACION AS FECHA_GENERACION,
						HS.FECHA_ENTREGA AS FECHA_ENTREGA,
						HS.FECHA_ENVIO AS FECHA_RECOLECCION,
						HS.FECHA_HORA_MOVIMIENTO AS FECHA_ULTIMO_MOVIMIENTO,
						--VZ.HORAS_VEJEZ_CREACION_A_ULTIMO_MOV AS Tiempo_de_Vida,

						CASE WHEN
							(
								CONVERT(FLOAT,CONVERT(DATETIME,DATEADD (hour , CASE WHEN REDOPE.TIEMPO_OFERTA=0 THEN 0 ELSE ISNULL(REDOPE.TIEMPO_OFERTA,0) END , @DATEFECHAACTUAL ) ))
								BETWEEN
									CONVERT(FLOAT,CONVERT(DATETIME,HS.FECHA_ENVIO ) )
									AND
									CONVERT(FLOAT,CONVERT(DATETIME,DATEADD (hour , CASE WHEN REDOPE.TIEMPO_OFERTA=0 THEN 0 ELSE ISNULL(REDOPE.TIEMPO_OFERTA,0) END , HS.FECHA_ENVIO ) ))		
							)
							THEN
							CONVERT(FLOAT,CONVERT(DATETIME,DATEADD (hour , CASE WHEN REDOPE.TIEMPO_OFERTA=0 THEN 0 ELSE ISNULL(REDOPE.TIEMPO_OFERTA,0) END , HS.FECHA_ENVIO ) ))
							- CONVERT(FLOAT,CONVERT(DATETIME,DATEADD (hour , CASE WHEN REDOPE.TIEMPO_OFERTA=0 THEN 0 ELSE ISNULL(REDOPE.TIEMPO_OFERTA,0) END , @DATEFECHAACTUAL ) )) 
							ELSE
								0
							END
									as Tiempo_de_Vida,


						--DATEADD (hour , ISNULL(REDOPE.TIEMPO_OFERTA,48) , HS.FECHA_ENVIO ) AS FECHA_PRUEBA,
						--@DATEFECHAACTUAL AS FECHA_DEL_DIA,

						PRS.NOMBRE_PROCESO_LOG AS ULTIMO_PROCESO_LOGISTICO,
						CIU.NOMBRE_CIUDAD AS CIUDAD_ULTIMO_MOVIMIENTO,
						UPPER(ISNULL(HS.LOGIN_EMPLEADO,'NO DISPONIBLE')) AS USUARIO_ULTIMO_MOVIMIENTO,
						ISNULL(US.LAST_NAME,'NO DISPONIBLE') AS NOMBRE_USUARIO_ULTIMO_MOVIMIENTO,
                                                                                                                ISNULL(CIU.NOMBRE_CIUDAD,'NO DISPONIBLE') + '-' + ISNULL(CIU_ORIG.NOMBRE_CIUDAD,'NO DISPONIBLE') AS ULTIMO_OPERATIVO,
						--ISNULL(CIU.NOMBRE_CIUDAD,'NO DISPONIBLE') + '-' + ISNULL(CIU_PENULT.NOMBRE_CIUDAD,'NO DISPONIBLE') AS ULTIMO_OPERATIVO,
						ISNULL(BOD.NOMBRE_DIVISION,'NO DISPONIBLE') AS BODEGA,
						ISNULL(CIU_ORIG.NOMBRE_CIUDAD,'NO DISPONIBLE') AS CIUDAD_ORDIGEN,
						ISNULL(REGIO_ORIG.NOMBRE_REGIONAL,'NO DISPONIBLE') AS REGIONAL_ORIGEN,
						ISNULL(CIU_DEST.NOMBRE_CIUDAD,'NO DISPONIBLE') AS CIUDAD_DESTINO,
						ISNULL(REGIO_DESTI.NOMBRE_REGIONAL,'NO DISPONIBLE') AS REGIONAL_DESTINO,
						HS.ID_REGIONAL_DESTINO AS REGIONA_ID_INTERNO,
						HS.ID_BODEGA_VEJEZ AS BODEGA_ID_INTERNO,
						ISNULL(REDOPE.TIEMPO_PROMESA_CUMPLE_H,'NO DISPONIBLE') AS TIEMPO_PROMESA_CUMPLE_H_RED_OPE,
						ISNULL(REDOPE.TIEMPO_PROMESA_H,0) AS TIEMPO_PROMESA_H_RED_OPE,
						CASE WHEN REDOPE.TIEMPO_OFERTA=0 THEN 0 ELSE ISNULL(REDOPE.TIEMPO_OFERTA,0) END AS TIEMPO_OFERTA_RED_OPE
					FROM  TMP.PRTEMP_PS_08 HS (nolock)
						  LEFT JOIN CTE_VEJEZ_AP VZ (nolock)
						  ON HS.NUMERO_GUIA=VZ.NUMERO_GUIA
						  LEFT JOIN PAR.PROCESOS PRS (nolock)
						  ON PRS.ID_PROCESO=HS.ID_PROCESO
						  LEFT JOIN PAR.CIUDADES CIU (nolock)
						  ON CIU.ID_CIUDAD=HS.ID_CIUDAD_DESTINO
						  LEFT JOIN SIG_MEVI_DM.DIM.USUARIOS US (nolock)
						  ON US.CONTACT_NAME=HS.LOGIN_EMPLEADO COLLATE Modern_Spanish_CI_AS
						  LEFT JOIN PAR.CIUDADES CIU_PENULT (nolock)
						  ON CIU_PENULT.ID_CIUDAD= dbo.UFN_SEPARATES_COLUMNS(HS.ID_BODEGA_VEJEZ_PENULTIMO_PROC,2,'-')
						  LEFT JOIN  SIG_COL_LOGISTICA_DW.DIM.DIVISIONES_BODEGAS  BOD (nolock)
						  ON BOD.ID_DIVISION= HS.ID_DIVISION_UBICACION -----dbo.UFN_SEPARATES_COLUMNS(HS.ID_BODEGA_VEJEZ_PENULTIMO_PROC,3,'-')
						  LEFT JOIN PAR.CIUDADES CIU_ORIG (nolock)
						  ON CIU_ORIG.ID_CIUDAD=HS.ID_CIUDAD_ORIGEN
						  LEFT JOIN PAR.REGIONALES_PAIS REGIO_ORIG (NOLOCK)
						  ON REGIO_ORIG.ID_REGIONAL=CIU_ORIG.ID_REGIONAL
						  LEFT JOIN PAR.CIUDADES CIU_DEST (nolock)
						  ON CIU_DEST.ID_CIUDAD=HS.ID_CIUDAD_DESTINO
						  LEFT JOIN PAR.REGIONALES_PAIS REGIO_DESTI (NOLOCK)
						  ON REGIO_DESTI.ID_REGIONAL=CIU_DEST.ID_REGIONAL
						  LEFT JOIN  [SIG_COL_LOGISTICA_DW].FAC.GUIAS_ENTREG_TIEMPO_PROMESA_RED_OPERATIVA REDOPE (nolock)
						  ON REDOPE.NUMERO_GUIA=HS.NUMERO_GUIA
	) AS TABLERO WHERE ID=1

