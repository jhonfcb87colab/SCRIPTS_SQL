SELECT 
CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,TABLA.FECHA_HORA_MOVIMIENTO))) AS TIME_ID,
TABLA.*,
CASE 
	WHEN TABLA.FECHA_ENTREGA IS NOT NULL OR TABLA.ID_PROCESO IN(11,24)
		THEN 0
		ELSE 
			CONVERT(NUMERIC(18,3),(CONVERT(DATETIME,TABLA.FECHA_HORA_MOVIMIENTO) 
			-
			CONVERT(DATETIME,TABLA.FECHA_HORA_MOVIMIENTO_PENULTIMO_PROC)))*24
		END
	AS HORAS_VEJEZ_BODEGA,
CASE 
	WHEN TABLA.FECHA_ENTREGA IS NOT NULL OR TABLA.ID_PROCESO IN(11,24)
		THEN 0
		ELSE 
			CONVERT(NUMERIC(18,3),(CONVERT(DATETIME,TABLA.FECHA_HORA_MOVIMIENTO) 
			-
			CONVERT(DATETIME,TABLA.FECHA_ENVIO)))*24
		END
	AS HORAS_VEJEZ_CREACION_A_ULTIMO_MOV,
CASE 
	WHEN TABLA.FECHA_ENTREGA IS NOT NULL OR TABLA.ID_PROCESO IN(11,24)
		THEN 0
		ELSE 
			CONVERT(NUMERIC(18,3),(CONVERT(DATETIME,TABLA.FECHA_EXTRACCION) 
			-
			CONVERT(DATETIME,TABLA.FECHA_ENVIO)))*24
		END
	AS HORAS_VEJEZ_CREACION_A_HOY
FROM 
(
SELECT [NUMERO_GUIA]
      ,[ID_PROCESO]
      ,[ID_CONCEPTO]
      ,[FECHA_HORA_MOVIMIENTO]
      ,[NUMERO_MOVIMI]
      ,[CONSECUT_MOVIMI]
      ,[FECHA_MODIFICACION]
      ,[ID_PRODUCTO]
      ,[ID_TIPOENVIO]
      ,[LLAVE_REGISTRO]
      ,[FECHA_CREACION]
      ,[ID_OPERATIVO]
      ,[FECHA_ENVIO]
      ,[FECHA_ENTREGA]
      ,[ID_CIUDAD_ORIGEN]
      ,[ID_CIUDAD_DESTINO]
      ,[ID_TIPOGUIA]
      ,[ID_DIVISION_UBICACION]
      ,[ID_ESTADOENVIO]
      ,[ID_ESTADOGUIA]
      ,[ID_BODEGA_ORGEN]
      ,[ID_BODEGA_DESTINO]
      ,[ID_BODEGA_VEJEZ]
      ,[ID_CLIENTE]
      ,[ID_REMITE]
      ,[NOMBRE_REMITE_GUIA]
      ,[ID_DESTINA]
      ,[NOMBRE_DESTINA_GUIA]
      ,[FECHA_EXTRACCION]
      ,[ID_TIME_ENVIO]
      ,[ID_TIME_MODIF]
      ,[ID_CIL]
      ,[MOVIMIENTO]
      ,[ID]
	  ,[LOGIN_EMPLEADO]
,[ID_REGIONAL_DESTINO]
      ,CASE WHEN ISNULL([ID_PROCESO_PENULTIMO_PROC],-888)=-888  THEN [ID_PROCESO] ELSE [ID_PROCESO_PENULTIMO_PROC] END AS [ID_PROCESO_PENULTIMO_PROC]
      ,CASE WHEN ISNULL([ID_CONCEPTO_PENULTIMO_PROC],-888)=-888  THEN [ID_CONCEPTO] ELSE [ID_CONCEPTO_PENULTIMO_PROC] END AS [ID_CONCEPTO_PENULTIMO_PROC]
      ,CASE WHEN ISNULL([FECHA_HORA_MOVIMIENTO_PENULTIMO_PROC],'1900-01-01')='1900-01-01'  THEN [FECHA_HORA_MOVIMIENTO] ELSE [FECHA_HORA_MOVIMIENTO_PENULTIMO_PROC] END AS [FECHA_HORA_MOVIMIENTO_PENULTIMO_PROC]
      ,CASE WHEN ISNULL([ID_BODEGA_VEJEZ_PENULTIMO_PROC],'NO DISPONIBLE')='NO DISPONIBLE'  THEN [ID_BODEGA_VEJEZ] ELSE [ID_BODEGA_VEJEZ_PENULTIMO_PROC] END AS [ID_BODEGA_VEJEZ_PENULTIMO_PROC]
      ,CASE WHEN ISNULL([ID_ESTADOGUIA_PENULTIMO_PROC],-888)=-888  THEN [ID_ESTADOGUIA] ELSE [ID_ESTADOGUIA_PENULTIMO_PROC] END AS [ID_ESTADOGUIA_PENULTIMO_PROC]      
      ,CASE WHEN ISNULL([ID_BODEGA_ORGEN_PENULTIMO_PROC],'NO DISPONIBLE')='NO DISPONIBLE'  THEN [ID_BODEGA_ORGEN] ELSE [ID_BODEGA_ORGEN_PENULTIMO_PROC] END AS [ID_BODEGA_ORGEN_PENULTIMO_PROC]
	  ,CASE WHEN ISNULL([ID_BODEGA_DESTINO_PENULTIMO_PROC],'NO DISPONIBLE')='NO DISPONIBLE'  THEN [ID_BODEGA_DESTINO] ELSE [ID_BODEGA_DESTINO_PENULTIMO_PROC] END AS [ID_BODEGA_DESTINO_PENULTIMO_PROC]
      ,CASE WHEN ISNULL([ID_CIL_PENULTIMO_PROC],-888)=-888  THEN [ID_CIL] ELSE [ID_CIL_PENULTIMO_PROC] END AS [ID_CIL_PENULTIMO_PROC]      
      ,CASE WHEN ISNULL([LOGIN_EMPLEADO_PENULTIMO_PROC],'NO DISPONIBLE')='NO DISPONIBLE'  THEN [LOGIN_EMPLEADO] ELSE [LOGIN_EMPLEADO_PENULTIMO_PROC] END AS [LOGIN_EMPLEADO_PENULTIMO_PROC]      
  FROM [TMP].[PRTEMP_PS_07] WITH (NOLOCK)
