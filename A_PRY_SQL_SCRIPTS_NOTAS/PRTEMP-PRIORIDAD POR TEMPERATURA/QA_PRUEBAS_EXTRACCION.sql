DECLARE @DATO INT,@CIL VARCHAR(10); 
SET @DATO=10;
---BARR

SELECT 
		ROW_NUMBER ( )   OVER ( PARTITION BY GUI.[NUMERO_GUIA] order by GUI.[FECHA_ULTIMA_MOD] desc )  id  
	   ,CONCAT(LTRIM(RTRIM(GUI.[NUMERO_GUIA])),'-',
	   LTRIM(RTRIM(SEG_ENV.ID_PROCESO)),'-',
	   LTRIM(RTRIM(SEG_ENV.NUMERO_MOVIMI)),'-',
	   LTRIM(RTRIM(SEG_ENV.CONSECUT_MOVIMI))) AS LLAVE_REGISTRO
	   ,GUI.[NUMERO_GUIA]
	   ,SEG_ENV.ID_PROCESO
	   ,LTRIM(RTRIM(SEG_ENV.NUMERO_MOVIMI)) NUMERO_MOVIMI
	   ,SEG_ENV.CONSECUT_MOVIMI
	   ,SEG_ENV.ID_CONCEPTO
	   ,GUI.[FECHA_CREACION]
	   ,GUI.ID_PRODUCTO
	   ,SEG_ENV.ID_TIPOENVIO
	   ,DOC.ID_OPERATIVO
	   ,GUI.FECHA_ENVIO
	   ,GUI.FECHA_ENTREGA
/*
	   ,GUI.ID_CIUDAD_ORIGEN
	   ,GUI.ID_CIUDAD_DESTINO}
	   ,DOC.ID_CIUDAD_DIVISION_ORIGEN AS ID_CIUDAD_ORIGEN
	   ,DOC.ID_CIUDAD_DESTINO  AS ID_CIUDAD_DESTINO

*/

	   ,ID_CIUDAD_ORIGEN = CASE WHEN DOC.ID_PROCESO IN(11,24)  THEN  DOC.ID_CIUDAD_DESTINO ELSE  DOC.ID_CIUDAD_DIVISION_ORIGEN  END
	   ,ID_CIUDAD_DESTINO = CASE WHEN DOC.ID_PROCESO IN(9)  THEN DOC.ID_CIUDAD_DIVISION_ORIGEN ELSE  DOC.ID_CIUDAD_DESTINO END

	   ,GUI.ID_TIPOGUIA
	   ,GUI.ID_DIVISION_UBICACION
	   ,GUI.ID_ESTADOENVIO
	   ,GUI.ID_ESTADOGUIA
	  ---------- ,CIU.ID_REGIONAL AS ID_REGIONAL_DESTINO
                    ----------------->NO ,ID_REGIONAL_DESTINO = CASE WHEN DOC.ID_PROCESO IN(9)  THEN CIU_ORG_PR9.ID_REGIONAL ELSE  DOC.ID_REPLICADO END
                      ,ID_REGIONAL_DESTINO = CASE WHEN DOC.ID_PROCESO IN(9)  THEN CIU_ORG_PR9.ID_REGIONAL ELSE  CIU.ID_REGIONAL END
	   ,CONCAT(DOC.ID_PAIS_DIVISION_ORIGEN ,'-', DOC.ID_CIUDAD_DIVISION_ORIGEN  ,'-', DOC.ID_DIVISION_ORIGEN) AS ID_BODEGA_ORGEN
	   ,CONCAT(DOC.ID_PAIS_DESTINO ,'-', DOC.ID_CIUDAD_DESTINO  ,'-', DOC.ID_DIVISION_DESTINO) AS ID_BODEGA_DESTINO
	   ,CASE WHEN
				SEG_ENV.ID_PROCESO=9 THEN CONCAT(DOC.ID_PAIS_DIVISION_ORIGEN ,'-', DOC.ID_CIUDAD_DIVISION_ORIGEN  ,'-', DOC.ID_DIVISION_ORIGEN)
			ELSE
				CONCAT(DOC.ID_PAIS_DESTINO ,'-', DOC.ID_CIUDAD_DESTINO  ,'-', DOC.ID_DIVISION_DESTINO) END AS ID_BODEGA_VEJEZ
	   ,SEG_ENV.FECHA_HORA_MOVIMIENTO
	   ,SEG_ENV.FECHA_MODIFICACION
	   ,ISNULL(GUI.ID_CLIENTE,-888) ID_CLIENTE
	   ,ISNULL(GUI.ID_REMITE,-888) ID_REMITE 
		,ISNULL(GUI.NOMBRE_REMITE_GUIA,'NO DISPONIBLE') NOMBRE_REMITE_GUIA  
		,ISNULL(GUI.ID_DESTINA,-888) ID_DESTINA  
		,ISNULL(GUI.NOMBRE_DESTINA_GUIA,'NO DISPONIBLE') NOMBRE_DESTINA_GUIA  
	   ,GETDATE() AS FECHA_EXTRACCION
,ISNULL(SEG_ENV.LOGIN_EMPLEADO,'NO DISPONIBLE') LOGIN_EMPLEADO
  FROM 
  
  --TABLA 1
	[dbo].[GUIAS] GUI WITH (NOLOCK) 
  LEFT JOIN 
  
  --TABLA 2
  [dbo].[SEGUIMIENTO_ENVIO] SEG_ENV WITH (NOLOCK)
  ON GUI.NUMERO_GUIA=SEG_ENV.[NUMERO_GUIA]
  LEFT JOIN 
  
  --TABLA 3
  [dbo].[DOCUMENTOS] DOC WITH (NOLOCK)
  ON 
  	   SEG_ENV.ID_PROCESO=DOC.ID_PROCESO 
	   AND SEG_ENV.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI
	   AND SEG_ENV.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI
  --TABLA 4
	LEFT JOIN 
	PARAMETROS..CIUDADES CIU WITH (NOLOCK)
	ON DOC.ID_CIUDAD_DESTINO=CIU.ID_CIUDAD
  --TABLA 5
	LEFT JOIN 
	PARAMETROS..CIUDADES CIU_ORG_PR9 WITH (NOLOCK)
	ON DOC.ID_CIUDAD_DIVISION_ORIGEN=CIU_ORG_PR9.ID_CIUDAD


  WHERE GUI.ID_PRODUCTO=54
  AND
   CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,SEG_ENV.FECHA_HORA_MOVIMIENTO)))
  >=
  CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,GETDATE()-@DATO)))


