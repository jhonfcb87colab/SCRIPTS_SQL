DECLARE @FECHA_INI DATETIME,@FECHA_FIN DATETIME;
SET @FECHA_INI=CONVERT(DATETIME,'2023-04-01')
SET @FECHA_FIN=CONVERT(DATETIME,'2023-05-23')
SELECT 
	SE.NUMERO_GUIA,
	SE.ID_PROCESO,
	SE.ID_CONCEPTO,
	SE.NUMERO_MOVIMI,
	SE.CONSECUT_MOVIMI,
	SE.FECHA_HORA_MOVIMIENTO 
	,CONVERT(VARCHAR (12) ,ZU.ID_PAIS_CANAL) + '-' + CONVERT(VARCHAR (12) ,ZU.ID_CIUDAD_CANAL)   + '-' + CONVERT(VARCHAR (12),ZU.ID_CANAL )  D_ID_GEOGRAFIA_EMP
FROM LOG.SEGUIMIENTO_ENVIO SE WITH (NOLOCK) 
 	INNER JOIN LOG.DOCUMENTOS D WITH(NOLOCK) 
				ON SE.ID_PROCESO = D.ID_PROCESO AND 
				SE.NUMERO_MOVIMI = D.NUMERO_MOVIMI AND
				SE.CONSECUT_MOVIMI = D.CONSECUT_MOVIMI 
	INNER JOIN PAR.ZONASURBANAS ZU WITH(NOLOCK) 
				ON D.ID_TIPO_ZONA_URBA = ZU.ID_TIPO_ZONA_URBA AND
				D.ID_PAIS_ZONA_URBA = ZU.ID_PAIS AND 
				D.ID_CIUDAD_ZONA_URBA = ZU.ID_CIUDAD AND
				D.ID_ZONA_URBA = ZU.ID_ZONA_URBA
WHERE SE.FECHA_HORA_MOVIMIENTO >= @FECHA_INI AND SE.FECHA_HORA_MOVIMIENTO < DATEADD(DAY,1, @FECHA_FIN)
--AND SE.ID_PROCESO = 9 AND SE.ID_CONCEPTO IN (7,8,9)
