WHERE EMP.TECNICA_PPES<>'INACTIVO' 
AND
	FAC.SE_ID_FECHA_SZU >= CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,@FECHA_INI))) 
	AND
	FAC.SE_ID_FECHA_SZU <= CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,@FECHA_FIN)))
AND FAC.D_ID_GEOGRAFIA_EMP='1-480-5'
AND FAC.ID_CIU










