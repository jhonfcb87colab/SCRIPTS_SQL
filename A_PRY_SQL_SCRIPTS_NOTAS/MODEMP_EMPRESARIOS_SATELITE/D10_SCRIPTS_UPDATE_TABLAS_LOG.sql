USE SIG_COLOMBIA_DW;
DROP TABLE IF EXISTS #TABLA_TEMPORAL
SELECT DISTINCT
 SEG.NUMERO_GUIA
 ,SEG.NUMERO_MOVIMI
 ,SEG.CONSECUT_MOVIMI
 ,SEG.ID_PROCESO
 INTO #TABLA_TEMPORAL
 FROM LOG.DOCUMENTOS_PROV D WITH(NOLOCK) 
	INNER JOIN [LOG].SEGUIMIENTO_ENVIO_PROV SEG WITH(NOLOCK) 
	ON D.ID_PROCESO = SEG.ID_PROCESO AND D.NUMERO_MOVIMI = SEG.NUMERO_MOVIMI AND D.CONSECUT_MOVIMI = SEG.CONSECUT_MOVIMI 	
	INNER JOIN PAR.ZONASURBANAS Z (NOLOCK) 
	ON Z.ID_PAIS = D.ID_PAIS_ZONA_URBA AND Z.ID_CIUDAD = D.ID_CIUDAD_ZONA_URBA AND Z.ID_TIPO_ZONA_URBA = D.ID_TIPO_ZONA_URBA AND Z.ID_ZONA_URBA = D.ID_ZONA_URBA --AND Z.CATEGORIA_ZONA_URBA = 8 --CLICOH
	INNER JOIN [PAR].[CATEGORIAZONAURBANA] CZ (NOLOCK) ON CZ.Id_Categoria=Z.CATEGORIA_ZONA_URBA
	WHERE D.ID_PROCESO = 9	
	and SEG.FECHA_HORA_MOVIMIENTO>='20250501 00:00:00' and SEG.FECHA_HORA_MOVIMIENTO<='20250520 23:59:59'
	--and d.ID_PROCESO=9 and d.NUMERO_MOVIMI='001001501931106052025' and d.CONSECUT_MOVIMI=1
	AND D.ID_CIUDAD_DIVISION_ORIGEN=15
	--,D.ID_CIUDAD_DIVISION_ORIGEN AS ID_CIUDAD_DIVISION
	AND Z.ID_ZONA_URBA=438
	AND SEG.ID_CONCEPTO=1
/**/
SELECT 
 SEG.NUMERO_GUIA
 ,SEG.NUMERO_MOVIMI
 ,SEG.CONSECUT_MOVIMI
 ,SEG.ID_PROCESO
 ,SEG.ID_CONCEPTO
 ----UPDATE SEG SET 
----SEG.ID_CONCEPTO=8
FROM [LOG].SEGUIMIENTO_ENVIO_PROV SEG WITH(NOLOCK) 
INNER JOIN #TABLA_TEMPORAL TMP
ON 	SEG.NUMERO_GUIA=TMP.NUMERO_GUIA
 AND SEG.NUMERO_MOVIMI=TMP.NUMERO_MOVIMI
 AND SEG.CONSECUT_MOVIMI=TMP.CONSECUT_MOVIMI
 AND SEG.ID_PROCESO=TMP.ID_PROCESO
