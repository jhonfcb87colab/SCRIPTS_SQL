	DIM.ESTADO_EMP ESTRE WITH (NOLOCK)
ON 
	FAC.[SE_ID_ESTADO_RE] = ESTRE.ID_ESTADO_EMP  
LEFT JOIN 
	DIM.ESTADO_EMP ESTREH WITH (NOLOCK)
ON 
	FAC.[SE_ID_ESTADO_RE_HOY] = ESTREH.ID_ESTADO_EMP  
LEFT JOIN 
	DIM.ESTADO_EMP ESTRD WITH (NOLOCK)
ON 
	FAC.[SE_ID_ESTADO_RD] = ESTRD.ID_ESTADO_EMP  
LEFT JOIN 
	DIM.ESTADO_EMP ESTPG WITH (NOLOCK)
ON 
	FAC.[SE_ID_ESTADO_PDTE_GEST] = ESTPG.ID_ESTADO_EMP 
LEFT JOIN
	DIM.ESTADO_EMP ESTLE WITH (NOLOCK)
ON 
	FAC.[P_ID_ESTADO_LIMT_ENTRE] = ESTLE.ID_ESTADO_EMP 
LEFT JOIN
	DIM.ESTADO_EMP ESTCF WITH (NOLOCK)
ON 
	FAC.SE_ID_ESTADO_CONF = ESTCF.ID_ESTADO_EMP  
LEFT JOIN 
	DIM.TIEMPOS_ENTREGA TIE WITH (NOLOCK)
ON 
	FAC.G_ID_TIEMPO_ENTREGA = TIE.ID_TIEMPO
LEFT JOIN 
	DIM.CLIENTES CLI WITH (NOLOCK)
ON 
	FAC.G_ID_CLIENTE = CLI.ID_CLIENTE 
LEFT JOIN
	DIM.ESTADOS_ENVIO ESEN WITH (NOLOCK)
ON
	FAC.G_ID_ESTADOENVIO = ESEN.ID_ESTADO_ENVIO 
											LEFT JOIN
												DIM.PROCESO_CONCEPTO PRC WITH (NOLOCK)
											ON
												FAC.SE_ID_PROCESO_ULT = PRC.ID_PROCESO
											 AND
												FAC.SE_ULTM_ID_CONCEPTO = PRC.ID_CONCEPTO
LEFT JOIN 
	DIM.CIUDADES_ZONA_URBA CZU WITH (NOLOCK)
ON
	FAC.SE_ID_ZONAURBAN = CZU.CLAVE_DIMENSION 
LEFT JOIN
	DIM.ESTADO_EMP  ESLG
ON 
	ISNULL(FAC.[GR_ESTADO_LEGALIZADO],'NO DISPONIBLE') = ESLG.ESTADO_EMP  /* ESTADO_LEGALIZADO*/
LEFT JOIN
	DIM.ESTADO_EMP  ESR
ON 
	ISNULL(FAC.[GR_ESTADO_RECAUDO],'NO DISPONIBLE') = EMVSRESTADO_EMP
LEFT JOIN
	DIM.ESTADO_EMP  ESPQR
ON 
	ISNULL(FAC.[TIENE_PQR],'NO') = ESPQR.ESTADO_EMP
LEFT JOIN 
	DIM.PQR PQR
ON 
	FAC.PQR_ID = PQR.ID_PQR AND FAC.PQR_FECHA=PQR.FECHA_PQR 
LEFT JOIN 
	DIM.PROCESOS_PQR AS PPQR /*TRAE ESTADO PQR */
ON ISNULL(PQR.ID_PROCESO_PQR,-888) = PPQR.ID_PROCESO_PQR
LEFT JOIN	
	DIM.TAREA AS TAR
ON FAC.PQR_ID = TAR.ID_PQR AND TAR.ID_PQR = PQR.ID_PQR ---AND FAC.PQR_FECHA = TAR.FECHA_TAREA
LEFT JOIN 
	DIM.ESTADO_EMP AS ESTAR  WITH (NOLOCK)	
ON (IIF(FAC.PQR_ID = TAR.ID_PQR, 1, IIF(ISNULL(FAC.PQR_ID,-888) =-888 AND ISNULL(TAR.ID_PQR,-888) =-888, -888,  0 ))  ) = ESTAR.ID_ESTADO_EMP

