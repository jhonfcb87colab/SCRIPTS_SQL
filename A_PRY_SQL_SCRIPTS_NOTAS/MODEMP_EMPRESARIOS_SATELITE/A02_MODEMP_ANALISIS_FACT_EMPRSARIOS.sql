	 ,FAC.SE_ULTM_ID_CONCEPTO
	 ------,FAC.SE_ULTM_NOMBRE_CONCEPTO_DEV -->NO EXISTE
	 ,'************************************' AS ESPACIO
	 -----------------------------------------------------------

	,FAC.[G_CANTIDAD_PIEZAS] AS CANTIDAD_PIEZAS
	,TIL.TIPO_LOGISTICA AS TIPO_LOGISTICA
	,ISNULL(FAC.[GRIR_VALOR_X_RECAUDAR],0) AS VALOR_A_RECAUDAR
	,CASE WHEN  ISNULL(FAC.GRIR_FECHA_RECAUDO,'1900-01-01') = '1900-01-01' THEN 'NO DISPONIBLE' ELSE FORMAT(CONVERT(DATETIME,(FAC.GRIR_FECHA_RECAUDO)),'dd/MM/yyyy - hh:mm:ss') END FECHA_RECAUDO
	,ISNULL(FAC.[GRIR_VALOR_RECAUDADO],0) AS VALOR_RECAUDO
	,ISNULL(FAC.[GR_ESTADO_RECAUDO],'NO') AS ESTADO_DEL_RECAUDO
	,ISNULL(ESLG.ESTADO_EMP,'NO DISPONIBLE') AS ESTADO_LEGALIZADO
	,ISNULL(FAC.EF_ID_FECHA_RECAUDO,'NO DISPONIBLE') AS FECHA_LEGALIZADO
	,ISNULL(FAC.[GRIR_VALOR_SALDO],0) AS VALOR_LEGALIZADO
	,CASE WHEN ISNULL(FAC.EF_ORDEN_SERVICIO,'NO DISPONIBLE') = 'NO DISPONIBLE' THEN 'NO' ELSE 'SI' END AS ORDEN_SERVICIO
	,ISNULL(FAC.EF_ORDEN_SERVICIO,'NO DISPONIBLE') AS NUMERO_ORDEN_SERVICIO
	,FAC.[SE_CANTIDAD_SZU] AS CANTIDAD_TOTAL_SZU
	,CASE WHEN  FAC.SE_PRIM_FECHA_HORA_SZU = '1900-01-01' THEN 'NO DISPONIBLE' ELSE FORMAT(CONVERT(DATETIME,(FAC.SE_PRIM_FECHA_HORA_SZU)),'dd/MM/yyyy - hh:mm:ss') END FECHA_HORA_1ERA_SZU
	,CASE WHEN  FAC.[SE_FECHA_HORA_SZU] = '1900-01-01' THEN 'NO DISPONIBLE' ELSE FORMAT(CONVERT(DATETIME,(FAC.[SE_FECHA_HORA_SZU])),'dd/MM/yyyy - hh:mm:ss') END FECHA_HORA_ULTIMA_SZU
	,FAC.[SE_CANTIDAD_RVO] AS CANTIDAD_TOTAL_RVO
	,CASE WHEN  FAC.[SE_FECHA_HORA_RVO] = '1900-01-01' THEN 'NO DISPONIBLE' ELSE FORMAT(CONVERT(DATETIME,(FAC.[SE_FECHA_HORA_RVO])),'dd/MM/yyyy - hh:mm:ss') END FECHA_HORA_1ERA_RVO
	,CASE WHEN  FAC.SE_ULTI_FECHA_HORA_RVO = '1900-01-01' THEN 'NO DISPONIBLE' ELSE FORMAT(CONVERT(DATETIME,(FAC.SE_ULTI_FECHA_HORA_RVO)),'dd/MM/yyyy - hh:mm:ss') END FECHA_HORA_ULTIMA_RVO
	,ESTR.ESTADO_EMP AS ESTADO_RETAIL_WEB
	,CASE WHEN  FAC.SE_ID_ESTADO_RTW = 1 THEN  FORMAT(CONVERT(DATETIME,(FAC.SE_FECHA_HORA_RTW)),'dd/MM/yyyy - hh:mm:ss') ELSE 'NO DISPONIBLE' END FECHA_HORA_RETAIL_WEB
	,ESTRE.ESTADO_EMP AS ESTADO_RE_EV
	,CASE WHEN  FAC.SE_ID_ESTADO_RE = 1 THEN  FORMAT(CONVERT(DATETIME,(FAC.SE_FECHA_HORA_EJECDO)),'dd/MM/yyyy - hh:mm:ss') ELSE 'NO DISPONIBLE' END FECHA_HORA_RE_EV
	,ESTREH.ESTADO_EMP AS ESTADO_RE_EV_HOY
	,ESTRD.ESTADO_EMP AS ESTADO_REPORTADO_DEVUELTO
	,CASE WHEN  FAC.SE_ID_ESTADO_RD = 1 THEN  FORMAT(CONVERT(DATETIME,(FAC.SE_FECHA_HORA_RD)),'dd/MM/yyyy - hh:mm:ss') ELSE 'NO DISPONIBLE' END FECHA_HORA_RD
	,EST.ESTADO_EMP AS ESTADO_DEVU_RT
	,ESTPG.ESTADO_EMP AS ESTADO_PDTE_GESTION
	,ESTLE.ESTADO_EMP AS CUMPLE_LIMITE_ENTRE
	,FAC.G_TIEMPO_HRS_EJECDO AS HORAS_EJERCIDO
	,FAC.P_HORA_LIMT_ENTREGA AS HORAS_LIMITE_ENTREGA
	,GEO.NOMBRE_REGIONAL AS REGIONAL_ORIGEN    
	,GEO.NOMBRE_CIUDAD_CABECERA AS DEPARTAMENTO_ORIGEN
	,GEO.NOMBRE_CIUDAD  AS CIUDAD_ORIGEN
	,GED.NOMBRE_REGIONAL AS REGIONAL_DESTINO   
	,GED.NOMBRE_CIUDAD_CABECERA AS DEPARTAMENTO_DESTINO
	,GED.NOMBRE_CIUDAD  AS CIUDAD_DESTINO
	,TIE.NOMBRE_TIEMPO AS TIEMPO_DE_ENTREGA
	,FAC.G_ID_CLIENTE AS ID_CLIENTE
	,ISNULL(CLI.RAZON_SOCIAL_CORTA,'NO DISPONIBLE') AS NOMBRE_CLIENTE
	,ISNULL(GEU.NOMBRE_REGIONAL,'NO DISPONIBLE') AS REGIONAL_ULTI_MOVI  
	,ISNULL(GEU.NOMBRE_CIUDAD_CABECERA,'NO DISPONIBLE') AS DEPARTAMENTO_ULTI_MOVI
	,ISNULL(GEU.NOMBRE_CIUDAD,'NO DISPONIBLE') AS CIUDAD_ULTI_MOVI
	,ESEN.ESTADO_ENVIO AS ESTADO_ENVIO
	,CASE WHEN  FAC.SE_FECHA_HORA_ULT = '1900-01-01' THEN 'NO DISPONIBLE' ELSE FORMAT(CONVERT(DATETIME,(FAC.SE_FECHA_HORA_ULT)),'dd/MM/yyyy - hh:mm:ss') END FECHA_ULTI_MOVI
	,PRC.NOMBRE_PROCESO AS PROCESO_ULTI_MOVI
	,VEJ.GRUPO_VEJEZ AS VEJEZ
	,ESTCF.ESTADO_EMP AS TIENE_CONFIRMACION
	,ISNULL(FAC.CNF_CANT_CONFIRMACION,0) AS CANTIDAD_TOTAL_CONFIRMACIONES
	,ISNULL(FAC.SE_PRIM_NOMBRE_SOLUCION_CONF,'NO DISPONIBLE') AS PRIMERA_SOLUCION_CONFIRMACION
	,ISNULL(FAC.SE_PENU_NOMBRE_SOLUCION_CONF,'NO DISPONIBLE') AS PENULTIMA_SOLUCION_CONFIRMACION
	,ISNULL(FAC.SE_NOMBRE_SOLUCION_CONF,'NO DISPONIBLE') AS ULTIMA_SOLUCION_CONFIRMACION
	,ISNULL(FAC.SE_PRIM_NOMBRE_CONCEPTO,'NO DISPONIBLE') AS PRIMER_CONCEPTO_DEVOLUCION_SZU
	,ISNULL(FAC.SE_PENU_NOMBRE_CONCEPTO,'NO DISPONIBLE') AS PENULTIMO_CONCEPTO_DEVOLUCION_SZU
	,ISNULL(FAC.SE_ULTM_NOMBRE_CONCEPTO_DEV,'NO DISPONIBLE') AS ULTIMO_CONCEPTO_DEVOLUCION_SZU
	,CZU.ID_ZONA_URBA AS ID_ZONA_SZU 
	,CZU.NOMBRE_ZONA_URBA AS NOMBRE_ZONA_SZU
	,EMP.CODIGO_EMPRESARIO AS ID_EMPRESARIO_SATELITE   
	,EMP.EMPRESARIO AS NOMBRE_EMPRESARIO_SATELITE
	,FAC.P_VALOR_LIQUIDADO AS VALOR_LIQUIDADO_ENVIO
	,ESPQR.ESTADO_EMP AS TIENE_PQR
	,ISNULL(PPQR.NOMBRE_PROCESO_PQR,'NO DISPONIBLE') AS ESTADO_PQR
	,VEJ.VEJEZ_EMP AS VEJEZ_PQR
	,ESTAR.ESTADO_EMP AS TIENE_TAREA
	,IIF(PPQR.ID_PROCESO_PQR in(7,-888), PPQR.NOMBRE_PROCESO_PQR ,'ACTIVO') AS ESTADO_TAREA
	,ISNULL(FAC.SE_NOVD_OPERATIVA_1,'NO DISPONIBLE') AS PRIMER_NOVEDAD_OPERATIVA	
	,ISNULL(FAC.SE_NOVD_OPERATIVA_2,'NO DISPONIBLE') AS SEGUNDA_NOVEDAD_OPERATIVA
	,ISNULL(FAC.SE_NOVD_OPERATIVA_3,'NO DISPONIBLE') AS TERCERA_NOVEDAD_OPERATIVA
