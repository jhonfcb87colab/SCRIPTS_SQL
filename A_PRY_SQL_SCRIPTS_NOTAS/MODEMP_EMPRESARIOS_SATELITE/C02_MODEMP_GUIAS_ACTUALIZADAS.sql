USE SIG_COLOMBIA_DW;

DROP TABLE IF EXISTS #TEMPORAL_MODEMP_GUIAS_ACTUALIZADAS_EN_EL_MERF_01;
CREATE TABLE #TEMPORAL_MODEMP_GUIAS_ACTUALIZADAS_EN_EL_MERF_01(
	[ID_ROW] [bigint] NULL,
	[NUMERO_GUIA] [bigint] NOT NULL,
	[FECHA_MODIFICACION_TRANSMISION] [datetime] NULL
) 

DROP TABLE IF EXISTS #TEMPORAL_MODEMP_GUIAS_ACTUALIZADAS_EN_EL_MERF_02;
CREATE TABLE #TEMPORAL_MODEMP_GUIAS_ACTUALIZADAS_EN_EL_MERF_02(
	[ID_ROW] [bigint] NULL,
	[NUMERO_GUIA] [numeric](20, 0) NOT NULL,
	[ID_PROCESO] [smallint] NOT NULL,
	[NUMERO_MOVIMI] [char](30) NOT NULL,
	[CONSECUT_MOVIMI] [numeric](7, 0) NOT NULL,
	[ID_CONCEPTO] [tinyint] NULL,
	[FECHA_HORA_MOVIMIENTO] [datetime] NULL
) 


DECLARE @FECHA_INI DATETIME,@FECHA_FIN DATETIME,@FECHA_HOY DATETIME;
SET @FECHA_HOY=CONVERT(DATETIME,CONVERT(DATE,GETDATE()))
SET @FECHA_INI=CONVERT(DATETIME,DATEADD(DAY,-5,@FECHA_HOY))
SET @FECHA_FIN=CONVERT(DATETIME,DATEADD(DAY,1,@FECHA_HOY))

INSERT INTO  #TEMPORAL_MODEMP_GUIAS_ACTUALIZADAS_EN_EL_MERF_01
	SELECT 
			T.* 
			FROM (
			SELECT 
			ROW_NUMBER ( )   OVER ( PARTITION BY NUMERO_GUIA order by FECHA_MODIFICACION_TRANSMISION desc ) ID_ROW,
			NUMERO_GUIA,FECHA_MODIFICACION_TRANSMISION
			FROM LOG.GUIA_RECAUDO WITH(NOLOCK) 
			WHERE FECHA_MODIFICACION_TRANSMISION BETWEEN @FECHA_INI AND @FECHA_FIN
			) T WHERE ID_ROW=1


INSERT INTO #TEMPORAL_MODEMP_GUIAS_ACTUALIZADAS_EN_EL_MERF_02
	SELECT 
		T.* 
		FROM (
				SELECT 
				ROW_NUMBER ( )   OVER ( PARTITION BY SE.NUMERO_GUIA order by SE.FECHA_HORA_MOVIMIENTO desc ) ID_ROW,
				 SE.NUMERO_GUIA,
				 SE.ID_PROCESO,
				 SE.NUMERO_MOVIMI,
				 SE.CONSECUT_MOVIMI,
				 SE.ID_CONCEPTO,
				 SE.FECHA_HORA_MOVIMIENTO 
				 FROM LOG.SEGUIMIENTO_ENVIO SE WITH (NOLOCK) 
				 INNER JOIN #TEMPORAL_MODEMP_GUIAS_ACTUALIZADAS_EN_EL_MERF_01 TMP WITH (NOLOCK) 
				 ON SE.NUMERO_GUIA=TMP.NUMERO_GUIA
				 WHERE 
				 SE.ID_PROCESO = 9 AND SE.ID_CONCEPTO IN (7,8,9)
			) T WHERE ID_ROW=1

INSERT INTO [TMP].[EMP_01]		
			SELECT 
			ID_PROCESO	
			,NUMERO_GUIA	
			,ID_CONCEPTO 
			,NUMERO_MOVIMI	
			,CONSECUT_MOVIMI	
			,FECHA_HORA_MOVIMIENTO
			FROM #TEMPORAL_MODEMP_GUIAS_ACTUALIZADAS_EN_EL_MERF_02









