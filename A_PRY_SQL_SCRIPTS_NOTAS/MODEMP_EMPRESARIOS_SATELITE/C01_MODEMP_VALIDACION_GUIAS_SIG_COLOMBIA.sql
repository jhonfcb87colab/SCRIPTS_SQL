			SELECT
				 IR.NUMERO_GUIA IR_NUMERO_GUIA
				,ISNULL(CASE WHEN IR.NUMERO_ORDEN_SERVICIO = ' THEN NULL ELSE IR.NUMERO_ORDEN_SERVICIO END,'NO DISPONIBLE') IR_NUMERO_ORDEN_SERVICIO
				,ISNULL(CASE WHEN IR.NUMERO_APROBACION = ' THEN NULL ELSE IR.NUMERO_APROBACION END, 'NO DISPONIBLE') IR_NUMERO_APROBACION
				,CONVERT(BIGINT ,case when GR.ID_TIPO_COBRO = 2 then IR.VALOR_PRODUCTO else 
				case when ID_TIPO_COBRO = 1 then IR.VALOR_FLETE + IR.VALOR_SOBREFLETE - IR.VALOR_DESCUENTO else
				case when ID_TIPO_COBRO = 3 then IR.VALOR_PRODUCTO + IR.VALOR_FLETE + IR.VALOR_SOBREFLETE - IR.VALOR_DESCUENTO else 0 end end end) as IR_VALOR_X_RECAUDAR
				,ISNULL(GIRE.VALOR, IR.VALOR_RECAUDADO ) AS IR_VALOR_RECAUDADO
				,ISNULL(IR.ID_MODALPAGO,-888) ID_MODALPAGO
				,ISNULL(IR.NUMERO_CODIGO_EFECTY,-888) IR_NUMERO_CODI_EFECTY
				,ISNULL(IR.FECHA_RECAUDO,'1900-01-01') IR_FECHA_RECAUDO
			FROM
				LOG.GUIA_RECAUDO GR (nolock)
			INNER JOIN
				LOG.GUIA_RECAUDO_INFORMACION_RECAUDO IR WITH(NOLOCK)
			ON 
				IR.NUMERO_GUIA = GR.NUMERO_GUIA
		    LEFT JOIN 
				LOG.GUIA_RECAUDO_INFORMACION_EFECTY GIRE (nolock)
			ON 
				GIRE.NUMERO_GUIA = GR.NUMERO_GUIA
