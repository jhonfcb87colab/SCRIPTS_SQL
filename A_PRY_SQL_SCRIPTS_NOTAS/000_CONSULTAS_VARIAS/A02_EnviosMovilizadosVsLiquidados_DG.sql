USE MECE_LOGISTICO;

DROP TABLE IF EXISTS #SEGUIMEINTO_ENVIO_TMP_20260521;
SELECT 
* INTO #SEGUIMEINTO_ENVIO_TMP_20260521
	FROM MECE_LOGISTICO..SEGUIMIENTO_ENVIO SEG WITH (NOLOCK)
	WHERE SEG.ID_PROCESO IN(5,6)
	AND SEG.FECHA_HORA_MOVIMIENTO >= '2026-05-01'
	AND SEG.FECHA_HORA_MOVIMIENTO < '2026-05-21'

DROP TABLE IF EXISTS #GUIAS_NESESARIAS;
SELECT
DISTINCT NUMERO_GUIA
INTO #GUIAS_NESESARIAS
FROM #SEGUIMEINTO_ENVIO_TMP_20260521



ALTER TABLE #GUIAS_NESESARIAS ADD  CONSTRAINT [ZZZZIDX_GUIAS_NECESARIAS] UNIQUE NONCLUSTERED 
(
NUMERO_GUIA	ASC)
WITH (PAD_INDEX = OFF, STATISTICS_NORECOMPUTE = OFF, SORT_IN_TEMPDB = OFF, IGNORE_DUP_KEY = OFF, ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON, FILLFACTOR = 80) ON [PRIMARY]

DROP TABLE IF EXISTS #GUIAS_TMP;
SELECT 
G.* 
INTO #GUIAS_TMP
FROM Mece_Logistico.DBO.GUIAS G WITH(NOLOCK) 
INNER JOIN #GUIAS_NESESARIAS TMP ON TMP.NUMERO_GUIA=G.NUMERO_GUIA



SELECT 
	FECHA_MOVIMIENTO = (((YEAR(SEG.FECHA_HORA_MOVIMIENTO)*100)+MONTH(SEG.FECHA_HORA_MOVIMIENTO)*100)*100)+DAY(SEG.FECHA_HORA_MOVIMIENTO)
	,TIPO_CLIENTE = CASE WHEN GUI.ID_CLIENTE IS NULL AND ISNULL(GUI.ID_CANAL,'0')<>'0' THEN 'CONTADOS'
						WHEN GUI.ID_CLIENTE IS NOT NULL AND ISNULL(GUI.ID_CANAL,'0')='0' THEN 'CREDITO'
						ELSE 'OTROS'
						END
	,COUNT(GUI.NUMERO_GUIA) CANT_NUMERO_GUIA
	,SUM(GUI.VALOR_DECLARADO_GUIA) VALOR_DECLARADO_GUIA
	,SUM(GUI.VALOR_DESCUENTO_GUIAS) VALOR_DESCUENTO_GUIAS
	,SUM(GUI.VALOR_FLETES_GUIAS) VALOR_FLETES_GUIAS
	,SUM(GUI.VALOR_SEG_MAN_GUIAS) VALOR_SEG_MAN_GUIAS
	FROM #GUIAS_TMP GUI WITH(NOLOCK)
	INNER JOIN  #SEGUIMEINTO_ENVIO_TMP_20260521 SEG WITH (NOLOCK)
	ON GUI.NUMERO_GUIA=SEG.NUMERO_GUIA
	--WHERE SEG.ID_PROCESO IN(5,6)
	--AND SEG.FECHA_HORA_MOVIMIENTO >= '2026-05-01'
	--AND SEG.FECHA_HORA_MOVIMIENTO < '2026-05-21'
GROUP BY (((YEAR(SEG.FECHA_HORA_MOVIMIENTO)*100)+MONTH(SEG.FECHA_HORA_MOVIMIENTO)*100)*100)+DAY(SEG.FECHA_HORA_MOVIMIENTO),
CASE WHEN GUI.ID_CLIENTE IS NULL AND ISNULL(GUI.ID_CANAL,'0')<>'0' THEN 'CONTADOS'
						WHEN GUI.ID_CLIENTE IS NOT NULL AND ISNULL(GUI.ID_CANAL,'0')='0' THEN 'CREDITO'
						ELSE 'OTROS'
						END