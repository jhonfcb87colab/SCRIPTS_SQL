USE SIG_COLOMBIA_DW;
SELECT 
     TMP.NUMERO_GUIA
    ,TMP.FECHA_MODIFICACION_DG
    ,ISNULL(R.TIEMPO_ENTREGA_COMERCIAL_DIA,0) TIEMPO_OFERTA_DIA
	,DATEADD(DAY,ISNULL(R.TIEMPO_ENTREGA_COMERCIAL_DIA,0),TMP.FECHA_MODIFICACION_DG) FECHA_PROXIMA_VECE
FROM
    LOG.GUIAS TMP WITH(NOLOCK) 
INNER JOIN
    SIG_COL_LOGISTICA_DW.TMP.RED_OPERATIVA_RUTA  RA WITH(NOLOCK) 
ON
    TMP.ID_CIUDAD_ORIGEN = RA.ID_CIUDAD_ORIGEN
AND
    TMP.ID_CIUDAD_DESTINO = RA.ID_CIUDAD_DESTINO
AND
    CASE WHEN ISNULL(TMP.ID_TIEMPO,0) <> 0 THEN TMP.ID_TIEMPO ELSE 1 END = RA.ID_TIEMPO
AND
    CASE WHEN ISNULL(TMP.ID_MEDTRANS,0) <> 0 THEN TMP.ID_MEDTRANS ELSE 1 END = RA.ID_MEDTRANS
INNER JOIN
    SIG_COL_LOGISTICA_DW.DIM.RED_OPERATIVA_RUTA R WITH(NOLOCK) 
ON
    RA.ID_RUTA = R.ID_RUTA
WHERE TMP.NUMERO_GUIA in (
    2170740322,
    2170741971,
    2170741956,
    2170741938)





