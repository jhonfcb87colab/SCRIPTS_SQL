,SUC_DEP.ID_DEPENDEN
,SUC.ID_PAIS_SUCURSAL	
,SUC.ID_CIUDAD	
,SUC.NOMBRE_SUCURSAL
,SUC.NOMBRE_SUCURSAL AS SUC_NOMBRE_SUCURSAL
