,SUC_DEP.FECHA_MODIFICACION
FROM PARAMETROS..CLIENTES_SUCURSALES_DEPENDEN SUC_DEP WITH(NOLOCK)
INNER JOIN PARAMETROS..CLIENTES_SUCURSALES SUC WITH(NOLOCK)
ON SUC_DEP.ID_CLIENTE=SUC.ID_CLIENTE
AND SUC_DEP.ID_SUCURSAL=SUC.ID_SUCURSAL
