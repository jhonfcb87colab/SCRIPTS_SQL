

DROP TABLE IF EXISTS #RED_OPERATIVA_CALCULO_TIEMPO_PROMESA;
;WITH CIUDADES_MOVIMIENTOS_MOVILIZADOS AS (
SELECT 
CD.ID_CIUDAD,
CD.NOMBRE_CIUDAD,
RG.ID_REGIONAL,
RG.NOMBRE_REGIONAL
FROM PARAMETROS.DBO.CIUDADES CD WITH(NOLOCK)
INNER JOIN PARAMETROS.DBO.REGIONALES_PAIS RG WITH(NOLOCK)
ON RG.ID_REGIONAL=CD.ID_REGIONAL
WHERE CD.ID_PAIS=1
)
SELECT 
	 R.ID_RUTA
	,GEO.NOMBRE_REGIONAL REGIONAL_ORIGEN
	,GEO.NOMBRE_CIUDAD CIUDAD_ORIGEN
	,R.ID_CIUDAD_ORIGEN
	,GED.NOMBRE_REGIONAL REGIONAL_DESTINO
	,GED.NOMBRE_CIUDAD CIUDAD_DESTINO
	,R.ID_CIUDAD_DESTINO
	,TE.NOMBRE_TIEMPO
	,R.ID_TIEMPO
	,MT.NOMBRE_MEDTRANS
	,R.ID_MEDTRANS
	,IM.NOMBRE_IMPEDANCIA
	,R.ID_IMPEDANCIA
	,FC.NOMBRE_FILTRO
	,R.ID_FILTRO_CRITICIDAD
	,R.VALOR_FILTRO_CRITICIDAD
	,R.VALOR_FILTRO_MODO_TRANSPORTE
	,R.TOTAL_TIEMPO_OPERATIVO
	,R.TOTAL_TIEMPO_OPERATIVO_REF
	,R.TOTAL_DISTANCIA
	,R.TOTAL_COSTO
	,R.TOTAL_ID_CRITICIDAD
	,R.TOTAL_ID_PESOCATEG
	,R.LOGIN_EMPLEADO_MODIFICACION
	,R.FECHA_MODIFICACION
	,R.ID_ESTADO_RUTA
	,R.ID_RUTA_NET
	,R.TOTAL_TIEMPO_OPERATIVO_REF_CALCULO
	,R.TOTAL_DISTANCIA_CALCULO
	-- REGLA DEL NEGOCIO TOMADA DE RDO_FUN_TIEMPO_ENTREGA_COMERCIAL DE REDOPERATIVA
	,CASE WHEN
			R.ID_CIUDAD_ORIGEN = R.ID_CIUDAD_DESTINO
		THEN
			CASE WHEN R.ID_TIEMPO = 2 THEN 0 ELSE 24 END
		ELSE
			ISNULL(R.TOTAL_TIEMPO_OPERATIVO_REF/60,0)
		END [TIEMPO_ENTREGA_COMERCIAL_HOR]
	,CASE WHEN
			R.ID_CIUDAD_ORIGEN = R.ID_CIUDAD_DESTINO
		THEN
			CASE WHEN R.ID_TIEMPO = 2 THEN 0 ELSE 1 END
		ELSE
			ISNULL(R.TOTAL_TIEMPO_OPERATIVO_REF/1440,0)
		END [TIEMPO_ENTREGA_COMERCIAL_DIA]
	,R.LOGIN_MODIFICACION_MANUAL
 INTO #RED_OPERATIVA_CALCULO_TIEMPO_PROMESA
FROM 
	REDOPERATIVA.DBO.RUTA R WITH(NOLOCK)
LEFT JOIN
	CIUDADES_MOVIMIENTOS_MOVILIZADOS GEO
ON
	R.ID_CIUDAD_ORIGEN = GEO.ID_CIUDAD
LEFT JOIN
	CIUDADES_MOVIMIENTOS_MOVILIZADOS GED 
ON
	R.ID_CIUDAD_DESTINO = GED.ID_CIUDAD
LEFT JOIN
	PARAMETROS.DBO.TIEMPOSENTREGA TE WITH(NOLOCK)
ON
	R.ID_TIEMPO = TE.ID_TIEMPO
LEFT JOIN
	PARAMETROS.DBO.MEDIOTRANSPORTE MT WITH(NOLOCK)
ON
	R.ID_MEDTRANS = MT.ID_MEDTRANS
LEFT JOIN
	REDOPERATIVA.DBO.IMPEDANCIA IM WITH(NOLOCK)
ON
	R.ID_IMPEDANCIA = IM.ID_IMPEDANCIA
LEFT JOIN
	REDOPERATIVA.DBO.FILTROCRITICIDAD FC WITH(NOLOCK)
ON
	R.ID_FILTRO_CRITICIDAD = FC.ID_FILTRO_CRITICIDAD
WHERE 
	(R.ID_PAIS_ORIGEN = 1 AND R.ID_PAIS_DESTINO = 1)


;WITH CTE AS (
	SELECT
		 ROW_NUMBER() OVER(PARTITION BY TB_LOG.NUMERO_GUIA ORDER BY RA.FECHA_MODIFICACION DESC) #ROW_ID
		,TB_LOG.NUMERO_GUIA
		,TB_LOG.ID_MEDTRANS TB_LOG_ID_MEDTRANS
		,TB_LOG.ID_TIEMPO TB_LOG_ID_TIEMPO
	/**********************************************************************/
		,ISNULL(RA.TIEMPO_ENTREGA_COMERCIAL_DIA,0) RA_TIEMPO_OFERTA_DIA
		,RA.ID_CIUDAD_ORIGEN RA_ID_CIUDAD_ORIGEN
		,RA.ID_CIUDAD_DESTINO RA_ID_CIUDAD_DESTINO
		,RA.ID_RUTA RA_ID_RUTA
		,TB_LOG.FECHA_MODIFICACION
		,TB_LOG.FECHA_MODIFICACION_DG
	FROM
		Mece_Logistico.DBO.GUIAS TB_LOG WITH(NOLOCK) 
	LEFT JOIN
		#RED_OPERATIVA_CALCULO_TIEMPO_PROMESA  RA WITH(NOLOCK) 
	ON
		TB_LOG.ID_CIUDAD_ORIGEN = RA.ID_CIUDAD_ORIGEN
	AND
		TB_LOG.ID_CIUDAD_DESTINO = RA.ID_CIUDAD_DESTINO
	AND
		CASE WHEN ISNULL(TB_LOG.ID_TIEMPO,0) <> 0 THEN TB_LOG.ID_TIEMPO ELSE 1 END = RA.ID_TIEMPO
	AND
		CASE WHEN ISNULL(TB_LOG.ID_MEDTRANS,0) <> 0 THEN TB_LOG.ID_MEDTRANS ELSE 1 END = RA.ID_MEDTRANS
	--INNER JOIN
	--    SIG_COL_LOGISTICA_DW.DIM.RED_OPERATIVA_RUTA R WITH(NOLOCK) 
	--ON
	--    RA.ID_RUTA = R.ID_RUTA
	WHERE TB_LOG.NUMERO_GUIA IN 
			(
		221253097
		,221309842)
		)
SELECT 
NUMERO_GUIA
,RA_TIEMPO_OFERTA_DIA	
,RA_ID_CIUDAD_ORIGEN	
,RA_ID_CIUDAD_DESTINO
,RA_ID_RUTA
,FECHA_MODIFICACION
,FECHA_MODIFICACION_DG
FROM CTE WHERE #ROW_ID=1