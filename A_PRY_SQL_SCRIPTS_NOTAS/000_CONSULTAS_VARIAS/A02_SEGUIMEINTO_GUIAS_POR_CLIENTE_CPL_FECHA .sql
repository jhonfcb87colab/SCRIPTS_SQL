USE MECE_LOGISTICO;
DROP TABLE IF EXISTS #CIUDADEES_ANEXAS_PRUEBAS_20230929_10_22;
SELECT CL.ID_CIUDAD,CL.CENTRO_LOGISTICO,CDANX.ID_CIUDAD_ANEXA 
INTO #CIUDADEES_ANEXAS_PRUEBAS_20230929_10_22
FROM PARAMETROS..CIUDADES_ANEXAS CDANX WITH(NOLOCK) 
INNER JOIN PAR.CENTROS_LOGISTICOS CL (NOLOCK) 
ON CL.ID_PAIS = CDANX.ID_PAIS AND CL.ID_CIUDAD = CDANX.ID_CIUDAD and CL.ID_ESTADO = 1
WHERE CL.CENTRO_LOGISTICO LIKE '%NEIVA%'


SELECT G.NUMERO_GUIA 
FROM ..GUIAS G WITH(NOLOCK)
INNER JOIN ..SEGUIMIENTO_ENVIO SEG WITH(NOLOCK)
ON G.NUMERO_GUIA=SEG.NUMERO_GUIA
INNER JOIN ..DOCUMENTOS DOC WITH(NOLOCK)
ON (SEG.ID_PROCESO=DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI)
INNER JOIN PARAMETROS..CIUDADES CD  WITH(NOLOCK)
ON (CD.ID_CIUDAD=DOC.ID_CIUDAD_DIVISION_ORIGEN AND CD.ID_PAIS=DOC.ID_PAIS_DIVISION_ORIGEN)
WHERE G.ID_CLIENTE='900355585'
AND CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,SEG.FECHA_HORA_MOVIMIENTO))) = '2022-10-28'
AND DOC.ID_CIUDAD_DIVISION_ORIGEN IN(SELECT ID_CIUDAD_ANEXA FROM #CIUDADEES_ANEXAS_PRUEBAS_20230929_10_22 )





