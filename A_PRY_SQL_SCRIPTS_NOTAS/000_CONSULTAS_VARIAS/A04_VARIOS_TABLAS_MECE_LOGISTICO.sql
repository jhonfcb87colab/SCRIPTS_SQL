SELECT DOC.NUMERO_MOVIMI,SEG.* FROM DBO.SEGUIMIENTO_ENVIO SEG WITH(NOLOCK) 
INNER JOIN  MECE_LOGISTICO..DOCUMENTOS DOC WITH (NOLOCK) 
	ON SEG.ID_PROCESO=DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI
WHERE 
(YEAR(SEG.FECHA_HORA_MOVIMIENTO)*100 + MONTH(SEG.FECHA_HORA_MOVIMIENTO) )*100+DAY(SEG.FECHA_HORA_MOVIMIENTO) = 20230511 
AND SEG.ID_PROCESO=6


