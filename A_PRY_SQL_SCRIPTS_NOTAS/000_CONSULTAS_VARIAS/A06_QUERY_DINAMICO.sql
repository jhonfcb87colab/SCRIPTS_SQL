--------ALTER PROCEDURE [dbo].[TURECAUDO_PYME_CLIENTE_FECHA]



declare @GR_ID_CLIENTE  VARCHAR(20) = NULL
declare @GR_COD_CLIENTE     VARCHAR(20) = NULL
declare @FECHAINI VARCHAR(100) = NULL
declare @FECHAFIN VARCHAR(100) = NULL
declare @ErrorMessage NVARCHAR(MAX) = NULL




SET DATEFORMAT MDY
SET @FECHAINI = CONVERT(VARCHAR,CONVERT(DATETIME,@FECHAINI),111)
SET @FECHAFIN = CONVERT(VARCHAR,CONVERT(DATETIME,@FECHAFIN),111)



BEGIN TRY
    IF (@GR_ID_CLIENTE IS NULL AND @GR_COD_CLIENTE IS NULL)
    BEGIN
    SET @ErrorMessage = REPLACE('1.0 Se debe digitar por lo menos un Parámetro',',')
    RAISERROR (@ErrorMessage,16,1)
    END
    ELSE
    BEGIN
    IF (@GR_ID_CLIENTE = ' ' AND @GR_COD_CLIENTE= ' ')
    BEGIN
    SET @ErrorMessage = REPLACE('1.0 Se debe digitar por lo menos un Parámetro',',')
    RAISERROR (@ErrorMessage,16,1)
    END
    END
    IF ((@GR_ID_CLIENTE <> ' ' AND @GR_COD_CLIENTE IS NOT NULL) AND (@GR_COD_CLIENTE <> ' ' AND @GR_ID_CLIENTE IS NOT NULL) )
    BEGIN
    SET @ErrorMessage = REPLACE('1.1 No se puede realizar la consulta con varios Parámetros',',')
    RAISERROR (@ErrorMessage,16,1)
    END
    IF (@FECHAINI IS NULL OR @FECHAFIN IS NULL)
    BEGIN
    SET @ErrorMessage = REPLACE('1.2 Debe ingresar fecha Desde - Hasta',',')
    RAISERROR (@ErrorMessage,16,1)
    END
    IF (@FECHAINI= ' ' OR  @FECHAFIN = ' ')
    BEGIN
    SET @ErrorMessage = REPLACE('1.2 Debe ingresar fecha Desde - Hasta',',')
    RAISERROR (@ErrorMessage,16,1)
    END        
    IF ((@GR_ID_CLIENTE IS NOT NULL AND  @FECHAINI < @FECHAFIN AND  (@GR_COD_CLIENTE IS NULL OR @GR_COD_CLIENTE = ' ')))
    BEGIN
    DECLARE @SQLR NVARCHAR(MAX)
    DECLARE @TMP TABLE(code bigint)
    SET @SQLR= 'SELECT GR_NUMERO_GUIA FROM [FAC].[TURECAUDO_PYMES_CE] WITH (NOLOCK)
    WHERE GR_ID_CLIENTE  = ''+@GR_ID_CLIENTE+ '' AND GR_FECHA_ENVIO >=  ''+@FECHAINI+'' AND CONVERT(VARCHAR,(CONVERT (DATE,GR_FECHA_ENVIO)),111) <=  ''+@FECHAFIN+''
     INSERT INTO  @TMP (code)
     EXEC (@SQLR)     
    IF((SELECT COUNT(*) FROM @TMP) = 0)
        BEGIN    
        SET @ErrorMessage = REPLACE('1.4 No existe información para esta consulta',',')
        RAISERROR (@ErrorMessage,16,1)
    END    
    END
    IF ((@GR_COD_CLIENTE IS NOT NULL AND @FECHAINI < @FECHAFIN AND  (@GR_ID_CLIENTE IS NULL OR @GR_ID_CLIENTE = ' ')))
    BEGIN
    DECLARE @SQLRC NVARCHAR(MAX)
    DECLARE @TMPC TABLE(code bigint)
    SET @SQLRC= 'SELECT GR_NUMERO_GUIA FROM [FAC].[TURECAUDO_PYMES_CE] WITH (NOLOCK)
    WHERE GR_CODIGO_CLIENTE  = ''+@GR_COD_CLIENTE+'' AND GR_FECHA_ENVIO >=  ''+@FECHAINI+'' AND CONVERT(VARCHAR,(CONVERT (DATE,GR_FECHA_ENVIO)),111) <= ''+@FECHAFIN+''
     INSERT INTO  @TMPC (code)
     EXEC (@SQLRC)     
    IF((SELECT COUNT(*) FROM @TMPC) = 0)
        BEGIN    
        SET @ErrorMessage = REPLACE('1.4 No existe información para esta consulta',',')
        RAISERROR (@ErrorMessage,16,1)
    END    
    END
    IF (@FECHAFIN < @FECHAINI)
    BEGIN
    SET @ErrorMessage = REPLACE('1.3 Fechas Desde - Hasta, no corresponden',',')
    RAISERROR (@ErrorMessage,16,1)
    END
    



   




DECLARE @VAR_GR_CLIENTE VARCHAR(20)
DECLARE @VAR_COD_CLIENTE VARCHAR(20)
DECLARE @VAR_FECHA_INI VARCHAR(100)
DECLARE @VAR_FECHA_FIN VARCHAR(100)



SET @VAR_GR_CLIENTE = REPLACE(@GR_ID_CLIENTE,',',',')    
SET @VAR_COD_CLIENTE = REPLACE(@GR_COD_CLIENTE,',',',')
SET @VAR_FECHA_INI = REPLACE(@FECHAINI,',',',')
SET @VAR_FECHA_FIN = REPLACE(@FECHAFIN,',',',')
IF (@GR_COD_CLIENTE IS  NULL OR @GR_COD_CLIENTE = ' ')
BEGIN
DECLARE @SQL NVARCHAR(MAX)
SET @SQL= '



SELECT [GR_NUMERO_GUIA]      
      ,[GR_FECHA_ENVIO]
      ,[GR_TIPO_ID_CLIENTE]
      ,[GR_ID_CLIENTE]
      ,[GR_ID_CLIENTE_VERI]
      ,[GR_CLIENTE]
      ,[GR_CODIGO_CLIENTE]
      ,[GR_ID_CLIENTE_REMI]
      ,[GR_NOMBRE_CLIENTE_REMI]
      ,[GR_CIUDAD_ORIG]
      ,[GR_CIUDAD_DEST]
      ,[GR_STATUS_FECHA]
      ,[GR_STATUS_PAGO]
      ,[GR_STATUS]
      ,[GR_STATUS_DESC]
      ,[TC_CIUDAD_ULTI_MOVI]
      ,[TC_ESTADO_ENVIO]
      ,[TC_PROCESO_ULTI_MOVI]
      ,[IR_VALOR_FACTURADO]
      ,[IR_VALOR_X_RECAUDAR]
      ,[IR_VALOR_RECAUDADO]
      ,[EF_ORDEN_SERVICIO]
      ,[EF_VALOR]
      ,[EF_FECHA_RECAUDO_DESC]
      ,[EF_PROYECTO]
      ,[GD_TIPO_CLIENTE_DEST]
      ,[GD_ID_CLIENTE_DEST]
      ,[GD_NOMBRE_CLIENTE_DEST]
  FROM [FAC].[TURECAUDO_PYMES_CE] WITH (NOLOCK)
  WHERE GR_ID_CLIENTE  = '' + @GR_ID_CLIENTE + '' AND GR_FECHA_ENVIO >=  '' + @FECHAINI + '' AND CONVERT(VARCHAR,(CONVERT (DATE,GR_FECHA_ENVIO)),111) <=  '' + @FECHAFIN + ''
  AND EF_PROYECTO = '111084'
AND GR_CODIGO_CLIENTE LIKE 'RET%''
-- OR GR_CODIGO_CLIENTE >= @GR_COD_CLIENTE
EXEC(@SQL)



END



IF (@GR_ID_CLIENTE IS  NULL OR @GR_ID_CLIENTE = ' ')
BEGIN
DECLARE @SQL2 NVARCHAR(MAX)
SET @SQL2= '



SELECT [GR_NUMERO_GUIA]     
      ,[GR_FECHA_ENVIO]
      ,[GR_TIPO_ID_CLIENTE]
      ,[GR_ID_CLIENTE]
      ,[GR_ID_CLIENTE_VERI]
      ,[GR_CLIENTE]
      ,[GR_CODIGO_CLIENTE]
      ,[GR_ID_CLIENTE_REMI]
      ,[GR_NOMBRE_CLIENTE_REMI]
      ,[GR_CIUDAD_ORIG]
      ,[GR_CIUDAD_DEST]
      ,[GR_STATUS_FECHA]
      ,[GR_STATUS_PAGO]
      ,[GR_STATUS]
      ,[GR_STATUS_DESC]
      ,[TC_CIUDAD_ULTI_MOVI]
      ,[TC_ESTADO_ENVIO]
      ,[TC_PROCESO_ULTI_MOVI]
      ,[IR_VALOR_FACTURADO]
      ,[IR_VALOR_X_RECAUDAR]
      ,[IR_VALOR_RECAUDADO]
      ,[EF_ORDEN_SERVICIO]
      ,[EF_VALOR]
      ,[EF_FECHA_RECAUDO_DESC]
      ,[EF_PROYECTO]
      ,[GD_TIPO_CLIENTE_DEST]
      ,[GD_ID_CLIENTE_DEST]
      ,[GD_NOMBRE_CLIENTE_DEST]
  FROM [FAC].[TURECAUDO_PYMES_CE] WITH (NOLOCK)
  WHERE GR_CODIGO_CLIENTE  = '' + @GR_COD_CLIENTE + '' AND GR_FECHA_ENVIO >=  '' + @FECHAINI + ''AND CONVERT(VARCHAR,(CONVERT (DATE,GR_FECHA_ENVIO)),111) <= '' + @FECHAFIN + ''
-- OR GR_CODIGO_CLIENTE >= @GR_COD_CLIENTE
EXEC(@SQL2)



END
END TRY  
BEGIN CATCH
    SET @ErrorMessage = ERROR_MESSAGE()
    RAISERROR (@ErrorMessage,16,1)
END CATCH