USE Mece_Logistico;
--GO

WITH CTE_CONSULTA_PROCESOS_LOGISTICOS
AS(
	SELECT  ROW_NUMBER ( )   OVER ( PARTITION BY GUI.[NUMERO_GUIA] order by SEG.FECHA_HORA_MOVIMIENTO desc )  #ROW_ID  
		,GUI.[NUMERO_GUIA]
		,CONCEP.NOMBRE_CONCEPTO
		,ESEV.NOMBRE_ESTADOENVIO
		,SEG.ID_PROCESO
		,PR.NOMBRE_PROCESO_LOG 
		,SEG.NUMERO_MOVIMI
		,SEG.CONSECUT_MOVIMI
		,SEG.FECHA_MODIFICACION
		,SEG.FECHA_HORA_MOVIMIENTO
		,GUI.FECHA_ENVIO
		,GUI.FECHA_MODIFICACION_DG	
		,'----DESTINOS------->' DESTINOS
		,DIV.ID_DIVISION AS ID_DIVISION_DESTINO 
		,DOC.ID_CIUDAD_DESTINO
		,CIUD.NOMBRE_CIUDAD	NOMBRE_CIUDAD_DESTINO
		,DIV.[NOMBRE_DIVISION] as NOMBRE_DIVISION_DESTINO
		,REGIO.NOMBRE_REGIONAL AS NOMBRE_REGIONAL_DESTINO
		,'----ORIGENES------->' ORIGENES
		,DOC.ID_CIUDAD_DIVISION_ORIGEN
		,DIV_org.ID_DIVISION AS ID_DIVISION_ORIGEN
		,DIV_org.[NOMBRE_DIVISION] as NOMBRE_DIVISION_ORIGEN
		,'--------------------' tt
		,ZONAS.NOMBRE_ZONA_URBA as ZONAS_NOMBRE_ZONA_URBA
		,DOC.ID_PAIS_DESTINO AS DOC_ID_PAIS_DESTINO
		,DOC.ID_CIUDAD_DESTINO AS DOC_ID_CIUDAD_DESTINO
		,DOC.ID_ZONA_URBA AS DOC_ID_ZONA_URBA
		,ZONAS.ID_TIPO_ZONA_URBA AS ZONAS_ID_TIPO_ZONA_URBA
		,DOC.ID_TIPO_ZONA_URBA AS DOC_ID_TIPO_ZONA_URBA
		,'--------------------' tt444
	FROM MECE_LOGISTICO..GUIAS GUI WITH(NOLOCK)
	LEFT JOIN  MECE_LOGISTICO..SEGUIMIENTO_ENVIO SEG WITH (NOLOCK)
	ON GUI.NUMERO_GUIA=SEG.NUMERO_GUIA
	LEFT JOIN  MECE_LOGISTICO..DOCUMENTOS DOC WITH (NOLOCK) 
	ON SEG.ID_PROCESO=DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI
	LEFT JOIN PARAMETROS..DIVISIONES DIV WITH (NOLOCK)
	ON DIV.ID_DIVISION=DOC.ID_DIVISION_DESTINO AND DOC.ID_CIUDAD_DESTINO=DIV.ID_CIUDAD 
	LEFT JOIN PARAMETROS..DIVISIONES DIV_org WITH (NOLOCK)
	ON DIV_org.ID_DIVISION=DOC.ID_DIVISION_ORIGEN AND DOC.ID_CIUDAD_DIVISION_ORIGEN=DIV_org.ID_CIUDAD 
	LEFT JOIN PARAMETROS..PROCESOS PR ON SEG.ID_PROCESO=PR.ID_PROCESO
	LEFT JOIN PARAMETROS..CIUDADES CIUD ON CIUD.ID_CIUDAD=DOC.ID_CIUDAD_DESTINO
	LEFT JOIN PARAMETROS..REGIONALES_PAIS REGIO ON REGIO.ID_REGIONAL=CIUD.ID_REGIONAL
	LEFT JOIN ..ESTADOSENVIO ESEV WITH(NOLOCK) ON ESEV.ID_ESTADOENVIO=GUI.ID_ESTADOENVIO
	LEFT JOIN [PARAMETROS].[dbo].[ITEM_CONCEPTO] CONCEP  WITH (NOLOCK)
	ON (CONCEP.ID_CONCEPTO=SEG.ID_CONCEPTO AND CONCEP.ID_PROCESO=SEG.ID_PROCESO)
	LEFT JOIN [PARAMETROS].[dbo].[ZONASURBANAS] ZONAS WITH (NOLOCK)
	ON (ZONAS.ID_ZONA_URBA=DOC.ID_ZONA_URBA
		AND ZONAS.ID_PAIS=1
		AND ZONAS.ID_CIUDAD=IIF(SEG.ID_PROCESO IN(9,32,24,31),DOC.ID_CIUDAD_DIVISION_ORIGEN,DOC.ID_CIUDAD_DESTINO) 
		AND ZONAS.ID_TIPO_ZONA_URBA=DOC.ID_TIPO_ZONA_URBA ) 
	WHERE 
	GUI.[NUMERO_GUIA] IN 
	 (
9166591693
  
)	 ---AND PR.ID_PROCESO=9
)
SELECT 
NUMERO_GUIA,
NOMBRE_DIVISION_DESTINO,
ZONAS_NOMBRE_ZONA_URBA,
DOC_ID_CIUDAD_DESTINO,
DOC_ID_PAIS_DESTINO,
DOC_ID_ZONA_URBA,
DOC_ID_TIPO_ZONA_URBA,
ID_PROCESO,
NOMBRE_PROCESO_LOG,
FECHA_MODIFICACION,
FECHA_HORA_MOVIMIENTO
FROM CTE_CONSULTA_PROCESOS_LOGISTICOS
WHERE  #ROW_ID BETWEEN 1 AND 10
--ORDER BY FECHA_HORA_MOVIMIENTO DESC
ORDER BY NUMERO_GUIA DESC


