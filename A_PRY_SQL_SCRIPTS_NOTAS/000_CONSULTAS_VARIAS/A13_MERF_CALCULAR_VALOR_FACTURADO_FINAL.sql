SELECT [NUMERO_GUIA], SUM(X1_VL_FAC) FROM (
SELECT [NUMERO_GUIA]
      ,[NUMERO_PIEZA]
	  ,X1_VL_FAC = ISNULL(VALOR_FLETES_PIEZA + VALOR_SEG_MAN_PIEZA - VALOR_DESCUENTO_PIEZA,0)
    FROM [dbo].[MECE_LOGISTICO_PIEZAS_ENVIO] WITH(NOLOCK)
where [NUMERO_GUIA] IN(3024172604)
) CY
GROUP BY [NUMERO_GUIA]

SELECT 
NUMERO_GUIA
,VALOR_FLETES_GUIAS
,VALOR_SEG_MAN_GUIAS
,VALOR_DESCUENTO_GUIAS
,X1_VL_FAC = ISNULL(VALOR_FLETES_GUIAS + VALOR_SEG_MAN_GUIAS - VALOR_DESCUENTO_GUIAS,0)
FROM [dbo].[MECE_LOGISTICO_GUIAS] WITH(NOLOCK)
where [NUMERO_GUIA] IN(3024172604)
