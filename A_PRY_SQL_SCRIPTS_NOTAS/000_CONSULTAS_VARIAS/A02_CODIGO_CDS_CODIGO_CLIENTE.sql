




-----------------------------> NOMBRE CLIENTE CORPORATIVO
SELECT
NOMBRE_CLIENTE = CONCAT(RTRIM(LTRIM(G.ID_CLIENTE)),'-',(ISNULL(CLI.NOMBRE_CLIENTE,'') + ' ' + ISNULL(CLI.APELLIDO_CLIENTE,'')))
FROM Mece_Logistico.DBO.GUIAS G (NOLOCK)
INNER JOIN PARAMETROS.DBO.CLIENTES CLI (NOLOCK) ON CLI.ID_PAIS = 1 AND CLI.ID_CLIENTE = G.ID_CLIENTE
WHERE G.NUMERO_GUIA=2117011410

-----------------------------> NOMBRE CENTRO DE SOLUCIONES CDS
SELECT
NOMBRE_CDS = CONCAT(RTRIM(LTRIM(DIV.CODIGO_ACTUAL)),'-',DIV.NOMBRE_DIVISION)
FROM Mece_Logistico.DBO.GUIAS G (NOLOCK)
LEFT JOIN PARAMETROS.DBO.DIVISIONES DIV (NOLOCK) 
ON DIV.ID_PAIS = G.ID_PAIS_ORIGEN AND DIV.ID_CIUDAD = G.ID_CIUDAD_ORIGEN AND DIV.ID_DIVISION = G.ID_CANAL
WHERE G.NUMERO_GUIA= 9147068585



