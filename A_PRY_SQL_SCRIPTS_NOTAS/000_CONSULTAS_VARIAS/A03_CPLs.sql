WITH CTE AS (
SELECT  ROWID = ROW_NUMBER() OVER(PARTITION BY CD.[ID_PAIS],CD.ID_CIUDAD ORDER BY CD.FECHA_MODIFICACION DESC)
        ,CD.[ID_PAIS]
        ,CD.[ID_CIUDAD]
		,CA.ID_CIUDAD AS ID_CIUDAD_PRINCIPAL
        ,CA.ID_CIUDAD_ANEXA
		,CD.ID_REGIONAL
  --      ,RTRIM(CL.CENTRO_LOGISTICO) AS CPL --VARCHAR(50)
		--,CL.FECHA_MODIFICACION
FROM PARAMETROS..CIUDADES CD (NOLOCK)
LEFT JOIN PARAMETROS..[CIUDADES_ANEXAS] CA (NOLOCK)
ON	CA.ID_CIUDAD_ANEXA = CD.ID_CIUDAD AND 	CA.ID_PAIS = CD.ID_PAIS
)SELECT
CT.ID_CIUDAD_PRINCIPAL
,CT.ID_PAIS	
,CT.ID_CIUDAD	
,CT.ID_CIUDAD_ANEXA	
,CT.ID_REGIONAL	
,CPL = CASE WHEN CL.CENTRO_LOGISTICO IS NOT NULL THEN CL.CENTRO_LOGISTICO 
			WHEN CL.CENTRO_LOGISTICO IS NULL AND CT.ID_CIUDAD_ANEXA	IS NOT NULL AND CT.ID_CIUDAD_PRINCIPAL IS NOT NULL THEN 'ERROR - NO EXISTE EN PARAMETROS CENTRO LOGISTICO'
			WHEN CL.CENTRO_LOGISTICO IS NULL AND CT.ID_CIUDAD_ANEXA	IS NULL THEN 'ERROR - NO EXISTE EN PARAMETROS CIUDAD ANEXA'
			--WHEN CL.CENTRO_LOGISTICO IS NULL AND CT.ID_CIUDAD_ANEXA	IS NULL THEN 
			ELSE 'SIN DATOS' END
----INTO #CPLBORRARPRUEBAS
FROM CTE CT
LEFT JOIN PARAMETROS..CENTROS_LOGISTICOS CL (NOLOCK)
ON CT.ID_PAIS = CL.ID_PAIS AND CT.ID_CIUDAD_PRINCIPAL = CL.ID_CIUDAD
AND CL.ID_CENTRO_LOGISTICO=1 AND CL.ID_ESTADO=1
WHERE ROWID=1




































