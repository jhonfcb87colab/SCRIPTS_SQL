DECLARE @FECHA_I DATETIME, @FECHA_INI DATETIME, @FECHA_FIN DATETIME, @FECHA_MANUAL DATETIME

SET @FECHA_MANUAL = '2017-04-01 00:00:00.000' --SE CAMBIA LA FECHA DEL 01/09/2016 POR 01/04/2017, YA QUE EL CAMBIO APLICA SOLO DESDE ABRIL 2017 
SET @FECHA_I =    '2026-09-10'; 
SET @FECHA_FIN =  '2026-09-11';
IF @FECHA_I >= @FECHA_MANUAL
	BEGIN
		SET @FECHA_INI = @FECHA_I
	END
ELSE
	BEGIN
		SET @FECHA_INI = @FECHA_MANUAL
	END

DROP TABLE IF EXISTS #GUIAS_ANALIZAR

	--;WITH CTE AS(
	SELECT	
	GUIAS.NUMERO_GUIA, 
	GUIAS.NUMERO_PIEZAS
	INTO #GUIAS_ANALIZAR
	FROM MECE_LOGISTICO.DBO.GUIAS GUIAS WITH (NOLOCK)
	INNER  JOIN MECE_LOGISTICO.DBO.SEGUIMIENTO_ENVIO SEG WITH (NOLOCK)
	ON SEG.NUMERO_GUIA = GUIAS.NUMERO_GUIA
	WHERE SEG.FECHA_HORA_MOVIMIENTO >=  @FECHA_INI 		
		AND SEG.FECHA_HORA_MOVIMIENTO <  @FECHA_FIN		
		AND SEG.ID_PROCESO IN (5,6) 
	OPTION(RECOMPILE)
	--) 
	
	SELECT 
	SUM(NUMERO_PIEZAS)
	FROM #GUIAS_ANALIZAR


----------------------------------------------------> SALIDAS A ZONA

SELECT
sum(GUIAS.NUMERO_PIEZAS) GUIAS_SALIDA_ZONA
--REGIO_ORIG.NOMBRE_REGIONAL AS NOMBRE_REGIONAL_ORIG,
--CIUD_ORIG.NOMBRE_CIUDAD AS NOMBRE_CIUDAD_ORG,
FROM MECE_LOGISTICO.DBO.GUIAS GUIAS WITH (NOLOCK)
	INNER JOIN	Mece_Logistico.dbo.SEGUIMIENTO_ENVIO AS SE_FECH   	
	ON SE_FECH.NUMERO_GUIA = GUIAS.NUMERO_GUIA 
	INNER JOIN  MECE_LOGISTICO..DOCUMENTOS DOC WITH (NOLOCK) 
	ON SE_FECH.ID_PROCESO=DOC.ID_PROCESO AND SE_FECH.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND SE_FECH.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI		
	-------------->CIUDAD DESTINO
	LEFT JOIN PARAMETROS..CIUDADES CIUD_DEST ON CIUD_DEST.ID_CIUDAD=DOC.ID_CIUDAD_DESTINO
	LEFT JOIN PARAMETROS..REGIONALES_PAIS REGIO_DESTI ON REGIO_DESTI.ID_REGIONAL=CIUD_DEST.ID_REGIONAL
	-------------->CIUDAD ORIGEN
	LEFT JOIN PARAMETROS..CIUDADES CIUD_ORIG ON CIUD_ORIG.ID_CIUDAD=DOC.ID_CIUDAD_DIVISION_ORIGEN
	LEFT JOIN PARAMETROS..REGIONALES_PAIS REGIO_ORIG ON REGIO_ORIG.ID_REGIONAL=CIUD_ORIG.ID_REGIONAL
		WHERE FECHA_HORA_MOVIMIENTO >= '2026-09-11' 
		AND FECHA_HORA_MOVIMIENTO < '2026-09-12'
		AND GUIAS.ID_DOCU_ULT_MOVI >= 4 -- ID_PROCESO
		AND SE_FECH.ID_PROCESO IN(9)
		AND LEN(GUIAS.NUMERO_GUIA) > 8
		AND DOC.ESTADO_MOVIMI = 2  /*   "ESTADO MANIFIESTO" 0=Iniciado / 1=abierto 2=Cerrado*/ 












