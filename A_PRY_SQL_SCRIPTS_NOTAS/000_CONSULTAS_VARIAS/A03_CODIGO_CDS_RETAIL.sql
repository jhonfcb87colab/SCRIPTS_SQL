  USE SIG_COLOMBIA_DW;
  SELECT TOP 100 INV.Number,SLTC.CountryId,SLTC.CityId,SLTC.SolutionCenterId, DV.NOMBRE_DIVISION,DV.CODIGO_ACTUAL 
  FROM RTW.INVOICE  INV WITH(NOLOCK)
  INNER JOIN [RTW].[CASHREGISTER] CSH WITH(NOLOCK)
  ON CSH.ID=INV.CashRegisterId
  INNER JOIN RTW.SOLUTIONCENTER SLTC WITH(NOLOCK)
  ON SLTC.Id=CSH.SolutionCenterId
  INNER JOIN PAR.DIVISIONES DV ON (
  SLTC.CountryId=DV.ID_PAIS AND
  SLTC.CityId=DV.ID_CIUDAD AND
  SLTC.SolutionCenterId=DV.ID_DIVISION
  )