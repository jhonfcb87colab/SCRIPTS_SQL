--GO
WITH CTE_CONSULTA_PROCESOS_LOGISTICOS
AS(
	SELECT  
	--ROW_NUMBER ( )   OVER ( PARTITION BY GUI.[NUMERO_GUIA] order by DOC.FECHA_HORA_MOVIMI desc )  #ROW_ID_DOC
	ROW_NUMBER ( )   OVER ( PARTITION BY GUI.[NUMERO_GUIA] order by SEG.FECHA_HORA_MOVIMIENTO asc )  #ROW_ID_SE
	--,ROW_NUMBER ( )   OVER ( PARTITION BY GUI.[NUMERO_GUIA] order by 
	--															IIF(SEG.FECHA_HORA_MOVIMIENTO > DOC.FECHA_HORA_MOVIMI , SEG.FECHA_HORA_MOVIMIENTO ,DOC.FECHA_HORA_MOVIMI)
	--															desc )  #ROW_ID_COMPLEMENTO
		,GUI.[NUMERO_GUIA]
		,SEG.ID_PROCESO
		,GUI.PESO_FISICO_GUIA
		,GUI.PESO_GUIA
		,SEG.PESO_ENVIO
		,GUI.ID_DESTINA
		,GUI.ID_CIUDAD_DESTINO as ID_CIUDAD_DESTINO_ENVIO
		,GUI.TELEFONO_DESTINA_GUIA
		--,doc.PLACA_VEHICULO_DOCU
		,DOC.PESO_TOTAL AS DOC_PESO_TOTAL
		,PR.NOMBRE_PROCESO_LOG
		,GUI.ID_ESTADOGUIA
		,GUI.ID_ESTADOENVIO
		,GUI.ID_REMITE
		,GUI.ID_CLIENTE
		,SEG.FECHA_CREACION AS SEG_FECHA_CREACION
		,CIUD_DEST_GUI.NOMBRE_CIUDAD AS NOMBRE_CIUDAD_ENVIO_DEST 
		,CIUD_ORIG_GUI.NOMBRE_CIUDAD AS NOMBRE_CIUDAD_ENVIO_ORG
		,CIUD_ZONA_URBA.NOMBRE_CIUDAD AS NOMBRE_CIUDAD_ZONA_URBA
		,GUI.FECHA_MODIFICACION_DG
		,SEG.FECHA_HORA_MOVIMIENTO SEGIM_FECHA_HORA_MOVIMIENTO
		,DOC.FECHA_HORA_MOVIMI DOCUM_FECHA_HORA_MOVIMIENTO
		,FECHA_MAX_FECHA_HORA_MOV = IIF(SEG.FECHA_HORA_MOVIMIENTO > DOC.FECHA_HORA_MOVIMI , SEG.FECHA_HORA_MOVIMIENTO ,DOC.FECHA_HORA_MOVIMI)
		,SEG.CONSECUT_MOVIMI
		,SEG.NUMERO_MOVIMI
		,SEG.FECHA_HORA_MOVIMIENTO
		,SEG.FECHA_MODIFICACION
		--,GUI.FECHA_MODIFICACION_DG
		,'----DESTINOS------->' DESTINOS
		,DIV_DEST.ID_DIVISION AS ID_DIVISION_DESTINO 
		,DOC.ID_CIUDAD_DESTINO
		,CIUD_DEST.NOMBRE_CIUDAD	NOMBRE_CIUDAD_DESTINO
		,DIV_DEST.[NOMBRE_DIVISION] as NOMBRE_DIVISION_DESTINO
		,REGIO_DESTI.NOMBRE_REGIONAL AS NOMBRE_REGIONAL_DESTINO

		,DOC.ID_AUXILIAR1_VEHICULO
		,DOC.ID_AUXILIAR2_VEHICULO
		,DOC.ID_COURIER_CONDUCTOR
		,DOC.PLACA_VEHICULO_DOCU
		,SEG.ID_EMPLEADO
		,SEG.ID_CONCEPTO
		,CONCEP.NOMBRE_CONCEPTO
		,SEG.FECHA_HORA_MOVIMIENTO AS SEG_FECHA_HORA_MOVIMIENTO
		,DOC.FECHA_HORA_MOVIMI AS DOC_FECHA_HORA_MOVIMI
		,GUI.FECHA_ENVIO
		,ESEV.NOMBRE_ESTADOENVIO
		,DOC.ID_PAIS_ZONA_URBA
		,DOC.ID_CIUDAD_ZONA_URBA
		,GUI.NUMERO_PIEZAS AS GUI_NUMERO_PIEZAS
		,SEG.NUMERO_PIEZAS AS SEG_NUMERO_PIEZAS
		,DOC.ID_ZONA_URBA
		,DOC.ID_TIPO_ZONA_URBA
		,ZNURB.NOMBRE_ZONA_URBA
		,DOC.FECHA_HORA_CIERRE
		,'----------' AS [------------]

		,'----ORIGENES------->' ORIGENES
		,DOC.ID_DIVISION_ORIGEN AS ID_DIVISION_ORIGEN 
		,DOC.ID_CIUDAD_DIVISION_ORIGEN
		,CIUD_ORIG.NOMBRE_CIUDAD	NOMBRE_CIUDAD_ORIGEN
		,DIV_ORIG.[NOMBRE_DIVISION] as NOMBRE_DIVISION_ORIGEN
		,REGIO_ORIG.NOMBRE_REGIONAL AS NOMBRE_REGIONAL_ORIGEN
		--,DOC.FECHA_HORA_CIERRE
		,DOC.FECHA_MODIFICACION AS DOC_FECHA_MODIFICACION
		,SEG.FECHA_MODIFICACION AS SEG_FECHA_MODIFICACION
		,PRD.NOMBRE_SUBPRODUCTO
	FROM MECE_LOGISTICO..GUIAS GUI WITH(NOLOCK)
	INNER JOIN  MECE_LOGISTICO..SEGUIMIENTO_ENVIO SEG WITH (NOLOCK)
	ON GUI.NUMERO_GUIA=SEG.NUMERO_GUIA
	INNER JOIN  MECE_LOGISTICO..DOCUMENTOS DOC WITH (NOLOCK) 
	ON SEG.ID_PROCESO=DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI
	LEFT JOIN PARAMETROS..PROCESOS PR ON SEG.ID_PROCESO=PR.ID_PROCESO

	LEFT JOIN PARAMETROS..SUBPRODUCTOS PRD ON GUI.ID_PRODUCTO=PRD.ID_PRODUCTO AND GUI.ID_SUBPRODUCTO=PRD.ID_SUBPRODUCTO
	
	-------------->CIUDAD DESTINO GUIA ENVIO
	LEFT JOIN PARAMETROS..CIUDADES CIUD_DEST_GUI ON CIUD_DEST_GUI.ID_CIUDAD=GUI.ID_CIUDAD_DESTINO
	-------------->CIUDAD ORIGEN GUIA ENVIO
	LEFT JOIN PARAMETROS..CIUDADES CIUD_ORIG_GUI ON CIUD_ORIG_GUI.ID_CIUDAD=GUI.ID_CIUDAD_ORIGEN

	-------------->CIUDAD ORIGEN ZONA URBA
	LEFT JOIN PARAMETROS..CIUDADES CIUD_ZONA_URBA ON CIUD_ORIG_GUI.ID_CIUDAD=GUI.ID_CIUDAD_ORIGEN
	AND CIUD_ZONA_URBA.ID_CIUDAD=DOC.ID_CIUDAD_ZONA_URBA

	
	-------------->CIUDAD DESTINO
	LEFT JOIN PARAMETROS..CIUDADES CIUD_DEST ON CIUD_DEST.ID_CIUDAD=DOC.ID_CIUDAD_DESTINO
	LEFT JOIN PARAMETROS..REGIONALES_PAIS REGIO_DESTI ON REGIO_DESTI.ID_REGIONAL=CIUD_DEST.ID_REGIONAL
	LEFT JOIN PARAMETROS..DIVISIONES DIV_DEST WITH (NOLOCK)
	ON DIV_DEST.ID_DIVISION=DOC.ID_DIVISION_DESTINO AND DOC.ID_CIUDAD_DESTINO=DIV_DEST.ID_CIUDAD 

	-------------->CIUDAD ORIGEN
	LEFT JOIN PARAMETROS..CIUDADES CIUD_ORIG ON CIUD_ORIG.ID_CIUDAD=DOC.ID_CIUDAD_DIVISION_ORIGEN
	LEFT JOIN PARAMETROS..REGIONALES_PAIS REGIO_ORIG ON REGIO_ORIG.ID_REGIONAL=CIUD_ORIG.ID_REGIONAL
	LEFT JOIN PARAMETROS..DIVISIONES DIV_ORIG WITH (NOLOCK)
	ON DIV_ORIG.ID_DIVISION=DOC.ID_DIVISION_ORIGEN AND DOC.ID_CIUDAD_DIVISION_ORIGEN=DIV_ORIG.ID_CIUDAD 

	-------------->ZONAS URBANAS
	LEFT JOIN PARAMETROS..ZONASURBANAS ZNURB (NOLOCK)
	ON(ZNURB.ID_TIPO_ZONA_URBA=DOC.ID_TIPO_ZONA_URBA 
		AND ZNURB.ID_ZONA_URBA=DOC.ID_ZONA_URBA 
		AND ZNURB.ID_CIUDAD=DOC.ID_CIUDAD_ZONA_URBA 
		AND ZNURB.ID_PAIS=1)

	LEFT JOIN Mece_Logistico..ESTADOSENVIO ESEV WITH(NOLOCK) ON ESEV.ID_ESTADOENVIO=GUI.ID_ESTADOENVIO
	LEFT JOIN [PARAMETROS].[dbo].[ITEM_CONCEPTO] CONCEP  WITH (NOLOCK)
	ON (CONCEP.ID_CONCEPTO=SEG.ID_CONCEPTO AND CONCEP.ID_PROCESO=SEG.ID_PROCESO)
    LEFT JOIN PARAMETROS.DBO.ZONASURBANAS ZURBA (NOLOCK) 
	ON 	DOC.ID_PAIS_ZONA_URBA=ZURBA.ID_PAIS AND DOC.ID_CIUDAD_ZONA_URBA=ZURBA.ID_CIUDAD AND DOC.ID_ZONA_URBA=ZURBA.ID_ZONA_URBA AND DOC.ID_TIPO_ZONA_URBA = ZURBA.ID_TIPO_ZONA_URBA

	
	WHERE 
	--YEAR(SEG.FECHA_HORA_MOVIMIENTO)=2024
	--AND MONTH(SEG.FECHA_HORA_MOVIMIENTO)=5
	--AND DAY(SEG.FECHA_HORA_MOVIMIENTO)=25--AND
	----SEG.ID_PROCESO=9 AND 
	 GUI.[NUMERO_GUIA] IN 
	 (	
2268866306
,2268866016
,2268866006
,2264104414
,2275317725
,2275317632
,2275317272
,2275317227
,2275317174
,2275317106
,2275317091
,2275317084
,2275316943
,2275122054
,2275049353
,2275049198
,2274848370

	 )
	 and SEG.ID_PROCESO > 5
	 )
SELECT
ct.NUMERO_GUIA
,CT.ID_PROCESO
,CT.NOMBRE_PROCESO_LOG
,CT.NOMBRE_DIVISION_DESTINO
,CT.NOMBRE_DIVISION_ORIGEN
,CT.FECHA_MODIFICACION_DG
,ct.SEGIM_FECHA_HORA_MOVIMIENTO
,CT.CONSECUT_MOVIMI
,CT.NUMERO_MOVIMI
,CT.ID_PROCESO
,CT.ID_REMITE
,CL.NOMBRE_CLIENTE
,ct.ID_CLIENTE
,CT.NOMBRE_SUBPRODUCTO
,CT.ID_ESTADOGUIA
,CT.ID_ESTADOENVIO
--,CT.ID_CLIENTE
