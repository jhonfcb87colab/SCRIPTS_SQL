--,ct.SEG_NUMERO_PIEZAS
--,ct.GUI_NUMERO_PIEZAS
--,ct.NOMBRE_PROCESO_LOG
,CT.SEG_FECHA_CREACION
--,ct.DOCUM_FECHA_HORA_MOVIMIENTO
--,CT.NUMERO_MOVIMI
--,CT.CONSECUT_MOVIMI
--,CT.ID_PROCESO
,CT.NOMBRE_PROCESO_LOG
,CT.NOMBRE_CIUDAD_ORIGEN  AS NOMBRE_CIUDAD_PROCESO_ORIGEN
,CT.NOMBRE_CIUDAD_DESTINO AS NOMBRE_CIUDAD_PROCESO_DESTINO
,CT.NOMBRE_CIUDAD_ENVIO_ORG

,ct.ID_CIUDAD_DESTINO_ENVIO
,CT.NOMBRE_CIUDAD_ENVIO_DEST 
,CT.NOMBRE_CIUDAD_ZONA_URBA
,CT.NOMBRE_ESTADOENVIO
--,CL.NOMBRE_CLIENTE
--,CT.GUI_NUMERO_PIEZAS
--,CT.SEG_NUMERO_PIEZAS

--,CT.CONSECUT_MOVIMI
--,CT.NUMERO_MOVIMI
--,CT.DOC_PESO_TOTAL
--,CT.PESO_FISICO_GUIA
--,CT.PESO_GUIA
--,CT.PESO_ENVIO
--,ct.DOC_FECHA_MODIFICACION
--,CT.SEG_FECHA_MODIFICACION
--,CT.FECHA_ENVIO
--,ct.ID_PROCESO
--,CT.ID_PAIS_ZONA_URBA
--,CT.ID_CIUDAD_ZONA_URBA
--,CT.ID_ZONA_URBA
--,CT.ID_TIPO_ZONA_URBA
,CT.NOMBRE_ZONA_URBA
--,CT.ID_CONCEPTO
--,CT.NOMBRE_CONCEPTO
--,CT.PLACA_VEHICULO_DOCU
--,ct.DOCUM_FECHA_HORA_MOVIMIENTO
--,ct.NOMBRE_ZONA_URBA
--,CT.FECHA_HORA_CIERRE
--,ID_DIVISION_DESTINO
