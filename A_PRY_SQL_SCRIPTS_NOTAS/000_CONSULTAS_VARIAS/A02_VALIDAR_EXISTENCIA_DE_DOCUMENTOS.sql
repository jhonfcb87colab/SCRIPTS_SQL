USE SIG_COLOMBIA_DW;
WITH CTE_VALIDAR_EXISTENCIA_DOCUMENTOS AS (
SELECT 
ROW_NUMBER ( )   OVER ( PARTITION BY GUI.[NUMERO_GUIA] order by SEG.FECHA_HORA_MOVIMIENTO desc )  #ROW_ID, 
GUI.NUMERO_GUIA,
SEG.NUMERO_MOVIMI SEG_NUMERO_MOVIMI,
SEG.CONSECUT_MOVIMI SEG_CONSECUT_MOVIMI,
SEG.ID_PROCESO SEG_ID_PROCESO,
DOC.NUMERO_MOVIMI DOC_NUMERO_MOVIMI,
DOC.CONSECUT_MOVIMI DOC_CONSECUT_MOVIMI,
DOC.ID_PROCESO DOC_ID_PROCESO
	FROM LOG.GUIAS GUI WITH(NOLOCK)
	LEFT JOIN  LOG.SEGUIMIENTO_ENVIO SEG WITH (NOLOCK)
	ON GUI.NUMERO_GUIA=SEG.NUMERO_GUIA
	LEFT JOIN LOG.DOCUMENTOS DOC WITH (NOLOCK) 
	ON SEG.ID_PROCESO=DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI
WHERE SEG.NUMERO_GUIA IN
(2174628248
---2132548850, 2149712166, 2150262376, 2150262812, 2153432004
)
)
SELECT * FROM CTE_VALIDAR_EXISTENCIA_DOCUMENTOS WHERE #ROW_ID BETWEEN 1 AND 5