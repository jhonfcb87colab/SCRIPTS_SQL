		,CIUD_DEST.NOMBRE_CIUDAD	NOMBRE_CIUDAD_DESTINO
		,DIV_DEST.[NOMBRE_DIVISION] as NOMBRE_DIVISION_DESTINO
		,REGIO_DESTI.NOMBRE_REGIONAL AS NOMBRE_REGIONAL_DESTINO

