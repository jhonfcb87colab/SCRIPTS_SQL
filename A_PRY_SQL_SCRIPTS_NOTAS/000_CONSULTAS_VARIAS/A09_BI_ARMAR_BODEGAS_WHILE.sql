


USE SIG_COLOMBIA_DW;
DECLARE @MAX_ID INT = (SELECT MAX(ID) ID FROM PAR.ACTVEJ_01_BODEGAS_ACTIVAS (NOLOCK))
DECLARE @MAX_ID_CT INT = 0
DECLARE @BODEGAS NVARCHAR(MAX)='-8888'
WHILE @MAX_ID_CT<=@MAX_ID
 BEGIN
   SET @BODEGAS = CONCAT(@BODEGAS,(SELECT CONVERT(VARCHAR,ID_DIVISION) FROM PAR.ACTVEJ_01_BODEGAS_ACTIVAS (NOLOCK) WHERE ESTADO=1 AND ID=@MAX_ID_CT),',')
   SET @MAX_ID_CT = @MAX_ID_CT+1;  
 END
SET @BODEGAS=CONCAT(@BODEGAS,'-8888')
SELECT CONVERT(VARCHAR(2000),@BODEGAS) AS ID_DIVISION