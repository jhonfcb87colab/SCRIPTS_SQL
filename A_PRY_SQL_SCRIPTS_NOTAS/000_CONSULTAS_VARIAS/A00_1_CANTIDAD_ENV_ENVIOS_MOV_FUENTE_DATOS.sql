
DECLARE @FECHA_I DATETIME, @FECHA_INI DATETIME, @FECHA_FIN DATETIME, @FECHA_MANUAL DATETIME

SET @FECHA_MANUAL = '2017-04-01 00:00:00.000' --SE CAMBIA LA FECHA DEL 01/09/2016 POR 01/04/2017, YA QUE EL CAMBIO APLICA SOLO DESDE ABRIL 2017 
SET @FECHA_I =    '2025-08-01'; 
SET @FECHA_FIN =  '2025-07-01';



DROP TABLE IF EXISTS #SOLICITUD_RELACION_DE_GUIAS_DEL_CUBO_DE_MOVILIZADO_POR_GUIA_MES_DE_AGOSTO_2025;

IF @FECHA_I >= @FECHA_MANUAL
	BEGIN
		SET @FECHA_INI = @FECHA_I
	END
ELSE
	BEGIN
		SET @FECHA_INI = @FECHA_MANUAL
	END


;WITH SEGUIMI_ENVIO AS (
	SELECT	MIN(SEG.FECHA_HORA_MOVIMIENTO) AS FECHA_HORA_MOVIMIENTO, NUMERO_GUIA
	FROM MECE_LOGISTICO.DBO.SEGUIMIENTO_ENVIO SEG WITH (NOLOCK)
	--INNER JOIN MECE_LOGISTICO.DBO.DOCUMENTOS DOC (NOLOCK)
	--ON (SEG.ID_PROCESO=DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI=DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI=DOC.CONSECUT_MOVIMI)
	WHERE SEG.FECHA_HORA_MOVIMIENTO >=  @FECHA_INI 		
		AND SEG.FECHA_HORA_MOVIMIENTO <  @FECHA_FIN		
		AND SEG.ID_PROCESO IN (5,6) 
		--AND DOC.ID_CIUDAD_DIVISION_ORIGEN=10
	GROUP BY SEG.NUMERO_GUIA
), CTE02 AS
(
SELECT 
		GUIAS.NUMERO_GUIA, --COUNT(DISTINCT GUIAS.NUMERO_GUIA) AS CANTIDAD_GUIAS,
		GUIAS.NUMERO_PIEZAS, --SUM(CASE WHEN ISNULL(GUIAS.NUMERO_PIEZAS,0) = 0 THEN 1 ELSE GUIAS.NUMERO_PIEZAS END) AS CANTIDAD_PIEZAS,
		SE_FECH.FECHA_HORA_MOVIMIENTO,
		GUIAS.ID_PAIS_ORIGEN, --ISNULL(GUIAS.ID_PAIS_ORIGEN,0) AS ID_PAIS_ORIGEN,
		GUIAS.ID_CIUDAD_ORIGEN, --ISNULL(GUIAS.ID_CIUDAD_ORIGEN,0) AS ID_CIUDAD_ORIGEN,
		GUIAS.ID_PAIS_DESTINO, --ISNULL(GUIAS.ID_PAIS_DESTINO,0) AS ID_PAIS_DESTINO,
		GUIAS.ID_CIUDAD_DESTINO, --ISNULL(GUIAS.ID_CIUDAD_DESTINO,0) AS ID_CIUDAD_DESTINO,
		NOMBRE_CIUDAD_ORIGEN = CONVERT(VARCHAR(100),NULL),
		NOMBRE_REGIONAL_ORIGEN = CONVERT(VARCHAR(100),NULL),
		GUIAS.ID_TIPOGUIA, --ISNULL(GUIAS.ID_TIPOGUIA,0) AS ID_TIPOGUIA,
		NOMBRE_TIPOGUIA = CONVERT(VARCHAR(100),NULL),
		GUIAS.ID_CLIENTE, --ISNULL(GUIAS.ID_CLIENTE,0) AS ID_CLIENTE,
		GUIAS.ID_ESTADOENVIO, --ISNULL(GUIAS.ID_ESTADOENVIO,0) AS ID_ESTADOENVIO,
		GUIAS.ID_DOCU_ULT_MOVI, --ISNULL(GUIAS.ID_DOCU_ULT_MOVI,0) AS   ID_PROCESO,
		GUIAS.ID_MEDTRANS, --ISNULL(GUIAS.ID_MEDTRANS,0) AS ID_MEDTRANS,
		GUIAS.ID_PRODUCTO, --ISNULL(GUIAS.ID_PRODUCTO,0) AS ID_PRODUCTO,
		GUIAS.ID_SUBPRODUCTO, --ISNULL(GUIAS.ID_SUBPRODUCTO,0) AS ID_SUBPRODUCTO,
		GUIAS.ID_ESTADOGUIA, --ISNULL(GUIAS.ID_ESTADOGUIA,0) AS ID_ESTADOGUIA,
		GUIAS.ID_TIEMPO AS ID_TIEMPO_ENTREGA, --ISNULL(GUIAS.ID_TIEMPO,0) AS ID_TIEMPO_ENTREGA,
		GUIAS.ID_REQUIERE_EMBALAJE AS ID_REQ_EMBALAJE, --ISNULL(GUIAS.ID_REQUIERE_EMBALAJE,0) AS ID_REQ_EMBALAJE,
		GUIAS.FECHA_ENTREGA, --ISNULL(DATEDIFF(MI,GUIAS.FECHA_ENTREGA,GUIAS.FECHA_MODIFICACION),0) AS TIEMPO_DIGITALIZACION,
		GUIAS.FECHA_MODIFICACION,
		GUIAS.ID_1 AS ID_SUCURSAL,	
		GUIAS.ID_2 AS ID_DEPENDEN,
		MANEJA_CLIENTE = CONVERT(VARCHAR(100),NULL),
		CODIGOSER = CONVERT(VARCHAR(100),NULL),
		RAZON_SOCIAL = CONVERT(VARCHAR(100),NULL),
		FECHA_PRIMER_MOVIMEINTO_LOG = CONVERT(DATETIME,NULL),
		FECHA_SISTEMA_PREFACTURACION = CONVERT(DATETIME,NULL)
FROM 	MECE_LOGISTICO.DBO.GUIAS GUIAS WITH (NOLOCK /*, INDEX(UK_GUIA)*/  )
		INNER JOIN	SEGUIMI_ENVIO AS SE_FECH  
			ON SE_FECH.NUMERO_GUIA = GUIAS.NUMERO_GUIA --SE.NUMERO_GUIA = SE_FECH.NUMERO_GUIA
		WHERE GUIAS.ID_DOCU_ULT_MOVI >= 4 -- ID_PROCESO
)
SELECT
*
INTO #SOLICITUD_RELACION_DE_GUIAS_DEL_CUBO_DE_MOVILIZADO_POR_GUIA_MES_DE_AGOSTO_2025
FROM CTE02


