
USE Mece_Logistico;


DECLARE @FECHA_INI  DATETIME = CONVERT(DATE,GETDATE());
DECLARE @FECHA_FIN  DATETIME = CONVERT(DATE,DATEADD(DAY,-3,GETDATE()));
--SELECT @FECHA_INI,@FECHA_FIN 
DROP TABLE IF EXISTS #TABLE_GUIAS;
CREATE TABLE #TABLE_GUIAS(NUMERO_GUIA NUMERIC(20,0))
CREATE NONCLUSTERED INDEX [IX_GUIAS] ON #TABLE_GUIAS([NUMERO_GUIA])

INSERT INTO #TABLE_GUIAS
SELECT NUMERO_GUIA 
FROM DBO.GUIAS (NOLOCK)
WHERE FECHA_MODIFICACION_DG BETWEEN @FECHA_FIN  AND @FECHA_INI  
AND ID_ESTADOGUIA>=3
GROUP BY NUMERO_GUIA

INSERT INTO #TABLE_GUIAS
SELECT NUMERO_GUIA 
FROM DBO.SEGUIMIENTO_ENVIO (NOLOCK)
WHERE FECHA_HORA_MOVIMIENTO BETWEEN @FECHA_FIN  AND @FECHA_INI  
GROUP BY NUMERO_GUIA


DELETE #TABLE_GUIAS
WHERE LEN(NUMERO_GUIA)<8

DROP TABLE IF EXISTS #TABLE_GUIAS_02;
CREATE TABLE #TABLE_GUIAS_02(NUMERO_GUIA NUMERIC(20,0))
CREATE NONCLUSTERED INDEX [IX_GUIAS_02] ON #TABLE_GUIAS([NUMERO_GUIA])

INSERT INTO #TABLE_GUIAS_02
SELECT NUMERO_GUIA FROM #TABLE_GUIAS GROUP BY NUMERO_GUIA



