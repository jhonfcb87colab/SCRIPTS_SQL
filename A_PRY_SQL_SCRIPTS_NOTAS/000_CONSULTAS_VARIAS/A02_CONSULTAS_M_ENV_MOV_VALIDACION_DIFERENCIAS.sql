
WITH SEGUIMI_ENVIO AS (
	SELECT	
	MIN(FECHA_HORA_MOVIMIENTO) AS FECHA_HORA_MOVIMIENTO
	,MAX(NUMERO_PIEZAS) AS NUM_PZ
	,NUMERO_GUIA
	FROM MECE_LOGISTICO.DBO.SEGUIMIENTO_ENVIO  WITH (NOLOCK) 
	WHERE FECHA_HORA_MOVIMIENTO >=  '2026-09-17' 		
		AND FECHA_HORA_MOVIMIENTO <  '2026-09-18'	
		AND ID_PROCESO IN (5,6) 
		AND LEN(NUMERO_GUIA) > 8
	GROUP BY NUMERO_GUIA
)
SELECT 
SUM(GUIAS.NUMERO_PIEZAS) CTPZ_TBL_G
,SUM(NUM_PZ) CTPZ_TBL_SEG
FROM 	MECE_LOGISTICO.DBO.GUIAS GUIAS WITH (NOLOCK /*, INDEX(UK_GUIA) */ )
		INNER JOIN	SEGUIMI_ENVIO AS SE_FECH   	ON SE_FECH.NUMERO_GUIA = GUIAS.NUMERO_GUIA --SE.NUMERO_GUIA = SE_FECH.NUMERO_GUIA
		--WHERE GUIAS.ID_DOCU_ULT_MOVI >= 4 -- ID_PROCESO
 OPTION (RECOMPILE) ; 



