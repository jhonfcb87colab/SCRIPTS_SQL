DECLARE @TIPOVALORVALOR_ INT = @PARA_TIPO_VALOR
DECLARE @PAR_ANIOMES INT = @PARA_TIEMPO;
DECLARE @PAR_ANIOMESDIA_INI DATETIME = CONVERT(DATETIME, CONVERT(VARCHAR(12), @PAR_ANIOMES * 100 + 1));
DECLARE @PAR_ANIOMESDIA_FIN DATETIME = DATEADD(DAY, -1, DATEADD(MONTH, 1, @PAR_ANIOMESDIA_INI));
DECLARE @GEOGRAFIAORIGENCIUDAD INT = @PARA_CIUDAD_ORIGEN;  --259
DECLARE @G_ID_CLIENTE VARCHAR(50) = @PARA_CLIENTE;
