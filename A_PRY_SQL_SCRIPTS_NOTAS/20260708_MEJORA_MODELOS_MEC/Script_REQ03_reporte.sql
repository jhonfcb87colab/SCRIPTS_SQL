DROP TABLE IF EXISTS #CIUDAD_REGIONAL;
SELECT * INTO #CIUDAD_REGIONAL FROM [DIM].[MEC_CIUDADES] WITH(NOLOCK)
DECLARE @QUERY_DINAMICO NVARCHAR(MAX)=' ';
DECLARE @QUERY_DINAMICO_EXEC NVARCHAR(MAX)=' ';

DROP TABLE IF EXISTS #FAC_MIS_ENVIOS_TEMPORAL_actual;

SELECT 
 G_NUMERO_GUIA,G_NUMERO_PIEZAS,G_REGIONAL_ORIGEN,G_CIUDAD_ORIGEN,G_COD_SER,SE_EFICIENCIA, SE_RESP_NOVD_OPERATIVA_1 AS NOVEDAD_RESPONSABLE                            --- NO ----[SE_DEPURADO_NOMBRE_RESP]
 , SE_ULTI_PROCESO,G_NOMBRE_ESTADOENVIO
 INTO #FAC_MIS_ENVIOS_TEMPORAL_actual
  FROM FAC.MIS_ENVIOS ENV WITH (NOLOCK)
   WHERE G_ID_CLIENTE = @G_ID_CLIENTE                          
      AND ENV.SE_ID_FECHA_INGRESO_CIL >= @PAR_ANIOMESDIA_INI 
      AND ENV.SE_ID_FECHA_INGRESO_CIL <= @PAR_ANIOMESDIA_FIN
    OPTION(RECOMPILE)


CREATE NONCLUSTERED INDEX  [ZZZZIDX_CIUDAD_REGIONAL] ON #CIUDAD_REGIONAL
(
 NOMBRE_CIUDAD	ASC
,NOMBRE_REGIONAL	ASC
)
WITH (PAD_INDEX = OFF, STATISTICS_NORECOMPUTE = OFF, SORT_IN_TEMPDB = OFF, IGNORE_DUP_KEY = OFF, ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON, FILLFACTOR = 80) ON [PRIMARY]

DROP TABLE IF EXISTS #TEMPORAL_MEC_INDICADORES;

    SELECT   
        G_CIUDAD_ORIGEN,
        G_COD_SER,
        SE_EFICIENCIA,
        SE_ULTI_PROCESO,
        G_NOMBRE_ESTADOENVIO,
        CONVERT(FLOAT,COUNT(G_NUMERO_GUIA)) AS CANTIDAD_GUIAS
        INTO #TEMPORAL_MEC_INDICADORES
    FROM #FAC_MIS_ENVIOS_TEMPORAL_actual ENV WITH (NOLOCK)   
    GROUP BY 
    G_CIUDAD_ORIGEN,
    G_COD_SER,
    SE_EFICIENCIA,
    SE_ULTI_PROCESO,
    G_NOMBRE_ESTADOENVIO
    OPTION(RECOMPILE)


DECLARE @WHERE_01 NVARCHAR(MAX);
DECLARE @WHERE_02 NVARCHAR(MAX);
    SET @WHERE_01 = 'AND CD.ID_CIUDAD = CONVERT(INT,'''+ CONVERT(VARCHAR(10),@GEOGRAFIAORIGENCIUDAD) +''') '
    SET @WHERE_02 = 'AND CT.G_COD_SER = '''+ @PARA_CODIGO_SER +''' '

IF @GEOGRAFIAORIGENCIUDAD = '0' OR @GEOGRAFIAORIGENCIUDAD = '' OR @GEOGRAFIAORIGENCIUDAD IS NULL
    BEGIN
        SET @WHERE_01 = ''
    END
IF @PARA_CODIGO_SER = '0' OR @PARA_CODIGO_SER = '' OR @PARA_CODIGO_SER IS NULL
    BEGIN
        SET @WHERE_02 = ''
    END

DROP TABLE IF EXISTS #TEMPORAL_MEC_INDICADORES_01;
CREATE TABLE #TEMPORAL_MEC_INDICADORES_01(EN_PROCESO_ENTREGA FLOAT,TOTAL_GUIAS FLOAT, ENTREGA_TARDE FLOAT, ENTREGA_TIEMPO FLOAT)

SET @QUERY_DINAMICO = '
                        INSERT INTO #TEMPORAL_MEC_INDICADORES_01
                            SELECT  IIF(G_NOMBRE_ESTADOENVIO=''EN PROCESAMIENTO'',SUM(CANTIDAD_GUIAS),SUM(0)) AS EN_PROCESO_ENTREGA,
                                    SUM(CANTIDAD_GUIAS) AS TOTAL_GUIAS,
                                    IIF(SE_EFICIENCIA = ''TARDE'',SUM(CANTIDAD_GUIAS),SUM(0)) AS ENTREGA_TARDE,
                                    IIF(SE_EFICIENCIA = ''A TIEMPO'',SUM(CANTIDAD_GUIAS),SUM(0)) AS ENTREGA_TIEMPO
                            FROM #TEMPORAL_MEC_INDICADORES CT 
                            INNER JOIN #CIUDAD_REGIONAL CD 
                            ON CT.G_CIUDAD_ORIGEN=CD.NOMBRE_CIUDAD 
                            WHERE 1=1                               
                            '
SET @QUERY_DINAMICO_EXEC = CONCAT(@QUERY_DINAMICO,@WHERE_01,@WHERE_02,' ','GROUP BY SE_EFICIENCIA,G_NOMBRE_ESTADOENVIO',' order by 2 desc');
--SELECT @QUERY_DINAMICO_EXEC

EXEC (@QUERY_DINAMICO_EXEC) 

SELECT
    SUM(EN_PROCESO_ENTREGA) EN_PROCESO_ENTREGA,
    SUM(ENTREGA_TARDE) ENTREGA_TARDE,
    SUM(ENTREGA_TIEMPO) ENTREGA_TIEMPO,
    CONVERT(FLOAT,SUM(ENTREGA_TARDE)) / CONVERT(FLOAT,SUM(TOTAL_GUIAS)) AS XMC_VARI_ENTREG_TARDE,                                      
    CONVERT(FLOAT,SUM(ENTREGA_TIEMPO))/ CONVERT(FLOAT,SUM(TOTAL_GUIAS)) AS XMC_VARI_ENTREG_TIEMPO  
FROM #TEMPORAL_MEC_INDICADORES_01 CT                               
























