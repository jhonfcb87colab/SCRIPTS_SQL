 CASE 
            WHEN (SE_RESP_NOVD_OPERATIVA_1 = 'NO DISPONIBLE' AND SE_RESP_NOVD_OPERATIVA_2 = 'NO DISPONIBLE' AND SE_RESP_NOVD_OPERATIVA_3 = 'NO DISPONIBLE') AND SE_DEPURADO_NOMBRE_RESP <> 'NO DISPONIBLE' THEN SE_DESC_CONC_DEPU
            ELSE SE_NOVD_OPERATIVA_1
    END 
    )))))))),
