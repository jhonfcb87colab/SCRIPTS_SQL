 IIF(
         IIF(SE_RESP_NOVD_OPERATIVA_1 = 'CLIENTE', SE_RESP_NOVD_OPERATIVA_1,
         IIF(SE_RESP_NOVD_OPERATIVA_2 = 'CLIENTE', SE_RESP_NOVD_OPERATIVA_2, 
         IIF(SE_RESP_NOVD_OPERATIVA_3 = 'CLIENTE', SE_RESP_NOVD_OPERATIVA_3,
         IIF(SE_DEPURADO_NOMBRE_RESP  = 'CLIENTE',  SE_DEPURADO_NOMBRE_RESP,
