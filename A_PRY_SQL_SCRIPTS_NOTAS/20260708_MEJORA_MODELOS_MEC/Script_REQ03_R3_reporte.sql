         IIF(SE_RESP_NOVD_OPERATIVA_3 IN( 'EXTERNO','EXTERNA'), SE_RESP_NOVD_OPERATIVA_3,
         IIF(SE_DEPURADO_NOMBRE_RESP  IN( 'EXTERNO','EXTERNA'),  SE_DEPURADO_NOMBRE_RESP,
         CASE 
            WHEN (SE_RESP_NOVD_OPERATIVA_1 = 'NO DISPONIBLE' AND SE_RESP_NOVD_OPERATIVA_2 = 'NO DISPONIBLE' AND SE_RESP_NOVD_OPERATIVA_3 = 'NO DISPONIBLE') AND SE_DEPURADO_NOMBRE_RESP <> 'NO DISPONIBLE' THEN SE_DEPURADO_NOMBRE_RESP
            ELSE SE_RESP_NOVD_OPERATIVA_1
            END
            ))))))))    =   'INTERNA'
    ,'SERVIENTREGA',
         IIF(SE_RESP_NOVD_OPERATIVA_1 = 'CLIENTE', SE_RESP_NOVD_OPERATIVA_1,
         IIF(SE_RESP_NOVD_OPERATIVA_2 = 'CLIENTE', SE_RESP_NOVD_OPERATIVA_2, 
         IIF(SE_RESP_NOVD_OPERATIVA_3 = 'CLIENTE', SE_RESP_NOVD_OPERATIVA_3,
         IIF(SE_DEPURADO_NOMBRE_RESP  = 'CLIENTE',  SE_DEPURADO_NOMBRE_RESP,
         IIF(SE_RESP_NOVD_OPERATIVA_1 IN( 'EXTERNO','EXTERNA'), SE_RESP_NOVD_OPERATIVA_1,
         IIF(SE_RESP_NOVD_OPERATIVA_2 IN( 'EXTERNO','EXTERNA'), SE_RESP_NOVD_OPERATIVA_2, 
         IIF(SE_RESP_NOVD_OPERATIVA_3 IN( 'EXTERNO','EXTERNA'), SE_RESP_NOVD_OPERATIVA_3,
         IIF(SE_DEPURADO_NOMBRE_RESP  IN( 'EXTERNO','EXTERNA'),  SE_DEPURADO_NOMBRE_RESP,
         CASE 
            WHEN (SE_RESP_NOVD_OPERATIVA_1 = 'NO DISPONIBLE' AND SE_RESP_NOVD_OPERATIVA_2 = 'NO DISPONIBLE' AND SE_RESP_NOVD_OPERATIVA_3 = 'NO DISPONIBLE') AND SE_DEPURADO_NOMBRE_RESP <> 'NO DISPONIBLE' THEN SE_DEPURADO_NOMBRE_RESP
            ELSE SE_RESP_NOVD_OPERATIVA_1
            END
            ))))))))    
    ),
 SE_DEPURADO_NOMBRE_RESP,
 SE_DESC_CONC_DEPU,		
 CNF_ID_CONFIRMACION,
 CNF_FECHA_CONF_1,
 SE_ID_FECHA_INGRESO_CIL,
 SE_ULTI_PROCESO,G_NOMBRE_ESTADOENVIO
 INTO #FAC_MIS_ENVIOS_TEMPORAL_actual
  FROM FAC.MIS_ENVIOS ENV WITH (NOLOCK)
   WHERE G_ID_CLIENTE = @G_ID_CLIENTE                          
      AND ENV.SE_ID_FECHA_INGRESO_CIL >= @PAR_ANIOMESDIA_INI 
      AND ENV.SE_ID_FECHA_INGRESO_CIL <= @PAR_ANIOMESDIA_FIN
    OPTION(RECOMPILE)

