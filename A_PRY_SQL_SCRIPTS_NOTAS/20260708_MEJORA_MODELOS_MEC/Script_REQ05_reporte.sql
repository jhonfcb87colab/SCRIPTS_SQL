SELECT 
NOVEDAD_RESPONSABLE AS NOMBRE_RESPONSABLE,
SUM(TOTAL_GUIAS) AS CANT_DERT,
CONVERT(FLOAT,SUM(TOTAL_GUIAS))/CONVERT(FLOAT,(SELECT SUM(TOTAL_GUIAS) FROM #TEMPORAL_MEC_INDICADORES_01) )  AS XMC_VARI_NOVEDAD_DERT
FROM #TEMPORAL_MEC_INDICADORES_01 CT  
GROUP BY NOVEDAD_RESPONSABLE



