DROP TABLE IF EXISTS #TEMPORAL_MEC_INDICADORES;

    SELECT   
        G_CIUDAD_ORIGEN,
        G_REGIONAL_ORIGEN,
        G_COD_SER,
        SE_EFICIENCIA,
        SE_ULTI_PROCESO,
        G_NOMBRE_ESTADOENVIO,
        NOVEDAD_RESPONSABLE = 
                    CASE 
                        WHEN NOVEDAD_REPORTADA = 'NO DISPONIBLE' THEN 'NO DISPONIBLE'
                        ELSE NOVEDAD_RESPONSABLE
                        END,
        CONVERT(FLOAT,COUNT(G_NUMERO_GUIA)) AS CANTIDAD_GUIAS
        INTO #TEMPORAL_MEC_INDICADORES
    FROM #FAC_MIS_ENVIOS_TEMPORAL_actual ENV WITH (NOLOCK)   
    WHERE G_NOMBRE_ESTADOENVIO IN('ENTREGADO A REMITENTE') --AND SE_EFICIENCIA='TARDE'
    GROUP BY 
    G_CIUDAD_ORIGEN,
    G_REGIONAL_ORIGEN,
    G_COD_SER,
    SE_EFICIENCIA,
    SE_ULTI_PROCESO,
    G_NOMBRE_ESTADOENVIO,
    NOVEDAD_RESPONSABLE,
                    CASE 
                        WHEN NOVEDAD_REPORTADA = 'NO DISPONIBLE' THEN 'NO DISPONIBLE'
                        ELSE NOVEDAD_RESPONSABLE
                        END
    OPTION(RECOMPILE)


