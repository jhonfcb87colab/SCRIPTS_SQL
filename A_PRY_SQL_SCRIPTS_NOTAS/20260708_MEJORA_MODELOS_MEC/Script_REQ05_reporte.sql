DROP TABLE IF EXISTS #TEMPORAL_MEC_INDICADORES_01;
CREATE TABLE #TEMPORAL_MEC_INDICADORES_01(NOVEDAD_RESPONSABLE VARCHAR(50), TOTAL_GUIAS FLOAT, ENTREGA_TARDE FLOAT)

SET @QUERY_DINAMICO = '
                        INSERT INTO #TEMPORAL_MEC_INDICADORES_01
                            SELECT  
                            NOVEDAD_RESPONSABLE,
                            SUM(CANTIDAD_GUIAS) AS TOTAL_GUIAS,
                            IIF(SE_EFICIENCIA= ''TARDE'',SUM(CANTIDAD_GUIAS),SUM(0)) AS ENTREGA_TARDE
                            FROM #TEMPORAL_MEC_INDICADORES CT 
                            INNER JOIN #CIUDAD_REGIONAL CD 
                            ON CT.G_CIUDAD_ORIGEN=CD.NOMBRE_CIUDAD  AND CT.G_REGIONAL_ORIGEN=CD.NOMBRE_REGIONAL
                            WHERE 1=1                               
                            '
SET @QUERY_DINAMICO_EXEC = CONCAT(@QUERY_DINAMICO,@WHERE_01,@WHERE_02,' ','GROUP BY NOVEDAD_RESPONSABLE,SE_EFICIENCIA ',' order by 2 desc');
