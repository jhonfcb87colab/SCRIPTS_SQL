DECLARE @WHERE_01 NVARCHAR(MAX);
DECLARE @WHERE_02 NVARCHAR(MAX);
    SET @WHERE_01 = 'AND CD.ID_CIUDAD = CONVERT(INT,'''+ CONVERT(VARCHAR(10),@GEOGRAFIAORIGENCIUDAD) +''') '
    SET @WHERE_02 = 'AND CT.G_COD_SER = '''+ @PARA_CODIGO_SER +''' '

IF @GEOGRAFIAORIGENCIUDAD = '0' OR @GEOGRAFIAORIGENCIUDAD = '' OR @GEOGRAFIAORIGENCIUDAD IS NULL
    BEGIN
        SET @WHERE_01 = ''
    END
IF @PARA_CODIGO_SER = '0' OR @PARA_CODIGO_SER = '' OR @PARA_CODIGO_SER IS NULL
    BEGIN
        SET @WHERE_02 = ''
    END

SET @QUERY_DINAMICO = '
                            SELECT 
	                            sum([CANTIDAD GUIAS_actual]) as CANTIDAD_GUIAS,	
                                IIF(sum([CANTIDAD GUIAS_actual])=0,0, (sum([CANTIDAD GUIAS_actual])-sum([CANTIDAD GUIAS_ant]))/sum([CANTIDAD GUIAS_actual])) as PORC_VARI_GUIAS,
	                            sum([CANTIDAD PIEZAS_actual]) as CANTIDAD_PIEZAS,
	                            IIF(sum([CANTIDAD PIEZAS_actual])=0,0, (sum([CANTIDAD PIEZAS_actual])-sum([CANTIDAD PIEZAS_ant]))/sum([CANTIDAD PIEZAS_actual])) as PORC_VARI_PIEZAS
                            FROM #TEMPORAL_MEC_INDICADORES CT 
                            INNER JOIN #CIUDAD_REGIONAL CD 
                            ON CT.G_CIUDAD_ORIGEN=CD.NOMBRE_CIUDAD AND CD.NOMBRE_REGIONAL=CT.G_REGIONAL_ORIGEN
                            WHERE 1=1                               
                            '
SET @QUERY_DINAMICO_EXEC = CONCAT(@QUERY_DINAMICO,@WHERE_01,@WHERE_02,' ');
