DROP TABLE IF EXISTS #CIUDAD_REGIONAL;
SELECT * INTO #CIUDAD_REGIONAL FROM [DIM].[MEC_CIUDADES] WITH(NOLOCK)
DECLARE @QUERY_DINAMICO NVARCHAR(MAX)=' ';
DECLARE @QUERY_DINAMICO_EXEC NVARCHAR(MAX)=' ';


CREATE NONCLUSTERED INDEX  [ZZZZIDX_CIUDAD_REGIONAL] ON #CIUDAD_REGIONAL
(
NOMBRE_CIUDAD	ASC
,NOMBRE_REGIONAL	ASC
)
WITH (PAD_INDEX = OFF, STATISTICS_NORECOMPUTE = OFF, SORT_IN_TEMPDB = OFF, IGNORE_DUP_KEY = OFF, ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON, FILLFACTOR = 80) ON [PRIMARY]


DROP TABLE IF EXISTS #TEMPORAL_MEC_INDICADORES_TD01;
    SELECT
        G_CIUDAD_ORIGEN,
		G_NOMBRE_ESTADOENVIO,
        G_ID_CLIENTE,
        G_REGIONAL_ORIGEN,
        G_COD_SER,
        G_NUMERO_GUIA,
        G_NUMERO_PIEZAS
     INTO #TEMPORAL_MEC_INDICADORES_TD01
    FROM FAC.MIS_ENVIOS ENV WITH (NOLOCK)   
    WHERE G_ID_CLIENTE = @G_ID_CLIENTE 
      AND ENV.SE_ID_FECHA_INGRESO_CIL >= @PAR_ANIOMESDIA_INI 
      AND ENV.SE_ID_FECHA_INGRESO_CIL <= @PAR_ANIOMESDIA_FIN
    OPTION(RECOMPILE)
---    UNION ALL
    
    -- Mes Anterior
DROP TABLE IF EXISTS #TEMPORAL_MEC_INDICADORES_TD02;
    SELECT 
        G_CIUDAD_ORIGEN,
        G_NOMBRE_ESTADOENVIO,
		G_ID_CLIENTE,
        G_REGIONAL_ORIGEN,
        G_COD_SER,
        G_NUMERO_GUIA,
        G_NUMERO_PIEZAS
        INTO #TEMPORAL_MEC_INDICADORES_TD02
    FROM FAC.MIS_ENVIOS ENV WITH (NOLOCK)   
    WHERE G_ID_CLIENTE = @G_ID_CLIENTE
      AND ENV.SE_ID_FECHA_INGRESO_CIL >= DATEADD(MONTH, -1, @PAR_ANIOMESDIA_INI) 
      AND ENV.SE_ID_FECHA_INGRESO_CIL <= DATEADD(MONTH, -1, @PAR_ANIOMESDIA_FIN)
    OPTION(RECOMPILE)


DROP TABLE IF EXISTS #TEMPORAL_MEC_INDICADORES;

    SELECT   
        G_CIUDAD_ORIGEN,
        G_REGIONAL_ORIGEN,
        G_COD_SER,
        CONVERT(FLOAT,COUNT(G_NUMERO_GUIA)) AS [CANTIDAD GUIAS_actual],
        CONVERT(FLOAT,SUM(G_NUMERO_PIEZAS)) AS [CANTIDAD PIEZAS_actual],
        CONVERT(FLOAT,0) AS [CANTIDAD GUIAS_ant],
        CONVERT(FLOAT,0) AS [CANTIDAD PIEZAS_ant]
     INTO #TEMPORAL_MEC_INDICADORES
    FROM #TEMPORAL_MEC_INDICADORES_TD01 ENV WITH (NOLOCK)  
	WHERE G_NOMBRE_ESTADOENVIO NOT IN('EN ALISTAMIENTO DEL CLIENTE')
    GROUP BY G_CIUDAD_ORIGEN,G_REGIONAL_ORIGEN,G_COD_SER
    OPTION(RECOMPILE)
---    UNION ALL
    
    -- Mes Anterior
    INSERT INTO #TEMPORAL_MEC_INDICADORES
    SELECT 
        G_CIUDAD_ORIGEN,
        G_REGIONAL_ORIGEN,
        G_COD_SER,
        CONVERT(FLOAT,0) AS [CANTIDAD GUIAS_actual],
        CONVERT(FLOAT,0) AS [CANTIDAD PIEZAS_actual],
        CONVERT(FLOAT,COUNT(G_NUMERO_GUIA)) AS [CANTIDAD GUIAS_ant],
        CONVERT(FLOAT,SUM(G_NUMERO_PIEZAS)) AS [CANTIDAD PIEZAS_ant]
    FROM #TEMPORAL_MEC_INDICADORES_TD02 ENV WITH (NOLOCK)   
	WHERE G_NOMBRE_ESTADOENVIO NOT IN('EN ALISTAMIENTO DEL CLIENTE')
    GROUP BY G_CIUDAD_ORIGEN,G_REGIONAL_ORIGEN,G_COD_SER
    OPTION(RECOMPILE)


