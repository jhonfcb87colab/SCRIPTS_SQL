DROP TABLE IF EXISTS #FAC_MIS_ENVIOS_TEMPORAL_actual;
DROP TABLE IF EXISTS #FAC_MIS_ENVIOS_TEMPORAL_anterior;
SELECT 
 G_NUMERO_GUIA,G_NUMERO_PIEZAS,G_REGIONAL_ORIGEN,G_CIUDAD_ORIGEN,G_COD_SER,G_NOMBRE_ESTADOENVIO, SE_RESP_NOVD_OPERATIVA_1 AS NOVEDAD_RESPONSABLE                            --- NO ----[SE_DEPURADO_NOMBRE_RESP]
 INTO #FAC_MIS_ENVIOS_TEMPORAL_actual
  FROM FAC.MIS_ENVIOS ENV WITH (NOLOCK)
   WHERE G_ID_CLIENTE = @G_ID_CLIENTE                          
      AND ENV.SE_ID_FECHA_INGRESO_CIL >= @PAR_ANIOMESDIA_INI 
      AND ENV.SE_ID_FECHA_INGRESO_CIL <= @PAR_ANIOMESDIA_FIN
    OPTION(RECOMPILE)

SELECT 
 G_NUMERO_GUIA,G_NUMERO_PIEZAS,G_REGIONAL_ORIGEN,G_CIUDAD_ORIGEN,G_COD_SER,G_NOMBRE_ESTADOENVIO,[SE_RESP_NOVD_OPERATIVA_1] AS NOVEDAD_RESPONSABLE                           --- NO ----[SE_DEPURADO_NOMBRE_RESP]
 INTO #FAC_MIS_ENVIOS_TEMPORAL_anterior
  FROM FAC.MIS_ENVIOS ENV WITH (NOLOCK)
   WHERE G_ID_CLIENTE = @G_ID_CLIENTE                          
      AND ENV.SE_ID_FECHA_INGRESO_CIL >= DATEADD(MONTH, -1, @PAR_ANIOMESDIA_INI) 
      AND ENV.SE_ID_FECHA_INGRESO_CIL <= DATEADD(MONTH, -1, @PAR_ANIOMESDIA_FIN)
    OPTION(RECOMPILE)




