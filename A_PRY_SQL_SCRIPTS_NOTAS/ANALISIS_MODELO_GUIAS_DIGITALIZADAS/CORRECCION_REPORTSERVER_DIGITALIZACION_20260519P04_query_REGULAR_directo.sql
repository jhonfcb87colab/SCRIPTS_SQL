

USE SIG_CCM_DM;
/**/
DECLARE @TIPO_CONSULTA NVARCHAR(MAX) = '1'
DECLARE @ID_TIPO_ENTREGA NVARCHAR(MAX) = '0'---1,2,
DECLARE @REGIONAL_ORIGEN NVARCHAR(MAX) = '0'
DECLARE @REGIONAL_DESTINO NVARCHAR(MAX) = '0'
DECLARE @PROCESO NVARCHAR(MAX) = '0'--24,11,
DECLARE @ESTADO_GUIA NVARCHAR(MAX) = '0'
DECLARE @ESTADO_DIGITALIZADA NVARCHAR(MAX) = 'NO DIGITALIZADA'
DECLARE @TIPO_CLIENTE NVARCHAR(MAX) = '1'
DECLARE @CIUDAD_ORIGEN NVARCHAR(MAX)  = '0'
DECLARE @CIUDAD_DESTINO NVARCHAR(MAX) = '0'
DECLARE @REP_FECHA_INICIAL DATETIME = '2026-05-01'
DECLARE @REP_FECHA_FINAL DATETIME = '2026-05-05'


-------------------------------------------------------------------------------------------------------------------------
-- 1. PROCESAMIENTO DE PARÁMETROS SSRS VÍA XML (Sintaxis nativa corregida para SQL Server y SSRS)
-------------------------------------------------------------------------------------------------------------------------

DROP TABLE IF EXISTS #REGIONAL_ORIGEN;
SELECT DISTINCT t.v.value('.', 'INT') AS REGIONAL_ORIGEN 
INTO #REGIONAL_ORIGEN 
FROM (SELECT CAST('<X>' + REPLACE(@REGIONAL_ORIGEN, ',', '</X><X>') + '</X>' AS XML) AS Tx) AS Main 
CROSS APPLY Tx.nodes('/X') AS t(v);

DROP TABLE IF EXISTS #REGIONAL_DESTINO;
SELECT DISTINCT t.v.value('.', 'INT') AS REGIONAL_DESTINO 
INTO #REGIONAL_DESTINO 
FROM (SELECT CAST('<X>' + REPLACE(@REGIONAL_DESTINO, ',', '</X><X>') + '</X>' AS XML) AS Tx) AS Main 
CROSS APPLY Tx.nodes('/X') AS t(v);

DROP TABLE IF EXISTS #REGIONAL_ALL;
SELECT DISTINCT REGIONAL_ALL INTO #REGIONAL_ALL 
FROM (
    SELECT REGIONAL_DESTINO AS REGIONAL_ALL FROM #REGIONAL_DESTINO 
    UNION ALL 
    SELECT REGIONAL_ORIGEN AS REGIONAL_ALL FROM #REGIONAL_ORIGEN
) ST_RG_ALL;

DROP TABLE IF EXISTS #CIUDAD_ORIGEN;
SELECT DISTINCT t.v.value('.', 'INT') AS CIUDAD_ORIGEN 
INTO #CIUDAD_ORIGEN 
FROM (SELECT CAST('<X>' + REPLACE(@CIUDAD_ORIGEN, ',', '</X><X>') + '</X>' AS XML) AS Tx) AS Main 
CROSS APPLY Tx.nodes('/X') AS t(v);

DROP TABLE IF EXISTS #CIUDAD_DESTINO;
SELECT DISTINCT t.v.value('.', 'INT') AS CIUDAD_DESTINO 
INTO #CIUDAD_DESTINO 
FROM (SELECT CAST('<X>' + REPLACE(@CIUDAD_DESTINO, ',', '</X><X>') + '</X>' AS XML) AS Tx) AS Main 
CROSS APPLY Tx.nodes('/X') AS t(v);

DROP TABLE IF EXISTS #CIUDAD_ALL;
SELECT DISTINCT CIUDAD_ALL INTO #CIUDAD_ALL 
FROM (
    SELECT CIUDAD_DESTINO AS CIUDAD_ALL FROM #CIUDAD_DESTINO 
    UNION ALL 
    SELECT CIUDAD_ORIGEN AS CIUDAD_ALL FROM #CIUDAD_ORIGEN
) ST_CD_ALL;

DROP TABLE IF EXISTS #PROCESO;
SELECT DISTINCT t.v.value('.', 'INT') AS PROCESO 
INTO #PROCESO 
FROM (SELECT CAST('<X>' + REPLACE(@PROCESO, ',', '</X><X>') + '</X>' AS XML) AS Tx) AS Main 
CROSS APPLY Tx.nodes('/X') AS t(v);

DROP TABLE IF EXISTS #ESTADO_GUIA;
SELECT DISTINCT t.v.value('.', 'INT') AS ESTADO_GUIA 
INTO #ESTADO_GUIA 
FROM (SELECT CAST('<X>' + REPLACE(@ESTADO_GUIA, ',', '</X><X>') + '</X>' AS XML) AS Tx) AS Main 
CROSS APPLY Tx.nodes('/X') AS t(v);

DROP TABLE IF EXISTS #ESTADO_DIGITALIZADA;
SELECT DISTINCT T.Item.value('.', 'VARCHAR(100)') AS ESTADO_DIGITALIZADA 
INTO #ESTADO_DIGITALIZADA 
FROM (SELECT CAST('<i>' + REPLACE(@ESTADO_DIGITALIZADA, ',', '</i><i>') +'</i>' AS XML) AS Tx) AS Main 
CROSS APPLY Tx.nodes('/i') T(Item);

DROP TABLE IF EXISTS #TIPO_CLIENTE;
SELECT DISTINCT t.v.value('.', 'INT') AS ID_TIPO_CLIENTE 
INTO #TIPO_CLIENTE 
FROM (SELECT CAST('<X>' + REPLACE(@TIPO_CLIENTE, ',', '</X><X>') + '</X>' AS XML) AS Tx) AS Main 
CROSS APPLY Tx.nodes('/X') AS t(v);

DROP TABLE IF EXISTS #TIPO_ENTREGA;
SELECT DISTINCT t.v.value('.', 'INT') AS ID_TIPO_ENTREGA 
INTO #TIPO_ENTREGA 
FROM (SELECT CAST('<X>' + REPLACE(@ID_TIPO_ENTREGA, ',', '</X><X>') + '</X>' AS XML) AS Tx) AS Main 
CROSS APPLY Tx.nodes('/X') AS t(v);

-------------------------------------------------------------------------------------------------------------------------
-- 2. CÁLCULO DE RANGOS DE FECHAS Y CONTROL DE AMPLITUD
-------------------------------------------------------------------------------------------------------------------------
DECLARE @MAX_DAYS_RANGE INT = 30;
IF 'NO DIGITALIZADA' IN (SELECT TOP 1 ESTADO_DIGITALIZADA FROM #ESTADO_DIGITALIZADA) 
   AND (SELECT COUNT(*) FROM #ESTADO_DIGITALIZADA) = 1   
BEGIN 
    SET @MAX_DAYS_RANGE = 180;
END;

DECLARE @ENT_TIPO_FECHA INT = CAST(@TIPO_CONSULTA AS INT);			
DECLARE @FECHA_INICIAL VARCHAR(15) = CONVERT(VARCHAR, CONVERT(DATETIME, @REP_FECHA_INICIAL), 112);
DECLARE @FECHA_FINAL VARCHAR(15) = CONVERT(VARCHAR, CONVERT(DATETIME, @REP_FECHA_FINAL), 112);
DECLARE @DIAS_AMPLITUDAD INT = DATEDIFF(DAY, @FECHA_INICIAL, @FECHA_FINAL);

DECLARE @FiltrarEstadoGuia BIT = CASE WHEN 0 IN (SELECT ESTADO_GUIA FROM #ESTADO_GUIA) THEN 0 ELSE 1 END;
DECLARE @FiltrarRegional BIT = CASE WHEN 0 IN (SELECT REGIONAL_ALL FROM #REGIONAL_ALL) THEN 0 ELSE 1 END;
DECLARE @FiltrarCiudadOrigen BIT = CASE WHEN 0 IN (SELECT CIUDAD_ORIGEN FROM #CIUDAD_ORIGEN) THEN 0 ELSE 1 END;
DECLARE @FiltrarCiudadDestino BIT = CASE WHEN 0 IN (SELECT CIUDAD_DESTINO FROM #CIUDAD_DESTINO) THEN 0 ELSE 1 END;
DECLARE @FiltrarProceso BIT = CASE WHEN 0 IN (SELECT PROCESO FROM #PROCESO) THEN 0 ELSE 1 END;

-------------------------------------------------------------------------------------------------------------------------
-- 3. EJECUCIÓN DEL REPORTE MEDIANTE CONSULTA LINEAL
-------------------------------------------------------------------------------------------------------------------------
IF @DIAS_AMPLITUDAD <= @MAX_DAYS_RANGE
BEGIN

    WITH CTE_DIGITALIZACION AS (
        SELECT ULT.* FROM [SIG_CCM_DM].[FAC].[DIGGUICCM_DIGITALIZACION_FINAL_ULTIMO_PROCESO_LOG] ULT WITH(NOLOCK)
        WHERE 1=1
          AND (
               (@ENT_TIPO_FECHA = 1 AND ULT.FECHA_HORA_MOVIMIENTO_EZ_EP >= @FECHA_INICIAL AND ULT.FECHA_HORA_MOVIMIENTO_EZ_EP <= @FECHA_FINAL) OR
               (@ENT_TIPO_FECHA = 2 AND ULT.[G_FECHA_ENVIO] >= @FECHA_INICIAL AND ULT.[G_FECHA_ENVIO] <= @FECHA_FINAL) OR
               (@ENT_TIPO_FECHA = 3 AND ULT.[UBIC_FECHA_HORA_MOVIMI] >= @FECHA_INICIAL AND ULT.[UBIC_FECHA_HORA_MOVIMI] <= @FECHA_FINAL)
          )
          AND ISNULL(ULT.ESTADO_DIGLIAIZADA, 'NO DIGITALIZADA') IN (SELECT ESTADO_DIGITALIZADA FROM #ESTADO_DIGITALIZADA)	
          AND ISNULL(ULT.[ID_TIPO_CLIENTE], 0) IN (SELECT ID_TIPO_CLIENTE FROM #TIPO_CLIENTE)
          AND ISNULL(ULT.ID_TIPO_ENTREGA, 0) IN (SELECT ID_TIPO_ENTREGA FROM #TIPO_ENTREGA)
          AND (@FiltrarEstadoGuia = 0 OR ISNULL(ULT.ID_ESTADOGUIA, 1) IN (SELECT ESTADO_GUIA FROM #ESTADO_GUIA))
    )
    SELECT 
        ULT.[NUMERO_GUIA] AS [G01_NUMERO_GUIA]
        ,ULT.[G_ID_CLIENTE] AS [G02_ID_CLIENTE]
        ,ULT.[ID_TIPO_CLIENTE] AS [G03_ID_TIPO_CLIENTE]
        ,ULT.[TIPO_CLIENTE] AS [G04_TIPO_CLIENTE]
        ,ULT.[G_ID_TIEMPO] AS [G05_ID_TIEMPO]
        ,ULT.[G_ID_MEDTRANS] AS [G06_ID_MEDTRANS] 
        ,ULT.[G_ID_REMITE] AS [G07_ID_REMITE]
        ,ULT.[G_NOMBRE_REMITE_GUIA] AS [G08_NOMBRE_REMITE_GUIA]
        ,ULT.[G_ID_DESTINATARIO] AS [G09_ID_DESTINATARIO] 
        ,ULT.[G_NOMBRE_DESTINANTARIO_GUIA] AS [G10_NOMBRE_DESTINANTARIO_GUIA]
        ,ULT.[ID_ESTADOGUIA] AS [G11_ID_ESTADOGUIA]
        ,SG.NOMBRE_ESTADOGUIA AS G12_NOMBRE_ESTADOGUIA
        ,ULT.[ID_ESTADOENVIO] AS [G13_ID_ESTADOENVIO]
        ,SE.NOMBRE_ESTADOENVIO AS G14_NOMBRE_ESTADOENVIO
        ,ULT.[G_ID_PRODUCTO] AS [G15_ID_PRODUCTO]
        ,PR.PRODUCTO AS G16_PRODUCTO
        ,RD.CIUDAD AS G17_CIUDAD_DESTINO	
        ,ULT.[G_ID_CIUDAD_DESTINO] AS [G18_ID_CIUDAD_DESTINO]
        ,RD.ID_REGIONAL AS G19_ID_REGIONAL_DESTINO 
        ,RD.REGIONAL AS G20_REGIONAL_DESTINO 
        ,RD.ID_DEPARTAMENTO AS G21_ID_DEPARTAMENTO_DESTINO	
        ,RD.DEPARTAMENTO AS G22_DEPARTAMENTO_DESTINO
        ,ULT.[G_ID_PAIS_DESTINO] [G23_ID_PAIS_DESTINO]  
        ,ULT.[G_ID_CIUDAD_ORIGEN] AS [G24_ID_CIUDAD_ORIGEN]
        ,RO.CIUDAD AS G25_CIUDAD_ORIGEN 
        ,RO.ID_REGIONAL AS G26_ID_REGIONAL_ORIGEN
        ,RO.REGIONAL AS G27_REGIONAL_ORIGEN
        ,RO.ID_DEPARTAMENTO AS G28_ID_DEPARTAMENTO_ORIGEN
        ,RO.DEPARTAMENTO AS G29_DEPARTAMENTO_ORIGEN
        ,ULT.[FECHA_CREACION] AS [G30_FECHA_CREACION]
        ,ULT.[G_FECHA_ENVIO] AS [G31_FECHA_ENVIO]
        ,ULT.FECHA_HORA_MOVIMIENTO_EZ_EP AS EZU01_FECHA_HORA_MOVIMIENTO_EZ_EP   
        ,RD_EZU.CIUDAD AS EZU02_DOC_NOMBRE_CIUDAD_DESTINO
        ,ULT.EZU_EPS_DOC_ID_CIUDAD_DESTINO AS EZU03_DOC_ID_CIUDAD_DESTINO 
        ,RD_EZU.ID_REGIONAL AS EZU04_DOC_ID_REGIONAL_DESTINO
        ,RD_EZU.REGIONAL AS EZU05_DOC_NOMBRE_REGIONAL_DESTINO
        ,ULT.[FECHA_DIGITALIZACION] AS [PE01_FECHA_DIGITALIZACION]
        ,ULT.[ESTADO_DIGLIAIZADA] AS [PE02_ESTADO_DIGLIAIZADA]
        ,ULT.[IMAGEN_GUIA] AS [PE03_IMAGEN_GUIA]
        ,ULT.[ID_TIPO_ENTREGA] AS [PE04_ID_TIPO_ENTREGA]
        ,ULT.[CIUDAD_REPORTADA_PRUEBAS_ENTREGA] AS [PE05_CIUDAD_REPORTADA_PRUEBAS_ENTREGA]
        ,ULT.[TIPO_ENTREGA] AS [PE06_TIPO_ENTREGA]
        ,ULT.[CAJA] AS [PE07_CAJA]
        ,ULT.[PAQUETE] AS [PE08_PAQUETE]
        ,ULT.[ID_ESTADO_AUDITADO] AS [PE09_ID_ESTADO_AUDITADO]
        ,ULT.[ESTADO_PAQUETE_AUDITADO] AS [PE11_ESTADO_PAQUETE_AUDITADO]
        ,ULT.[FECHA_DIGITALIZACION_VS_FECHA_CREACION] AS [PE12_FECHA_DIGITALIZACION_VS_FECHA_CREACION]
        ,ULT.[FECHA_HORA_MOVIMIENTO_VS_FECHA_CREACION] AS [PE13_FECHA_HORA_MOVIMIENTO_VS_FECHA_CREACION]
        ,ULT.[FECHA_HORA_MOVIMIENTO_VS_FECHA_DIGITALIZACION] AS [PE14_FECHA_HORA_MOVIMIENTO_VS_FECHA_DIGITALIZACION]
        ,ULT.[NUMERO_MOVIMI] AS [CROSS01_NUMERO_MOVIMI] 
        ,ULT.[CONSECUT_MOVIMI] AS [CROSS02_CONSECUT_MOVIMI] 
        ,ULT.[ID_PROCESO] AS [CROSS03_ID_PROCESO]
        ,ULT.[NOMBRE_PROCESO_LOG] AS [CROSS04_NOMBRE_PROCESO_LOG]
        ,ULT.[FECHA_HORA_MOVIMIENTO] AS [CROSS05_FECHA_HORA_MOVIMIENTO]
        ,CLO.CIUDAD AS CROSS06_DOC_NOMBRE_CIUDAD_ORIGEN
        ,ULT.DO_ID_CIUDAD_DIVISION_ORIGEN AS CROSS07__DOC_ID_CENTRO_LOGISTICO_ORIGEN
        ,CPD.CIUDAD AS CROSS08_DOC_NOMBRE_CIUDAD_DESTINO
        ,ULT.[DO_ID_CIUDAD_DESTINO] AS [CROSS09_DOC_ID_CIUDAD_DESTINO]
        ,ULT.[DO_ID_ZONA_URBA] AS [CROSS10_DOC_ID_ZONA_URBA]
        ,ULT.[DO_ID_CIUDAD_ZONA_URBA] AS [CROSS11_DOC_ID_CIUDAD_ZONA_URBA] 
        ,ULT.[DO_ID_TIPO_ZONA_URBA] AS [CROSS12_DOC_ID_TIPO_ZONA_URBA] 
        ,REPLACE(REPLACE(ULT.[NOMBRE_ZONA_URBANA], ';', ''), ',', '') AS CROSS13_DOC_NOMBRE_ZONA_URBANA
        ,ULT.[UBIC_ID_PROCESO] AS [ULT01_UBIC_ID_PROCESO]
        ,ULT.[UBIC_NOMBRE_PROCESO_LOG] AS [ULT02_UBIC_NOMBRE_PROCESO_LOG]
        ,ULT.[UBIC_FECHA_HORA_MOVIMI] AS [ULT03_UBIC_FECHA_HORA_MOVIMI]
        ,ULT.[UBIC_ID_DIV_BODEGA_UBICACION] AS [ULT04_UBIC_ID_BODEGA_UBICACION]
        ,ULT.[UBIC_BODEGA_UBICACION] AS [ULT05_UBIC_BODEGA_UBICACION]
        ,ULT.[UBIC_ID_CIUDAD_UBICACION] AS [ULT06_UBIC_ID_CIUDAD_UBICACION]
        ,ULT.[UBIC_CIUDAD_UBICACION] AS [ULT07_UBIC_CIUDAD_UBICACION]
        ,ULT.[CPL] AS [ULT08_UBIC_CPL]
        ,ULT.[UBIC_ID_REGIONAL_UBICACION] AS [ULT09_UBIC_ID_REGIONAL_UBICACION]
        ,ULT.[UBIC_NOMBRE_REGIONAL_UBICACION] AS [ULT10_UBIC_NOMBRE_REGIONAL_UBICACION]
        ,ULT.[ULT_SEG_NUMERO_PIEZAS] AS [ULT11_UBIC_SEG_NUMERO_PIEZAS]
        ,ULT.[ULT_ID_ZONA_URBA] AS [ULT12_UBIC_ID_ZONA_URBA]
        ,ULT.[ULT_ID_CIUDAD_ZONA_URBA] AS [ULT13_UBIC_ID_CIUDAD_ZONA_URBA]
        ,ULT.[ULT_ID_TIPO_ZONA_URBA] AS [ULT14_UBIC_ID_TIPO_ZONA_URBA]
        ,REPLACE(REPLACE(ULT_UBIC_Z.[ZONA_URBANA], ';', ''), ',', '') AS [ULT15_UBIC_NOMBRE_ZONA_URBA]
        ,ULT.[FECHA_EXTRACCION_DW] AS [CRTL01_FECHA_EXTRACCION_DW]
    FROM CTE_DIGITALIZACION ULT 
    LEFT JOIN DIM.GEOGRAFIA RO WITH (NOLOCK) ON ULT.G_ID_CIUDAD_ORIGEN = RO.ID_CIUDAD
    LEFT JOIN DIM.GEOGRAFIA CLO WITH (NOLOCK) ON ISNULL(ULT.DO_ID_CIUDAD_DIVISION_ORIGEN, ULT.DO_ID_CIUDAD_ZONA_URBA) = CLO.ID_CIUDAD
    LEFT JOIN DIM.GEOGRAFIA RD WITH (NOLOCK) ON ULT.G_ID_CIUDAD_DESTINO = RD.ID_CIUDAD
    LEFT JOIN DIM.GEOGRAFIA CPD WITH (NOLOCK) ON ULT.DO_ID_CIUDAD_DESTINO = CPD.ID_CIUDAD
    LEFT JOIN DIM.GEOGRAFIA RD_EZU WITH (NOLOCK) ON ULT.EZU_EPS_DOC_ID_CIUDAD_DESTINO = RD_EZU.ID_CIUDAD
    LEFT JOIN DIM.GEOGRAFIA RD_UBIC WITH (NOLOCK) ON ULT.EZU_EPS_DOC_ID_CIUDAD_DESTINO = RD_UBIC.ID_CIUDAD
    LEFT JOIN DIM.ZONAS_URBANAS ULT_UBIC_Z WITH (NOLOCK) 
        ON ULT.[ULT_ID_TIPO_ZONA_URBA] = ULT_UBIC_Z.ID_TIPO_ZONA_URBA 
        AND ULT.[ULT_ID_ZONA_URBA] = ULT_UBIC_Z.ID_ZONA_URBA 
        AND ULT.[ULT_ID_CIUDAD_ZONA_URBA] = ULT_UBIC_Z.ID_CIUDAD
    LEFT JOIN [DIM].[ESTADOS_ENVIO] SE WITH (NOLOCK) ON ULT.ID_ESTADOENVIO = SE.ID_ESTADOENVIO
    LEFT JOIN [DIM].[ESTADOS_GUIA] SG WITH (NOLOCK) ON ULT.ID_ESTADOGUIA = SG.ID_ESTADOGUIA
    LEFT JOIN SIG_CCM_DM.DIM.PRODUCTO PR ON ULT.G_ID_PRODUCTO = PR.ID_PRODUCTO
    WHERE 1=1
      AND (
          @FiltrarRegional = 0 OR
          (@ENT_TIPO_FECHA = 1 AND RD_EZU.ID_REGIONAL IN (SELECT REGIONAL_ALL FROM #REGIONAL_ALL)) OR
          (@ENT_TIPO_FECHA = 2 AND ISNULL(RD.[ID_REGIONAL], 0) IN (SELECT REGIONAL_DESTINO FROM #REGIONAL_DESTINO)) OR
          (@ENT_TIPO_FECHA = 3 AND ISNULL(RD_UBIC.[ID_REGIONAL], 0) IN (SELECT REGIONAL_ALL FROM #REGIONAL_ALL))
      )
      AND (
          @FiltrarCiudadOrigen = 0 OR
          (@ENT_TIPO_FECHA = 1 AND ISNULL(ULT.EZU_EPS_DOC_ID_CIUDAD_DESTINO, 0) IN (SELECT CIUDAD_ORIGEN FROM #CIUDAD_ORIGEN)) OR
          (@ENT_TIPO_FECHA = 2 AND ISNULL(ULT.[G_ID_CIUDAD_DESTINO], 0) IN (SELECT CIUDAD_DESTINO FROM #CIUDAD_DESTINO)) OR
          (@ENT_TIPO_FECHA = 3 AND ISNULL(ULT.[UBIC_ID_CIUDAD_UBICACION], 0) IN (SELECT CIUDAD_ALL FROM #CIUDAD_ALL))
      )
      AND (
          @FiltrarCiudadDestino = 0 OR
          (@ENT_TIPO_FECHA = 1 AND ISNULL(ULT.EZU_EPS_DOC_ID_CIUDAD_DESTINO, 0) IN (SELECT CIUDAD_DESTINO FROM #CIUDAD_DESTINO)) OR
          (@ENT_TIPO_FECHA = 2 AND ISNULL(ULT.[G_ID_CIUDAD_DESTINO], 0) IN (SELECT CIUDAD_DESTINO FROM #CIUDAD_DESTINO)) OR
          (@ENT_TIPO_FECHA = 3 AND ISNULL(ULT.[UBIC_ID_CIUDAD_UBICACION], 0) IN (SELECT CIUDAD_ALL FROM #CIUDAD_ALL))
      )
      AND (
          @FiltrarProceso = 0 OR
          (@ENT_TIPO_FECHA = 1 AND ISNULL(ULT.[ID_PROCESO], 0) IN (SELECT PROCESO FROM #PROCESO)) OR
          (@ENT_TIPO_FECHA IN (2,3) AND ISNULL(ULT.[UBIC_ID_PROCESO], 0) IN (SELECT PROCESO FROM #PROCESO))
      );
END;