use SIG_COLOMBIA_DW;
SELECT 
	#ROW_ID
	,YEAR(G_FECHA_ENVIO)*100+MONTH(G_FECHA_ENVIO) AS PERIODO
	,TEMP.NUMERO_GUIA
	,TEMP.ID_PROCESO
	,NOMBRE_PROCESO_LOG = CASE WHEN TEMP.ID_PROCESO=11 THEN 'ENTREGA VERIFICADA'
							WHEN TEMP.ID_PROCESO=24 THEN 'REPORTADO ENTREGADO' ELSE 'NO APLICA' END	
	,PR_ENT.FECHA_CREACION
	,PR_ENT.FECHA_DIGITALIZACION
	,TEMP.FECHA_HORA_MOVIMIENTO
	,DATEDIFF(DAY,PR_ENT.FECHA_DIGITALIZACION,PR_ENT.FECHA_CREACION) AS FECHA_DIGITALIZACION_VS_FECHA_CREACION
	,DATEDIFF(DAY,TEMP.FECHA_HORA_MOVIMIENTO,PR_ENT.FECHA_CREACION) AS FECHA_HORA_MOVIMIENTO_VS_FECHA_CREACION
	,DATEDIFF(DAY,TEMP.FECHA_HORA_MOVIMIENTO,PR_ENT.FECHA_DIGITALIZACION) AS FECHA_HORA_MOVIMIENTO_VS_FECHA_DIGITALIZACION
	,IIF(PR_ENT.NUMERO_GUIA IS NULL,'NO DIGITALIZADA','DIGITALIZADA') ESTADO_DIGLIAIZADA
	,PR_ENT.TIPO_PRUEBA_ENTREGA AS ID_TIPO_ENTREGA
	,CASE WHEN PR_ENT.TIPO_PRUEBA_ENTREGA=1 THEN 'FISICA' 
			WHEN PR_ENT.TIPO_PRUEBA_ENTREGA=2 THEN 'VIRTUAL'
			ELSE 'NO DISPONIBLE' END AS TIPO_ENTREGA
	,TEMP.ID_CIUDAD_DIVISION_ORIGEN DO_ID_CIUDAD_DIVISION_ORIGEN
	,TEMP.ID_CIUDAD_DESTINO  DO_ID_CIUDAD_DESTINO
	,PR_ENT.ID_CIUDAD as CIUDAD_REPORTADA_PRUEBAS_ENTREGA
	,TEMP.ID_ESTADOGUIA
	,TEMP.ID_ESTADOENVIO
	,TEMP.NUMERO_MOVIMI
	,TEMP.CONSECUT_MOVIMI
	,G_ID_CIUDAD_ORIGEN
	,G_ID_CIUDAD_DESTINO
	,G_FECHA_ENVIO
	,G_NOMBRE_REMITE_GUIA
	,G_ID_PRODUCTO
	,G_ID_CLIENTE
	,IIF(G_ID_CLIENTE IS NULL,0,1) AS ID_TIPO_CLIENTE
FROM [TMP_BORRAR].[DBO].[TEMPORAL_GUIAS_DIGITALIZADAS_FINAL] TEMP WITH(NOLOCK)
LEFT JOIN LOG.PRUEBAS_ENTREGA PR_ENT  WITH(NOLOCK)
ON PR_ENT.NUMERO_GUIA=TEMP.NUMERO_GUIA

