							AND RD_UBIC.[ID_REGIONAL]  IN(SELECT IDS FROM #ID_REGIONAL_ORIGEN)
							AND RD_UBIC.[ID_REGIONAL] IN(SELECT IDS FROM #ID_REGIONAL_DESTINO)
