									LEFT JOIN [DIM].[ESTADOS_ENVIO] SE WITH (NOLOCK)
										ON ULT.ID_ESTADOENVIO = SE.ID_ESTADOENVIO
									LEFT JOIN [DIM].[ESTADOS_GUIA] SG WITH (NOLOCK)
										ON ULT.ID_ESTADOGUIA = SG.ID_ESTADOGUIA
									LEFT JOIN DIM.ZONAS_URBANAS Z WITH (NOLOCK)
										ON ULT.DO_ID_TIPO_ZONA_URBA = Z.ID_TIPO_ZONA_URBA AND
										ULT.DO_ID_ZONA_URBA = Z.ID_ZONA_URBA AND
										ULT.DO_ID_CIUDAD_ZONA_URBA = Z.ID_CIUDAD
									LEFT JOIN #SIG_CCM_DM_DIM_PRODUCTO PR ON ULT.G_ID_PRODUCTO = PR.ID_PRODUCTO
