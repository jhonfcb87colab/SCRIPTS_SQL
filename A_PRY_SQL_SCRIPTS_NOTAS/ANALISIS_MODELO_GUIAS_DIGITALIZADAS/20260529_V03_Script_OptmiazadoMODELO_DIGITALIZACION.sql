          AND ISNULL(ULT.ID_TIPO_ENTREGA, 0) IN (SELECT CAST(VALUE AS INT) FROM STRING_SPLIT('''+@ID_TIPO_ENTREGA+''', '',''))        
          AND ISNULL(ULT.ID_ESTADOGUIA, 1) IN (SELECT CAST(VALUE AS INT) FROM STRING_SPLIT('''+@ESTADO_GUIA+''', '',''))    
        OPTION(RECOMPILE);';   
 
