    DECLARE @ENT_TIPO_FECHA INT = @TIPO_CONSULTA;            
    DECLARE @FECHA_INICIAL VARCHAR(15) = CONVERT(VARCHAR, @REP_FECHA_INICIAL, 112);
    DECLARE @FECHA_FINAL VARCHAR(15) = CONVERT(VARCHAR, @REP_FECHA_FINAL, 112); 
    DECLARE @DIAS_AMPLITUDAD INT = DATEDIFF(DAY, @REP_FECHA_INICIAL, @REP_FECHA_FINAL);

    -- ==========================================
    -- 2. CONTROL DE RANGOS DE FECHAS (OPTIMIZADO SIN TABLAS)
    -- ==========================================
    -- Evaluamos los estados directamente usando la variable original
    DECLARE @TieneDigitalizada INT = (SELECT COUNT(1) FROM STRING_SPLIT(@ESTADO_DIGITALIZADA, ',') WHERE CAST(VALUE AS INT) = 1);
    DECLARE @TieneNoDigitalizada INT = (SELECT COUNT(1) FROM STRING_SPLIT(@ESTADO_DIGITALIZADA, ',') WHERE CAST(VALUE AS INT) <> 1);
    DECLARE @TotalEstados INT = @TieneDigitalizada + @TieneNoDigitalizada;

    IF @DIAS_AMPLITUDAD > 31 AND @TIPO_CONSULTA <> 1 AND (@TieneDigitalizada = 0 OR @TotalEstados > 1)
        BEGIN
            SET @MAX_DAYS_RANGE = 31;         
            SET @FECHA_INICIAL = CONVERT(VARCHAR, DATEADD(DAY,-@MAX_DAYS_RANGE,CONVERT(DATETIME,@FECHA_FINAL)), 112);
        END

    IF @TieneNoDigitalizada > 0 AND @TotalEstados = 1 AND @DIAS_AMPLITUDAD > 180 AND @TIPO_CONSULTA = 1
        BEGIN
            SET @MAX_DAYS_RANGE = 180;  
            SET @FECHA_INICIAL = CONVERT(VARCHAR, DATEADD(DAY,-@MAX_DAYS_RANGE,CONVERT(DATETIME,@FECHA_FINAL)), 112);
        END
    
    IF @DIAS_AMPLITUDAD > 31 AND (@TIPO_CONSULTA <> 1 OR (@TieneDigitalizada > 0 OR @TotalEstados > 1))
        BEGIN
            SET @MAX_DAYS_RANGE = 31;         
            SET @FECHA_INICIAL = CONVERT(VARCHAR, DATEADD(DAY,-@MAX_DAYS_RANGE,CONVERT(DATETIME,@FECHA_FINAL)), 112);
        END

