WITH PREFACT_DETAMOV (
sROW	
,ID_MOVDETALLE	
,ID_MOVIMIENTO	
,ID_TIPO_DOCUMENTO	
,NUMERO_DOCUMENTO	
,ID_TIPO_DETALLE_MOVIMIENTO	
,VALOR_MOVDETALLE	
,NOMBRE_DETALLE	
,NATURALEZA	
,FECHA_CREACION	
,FECHA_MOFICACION
)as(
SELECT 
ROW_NUMBER() OVER (PARTITION BY M.NUMERO_DOCUMENTO, M.ID_MOVIMIENTO ORDER BY M.FECHA_CREACION DESC ) AS sROW,
M.ID_MOVDETALLE, 
M.ID_MOVIMIENTO, 
M.ID_TIPO_DOCUMENTO, 
M.NUMERO_DOCUMENTO,
M.ID_TIPO_DETALLE_MOVIMIENTO, 
M.VALOR_MOVDETALLE, 
D.NOMBRE_DETALLE, 
D.NATURALEZA, 
M.FECHA_CREACION, 
M.FECHA_MOFICACION
FROM MERF_INGRESOS..DETALLES_MOVIMIENTOS M (NOLOCK) 
INNER JOIN MERF_INGRESOS.DBO.TIPO_DETALLE_MOVIMIENTO D (NOLOCK) ON D.ID_TIPO_DETALLE_MOVIMIENTO=M.ID_TIPO_DETALLE_MOVIMIENTO
WHERE M.ID_CANAL = D.ID_CANAL AND D.NATURALEZA ='CR'
AND M.NUMERO_DOCUMENTO --=202568967	--213234526
				IN(
				204848966,
				210020118,
				211425266,
				212446770,
				213234526
				)
) 
SELECT
	P.ID_MOVDETALLE,
	P.ID_MOVIMIENTO,
	FC.ID_PREFACTURA,
	P.ID_TIPO_DOCUMENTO,
	P.NUMERO_DOCUMENTO,
	D.ID_TIPOGUIA,
	P.ID_TIPO_DETALLE_MOVIMIENTO,
	P.VALOR_MOVDETALLE,
	P.NOMBRE_DETALLE,
	P.NATURALEZA,
	P.FECHA_CREACION,
	P.FECHA_MOFICACION
FROM PREFACT_DETAMOV P (NOLOCK)
INNER JOIN MERF_INGRESOS..MECE_LOGISTICO_GUIAS D (NOLOCK)
ON P.NUMERO_DOCUMENTO=D.NUMERO_GUIA
LEFT JOIN MERF_INGRESOS..PREFACTURAS FC (NOLOCK)
ON FC.ID_MOVIMIENTO=P.ID_MOVIMIENTO
WHERE P.sROW = 1



