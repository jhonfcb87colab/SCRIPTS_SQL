USE PARAMETROS;

WITH ARCHIVOS_A_CARGAR AS (
SELECT DISTINCT 
FECHA_CREACION
,ID_CARGUE_ARCHIVO	
,NOMBRE_ARCHIVO	
,ACCION	
,CANTIDAD_REGISTROS	
,RESULTADO	
,CAUSAL_FALLO	
,VERSION_SHAREPOINT
,LOGIN_CREACION	
,ID_MASTER_ARCHIVO
FROM  BI_CARGUE_ARCHIVO WITH (NOLOCK)
WHERE ID_MASTER_ARCHIVO IN(SELECT ID_MASTER_ARCHIVO FROM  BI_MASTER_ARCHIVO WITH (NOLOCK) WHERE SINCRONIZADO=0)
AND RESULTADO='EXITOSO' 
) ,MAXIMAS_FECHAS_DE_CARGUE AS (
SELECT 
MAX(FECHA_CREACION) AS FECHA_CREACION,NOMBRE_ARCHIVO
FROM ARCHIVOS_A_CARGAR
GROUP BY  NOMBRE_ARCHIVO
),ID_ARCHIVOS_CARGUE AS (
SELECT DISTINCT
C.ID_CARGUE_ARCHIVO
--,C.FECHA_CREACION
--,M.NOMBRE_ARCHIVO
FROM ARCHIVOS_A_CARGAR C
INNER JOIN MAXIMAS_FECHAS_DE_CARGUE M ON C.NOMBRE_ARCHIVO=M.NOMBRE_ARCHIVO AND CONVERT(VARCHAR,C.FECHA_CREACION)=CONVERT(VARCHAR,M.FECHA_CREACION)
)
SELECT *FROM  BI_FACILITADOR_CLIENTES_NUEVOS WHERE ID_CARGUE_ARCHIVO IN (SELECT * FROM ID_ARCHIVOS_CARGUE)