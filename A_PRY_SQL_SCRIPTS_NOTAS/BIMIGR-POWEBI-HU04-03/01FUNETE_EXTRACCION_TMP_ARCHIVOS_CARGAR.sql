WITH ARCHIVOS_A_CARGAR AS (
SELECT DISTINCT 
CA.FECHA_CREACION
,CA.ID_CARGUE_ARCHIVO
,CA.NOMBRE_ARCHIVO	
,MA.TIPO_ARCHIVO
,MA.ANIO
,MA.MES
,CA.CANTIDAD_REGISTROS	
,CA.RESULTADO	
,CA.ID_MASTER_ARCHIVO
FROM  BI_CARGUE_ARCHIVO CA WITH (NOLOCK)
LEFT JOIN BI_MASTER_ARCHIVO MA WITH (NOLOCK) ON CA.ID_MASTER_ARCHIVO=MA.ID_MASTER_ARCHIVO
WHERE CA.ID_MASTER_ARCHIVO IN(SELECT ID_MASTER_ARCHIVO FROM  BI_MASTER_ARCHIVO WITH (NOLOCK) WHERE SINCRONIZADO=0)
AND RESULTADO='EXITOSO' 
) ,MAXIMAS_FECHAS_DE_CARGUE AS (
SELECT 
MAX(FECHA_CREACION) AS FECHA_CREACION
,NOMBRE_ARCHIVO
,TIPO_ARCHIVO
,ANIO
,MES
FROM ARCHIVOS_A_CARGAR
GROUP BY  NOMBRE_ARCHIVO,ANIO,MES,TIPO_ARCHIVO
)
SELECT DISTINCT
C.ID_CARGUE_ARCHIVO
,C.FECHA_CREACION
,M.NOMBRE_ARCHIVO
,M.TIPO_ARCHIVO
,M.ANIO
,M.MES
,C.ID_MASTER_ARCHIVO
FROM ARCHIVOS_A_CARGAR C
INNER JOIN MAXIMAS_FECHAS_DE_CARGUE M ON C.NOMBRE_ARCHIVO=M.NOMBRE_ARCHIVO AND CONVERT(VARCHAR,C.FECHA_CREACION)=CONVERT(VARCHAR,M.FECHA_CREACION)





