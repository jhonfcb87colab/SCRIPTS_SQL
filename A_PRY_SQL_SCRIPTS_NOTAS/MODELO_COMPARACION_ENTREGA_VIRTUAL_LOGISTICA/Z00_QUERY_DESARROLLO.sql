WITH CTE_PRUEB_ENTREGA_VIRTUAl (
	ROW_ID	
	,TIME_ID	
	,NUMERO_GUIA	
	,SE_ID_PROCESO	
	,NUMERO_MOVIMI	
	,CONSECUT_MOVIMI	
	,ID_CIUDAD_ZONA_URBA	
	,ID_REGIONAL	
	,ID_TIPO_LOGISTICA	
	,ORDEN	
	,FECHA_ENTREGA	
	,FECHA_HORA_MOVIMI	
	,FECHA_GENERACION	
	,SE_FECHA_HORA_MOVIMIENTO	
	,DC_ID_CIUDAD_CANAL	
	,DC_ID_CIUDAD_DESTINO	
	,DC_ID_DIVISION_DESTINO	
	,DC_ID_CIUDAD_DIVISION_ORIGEN	
	,DC_ID_CANAL	
	,ID_CIUDAD_OPERATIVO	
	,[FECHA_ENTREGA (Formato)]
	,[FECHA_HORA_MOVIMI (Formato)]
)
AS(
	SELECT 
		[ROW_ID]= ROW_NUMBER ( )   OVER ( PARTITION BY TMP.[NUMERO_GUIA] order by TMP.[FECHA_HORA_MOVIMI] desc )
		,[TIME_ID] = CONVERT(INT,CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,TMP.[FECHA_HORA_MOVIMI])))) 
		,TMP.[NUMERO_GUIA]
		,TMP.[SE_ID_PROCESO]
		,TMP.[NUMERO_MOVIMI]
		,TMP.[CONSECUT_MOVIMI]
		,TMP.[ID_CIUDAD_ZONA_URBA]
		,CIU.ID_REGIONAL
		,TMP.[ID_TIPO_LOGISTICA]
		,TMP.[ORDEN]
		,TMP.[FECHA_ENTREGA]
		,TMP.[FECHA_HORA_MOVIMI]
		,TMP.[FECHA_GENERACION]
		,TMP.[SE_FECHA_HORA_MOVIMIENTO]
		,TMP.[DC_ID_CIUDAD_CANAL]
		,TMP.[DC_ID_CIUDAD_DESTINO]
		,[DC_ID_DIVISION_DESTINO] = TMP.[ID_DIVISION_DESTINO]
		,TMP.[DC_ID_CIUDAD_DIVISION_ORIGEN]
		,TMP.[DC_ID_CANAL]
		,TMP.[ID_CIUDAD_OPERATIVO]
		,[FECHA_ENTREGA (Formato)] = CONVERT(VARCHAR,CONVERT(DATE,CONVERT(DATETIME,TMP.FECHA_ENTREGA)),121)-----LEFT(FECHA_ENTREGA,10)
		,[FECHA_HORA_MOVIMI (Formato)] = CONVERT(VARCHAR,CONVERT(DATE,CONVERT(DATETIME,FECHA_HORA_MOVIMI)),121)-----LEFT([FECHA_HORA_MOVIMI],10)
	FROM [TMP].[MBIENTVI_GUIAS_01] TMP WITH(NOLOCK)
	LEFT JOIN PAR.CIUDADES CIU WITH(NOLOCK)
	ON CIU.ID_CIUDAD=TMP.ID_CIUDAD_ZONA_URBA
)
