		CONVERT(VARCHAR, DATEADD(minute,2, GP.FECHA_HORA_MOVIMIENTO), 120) AS FECHA_HORA_MOVIMI,					
		ROW_NUMBER() OVER(ORDER BY GP.NUMERO_GUIA) ORDEN,
		GETDATE() AS FECHA_GENERACION
		INTO [tmp_borrar].DBO.GUIASPROCESAR_20230209_SR
	FROM #GUIASPROCESAR_20230209_SR GP 
	INNER JOIN MECE_LOGISTICO..GUIAS G WITH(NOLOCK) ON ( G.NUMERO_GUIA = GP.NUMERO_GUIA )
	--ORDER BY GP.NUMERO_GUIA
	GO
