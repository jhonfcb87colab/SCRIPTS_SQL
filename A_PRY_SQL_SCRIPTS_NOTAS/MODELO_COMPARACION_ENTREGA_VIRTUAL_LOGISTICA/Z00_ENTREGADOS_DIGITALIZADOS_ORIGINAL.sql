	CREATE NONCLUSTERED INDEX IXD2 ON #GUIASPROCESAR_20230209_SR (ID_PROCESO, NUMERO_MOVIMI, CONSECUT_MOVIMI ) 	
	CREATE NONCLUSTERED INDEX IXD3 ON #GUIASPROCESAR_20230209_SR (NUMERO_MOVIMI, CONSECUT_MOVIMI, NUMERO_GUIA) 	

