	DECLARE @FechaInicial AS DATETIME, @FechaFinal AS DATETIME, @fecha_actual_parametros AS DATETIME, @fecha_inicial_parametros AS DATETIME

	--SELECT @FechaInicial = FECHA_CONTROL 
	--FROM Mece_Logistico..SERVICIOS_EJECUCION_CONTROL
	--WHERE SERVICIO = 'ENTREGA_VERIFICADA_MASIVA'

	--SET @FechaFinal   = DATEADD(SECOND,-1,CAST(CAST(GETDATE() AS DATE) AS DATETIME))


	SET @fecha_inicial_parametros = DATEADD(DAY,-7,convert(datetime,'"+ (DT_WSTR,12)@[User::DT_NUMERIC_01_FEC_INI] +"'))
	SET @fecha_actual_parametros = DATEADD(DAY,1,convert(datetime,'"+  (DT_WSTR,12)@[User::DT_NUMERIC_02_FEC_FIN]   +"'))


	SET @FechaInicial   = CONVERT(DATETIME,CONVERT(DATE,CONVERT(DATETIME,@fecha_inicial_parametros))) 
	SET @FechaFinal		= CONVERT(DATETIME,CONVERT(DATE,@fecha_actual_parametros))
	

