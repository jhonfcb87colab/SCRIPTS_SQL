	-- SE DBE CREAR INDICE A LA TABLA SEGUIMIENTO_ENVIO_INF_ADICIONAL_MOVIL POR LOS CAMPOS (ID_PROCESO, TIPO_PRUEBA_ENTREGA, FECHA_MODIFICACION)
	INSERT INTO #GUIASPROCESAR_20230209_SR(ID_PROCESO, NUMERO_MOVIMI, CONSECUT_MOVIMI, ID_CIUDAD_ZONA_URBA, ID_TIPO_LOGISTICA, NUMERO_GUIA, FECHA_HORA_MOVIMIENTO)
	SELECT ID_PROCESO,
		NUMERO_MOVIMI,
		CONSECUT_MOVIMI,
		NULL AS ID_CIUDAD_ZONA_URBA,
		NULL AS ID_TIPO_LOGISTICA,
		NUMERO_GUIA,
		FECHA_MODIFICACION	-- TIENE EL MISMO VALOR DE LA FECHA_HORA_MOVIMIENTO	
	FROM MECE_LOGISTICO..SEGUIMIENTO_ENVIO_INF_ADICIONAL_MOVIL (NOLOCK)
	WHERE ( ID_PROCESO = 24	--REPORTADO ENTREGADO
	AND TIPO_PRUEBA_ENTREGA = 2	--ENTREGA VIRTUAL
	AND FECHA_MODIFICACION BETWEEN @FechaInicial AND @FechaFinal )

	GO
	--Se valida que no hallan registros de movimientos posteriores con el estado 30 REVERSION REPORTADO ENTREGADO , 10 DEVOLUCION ZONA URBANA y 11 ENTREGA VERIFICADA
	DELETE G
	FROM #GUIASPROCESAR_20230209_SR G 
	INNER JOIN MECE_LOGISTICO..SEGUIMIENTO_ENVIO SE WITH(NOLOCK) ON ( SE.ID_PROCESO IN (10,30) AND SE.NUMERO_MOVIMI = G.NUMERO_MOVIMI AND SE.CONSECUT_MOVIMI = G.CONSECUT_MOVIMI AND SE.NUMERO_GUIA = G.NUMERO_GUIA )--11,
	
	-- Se actualiza la Ciudad de la Zona Urbana a la cual se realizara el registro de la Entrega Veriicada Masiva.
	UPDATE SEG SET ID_CIUDAD_ZONA_URBA = DOC.ID_CIUDAD_ZONA_URBA, ID_TIPO_LOGISTICA = DOC.ID_TIPO_LOGISTICA
	FROM #GUIASPROCESAR_20230209_SR SEG (NOLOCK)
	INNER JOIN MECE_LOGISTICO..DOCUMENTOS DOC (NOLOCK) ON ( SEG.ID_PROCESO = DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI = DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI = DOC.CONSECUT_MOVIMI )

	GO
	--Por ultimo se cruza con la tabla guias y se presenta la informacion para ser consumida por el servicio
	SELECT 
		GP.NUMERO_MOVIMI,
		GP.CONSECUT_MOVIMI,
		GP.NUMERO_GUIA,
		GP.ID_CIUDAD_ZONA_URBA,
		GP.ID_TIPO_LOGISTICA,
