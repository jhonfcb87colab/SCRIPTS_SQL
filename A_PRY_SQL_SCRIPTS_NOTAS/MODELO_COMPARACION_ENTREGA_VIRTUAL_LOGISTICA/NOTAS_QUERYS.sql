	SET NOCOUNT ON;

	DECLARE @FechaInicial AS DATETIME, @FechaFinal AS DATETIME

	--SELECT @FechaInicial = FECHA_CONTROL 
	--FROM Mece_Logistico..SERVICIOS_EJECUCION_CONTROL
	--WHERE SERVICIO = 'ENTREGA_VERIFICADA_MASIVA'

	--SET @FechaFinal   = DATEADD(SECOND,-1,CAST(CAST(GETDATE() AS DATE) AS DATETIME))

	SET @FechaInicial   = CAST('2023-02-11 00:00:00' AS DATETIME)
	SET @FechaFinal		= CAST(GETDATE() AS DATETIME)
	
    -- Crear Tabla temporal donde se guardaran la información de las guías a procesar que cumplan con las fechas y el proceso 24 - Proceso_Entregado, excluyendo procesos 10,11 y 30
	CREATE TABLE #GUIASPROCESAR(ID_PROCESO				SMALLINT      NULL,
	                            NUMERO_MOVIMI			CHAR(30)      NULL,
								CONSECUT_MOVIMI			NUMERIC( 7,0) NULL,
								ID_CIUDAD_ZONA_URBA		INT           NULL,
								ID_TIPO_LOGISTICA		TINYINT       NULL,
								NUMERO_GUIA				NUMERIC(20,0) NULL,
							    FECHA_HORA_MOVIMIENTO   DATETIME	  NULL)

	CREATE NONCLUSTERED INDEX IXD1 ON #GUIASPROCESAR (NUMERO_GUIA) 	
	CREATE NONCLUSTERED INDEX IXD2 ON #GUIASPROCESAR (ID_PROCESO, NUMERO_MOVIMI, CONSECUT_MOVIMI ) 	
	CREATE NONCLUSTERED INDEX IXD3 ON #GUIASPROCESAR (NUMERO_MOVIMI, CONSECUT_MOVIMI, NUMERO_GUIA) 	
	

	-- SE DBE CREAR INDICE A LA TABLA SEGUIMIENTO_ENVIO_INF_ADICIONAL_MOVIL POR LOS CAMPOS (ID_PROCESO, TIPO_PRUEBA_ENTREGA, FECHA_MODIFICACION)
	INSERT INTO #GUIASPROCESAR(ID_PROCESO, NUMERO_MOVIMI, CONSECUT_MOVIMI, ID_CIUDAD_ZONA_URBA, ID_TIPO_LOGISTICA, NUMERO_GUIA, FECHA_HORA_MOVIMIENTO)
	SELECT ID_PROCESO,
		NUMERO_MOVIMI,
		CONSECUT_MOVIMI,
		NULL AS ID_CIUDAD_ZONA_URBA,
		NULL AS ID_TIPO_LOGISTICA,
		NUMERO_GUIA,
		FECHA_MODIFICACION	-- TIENE EL MISMO VALOR DE LA FECHA_HORA_MOVIMIENTO	
	FROM MECE_LOGISTICO..SEGUIMIENTO_ENVIO_INF_ADICIONAL_MOVIL (NOLOCK)
	WHERE ( ID_PROCESO = 24	--REPORTADO ENTREGADO
	AND TIPO_PRUEBA_ENTREGA = 2	--ENTREGA VIRTUAL
	AND FECHA_MODIFICACION BETWEEN @FechaInicial AND @FechaFinal )

	--Se valida que no hallan registros de movimientos posteriores con el estado 
	---30 REVERSION REPORTADO ENTREGADO , 10 DEVOLUCION ZONA URBANA y 11 ENTREGA VERIFICADA
	DELETE G
	FROM #GUIASPROCESAR G 
	INNER JOIN MECE_LOGISTICO..SEGUIMIENTO_ENVIO SE WITH(NOLOCK) ON ( SE.ID_PROCESO IN (10,11,30) 
	AND SE.NUMERO_MOVIMI = G.NUMERO_MOVIMI 
	AND SE.CONSECUT_MOVIMI = G.CONSECUT_MOVIMI 
	AND SE.NUMERO_GUIA = G.NUMERO_GUIA )
	
	-- Se actualiza la Ciudad de la Zona Urbana a la cual se realizara el registro de la Entrega Veriicada Masiva.
	UPDATE SEG SET ID_CIUDAD_ZONA_URBA = DOC.ID_CIUDAD_ZONA_URBA, ID_TIPO_LOGISTICA = DOC.ID_TIPO_LOGISTICA
	FROM #GUIASPROCESAR SEG (NOLOCK)
	INNER JOIN MECE_LOGISTICO..DOCUMENTOS DOC (NOLOCK) ON ( SEG.ID_PROCESO = DOC.ID_PROCESO AND SEG.NUMERO_MOVIMI = DOC.NUMERO_MOVIMI AND SEG.CONSECUT_MOVIMI = DOC.CONSECUT_MOVIMI )

	--Por ultimo se cruza con la tabla guias y se presenta la informacion para ser consumida por el servicio
	SELECT 
		GP.NUMERO_MOVIMI,
		GP.CONSECUT_MOVIMI,
		GP.NUMERO_GUIA,
		GP.ID_CIUDAD_ZONA_URBA,
		GP.ID_TIPO_LOGISTICA,
		CONVERT(VARCHAR, DATEADD(minute,2, G.FECHA_ENTREGA), 120) AS FECHA_ENTREGA,	
		CONVERT(VARCHAR, DATEADD(minute,2, GP.FECHA_HORA_MOVIMIENTO), 120) AS FECHA_HORA_MOVIMI,					
		ROW_NUMBER() OVER(ORDER BY GP.NUMERO_GUIA) ORDEN
	FROM #GUIASPROCESAR GP 
	INNER JOIN MECE_LOGISTICO..GUIAS G WITH(NOLOCK) ON ( G.NUMERO_GUIA = GP.NUMERO_GUIA )
	--ORDER BY GP.NUMERO_GUIA

	-- Se borran las tablas temporales
	DROP TABLE #GUIASPROCESAR

--END

