WITH CTE
(
	NUMERO_GUIA	
	,SE_NUMERO_MOVIMI	
	,SE_CONSECUT_MOVIMI	
	,SE_ID_PROCESO	
	,SE_ID_CONCEPTO	
	,ID_CLIENTE	
	,VOLUMEN_DIGITALIZACION	
	,PATH_IMAGEN	
	,GENERO_PRUEBA	
	,FECHA_CREACION	
	,ID_CIUDAD	
	,USUARIO_DIGITALIZA	
	,FECHA_PROCESO	
	,SERVIDOR
)AS(
SELECT TMP04.[NUMERO_GUIA]
	,SE_NUMERO_MOVIMI = TMP05.NUMERO_MOVIMI
	,SE_CONSECUT_MOVIMI = TMP05.CONSECUT_MOVIMI
	,SE_ID_PROCESO = TMP05.ID_PROCESO
	,SE_ID_CONCEPTO = TMP05.ID_CONCEPTO
	,TMP04.[ID_CLIENTE]
	,TMP04.[VOLUMEN_DIGITALIZACION]
	,TMP04.[PATH_IMAGEN]
	,TMP04.[GENERO_PRUEBA]
	,TMP04.[FECHA_CREACION]
	,TMP04.[ID_CIUDAD]
	,TMP04.[USUARIO_DIGITALIZA]
	,TMP04.[FECHA_PROCESO]
	,TMP04.[SERVIDOR]
  FROM [SIG_COLOMBIA_DW].[TMP].[MBIENTVI_GUIAS_04] TMP04
  LEFT JOIN  [TMP].[MBIENTVI_GUIAS_05] TMP05
  ON TMP05.NUMERO_GUIA=TMP04.NUMERO_GUIA AND TMP05.ID=1
) 
SELECT * FROM CTE




