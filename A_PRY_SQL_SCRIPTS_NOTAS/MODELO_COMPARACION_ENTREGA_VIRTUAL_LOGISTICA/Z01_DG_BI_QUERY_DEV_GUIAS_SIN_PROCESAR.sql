		,SE.ID_SUBPRODUCTO
		,SE.ID_TIPOENVIO
		,SE.ID_CONSECUTIVO_SEGUIMIENTO
		,SE.ID_ENVIO_CRUZADO
		,SE.PESO_ENVIO
		,SE.LARGO_ENVIO
		,SE.ANCHO_ENVIO
		,SE.ALTO_ENVIO
		,SE.HORA_INICIAL_ENTREGA
		,SE.HORA_FINAL_ENTREGA
		,SE.FECHA_HORA_MOVIMIENTO
		,SE.ID_MODO_REGISTRO
		,SE.NUMERO_PIEZAS
		,SE.ID_EST_EMBALAJE
		,SE.ID_TIPOENVIO_PRODUCTIVIDAD
		,SE.DEVOLUCION_REGIONAL
		,SE.LOGIN_EMPLEADO
		,SE.FECHA_CREACION
		,SE.FECHA_MODIFICACION
		,SE.ID_REPLICADO
		FROM MECE_LOGISTICO.DBO.SEGUIMIENTO_ENVIO SE WITH (NOLOCK) 
		INNER JOIN @NUMERO_GUIAS_ENTREGADAS TMP ON SE.NUMERO_GUIA=TMP.NUMERO_GUIA
		 --NUMERO_GUIA 
		 --IN (
			-- SELECT DISTINCT NUMERO_GUIA FROM SEGUIMIENTO_ENVIO WITH(NOLOCK)
			--WHERE FECHA_HORA_MOVIMIENTO BETWEEN @FechaInicial AND @FechaFinal AND ID_PROCESO IN (11,24)
		 --) 
 )
 SELECT 
 C.*, 
 G_FECHA_ENTREGA = G.FECHA_ENTREGA
 ,G_FECHA_ENVIO = G.FECHA_ENVIO
 ,G_ID_CLIENTE = G.ID_CLIENTE
 ,DOC_ID_CIUDAD_CANAL = DOC.ID_CIUDAD_CANAL
 ,DOC_ID_CIUDAD_ZONA_URBA = DOC.ID_CIUDAD_ZONA_URBA
 ,DOC_ID_TIPO_LOGISTICA = DOC.ID_TIPO_LOGISTICA
 ,DOC_FECHA_MODIFICACION = DOC.FECHA_MODIFICACION
 ,DOC_ID_CIUDAD_CANAL = DOC.ID_CIUDAD_CANAL
 ,DOC_ID_CIUDAD_OPERATIVO = DOC.ID_CIUDAD_OPERATIVO
 ,DOC_ID_CIUDAD_DESTINO = DOC.ID_CIUDAD_DESTINO
 ,DOC_ID_REGIONAL = CD.ID_REGIONAL
 ,DOC.ID_DIVISION_DESTINO
 ,DOC.ID_CIUDAD_DIVISION_ORIGEN
 ,DOC.ID_DIVISION_ORIGEN
 ,FECHA_EXTRACCION = GETDATE()
 ,[G_FECHA_ENTREGA (Formato)] = CONVERT(VARCHAR,CONVERT(DATE,CONVERT(DATETIME,G.FECHA_ENTREGA)),121)-----LEFT(FECHA_ENTREGA,10)
 ,[SE_FECHA_HORA_MOVIMI (Formato)] = CONVERT(VARCHAR,CONVERT(DATE,CONVERT(DATETIME,C.FECHA_HORA_MOVIMIENTO)),121)-----LEFT([FECHA_HORA_MOVIMI],10)
 FROM CTE C 
 INNER JOIN DBO.DOCUMENTOS DOC WITH(NOLOCK)
 ON DOC.CONSECUT_MOVIMI=C.CONSECUT_MOVIMI
 AND DOC.NUMERO_MOVIMI=C.NUMERO_MOVIMI
 AND DOC.ID_PROCESO=C.ID_PROCESO
 INNER JOIN dbo.GUIAS G WITH(NOLOCK)
 ON G.NUMERO_GUIA=C.NUMERO_GUIA
 LEFT JOIN PARAMETROS..CIUDADES CD WITH(NOLOCK)
 ON CD.ID_CIUDAD=DOC.ID_CIUDAD_ZONA_URBA
 WHERE C.ID IN (1,2)



