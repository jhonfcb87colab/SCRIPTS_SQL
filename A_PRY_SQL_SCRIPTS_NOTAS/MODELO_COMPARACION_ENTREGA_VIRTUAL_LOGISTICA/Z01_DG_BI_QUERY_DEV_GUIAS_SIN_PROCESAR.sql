with CTE 
(
ID
,ID_PROCESO
,NUMERO_MOVIMI
,CONSECUT_MOVIMI
,NUMERO_GUIA
,ID_CONCEPTO
,ID_EMPLEADO
,ID_ESTA_FISICO
,ID_PRODUCTO
,ID_SUBPRODUCTO
,ID_TIPOENVIO
,ID_CONSECUTIVO_SEGUIMIENTO
,ID_ENVIO_CRUZADO
,PESO_ENVIO
,LARGO_ENVIO
,ANCHO_ENVIO
,ALTO_ENVIO
,HORA_INICIAL_ENTREGA
,HORA_FINAL_ENTREGA
,FECHA_HORA_MOVIMIENTO
,ID_MODO_REGISTRO
,NUMERO_PIEZAS
,ID_EST_EMBALAJE
,ID_TIPOENVIO_PRODUCTIVIDAD
,DEVOLUCION_REGIONAL
,LOGIN_EMPLEADO
,FECHA_CREACION
,FECHA_MODIFICACION
,ID_REPLICADO
)AS(
		SELECT 
		ROW_NUMBER ( )   OVER ( PARTITION BY SE.NUMERO_GUIA order by SE.FECHA_HORA_MOVIMIENTO desc )  ID  
		,SE.ID_PROCESO
		,SE.NUMERO_MOVIMI
		,SE.CONSECUT_MOVIMI
		,SE.NUMERO_GUIA
		,SE.ID_CONCEPTO
		,SE.ID_EMPLEADO
		,SE.ID_ESTA_FISICO
