

/*			ASIGNAR ESTADO DEL ENVIO  Y ESTADO DE LA GUIA				*/  


DROP TABLE IF EXISTS #PAR_ESTADOSENVIO_TEMP
SELECT 
ID_ESTADOENVIO	
,NOMBRE_ESTADOENVIO
INTO #PAR_ESTADOSENVIO_TEMP
FROM PAR.ESTADOSENVIO WITH(NOLOCK)

DROP TABLE IF EXISTS #PAR_ESTADOSGUIA_TEMP
SELECT 
ID_ESTADOGUIA	
,NOMBRE_ESTADOGUIA
INTO #PAR_ESTADOSGUIA_TEMP
FROM PAR.ESTADOSGUIA

UPDATE TMP SET 
TMP.G_NOMBRE_ESTADOENVIO = EV.NOMBRE_ESTADOENVIO
FROM [TMP].[MPCCO_VJ_PS01] TMP WITH(NOLOCK)
INNER JOIN #PAR_ESTADOSENVIO_TEMP EV ON EV.ID_ESTADOENVIO=TMP.G_ID_ESTADOENVIO

UPDATE TMP SET 
TMP.G_NOMBRE_ESTADOGUIA  = EG.NOMBRE_ESTADOGUIA
FROM [TMP].[MPCCO_VJ_PS01] TMP WITH(NOLOCK)
INNER JOIN #PAR_ESTADOSGUIA_TEMP EG ON EG.ID_ESTADOGUIA=TMP.G_ID_ESTADOGUIA




