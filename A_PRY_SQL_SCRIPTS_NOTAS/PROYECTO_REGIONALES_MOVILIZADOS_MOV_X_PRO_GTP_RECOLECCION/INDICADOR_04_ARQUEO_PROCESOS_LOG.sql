DECLARE @ANT INT = 4;
DECLARE @FECH_INI DATETIME = CONVERT(DATETIME,CONVERT(DATE,DATEADD(DAY,-@ANT,GETDATE())))
DECLARE @FECH_FIN DATETIME = CONVERT(DATETIME,CONVERT(DATE,DATEADD(DAY,1,GETDATE())))
