DROP TABLE IF EXISTS #MPCCO_ARQUEO_SEGUIMIENTO_ENVIO;
SELECT 
 ID_PROCESO	
,NUMERO_MOVIMI	
,CONSECUT_MOVIMI	
,NUMERO_GUIA
,ID_PRODUCTO
,NUMERO_PIEZAS
INTO #MPCCO_ARQUEO_SEGUIMIENTO_ENVIO
FROM Mece_Logistico.DBO.SEGUIMIENTO_ENVIO SE WITH(NOLOCK)
WHERE SE.FECHA_HORA_MOVIMIENTO BETWEEN @FECH_INI AND @FECH_FIN 
AND SE.ID_PROCESO IN (5,6,14,12,9)
OPTION (RECOMPILE)

DROP TABLE IF EXISTS #MPCCO_ARQUEO_MANIFIESTOS;
SELECT 
 ID_PROCESO	
,NUMERO_MOVIMI	
,CONSECUT_MOVIMI	
INTO #MPCCO_ARQUEO_MANIFIESTOS
FROM #MPCCO_ARQUEO_SEGUIMIENTO_ENVIO
GROUP BY 
 ID_PROCESO	
,NUMERO_MOVIMI	
,CONSECUT_MOVIMI	


CREATE NONCLUSTERED INDEX [MPCCO_MANIFIESTO] ON #MPCCO_ARQUEO_MANIFIESTOS
(
ID_PROCESO	ASC
,NUMERO_MOVIMI	ASC
,CONSECUT_MOVIMI ASC)
WITH (PAD_INDEX = OFF, STATISTICS_NORECOMPUTE = OFF, SORT_IN_TEMPDB = OFF, 
IGNORE_DUP_KEY = OFF, 
ONLINE = OFF, 
ALLOW_ROW_LOCKS = ON, 
ALLOW_PAGE_LOCKS = ON, 
FILLFACTOR = 80) ON [PRIMARY]

--DROP TABLE IF EXISTS #MPCCO_ARQUEO_PROCESOS_LOG;
SELECT 
 DOC.ID_PROCESO	
,DOC.NUMERO_MOVIMI	
,DOC.CONSECUT_MOVIMI	
,DOC.ESTADO_MOVIMI
,DOC.ID_CANAL
,DOC.ID_CIUDAD_CANAL
,DOC.ID_CIUDAD_DIVISION_ORIGEN AS ID_CIUDAD_ORIGEN 
,DOC.ID_DIVISION_DESTINO
,DOC.ID_DIVISION_ORIGEN
,DOC.ID_ZONA_URBA
,DOC.ID_CIUDAD_ZONA_URBA
,DOC.ID_TIPO_ZONA_URBA
,DOC.PLACA_VEHICULO_DOCU
--INTO #MPCCO_ARQUEO_PROCESOS_LOG
FROM Mece_Logistico.DBO.DOCUMENTOS DOC WITH(NOLOCK)
INNER JOIN #MPCCO_ARQUEO_MANIFIESTOS TMP
ON 	DOC.ID_PROCESO=TMP.ID_PROCESO	
AND DOC.NUMERO_MOVIMI=TMP.NUMERO_MOVIMI	
AND DOC.CONSECUT_MOVIMI=TMP.CONSECUT_MOVIMI 
OPTION (RECOMPILE)

