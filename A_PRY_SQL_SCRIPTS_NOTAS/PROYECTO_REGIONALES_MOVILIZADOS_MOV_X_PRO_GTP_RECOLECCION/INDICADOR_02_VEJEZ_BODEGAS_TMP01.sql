DROP TABLE IF EXISTS #PAR_CIUDADES_REGIONAL;
SELECT 
CD.ID_PAIS,
CD.ID_CIUDAD, 
CD.NOMBRE_CIUDAD,
RG.ID_REGIONAL,
RG.NOMBRE_REGIONAL
INTO #PAR_CIUDADES_REGIONAL
FROM PAR.CIUDADES CD WITH(NOLOCK)
INNER JOIN PAR.REGIONALES_PAIS RG WITH(NOLOCK)
ON RG.ID_REGIONAL=CD.ID_REGIONAL
WHERE CD.ID_PAIS=1 AND RG.ID_EST_REGIONAL=1



DROP TABLE IF EXISTS #CLIENTES_TEMP
SELECT ID_CLIENTE,NOMBRE_CLIENTE,RAZON_SOCIAL_CORTA 
INTO #CLIENTES_TEMP
FROM PAR.CLIENTES WITH(NOLOCK)



DROP TABLE IF EXISTS #ZONA_URBA_TEMP
SELECT 
ID_PAIS	
,ID_CIUDAD	
,ID_TIPO_ZONA_URBA	
,ID_ZONA_URBA	
,NOMBRE_ZONA_URBA	
,CATEGORIA_ZONA_URBA AS ID_CATEGORIA_ZONA_URBA
,CTZU.Nombre_Categoria AS NOMBRE_CATEGORIA_ZONA_URBA
INTO #ZONA_URBA_TEMP
FROM PAR.ZONASURBANAS Z WITH(NOLOCK)  
LEFT JOIN [PAR].[CATEGORIAZONAURBANA] CTZU WITH(NOLOCK)  
ON Z.CATEGORIA_ZONA_URBA=CTZU.Id_Categoria




DROP TABLE IF EXISTS #PAR_ESTADOSENVIO_TEMP
SELECT 
ID_ESTADOENVIO	
,NOMBRE_ESTADOENVIO
INTO #PAR_ESTADOSENVIO_TEMP
FROM PAR.ESTADOSENVIO WITH(NOLOCK)

DROP TABLE IF EXISTS #PAR_ESTADOSGUIA_TEMP
