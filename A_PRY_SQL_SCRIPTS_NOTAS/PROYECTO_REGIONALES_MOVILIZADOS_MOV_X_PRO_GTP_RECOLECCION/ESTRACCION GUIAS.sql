use Mece_Logistico;

DECLARE @VAR_INT INT = -2;
DECLARE @FECHA_INI DATETIME = CONVERT(DATETIME,CONVERT(DATE,DATEADD(DAY,@VAR_INT,GETDATE()))); 
DECLARE @FECHA_FIN DATETIME = CONVERT(DATETIME,CONVERT(DATE,GETDATE()));

DROP TABLE IF EXISTS #TMP_TABLAS_TEMPORALES_GUIAS;

SELECT * 
INTO #TMP_TABLAS_TEMPORALES_GUIAS
FROM Mece_Logistico.DBO.GUIAS WITH(NOLOCK)
WHERE FECHA_ENVIO BETWEEN @FECHA_INI  AND @FECHA_FIN 
AND ID_ESTADOGUIA>=3

INSERT INTO #TMP_TABLAS_TEMPORALES_GUIAS
SELECT * 
FROM Mece_Logistico.DBO.GUIAS WITH(NOLOCK)
WHERE FECHA_MODIFICACION_DG BETWEEN @FECHA_INI  AND @FECHA_FIN 
AND ID_ESTADOGUIA>=3

;WITH CTE_TABLE_TEMPORAL_20250717 AS(
SELECT
DUMPLICADOS = ROW_NUMBER() OVER(PARTITION BY NUMERO_GUIA ORDER BY FECHA_ENVIO DESC)
FROM #TMP_TABLAS_TEMPORALES_GUIAS
)
DELETE CTE_TABLE_TEMPORAL_20250717 WHERE  DUMPLICADOS>1

DELETE #TMP_TABLAS_TEMPORALES_GUIAS WHERE LEN(NUMERO_GUIA)<=7

SELECT NUMERO_GUIA,COUNT(1) TT FROM #TMP_TABLAS_TEMPORALES_GUIAS
GROUP BY NUMERO_GUIA
HAVING COUNT(1) >1

SELECT * FROM #TMP_TABLAS_TEMPORALES_GUIAS WHERE LEN(NUMERO_GUIA)<=7

SELECT COUNT(1) TT FROM #TMP_TABLAS_TEMPORALES_GUIAS


